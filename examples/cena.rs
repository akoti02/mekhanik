//! 🟥 14.11 СТЕНД ЦЕНЫ «МЕХАНИКА» (пакет «цена»): прогнать те же куски главного окна по отдельности на живой машине
//! (только чтение) и напечатать микросекунды на кусок. По нему видно, что дороже, и сверяются цифры «до/после»
//! удешевления. В программу «Механика» не входит.
//!
//!   cargo run --example cena --release
//!
//! Стенд ничего не меняет: только читает процессы, датчики и файлы (профили «Механика» читаются, но не пишутся;
//! barsu.json и sejchas.json НЕ трогаются — арбитр и публикатор окна пишут на диск, поэтому их шаг здесь не гоняем,
//! а меряем лишь чистые части: вердикт моста и сбор карточек).
#![allow(confusable_idents, mixed_script_confusables)]

use std::time::Instant;

use mekhanik::kto::{self, Картина};
use mekhanik::okna;
use mekhanik::predvidenie;
use mekhanik::vnimanie;
use mekhanik::arbitr;

/// Прогнать `f` `n` раз, вернуть микросекунды на один раз (после прогрева).
fn мкс<F: FnMut()>(n: u32, mut f: F) -> f64 {
    f(); // прогрев (первый раз заполняет кэши)
    let т = Instant::now();
    for _ in 0..n {
        f();
    }
    т.elapsed().as_nanos() as f64 / n as f64 / 1000.0
}

fn строка(имя: &str, мкс_раз: f64) {
    // 500 окон в час (окно 2 с) × мкс → доля ядра за час в процентах (ядро = 36_000_000 мкс/час)
    let доля = мкс_раз * 1800.0 / 36_000_000.0 * 100.0;
    println!("  {имя:<42} {мкс_раз:>9.1} мкс/раз   ≈ {доля:>6.3} % ядра (раз в окно)");
}

fn снять_снимок(буф: &mut Vec<u8>) -> kto::Снимок {
    let все = okna::процессы();
    let сн = okna::снимок(буф).unwrap_or_default();
    let когда = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH)
        .map(|д| д.as_millis() as u64).unwrap_or(0);
    let процессы = все.iter().map(|&(pid, родитель, ref имя)| {
        let п = сн.get(&pid);
        kto::ВходПроцесса {
            pid,
            родитель,
            создан: п.map(|p| p.создан).unwrap_or(0),
            сеанс: okna::сеанс(pid).unwrap_or(1),
            имя: имя.clone(),
            путь: okna::путь_процесса(pid),
            личная_мб: п.map(|p| p.рабочий >> 20).unwrap_or(0),
            ..Default::default()
        }
    }).collect();
    kto::Снимок { когда_мс: когда, процессы }
}

fn main() {
    println!("\n=== СТЕНД ЦЕНЫ «МЕХАНИКА» (только чтение) ===");
    let mut буф = vec![0u8; 2 << 20];
    let все = okna::процессы();
    println!("процессов в снимке: {}\n", все.len());

    println!("-- снимок и список процессов --");
    строка("снимок (okna::снимок)", мкс(50, || { okna::снимок(&mut буф).unwrap_or_default(); }));
    строка("процессы Toolhelp (было, в kto)", мкс(50, || { let _ = okna::процессы(); }));
    // ПОСЛЕ: список (pid, родитель, имя) для kto берём из уже снятого снимка — второй обход не нужен
    let сн_для_все = okna::снимок(&mut буф).unwrap_or_default();
    строка("(pid,родитель,имя) из снимка (стало)", мкс(50, || {
        let _: Vec<(u32, u32, String)> = сн_для_все.iter().map(|(pid, п)| (*pid, п.родитель, п.имя.clone())).collect();
    }));

    println!("\n-- путь и сеанс процессов (их читает kto_снимок) --");
    // ДО удешевления: путь+сеанс каждому процессу каждое окно; ПОСЛЕ: только новым (кэш по личности) — почти ноль
    строка("путь+сеанс ВСЕХ (было каждое окно)", мкс(10, || {
        for &(pid, _, _) in &все {
            let _ = okna::путь_процесса(pid);
            let _ = okna::сеанс(pid);
        }
    }));
    println!("    (после удешевления kto_снимок читает их лишь НОВЫМ процессам — в ровном ходе ≈ 0)");

    println!("\n-- kto: понимание процессов --");
    let mut картина = Картина::новая();
    let снимок = снять_снимок(&mut буф);
    картина.обновить(&снимок); // прогрев: первый такт строит базы
    // лёгкий такт (в ровном ходе — почти каждое окно): база из кэша, только поведение+решение
    строка("kto обновить — ЛЁГКИЙ такт", мкс(50, || { картина.обновить(&снимок); }));
    // полный такт (новым процессам и раз в 15 с): паспорт, справочник, родословная, строки запуска
    let mut t = снимок.когда_мс;
    строка("kto обновить — ПОЛНЫЙ такт", мкс(20, || {
        t += 20_000; // сдвиг времени заставляет пересобрать базы
        let s = kto::Снимок { когда_мс: t, процессы: снимок.процессы.clone() };
        картина.обновить(&s);
    }));

    println!("\n-- внимание (vnimanie) --");
    строка("звук процессов (COM)", мкс(20, || { let _ = vnimanie::звук_процессов(); }));
    строка("микрофон+камера (реестр)", мкс(20, || {
        let _ = vnimanie::микрофон_занят();
        let _ = vnimanie::камера_занята();
    }));
    let сост = vnimanie::Состояние::default();
    строка("снять ВСЁ каждое окно (было)", мкс(20, || { let _ = vnimanie::снять(&сост, false); }));
    // опрос с кэшем: дорогое — раз в 10 с, прочее каждое окно; амортизируем по 50 окнам
    let mut опрос = vnimanie::Опрос::новый();
    опрос.снять(&сост, false);
    строка("Опрос::снять (дорогое раз в 10 с)", мкс(50, || { let _ = опрос.снять(&сост, false); }));

    println!("\n-- видеокарта по процессам (PDH) --");
    match okna::ВидеокартаПроцессов::открыть() {
        Some(с) => {
            с.снять(None); // прогрев
            строка("доли видеокарты (снять)", мкс(30, || { let _ = с.снять(None); }));
        }
        None => println!("  (счётчик видеокарты по процессам недоступен)"),
    }

    println!("\n-- предвидение --");
    let mut предв = predvidenie::Предвидение::новая();
    let мс_now = снимок.когда_мс;
    let now_ft = (мс_now + 11_644_473_600_000) * 10_000;
    let тяжёлые: Vec<predvidenie::Тяжёлая> = картина.карточки()
        .filter(|к| к.решение.тяжёлое || к.решение.род == kto::Род::Просмотр)
        .map(|к| {
            let профиль = картина.профили().профиль(&к.ключ_профиля);
            let возраст = (now_ft.saturating_sub(к.личность.создан) as f64 / 1e7).max(0.0);
            predvidenie::Тяжёлая {
                кому: predvidenie::sovet::Кому { pid: к.личность.pid, создан: к.личность.создан },
                подпись: к.подпись.clone(),
                его_работа: к.решение.чей == kto::Чей::ЕгоРабота,
                просмотр: к.решение.род == kto::Род::Просмотр,
                окно_достоин: к.решение.нужно.nvidia
                    && matches!(к.решение.род, kto::Род::Игра | kto::Род::Сапр | kto::Род::Рендер3д),
                ожидаемый_озу_мб: к.ожидаемый_озу_мб,
                ожидаемая_видеопамять_нв_мб: к.ожидаемая_видеопамять_мб,
                сейчас_озу_мб: 0,
                сейчас_видео_нв_мб: к.видео_нв_мб,
                с_начала_с: возраст,
                до_пика_с: профиль.and_then(|п| п.до_пика_с(мс_now)),
                длительность_с: профиль.and_then(|п| п.обычная_длительность_с(мс_now)),
            }
        }).collect();
    println!("  (тяжёлых/просмотр в снимке: {})", тяжёлые.len());
    let вход = predvidenie::Вход {
        когда_мс: мс_now, доступно_мб: None, зачислено_своб_мб: None, видеопамять_нв_своб_мб: None,
        за_пк: true, тяжёлые, окно_впереди: None, разум: None, разум_простаивает: false,
        тормоз_памяти_только_что: false, тень: false,
    };
    строка("предвидение шаг", мкс(50, || { let _ = предв.шаг(&вход); }));

    println!("\n-- мост (вердикт для barsu.json; сам мост на диск здесь не пишем) --");
    let арбитр = arbitr::Арбитр::новый();
    let разум = arbitr::most::Разум { печатает: false, загружен: false, простой_с: None };
    строка("мост::вердикт", мкс(200, || {
        let _ = arbitr::most::вердикт(арбитр.положение(), &разум, "");
    }));

    println!("\n(окно для значка и ящик здесь не меряем: публикатор окна и чёрный ящик пишут на диск / идут своим \
        потоком; их цену даёт часовая строка сторож_тормозов_час полем «цена_кусков_мкс».)");
    println!("\n=== готово ===\n");
}
