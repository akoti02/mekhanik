//! 🟥 ПОВТОР (волна 2б, разбор `predvoskhishchenie.md` §7.1): прогон предвидения по СТАРОМУ журналу «Механика»
//! (`%LOCALAPPDATA%\mekhanik\zhurnal\*.jsonl`, только чтение). Берём точки свободной памяти (доступно ОЗУ и
//! зачисленная), какие журнал записал, прогоняем через те же чистые функции предвидения (`ryad`, `prognoz`) и считаем:
//! сколько тормозов памяти предвидение поймало БЫ заранее (тревога за 3–300 с до начала) и сколько тревог оказалось
//! ложными (за ними тормоза памяти в 300 с не было). Правку порогов проверяют здесь, без него и без нагрузки на ПК.
//!
//! Запуск из своей копии через очередь:
//!   Set-Location C:\dev\wt\mekh-predvidenie; $env:CARGO_TARGET_DIR='C:\dev\wt-target\mekh-predvidenie';
//!   & C:\dev\wt\cargo-ochered.ps1 run --example povtor
//!
//! В журнале нет непрерывных рядов (точки редки и в основном во время тормозов) — цифры осторожные, это НИЖНЯЯ оценка;
//! настоящую точность даёт чёрный ящик (кадр в секунду) и неделя в тени. В программу «Механика» povtor не входит.
#![allow(confusable_idents, mixed_script_confusables)]

// чистое ядро предвидения — включаем из своих файлов на уровне крейта примера (examples — отдельный крейт, модули
// крейта ему недоступны). `prognoz` зовёт `super::ryad` — потому оба на уровне корня примера.
#[path = "../src/predvidenie/ryad.rs"]
mod ryad;
#[path = "../src/predvidenie/prognoz.rs"]
mod prognoz;
use crate::prognoz::{пороги_зачисленной, пороги_озу, уровень, Пороги, Уровень};
use crate::ryad::{согласованный_наклон, Окно};

use chrono::DateTime;
use serde_json::Value;
use std::path::{Path, PathBuf};

/// Точка памяти из журнала.
#[derive(Clone, Copy)]
struct Точка {
    мс: u64,
    доступно: Option<f64>,
    зачислено: Option<f64>,
    тормоз_памяти: bool,
}

const ОКНО_ЗА: u64 = 300_000; // смотрим тревогу за 300 с до тормоза
const ОКНО_МИН: u64 = 3_000; // и не позже чем за 3 с
const ДЕБАУНС_МС: u64 = 60_000; // одна тревога не чаще раза в минуту

fn главный_журнал() -> Option<PathBuf> {
    std::env::var_os("LOCALAPPDATA").map(|д| Path::new(&д).join("mekhanik").join("zhurnal"))
}

fn файлы(папка: &Path) -> Vec<PathBuf> {
    let mut в = Vec::new();
    собрать(папка, &mut в);
    // и перенесённую историю, если есть
    собрать(&папка.join("staroe"), &mut в);
    в.sort();
    в
}

fn собрать(папка: &Path, в: &mut Vec<PathBuf>) {
    if let Ok(чтение) = std::fs::read_dir(папка) {
        for запись in чтение.flatten() {
            let п = запись.path();
            if п.extension().and_then(|e| e.to_str()) == Some("jsonl") { в.push(п); }
        }
    }
}

fn мс_из_ts(ts: &str) -> Option<u64> {
    DateTime::parse_from_rfc3339(ts).ok().map(|dt| dt.timestamp_millis() as u64)
}

/// Признак тормоза памяти: среди признаков есть «память» или «зачислен».
fn это_тормоз_памяти(data: &Value) -> bool {
    data.get("признаки").and_then(Value::as_array).map(|а| а.iter().filter_map(Value::as_str)
        .any(|п| п.starts_with("память") || п.contains("зачислен"))).unwrap_or(false)
}

fn разобрать(файлы: &[PathBuf]) -> Vec<Точка> {
    let mut точки = Vec::new();
    for ф in файлы {
        let Ok(текст) = std::fs::read_to_string(ф) else { continue; };
        for строка in текст.lines() {
            let Ok(o) = serde_json::from_str::<Value>(строка) else { continue; };
            let (Some(событие), Some(ts)) = (o.get("event").and_then(Value::as_str), o.get("ts").and_then(Value::as_str))
            else { continue; };
            let Some(мс) = мс_из_ts(ts) else { continue; };
            let data = o.get("data").cloned().unwrap_or(Value::Null);

            let (мут_доступно, мут_зачислено, тормоз) = match событие {
                "тормоз_пк" => (
                    data.get("доступно_мб").and_then(Value::as_f64),
                    data.get("зачислено_своб_мб").and_then(Value::as_f64),
                    это_тормоз_памяти(&data),
                ),
                "механик_исчерпал" | "механик_лечит" => {
                    let после = data.get("после").cloned().unwrap_or(Value::Null);
                    (после.get("доступно_мб").and_then(Value::as_f64),
                     после.get("зачислено_своб_мб").and_then(Value::as_f64), false)
                }
                _ => (None, None, false),
            };
            if мут_доступно.is_some() || мут_зачислено.is_some() || тормоз {
                точки.push(Точка { мс, доступно: мут_доступно, зачислено: мут_зачислено, тормоз_памяти: тормоз });
            }
        }
    }
    точки.sort_by_key(|т| т.мс);
    точки
}

/// Прогнать один ресурс (по выбору значения из точки) через окна и собрать времена тревог (мягко и сильнее).
fn тревоги(точки: &[Точка], выбрать: impl Fn(&Точка) -> Option<f64>, пороги: &Пороги) -> Vec<u64> {
    let mut к = Окно::новое(10_000);
    let mut д = Окно::новое(30_000);
    let mut тревоги = Vec::new();
    let mut последняя = 0u64;
    for т in точки {
        let Some(знач) = выбрать(т) else { continue; };
        к.добавить(т.мс, знач);
        д.добавить(т.мс, знач);
        let наклон = согласованный_наклон(&к, &д).unwrap_or(0.0);
        // без профиля (журнал не знает запусков) — только наклон и уровень
        if уровень(знач, 0.0, наклон, пороги) != Уровень::Нет && т.мс.saturating_sub(последняя) >= ДЕБАУНС_МС {
            тревоги.push(т.мс);
            последняя = т.мс;
        }
    }
    тревоги
}

fn main() {
    let Some(папка) = главный_журнал() else { println!("нет LOCALAPPDATA"); return; };
    let файлы = файлы(&папка);
    if файлы.is_empty() { println!("журнал не найден: {}", папка.display()); return; }
    let точки = разобрать(&файлы);

    let тормоза: Vec<u64> = точки.iter().filter(|т| т.тормоз_памяти).map(|т| т.мс).collect();
    // «гроздья»: тормоза ближе 10 мин считаем за один эпизод (как в разборе §2)
    let mut эпизоды: Vec<u64> = Vec::new();
    for &т in &тормоза {
        if эпизоды.last().map(|&п| т.saturating_sub(п) > 600_000).unwrap_or(true) { эпизоды.push(т); }
    }

    let mut тревоги_все = тревоги(&точки, |т| т.доступно, &пороги_озу());
    тревоги_все.extend(тревоги(&точки, |т| т.зачислено, &пороги_зачисленной()));
    тревоги_все.sort_unstable();
    тревоги_все.dedup();

    // поймано заранее: у эпизода есть тревога в [t-300с, t-3с]
    let mut поймано = 0;
    let mut упреждения: Vec<i64> = Vec::new();
    for &т in &эпизоды {
        if let Some(&тр) = тревоги_все.iter().rev()
            .find(|&&тр| тр + ОКНО_МИН <= т && тр + ОКНО_ЗА >= т)
        {
            поймано += 1;
            упреждения.push((т - тр) as i64 / 1000);
        }
    }

    // ложные тревоги: за тревогой нет тормоза памяти в следующие 300 с
    let mut ложных = 0;
    for &тр in &тревоги_все {
        let есть = тормоза.iter().any(|&т| т >= тр && т <= тр + ОКНО_ЗА);
        if !есть { ложных += 1; }
    }

    упреждения.sort_unstable();
    let медиана = упреждения.get(упреждения.len() / 2).copied().unwrap_or(0);

    println!("=== ПОВТОР предвидения по журналу «Механика» ===");
    println!("файлов журнала: {}", файлы.len());
    println!("точек памяти в журнале: {}", точки.len());
    println!("тормозов памяти (строк): {}", тормоза.len());
    println!("эпизодов памяти (гроздья <10 мин): {}", эпизоды.len());
    println!("тревог предвидения (по наклону, без профилей): {}", тревоги_все.len());
    println!();
    let доля = if эпизоды.is_empty() { 0.0 } else { поймано as f64 / эпизоды.len() as f64 * 100.0 };
    println!("поймано заранее (за 3–300 с): {поймано} из {} ({доля:.0} %)", эпизоды.len());
    println!("медианное упреждение: {медиана} с");
    let доля_лож = if тревоги_все.is_empty() { 0.0 } else { ложных as f64 / тревоги_все.len() as f64 * 100.0 };
    println!("ложных тревог: {ложных} из {} ({доля_лож:.0} %)", тревоги_все.len());
    println!();
    println!("Замечание: журнал редок и в основном во время тормозов — это НИЖНЯЯ оценка.");
    println!("Профили программ (запуск → пик) в журнале не записаны; с ними упреждение больше (см. чёрный ящик, тень).");
}
