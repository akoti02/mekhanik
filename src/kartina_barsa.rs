    /// 🟥 Живой `ot_barsa.json` 13.11 22:03 — как есть (БАРС до правки 13.11: 10 полей, без `proto`, `mind_pid`, `word`).
    pub const ОБРАЗЕЦ_V0: &str = r#"{"compute":[24028,40092,40392],"engines":[24028,40092,40392],"head":18492,"mind_idle_s":null,"mind_loaded":false,"mode":"СВОБОДЕН","ms":1794607410636,"video":false,"window":20324,"work":["судья экрана E4B"]}"#;
    /// Живая отметка 13.11 20:42:55 (разбор `osvedomlennost_bars.md` §2) — он смотрит видео.
    const ОБРАЗЕЦ_СМОТРИТ: &str = r#"{"compute":[24028,40092],"engines":[24028,40092],"head":18492,"mind_idle_s":null,"mind_loaded":false,"mode":"СМОТРИТ","ms":1794602575622,"video":true,"window":20324,"work":["судья экрана E4B"]}"#;

    /// Контракт с БАРСом на живом образце: все 10 полей читаются; `word` нет — «не знаю», а не «нет»; режим ПЕЧАТАЕТ —
    /// он печатает разуму: `слово` (разум не опускать, 27B не выгружать). КРАСНЫЙ на старом коде: `слово` было только
    /// полем `word`, которого БАРС не пишет, — при «ПЕЧАТАЕТ» `слово` = false (30 лишних просьб выгрузить 27B за 19 дней).
    #[test]
    fn договор_на_живом_образце() {
        let мс = 1_794_607_410_636u64;
        let v: Value = serde_json::from_str(ОБРАЗЕЦ_V0).unwrap();
        let mut поля: Vec<&str> = v.as_object().unwrap().keys().map(String::as_str).collect();
        поля.sort_unstable();
        assert_eq!(поля, ПОЛЯ_V0.to_vec(), "БАРС сменил набор полей — сверить договор (документация §3)");
        let б = разобрать_барс(ОБРАЗЕЦ_V0, мс + 1_000);
        assert!(б.жив && б.окно == Some(20324) && б.голова == Some(18492));
        assert_eq!((б.движки.clone(), б.счёт.clone()), (vec![24028, 40092, 40392], vec![24028, 40092, 40392]));
        assert_eq!(б.работа, vec!["судья экрана E4B".to_string()]);
        assert!(!б.разум_загружен && б.разум_простой_с.is_none() && !б.видео && б.режим.as_deref() == Some("СВОБОДЕН"));
        assert_eq!((б.протокол, б.слово_барса, б.слово, б.печатает), (0, None, false, false), "v0: слово — «не знаю»");
        let печатает = ОБРАЗЕЦ_V0.replace("СВОБОДЕН", "ПЕЧАТАЕТ");
        let б = разобрать_барс(&печатает, мс + 1_000);
        assert!(б.слово, "он печатает разуму — разум держим для его слова");
        assert!(б.печатает);
        let смотрит = разобрать_барс(ОБРАЗЕЦ_СМОТРИТ, 1_794_602_575_622 + 500);
        assert!(смотрит.видео && !смотрит.слово && смотрит.режим.as_deref() == Some("СМОТРИТ"));
        // БАРС после правки 13.11 (`mekhanik_svyaz.rs::отметить_барс` + `поля_разума`): `mind_pid` и `word`
        let новый = ОБРАЗЕЦ_V0.replace("\"window\"", "\"mind_pid\":40092,\"word\":true,\"window\"");
        let б = разобрать_барс(&новый, мс + 1_000);
        assert_eq!((б.разум_pid, б.слово_барса, б.слово), (Some(40092), Some(true), true));
        let без = ОБРАЗЕЦ_V0.replace("\"window\"", "\"mind_pid\":null,\"word\":false,\"window\"");
        assert_eq!(разобрать_барс(&без, мс + 1_000).слово_барса, Some(false));
        // протокол словами — что БАРС не шлёт
        let п = протокол_словами(ОБРАЗЕЦ_V0);
        assert_eq!(п["протокол"], 0);
        assert_eq!(п["нет_полей"], json!(["mind_pid", "word"]));
        assert_eq!(протокол_словами(&новый)["нет_полей"], json!([]));
        // отметка 16 с — БАРСа нет
        assert!(!разобрать_барс(ОБРАЗЕЦ_V0, мс + 16_000).жив);
    }

    /// Своя «система» для теста: номера → (создан мс, путь, имя), папки БАРСа.
    struct Проба { проц: HashMap<u32, (u64, String)>, папки_есть: bool }
    fn ft(мс: u64) -> u64 { (мс + 11_644_473_600_000) * 10_000 }
    impl Ос for Проба {
        fn создан(&self, pid: u32) -> Option<u64> { self.проц.get(&pid).map(|(с, _)| ft(*с)) }
        fn путь(&self, pid: u32) -> Option<String> { self.проц.get(&pid).map(|(_, п)| п.clone()) }
        fn процессы(&self) -> Vec<(u32, u32, String)> {
            self.проц.iter().map(|(p, (_, п))| (*p, 1, п.rsplit('\\').next().unwrap_or("").to_string())).collect()
        }
        fn папки_барса(&self) -> Vec<String> { vec![r"c:\u\appdata\local\programs\bars\".into(), r"c:\u\appdata\local\bars\".into()] }
        fn папка_есть(&self, _: &str) -> bool { self.папки_есть }
        fn свой_pid(&self) -> u32 { 7 }
        fn папка_windows(&self) -> String { r"c:\windows\".into() }
    }

    fn проба() -> Проба {
        let мс = 1_794_607_000_000u64;
        let mut проц = HashMap::new();
        проц.insert(20324, (мс, r"C:\U\AppData\Local\Programs\BARS\bars.exe".to_string()));
        проц.insert(18492, (мс, r"C:\U\AppData\Local\bars\golova\bars-hub.exe".to_string()));
        проц.insert(24028, (мс, r"C:\Python312\pythonw.exe".to_string()));
        // номер 40092 достался dwm (создан позже отметки), 40392 — заставка, созданная раньше
        проц.insert(40092, (мс + 500_000, r"C:\Windows\System32\dwm.exe".to_string()));
        проц.insert(40392, (мс, r"C:\Windows\System32\Ribbons.scr".to_string()));
        Проба { проц, папки_есть: true }
    }

    /// 🟥 Номера из отметки сверяются: чужой процесс с номером движка (dwm, заставка) — не БАРС: его не морозят и не
    /// опускают как БАРС. КРАСНЫЙ на старом коде: номера брались как есть (dwm.exe 65 раз «процесс БАРСа»).
    #[test]
    fn номера_барса_проверяются() {
        let о = проба();
        let mut к = Картина::default();
        let б = к.шаг(Some(ОБРАЗЕЦ_V0), 1_794_607_410_636 + 1_000, Some(1_000), false, &о);
        assert_eq!(к.состояние(), Состояние::Свеж);
        assert_eq!((б.окно, б.голова), (Some(20324), Some(18492)));
        assert_eq!(б.движки, vec![24028], "dwm и заставка — не движки БАРСа");
        assert_eq!(б.счёт, vec![24028]);
        assert!(к.строки.iter().filter(|(с, _)| *с == "барс_номер_не_его").count() == 2);
        assert!(к.строки.iter().any(|(с, _)| *с == "барс_протокол"));
        assert_eq!(судить(Роль::Движок, Some(r"C:\dev\llamacpp-cuda\llama-server.exe"), 10, 20, false, &[], r"c:\windows\"), Ok(()));
        assert!(судить(Роль::Окно, Some(r"C:\Program Files\Vivaldi\vivaldi.exe"), 10, 20, false, &[], r"c:\windows\").is_err());
        assert!(судить(Роль::Движок, None, 10, 20, true, &[], "").is_err(), "сам «Механик» — не БАРС");
        assert_eq!(судить(Роль::Движок, None, 30_000, 20, false, &[], ""), Err("процесс создан позже отметки БАРСа — номер достался другому"));
    }

    /// 🟥 Замолк (15–120 с) — последняя картина держится: процессы БАРСа неприкасаемы, но `жив: false` (не морозим, не
    /// просим, разум не опускаем); дольше 2 мин — только процессы из папок БАРСа; нет ни папок, ни процессов — удалён.
    /// КРАСНЫЙ на старом коде: отметка старше 15 с — `Барс::default()`, его голова и движки становились «чужими».
    #[test]
    fn свеж_замолк_нет_удалён() {
        let mut о = проба();
        let мс = 1_794_607_410_636u64;
        let mut к = Картина::default();
        к.шаг(Some(ОБРАЗЕЦ_V0), мс + 1_000, Some(10_000), false, &о);
        let б = к.шаг(Some(ОБРАЗЕЦ_V0), мс + 30_000, Some(39_000), false, &о);
        assert_eq!(к.состояние(), Состояние::Замолк);
        assert!(!б.жив && б.окно == Some(20324) && б.голова == Some(18492) && б.движки == vec![24028]);
        assert!(б.работа.is_empty() && !б.разум_загружен, "что БАРС делает сейчас — не знаем");
        // номер головы достался другому процессу — больше не защищаем
        о.проц.insert(18492, (мс + 20_000, r"C:\U\AppData\Local\bars\golova\bars-hub.exe".to_string()));
        assert_eq!(к.шаг(None, мс + 40_000, Some(49_000), false, &о).голова, None);
        // дольше 2 мин — по папкам
        let б = к.шаг(None, мс + 200_000, Some(209_000), false, &о);
        assert_eq!(к.состояние(), Состояние::Нет);
        assert_eq!(б.окно, Some(20324));
        assert!(б.движки.is_empty() && б.голова == Some(18492), "pythonw не в папке БАРСа; голова — по папке");
        assert_eq!(к.видели_без_сна(), Some(10_000), "видели последний раз — по времени без сна (сон не в счёт)");
        // БАРС удалён
        let mut пусто = Проба { проц: HashMap::new(), папки_есть: false };
        пусто.проц.insert(24028, (мс, r"C:\Python312\pythonw.exe".into()));
        let mut к2 = Картина::default();
        let б = к2.шаг(None, мс, Some(1), false, &пусто);
        assert_eq!((к2.состояние(), б.состояние), (Состояние::Удалён, Состояние::Удалён));
        assert!(б.движки.is_empty() && б.окно.is_none());
        // флаг выключенного разума — в картине при любом состоянии
        assert!(к2.шаг(None, мс + 1, Some(2), true, &пусто).разум_выключен);
        assert!(к.шаг(Some(ОБРАЗЕЦ_V0), мс + 210_000 - 200_000, Some(300_000), true, &о).разум_выключен);
    }

