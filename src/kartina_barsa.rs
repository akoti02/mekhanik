#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Состояние { Свеж, Замолк, #[default] Нет, Удалён }

impl Состояние {
    pub fn имя(self) -> &'static str {
        match self { Состояние::Свеж => "свеж", Состояние::Замолк => "замолк", Состояние::Нет => "нет", Состояние::Удалён => "удалён" }
    }
}

/// Кем процесс назван в отметке.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Роль { Окно, Голова, Движок }

impl Роль {
    fn имя(self) -> &'static str { match self { Роль::Окно => "окно", Роль::Голова => "голова", Роль::Движок => "движок" } }
}

/// Что «Механик» знает о системе (на Windows — `okna`; в тесте — своё).
pub trait Ос {
    /// Время создания процесса (FILETIME, 100 нс с 1601); `None` — процесса нет или не открыть.
    fn создан(&self, pid: u32) -> Option<u64>;
    fn путь(&self, pid: u32) -> Option<String>;
    /// (номер, родитель, имя) всех процессов.
    fn процессы(&self) -> Vec<(u32, u32, String)>;
    /// Папки БАРСа — в нижнем регистре, с `\` на конце.
    fn папки_барса(&self) -> Vec<String>;
    fn папка_есть(&self, папка: &str) -> bool;
    fn свой_pid(&self) -> u32;
    /// Папка Windows — в нижнем регистре, с `\` на конце.
    fn папка_windows(&self) -> String;
}

/// Настоящая система.
pub struct Windows;

impl Ос for Windows {
    fn создан(&self, pid: u32) -> Option<u64> { crate::okna::создан(pid) }
    fn путь(&self, pid: u32) -> Option<String> { crate::okna::путь_процесса(pid) }
    fn процессы(&self) -> Vec<(u32, u32, String)> { crate::okna::процессы() }
    fn папки_барса(&self) -> Vec<String> {
        let Some(м) = std::env::var_os("LOCALAPPDATA") else { return Vec::new() };
        let м = м.to_string_lossy().to_lowercase().trim_end_matches('\\').to_string();
        vec![format!("{м}\\programs\\bars\\"), format!("{м}\\bars\\")]
    }
    fn папка_есть(&self, папка: &str) -> bool { std::path::Path::new(папка).is_dir() }
    fn свой_pid(&self) -> u32 { std::process::id() }
    fn папка_windows(&self) -> String {
        let к = std::env::var("SystemRoot").unwrap_or_else(|_| r"C:\Windows".into()).to_lowercase();
        format!("{}\\", к.trim_end_matches('\\'))
    }
}

/// Чистая: FILETIME (100 нс с 1601) → мс эпохи UTC.
pub fn мс_из_filetime(ft: u64) -> u64 { (ft / 10_000).saturating_sub(11_644_473_600_000) }

/// Чистая (видно в тесте): верить ли, что процесс — тот, кого назвал БАРС. `Err` — почему нет.
pub fn судить(роль: Роль, путь: Option<&str>, создан_мс: u64, отметка_мс: u64, свой: bool, папки: &[String], windows: &str)
    -> Result<(), &'static str> {
    if свой { return Err("это сам «Механик»"); }
    if создан_мс > отметка_мс.saturating_add(ЗАПАС_СОЗДАН_МС) {
        return Err("процесс создан позже отметки БАРСа — номер достался другому");
    }
    // путь не прочесть — верим отметке (номер и время создания сошлись)
    let Some(путь) = путь else { return Ok(()) };
    let п = путь.to_lowercase().replace('/', "\\");
    let имя = п.rsplit('\\').next().unwrap_or("");
    if СИСТЕМНЫЕ.contains(&имя) || имя.ends_with(".scr") { return Err("программа Windows — не БАРС"); }
    if !windows.is_empty() && п.starts_with(windows) { return Err("программа из папки Windows — не БАРС"); }
    let в_папке = папки.iter().any(|д| п.starts_with(д.as_str()));
    match роль {
        Роль::Окно if !(имя == "bars.exe" || в_папке) => Err("окно БАРСа — не bars.exe"),
        Роль::Голова if !(имя == "bars-hub.exe" || в_папке) => Err("голова БАРСа — не bars-hub.exe"),
        _ => Ok(()),
    }
}

/// Чистая (видно в тесте): дерево процессов от проверенных корней — до `колен` колен; ребёнок признаётся, только если
/// создан не раньше родителя (номер умершего родителя мог достаться другому: 13.11 держатель заказа видеокарты
/// числился сыном Vivaldi). `все` — (номер, родитель, имя, время создания); без времени — не признаём.
#[allow(dead_code)] // для сведения: `storozh::барс_с_детьми` и `движки_с_детьми` — по нему, когда снимок даст время создания
pub fn дерево(корни: &[u32], все: &[(u32, u32, String, Option<u64>)], колен: usize) -> HashSet<u32> {
    let создан: HashMap<u32, Option<u64>> = все.iter().map(|(п, _, _, с)| (*п, *с)).collect();
    let mut свои: HashSet<u32> = корни.iter().copied().filter(|п| *п != 0 && создан.contains_key(п)).collect();
    for _ in 0..колен {
        let дети: Vec<u32> = все.iter().filter(|(п, р, _, с)| !свои.contains(п) && свои.contains(р)
            && matches!((с, создан.get(р).copied().flatten()), (Some(д), Some(о)) if *д >= о)).map(|(п, _, _, _)| *п).collect();
        if дети.is_empty() { break; }
        свои.extend(дети);
    }
    свои
}

/// Что узнали о номере при первой встрече.
#[derive(Clone, Debug, PartialEq)]
struct Проверен { создан: u64, годен: bool }

/// Картина БАРСа: последняя свежая отметка, проверенные номера, состояние.
#[derive(Default)]
pub struct Картина {
    /// Последняя свежая картина и миг её отметки.
    последняя: Option<(Барс, u64)>,
    знаем: HashMap<u32, Проверен>,
    состояние: Состояние,
    /// Время без сна, когда БАРС был свеж последний раз (сон в «нет давно» не входит).
    видели_без_сна: Option<u64>,
    /// Процессы из папок БАРСа (когда отметки нет): когда искали и кого нашли (номер, время создания, имя).
    поиск: Option<(u64, Vec<(u32, u64, String)>)>,
    /// Папки БАРСа: когда смотрели и есть ли.
    папки: Option<(u64, bool)>,
    /// Окно БАРСа, чей протокол уже записан (новое окно — БАРС перезапущен).
    протокол_окна: Option<u32>,
    /// Итог последнего шага.
    итог: Барс,
    /// Строки своего журнала, что набрались за шаг (забирает `svyaz`).
    pub строки: Vec<(&'static str, Value)>,
}

impl Картина {
    /// Последний итог (без нового чтения).
    pub fn итог(&self) -> &Барс { &self.итог }
    pub fn состояние(&self) -> Состояние { self.состояние }

    /// Время без сна, когда БАРС был свеж последний раз (`None` — не видели): «нет давно» — без сна ПК.
    pub fn видели_без_сна(&self) -> Option<u64> { self.видели_без_сна }

    /// Шаг картины: `текст` — `ot_barsa.json` (нет файла — `None`), `сейчас` — мс эпохи, `без_сна` — время без сна, мс,
    /// `флаг` — лежит ли флаг «разум выключен его словом».
    pub fn шаг(&mut self, текст: Option<&str>, сейчас: u64, без_сна: Option<u64>, флаг: bool, ос: &dyn Ос) -> Барс {
        let б = текст.map(|т| разобрать_барс(т, сейчас)).unwrap_or_default();
        let было = self.состояние;
        let mut итог = if б.жив {
            let отметка_мс = текст.and_then(|т| serde_json::from_str::<Value>(т.trim_start_matches('\u{feff}')).ok())
                .and_then(|v| v.get("ms").and_then(Value::as_u64)).unwrap_or(сейчас);
            if self.протокол_окна != б.окно {
                self.протокол_окна = б.окно;
                self.строки.push(("барс_протокол", протокол_словами(текст.unwrap_or(""))));
            }
            let б = self.проверить(б, отметка_мс, ос);
            self.последняя = Some((б.clone(), сейчас));
            self.видели_без_сна = без_сна.or(self.видели_без_сна);
            self.поиск = None;
            self.состояние = Состояние::Свеж;
            б
        } else if let Some((п, _)) = self.последняя.clone().filter(|(_, к)| сейчас.saturating_sub(*к) <= ЗАМОЛК_МС) {
            // замолк: номера держим (сверив время создания), а «что сейчас» — неизвестно
            self.состояние = Состояние::Замолк;
            let живые = |pids: &[u32]| -> Vec<u32> { pids.iter().copied().filter(|p| self.тот_же(*p, ос)).collect() };
            let окно = п.окно.filter(|p| self.тот_же(*p, ос));
            let голова = п.голова.filter(|p| self.тот_же(*p, ос));
            let разум_pid = п.разум_pid.filter(|p| self.тот_же(*p, ос));
            let (движки, счёт) = (живые(&п.движки), живые(&п.счёт));
            Барс { окно, голова, движки, счёт, разум_pid, протокол: п.протокол, состояние: Состояние::Замолк, ..Барс::default() }
        } else {
            self.последняя = None;
            let найдено = self.найти_по_папкам(сейчас, ос);
            let папки_есть = self.папки_есть(сейчас, ос);
            self.состояние = if найдено.is_empty() && !папки_есть { Состояние::Удалён } else { Состояние::Нет };
            let mut б = Барс { состояние: self.состояние, ..Барс::default() };
            for (pid, _, имя) in найдено {
                match имя.as_str() {
                    "bars.exe" if б.окно.is_none() => б.окно = Some(pid),
                    "bars-hub.exe" if б.голова.is_none() => б.голова = Some(pid),
                    _ => б.движки.push(pid),
                }
            }
            б
        };
        итог.разум_выключен = итог.разум_выключен || флаг;
        if было != self.состояние {
            self.строки.push(("барс_состояние", json!({ "было": было.имя(), "стало": self.состояние.имя(),
                "смысл": смысл_состояния(self.состояние) })));
        }
        // память номеров не растёт без конца: держим только тех, кто в картине
        if self.знаем.len() > 256 {
            let в_деле: HashSet<u32> = итог.движки.iter().chain(&итог.счёт).copied().chain(итог.окно).chain(итог.голова).collect();
            self.знаем.retain(|p, _| в_деле.contains(p));
        }
        self.итог = итог.clone();
        итог
    }

    /// Свежая отметка: оставить только проверенные номера.
    fn проверить(&mut self, mut б: Барс, отметка_мс: u64, ос: &dyn Ос) -> Барс {
        let папки = ос.папки_барса();
        let windows = ос.папка_windows();
        if let Some(p) = б.окно { if !self.годен(p, Роль::Окно, отметка_мс, &папки, &windows, ос) { б.окно = None; } }
        if let Some(p) = б.голова { if !self.годен(p, Роль::Голова, отметка_мс, &папки, &windows, ос) { б.голова = None; } }
        if let Some(p) = б.разум_pid { if !self.годен(p, Роль::Движок, отметка_мс, &папки, &windows, ос) { б.разум_pid = None; } }
        let mut движки = Vec::new();
        for p in std::mem::take(&mut б.движки) {
            if self.годен(p, Роль::Движок, отметка_мс, &папки, &windows, ос) { движки.push(p); }
        }
        let mut счёт = Vec::new();
        for p in std::mem::take(&mut б.счёт) {
            if self.годен(p, Роль::Движок, отметка_мс, &папки, &windows, ос) { счёт.push(p); }
        }
        б.движки = движки;
        б.счёт = счёт;
        б
    }

    fn годен(&mut self, pid: u32, роль: Роль, отметка_мс: u64, папки: &[String], windows: &str, ос: &dyn Ос) -> bool {
        let Some(создан) = ос.создан(pid) else { self.знаем.remove(&pid); return false };
        if let Some(з) = self.знаем.get(&pid) { if з.создан == создан { return з.годен; } }
        let путь = ос.путь(pid);
        let суд = судить(роль, путь.as_deref(), мс_из_filetime(создан), отметка_мс, pid == ос.свой_pid(), папки, windows);
        if let Err(почему) = суд {
            self.строки.push(("барс_номер_не_его", json!({ "pid": pid, "роль": роль.имя(), "путь": путь, "почему": почему,
                "смысл": "номер из отметки БАРСа — не его процесс: не трогаю его как БАРС и не защищаю как БАРС" })));
        }
        self.знаем.insert(pid, Проверен { создан, годен: суд.is_ok() });
        суд.is_ok()
    }

    /// Номер — тот же процесс, что был проверен (время создания не сменилось).
    fn тот_же(&self, pid: u32, ос: &dyn Ос) -> bool {
        self.знаем.get(&pid).is_some_and(|з| з.годен && ос.создан(pid) == Some(з.создан))
    }

    fn найти_по_папкам(&mut self, сейчас: u64, ос: &dyn Ос) -> Vec<(u32, u64, String)> {
        if let Some((когда, н)) = &self.поиск {
            if сейчас.saturating_sub(*когда) < ПОИСК_РАЗ_В_МС {
                return н.iter().filter(|(p, с, _)| ос.создан(*p) == Some(*с)).cloned().collect();
            }
        }
        let папки = ос.папки_барса();
        let mut н = Vec::new();
        if !папки.is_empty() {
            for (pid, _, имя) in ос.процессы() {
                let имя = имя.to_lowercase();
                if !ИМЕНА_БАРСА.contains(&имя.as_str()) { continue; }
                let Some(путь) = ос.путь(pid) else { continue };
                let п = путь.to_lowercase().replace('/', "\\");
                if !папки.iter().any(|д| п.starts_with(д.as_str())) { continue; }
                if let Some(с) = ос.создан(pid) { н.push((pid, с, имя)); }
            }
        }
        self.поиск = Some((сейчас, н.clone()));
        н
    }

    fn папки_есть(&mut self, сейчас: u64, ос: &dyn Ос) -> bool {
        if let Some((когда, есть)) = self.папки { if сейчас.saturating_sub(когда) < ПАПКИ_РАЗ_В_МС { return есть; } }
        let есть = ос.папки_барса().iter().any(|д| ос.папка_есть(д));
        self.папки = Some((сейчас, есть));
        есть
    }
}

fn смысл_состояния(с: Состояние) -> &'static str {
    match с {
        Состояние::Свеж => "отметка БАРСа свежа — всё по ней",
        Состояние::Замолк => "отметка БАРСа старше 15 с: его процессы по последней картине неприкасаемы, ни о чём не прошу",
        Состояние::Нет => "отметки БАРСа нет дольше 2 мин: неприкасаемы только процессы из его папок",
        Состояние::Удалён => "нет ни папок БАРСа, ни его процессов: работаю целиком сам, БАРСу не пишу",
    }
}

/// Чистая (видно в тесте): что в отметке — для строки «вижу протокол vN, нет полей …» (раз на запуск БАРСа).
pub fn протокол_словами(текст: &str) -> Value {
    let v: Value = serde_json::from_str(текст.trim_start_matches('\u{feff}')).unwrap_or_default();
    let есть = |к: &str| v.get(к).is_some();
    let протокол = v.get("proto").and_then(Value::as_u64).unwrap_or(0);
    let нет: Vec<&str> = ПОЛЯ_V0.iter().chain(ПОЛЯ_V0_ПЛЮС.iter()).copied().filter(|к| !есть(к)).collect();
    let лишние: Vec<String> = v.as_object().map(|о| о.keys().filter(|к| !ПОЛЯ_V0.contains(&к.as_str())
        && !ПОЛЯ_V0_ПЛЮС.contains(&к.as_str())).cloned().collect()).unwrap_or_default();
    json!({ "протокол": протокол, "знаю": ЗНАЮ_ПРОТОКОЛ, "нет_полей": нет, "новые_поля": лишние,
        "смысл": if протокол as u32 > ЗНАЮ_ПРОТОКОЛ { "протокол БАРСа новее — читаю знакомое" }
            else if нет.iter().any(|к| ПОЛЯ_V0_ПЛЮС.contains(к)) { "БАРС не пишет mind_pid и word: его слово — по режиму ПЕЧАТАЕТ, разум — по пути" }
            else { "договор сходится" } })
}

