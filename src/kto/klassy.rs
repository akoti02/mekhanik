/// Путь под папкой Windows (системные файлы подписаны каталогом и живут там).
pub fn путь_windows(путь: &str) -> bool {
    let п = путь.to_lowercase().replace('/', "\\");
    let корень = std::env::var("SystemRoot").map(|с| с.to_lowercase()).unwrap_or_else(|_| "c:\\windows".into());
    п.starts_with(&format!("{корень}\\")) || п.starts_with("c:\\windows\\")
        || п.contains("\\windows defender\\") || п.contains("\\microsoft\\windows defender\\")
}

/// Род по библиотекам — сильные признаки (у кого CUDA с математикой, OptiX, античит).
fn род_по_библиотекам(п: &Признаки, спр: &Справочник) -> Option<(Род, f32, &'static str)> {
    let б = п.библиотеки;
    let питон = б & биб::PYTHON != 0 || спр.обёртка(&п.имя) && п.имя.to_lowercase().starts_with("python");
    if б & биб::TORCH_CUDA != 0 || (б & биб::CUDA_МАТ != 0 && питон) {
        return Some((Род::Обучение, 0.8, "библиотеки: CUDA для обучения"));
    }
    if б & биб::АНТИЧИТ != 0 { return Some((Род::Игра, 0.8, "библиотеки: античит игры")); }
    if б & биб::OPTIX != 0 { return Some((Род::Рендер3д, 0.75, "библиотеки: OptiX")); }
    if б & биб::МОДЕЛИ_ГПУ != 0 { return Some((Род::Расчёт, 0.7, "библиотеки: счёт моделей на видеокарте")); }
    if б & биб::CUDA_МАТ != 0 { return Some((Род::Расчёт, 0.65, "библиотеки: математика CUDA")); }
    None
}

/// Род по поведению — когда ни справочник, ни библиотеки не сказали.
fn род_по_поведению(п: &Признаки) -> Option<(Род, f32, &'static str)> {
    let б = п.библиотеки;
    let трёхмерное = б & (биб::OPENGL_NV | биб::OPENGL_INTEL | биб::VULKAN | биб::D3D12) != 0;
    if п.окно && п.весь_экран && п.впереди && (п.гпу >= 10.0 || п.видео_мб >= ТЯЖ_ВИДЕО_МБ) && п.декодер < 0.5
        && !п.заголовок_видео {
        return Some((Род::Игра, 0.6, "поведение: на весь экран и видеокарта занята"));
    }
    if б & биб::CUDA != 0 && п.видео_нв_мб >= НВ_ДЕРЖИТ_МБ {
        return Some((Род::Расчёт, 0.6, "поведение: CUDA и видеопамять NVIDIA"));
    }
    if п.кодер >= 3.0 || (б & биб::NVENC != 0 && п.ядер >= ТЯЖ_ЯДЕР && !п.окно) {
        return Some((Род::ВидеоМонтаж, 0.55, "поведение: кодер видео"));
    }
    if трёхмерное && п.окно && (п.гпу >= 10.0 || п.видео_мб >= ТЯЖ_ВИДЕО_МБ) && п.декодер < 0.5 {
        return Some((Род::Рендер3д, 0.5, "поведение: 3D в окне и видеокарта занята"));
    }
    if п.ядер >= 4.0 && !п.окно { return Some((Род::Расчёт, 0.45, "поведение: 4 ядра и больше без окна")); }
    None
}

/// Чистая (видно в тесте): решить, чей процесс и какого рода. Порядок: сам → система → БАРС → род (справочник,
/// библиотеки, поведение, наследство) → просмотр → чей (впереди и звук → он; сессия, окно разработки → его работа;
/// хозяин из справочника; род) → тяжесть по поведению (просмотр — никогда).
pub fn решить(п: &Признаки, спр: &Справочник) -> Решение {
    let mut почему: Vec<String> = Vec::new();
    let зап = п.запись.and_then(|(н, у)| спр.записи.get(н).map(|з| (з, у)));
    // 🟥 14.11 (защиты): защитный класс программы берём из справочника — он держится поверх «чьего» порядка.
    // 🟥 14.11 (живая проба): своего класса нет — класс ближайшего предка (помощник WebView2 мессенджера — как он сам)
    let защита = зап.and_then(|(з, _)| з.защита).or(п.защита_предка);
    let тяжёлое_сейчас = п.ядер >= ТЯЖ_ЯДЕР || п.личная_мб >= ТЯЖ_ПАМЯТЬ_МБ || п.видео_мб >= ТЯЖ_ВИДЕО_МБ || п.гпу >= ТЯЖ_ГПУ;
    let по_поведению_тяжёлое = тяжёлое_сейчас || п.тяжёлое_недавно;
    let пусто = |чей, род, у, почему| Решение { чей, род, уверенность: у, уверенность_рода: у, тяжёлое: false,
        нужно: Нужда::default(), морозить_можно: false, неприкасаемый: true, часть_барса: None, защита: None,
        дерево_его: false, почему };

    if п.сам { return пусто(Чей::Сам, Род::Утилита, 1.0, vec!["сам «Механик» или его ребёнок".into()]); }
    let файл = п.имя.to_lowercase();
    let под_windows = п.путь.as_deref().is_none_or(путь_windows);
    // системное по имени — только из папки Windows (тёзка из «Загрузок» системой не станет); запись справочника
    // (обслуживание Windows, ВМ) — сильнее имени
    let запись_есть = зап.is_some_and(|(з, _)| з.род != Род::Неизвестно || з.чей.is_some());
    if п.pid <= 4 || (спр.системный(&файл) && под_windows && !запись_есть) {
        let слово = if файл.ends_with(".scr") { "заставка Windows — его нет за ПК" } else { "системный процесс Windows" };
        return пусто(Чей::Система, Род::Неизвестно, 0.95, vec![слово.into()]);
    }

    // ── род ──
    let mut род = Род::Неизвестно;
    let mut у_род: f32 = 0.0;
    let mut свой_род = false;
    let библ = род_по_библиотекам(п, спр);
    let из_записи = зап.filter(|(з, _)| з.род != Род::Неизвестно);
    match (библ, из_записи) {
        (Some((рб, уб, сл)), Some((з, уз))) => {
            // библиотеки сильнее только слабой записи (одно имя файла): python с torch_cuda — обучение, Blender с
            // OptiX — всё равно Blender
            if уб > уз { род = рб; у_род = уб; почему.push(сл.into()); }
            else { род = з.род; у_род = уз; почему.push(format!("справочник: {}", з.подпись)); }
            свой_род = true;
        }
        (Some((рб, уб, сл)), None) => { род = рб; у_род = уб; почему.push(сл.into()); свой_род = true; }
        (None, Some((з, уз))) => { род = з.род; у_род = уз; почему.push(format!("справочник: {}", з.подпись)); свой_род = true; }
        (None, None) => {}
    }
    let обёртка = спр.обёртка(&файл) && !свой_род;
    if !свой_род {
        if let Some((рп, уп, сл)) = род_по_поведению(п) { род = рп; у_род = уп; почему.push(сл.into()); свой_род = true; }
    }
    let mut унаследовано = false;
    if !свой_род {
        if let Some((_, рн, ун)) = п.наследство {
            род = рн; у_род = ун * 0.9; унаследовано = true;
            почему.push(if обёртка { "обёртка: род того, кто запустил".into() } else { "помощник: род программы-родителя".into() });
        }
    }
    if род == Род::Неизвестно && (п.сессия || п.окно_помощника) {
        род = Род::Claude;
        у_род = 0.9;
    }
    // ── просмотр: видео у окна впереди, на весь экран или со звуком — не тяжёлое ──
    let плеер = род == Род::Просмотр;
    if род == Род::Браузер || плеер || (п.окно && род == Род::Неизвестно) {
        let видео = п.декодер >= 0.5 || п.заголовок_видео || плеер;
        let смотрит = п.впереди || п.весь_экран || п.звук;
        if видео && смотрит {
            if !плеер { у_род = у_род.max(0.7); }
            род = Род::Просмотр;
            почему.push(format!("смотрит видео ({})", [(п.декодер >= 0.5, "декодер видео"), (п.заголовок_видео, "сайт видео"),
                (плеер, "видеоплеер"), (п.весь_экран, "на весь экран"), (п.звук, "звук")].iter()
                .filter(|(да, _)| *да).map(|(_, с)| *с).collect::<Vec<_>>().join(", ")));
        }
    }

    // ── чей ──
    let (mut чей, mut у_чей);
    let хозяин_записи = зап.and_then(|(з, _)| з.чей);
    if п.впереди || п.звук || п.микрофон {
        чей = Чей::Он;
        у_чей = 1.0;
        почему.push([(п.впереди, "окно впереди"), (п.звук, "играет звук"), (п.микрофон, "микрофон или камера")].iter()
            .filter(|(да, _)| *да).map(|(_, с)| *с).collect::<Vec<_>>().join(", "));
    } else if let Some(часть) = п.барс {
        чей = Чей::Барс;
        у_чей = 0.95;
        почему.push(format!("БАРС ({}), проверен путём и временем создания", часть.слово()));
    } else if хозяин_записи == Some(Чей::Он) {
        чей = Чей::Он;
        у_чей = 0.8;
        почему.push("его ввод".into());
    } else if п.сессия {
        чей = Чей::ЕгоРабота;
        у_чей = 0.9;
        почему.push("предок — сессия разработки".into());
    } else if п.окно_помощника {
        чей = Чей::ЕгоРабота;
        у_чей = 0.9;
        почему.push("окно его программы разработки".into());
    } else if п.под_разработкой {
        чей = Чей::ЕгоРабота;
        у_чей = 0.9;
        почему.push("запущено из окна разработки или терминала".into());
    } else if let Some(х) = хозяин_записи {
        чей = х;
        у_чей = зап.map(|(_, у)| у).unwrap_or(0.5);
    } else if унаследовано {
        let (чн, _, ун) = п.наследство.unwrap_or((Чей::Фон, Род::Неизвестно, 0.3));
        чей = чн;
        у_чей = ун * 0.9;
    } else if род.работа() && свой_род {
        // работа по справочнику или библиотекам — его, если это его сеанс; по одному поведению — если запустил он
        let по_данным = зап.is_some() || библ.is_some();
        if п.сеанс == 0 && !по_данным {
            чей = Чей::Система;
            у_чей = 0.6;
        } else if по_данным || п.запущен_им || п.окно {
            чей = Чей::ЕгоРабота;
            у_чей = if по_данным { у_род } else { 0.5 };
        } else {
            чей = Чей::Фон;
            у_чей = 0.4;
            почему.push("тяжёлое без окна и не им запущено".into());
        }
    } else if п.сеанс == 0 {
        чей = if род == Род::Утилита || род == Род::Телеметрия { Чей::Фон } else { Чей::Система };
        у_чей = 0.6;
        if чей == Чей::Система { почему.push("служба Windows (сеанс 0)".into()); }
    } else if !свой_род && по_поведению_тяжёлое && (п.запущен_им || п.окно) {
        // 13.11: любое тяжёлое, что запустил он, — его работа, даже без строчки справочника
        чей = Чей::ЕгоРабота;
        у_чей = 0.5;
        почему.push("тяжёлое, запустил он".into());
    } else {
        чей = Чей::Фон;
        у_чей = if свой_род { у_род.max(0.5) } else { 0.3 };
    }
    // запущено из окна разработки, но сама программа — фон (обновлялка из окна) — фон по справочнику
    if чей == Чей::ЕгоРабота && хозяин_записи == Some(Чей::Фон) && !п.сессия {
        чей = Чей::Фон;
        у_чей = 0.6;
    }
    if у_род == 0.0 { у_род = 0.3; }

    // ── тяжесть по поведению ──
    let тяжёлое = род != Род::Просмотр && по_поведению_тяжёлое;
    if род == Род::Просмотр && по_поведению_тяжёлое { почему.push("просмотр — не тяжёлое".into()); }
    let б = п.библиотеки;
    let нужно = if тяжёлое {
        Нужда {
            nvidia: п.видео_нв_мб >= НВ_ДЕРЖИТ_МБ || п.гпу_нв >= 10.0
                || (б & (биб::CUDA | биб::TORCH_CUDA | биб::OPTIX | биб::МОДЕЛИ_ГПУ) != 0 && п.видео_нв_мб > 0),
            видеопамять: п.видео_мб >= ТЯЖ_ВИДЕО_МБ,
            озу: п.личная_мб >= ТЯЖ_ПАМЯТЬ_МБ,
            процессор: п.ядер >= ТЯЖ_ЯДЕР,
        }
    } else { Нужда::default() };
    let морозить_можно = зап.is_some_and(|(з, _)| з.морозить) && чей == Чей::ЕгоРабота && !п.впереди;
    let неприкасаемый = matches!(чей, Чей::Система | Чей::Сам | Чей::Он)
        || matches!(п.барс, Some(ЧастьБарса::Судья | ЧастьБарса::Окно | ЧастьБарса::Голова));
    if п.библиотеки != 0 && !почему.iter().any(|с| с.starts_with("библиотеки")) {
        let сл = биб::слова(п.библиотеки);
        if !сл.is_empty() { почему.push(format!("библиотеки: {}", сл.join(", "))); }
    }
    // 🟥 14.11: дерево его приложения — для распорядителя «его окно» (части БАРСа держат свою защиту)
    let дерево_его = п.дерево_его && п.барс.is_none() && чей != Чей::Он;
    if дерево_его { почему.push("дерево его окна (впереди, звук или микрофон у его приложения)".into()); }
    Решение { чей, род, уверенность: у_чей.clamp(0.0, 1.0), уверенность_рода: у_род.clamp(0.0, 1.0), тяжёлое, нужно,
        морозить_можно, неприкасаемый, часть_барса: п.барс, защита, дерево_его, почему }
}

// ───────────────────────────── подпись словами ─────────────────────────────

/// Число по-русски: «6,1».
pub fn число(x: f64, знаков: usize) -> String { format!("{x:.знаков$}").replace('.', ",") }

/// Объём словами: «6,1 ГБ» или «740 МБ».
pub fn объём(мб: u64) -> String {
    if мб >= 1024 { format!("{} ГБ", число(мб as f64 / 1024.0, 1)) } else { format!("{мб} МБ") }
}

/// «1 ядро», «3 ядра», «5 ядер», «1,5 ядра».
pub fn ядра(x: f64) -> String {
    let целое = (x - x.round()).abs() < 0.05;
    if !целое { return format!("{} ядра", число(x, 1)); }
    let н = x.round() as u64;
    let слово = match (н % 10, н % 100) { (1, к) if к != 11 => "ядро", (2..=4, к) if !(12..=14).contains(&к) => "ядра", _ => "ядер" };
    format!("{н} {слово}")
}

/// Имя программы для людей: ProductName без значков, а у системных файлов — описание; нет — имя файла.
pub fn имя_программы(имя_файла: &str, продукт: Option<&str>, описание: Option<&str>) -> String {
    let чистить = |с: &str| с.replace(['®', '™'], "").replace("(R)", "").replace("(TM)", "")
        .split_whitespace().collect::<Vec<_>>().join(" ");
    if let Some(п) = продукт.map(чистить).filter(|п| !п.is_empty() && !п.to_lowercase().contains("operating system")) {
        return п;
    }
    if let Some(о) = описание.map(чистить).filter(|о| !о.is_empty()) { return о; }
    имя_файла.rsplit_once('.').map(|(и, р)| if р.eq_ignore_ascii_case("exe") { и } else { имя_файла })
        .unwrap_or(имя_файла).to_string()
}

/// Чистая (видно в тесте): подпись словами — «Fusion 360 — САПР, NVIDIA, 6,1 ГБ видеопамяти». `метка` — подпись из
/// справочника: имя собственное («Fusion 360») — вместо имени программы, описание («компилятор Rust») — вместо рода,
/// с « — » («БАРС — разум») — целиком. `роль` — уточнение рода по делу («окно»).
pub fn подпись(р: &Решение, п: &Признаки, метка: Option<&str>, роль: Option<&str>) -> String {
    let своё = имя_программы(&п.имя, п.продукт.as_deref(), п.описание.as_deref());
    let род_слово = |р: &Решение| роль.map(str::to_string).unwrap_or_else(|| р.род.слово().to_string());
    let (имя, что) = match метка.filter(|м| !м.is_empty()) {
        _ if р.род == Род::Просмотр => (метка.filter(|м| м.chars().next().is_some_and(char::is_uppercase) && !м.contains(" — "))
            .map(str::to_string).unwrap_or(своё), Some("просмотр видео".to_string())),
        Some(м) if м.contains(" — ") => (м.to_string(), None),
        Some(м) if м.chars().next().is_some_and(char::is_uppercase) => (м.to_string(), Some(род_слово(р))),
        Some(м) => (своё, Some(роль.map(str::to_string).unwrap_or_else(|| м.to_string()))),
        None => (своё, Some(род_слово(р))),
    };
    let mut части: Vec<String> = Vec::new();
    if let Some(ч) = что { части.push(ч); }
    if р.род == Род::Просмотр {
        части.push("не тяжёлое".into());
    } else {
        if р.нужно.nvidia || п.видео_нв_мб >= НВ_ДЕРЖИТ_МБ { части.push("NVIDIA".into()); }
        if п.видео_мб >= НВ_ДЕРЖИТ_МБ { части.push(format!("{} видеопамяти", объём(п.видео_мб))); }
        if п.ядер >= 1.0 { части.push(ядра(п.ядер)); }
        if п.личная_мб >= 1024 { части.push(format!("{} памяти", объём(п.личная_мб))); }
    }
    let хвост = части.join(", ");
    if хвост.is_empty() { имя } else { format!("{имя} — {хвост}") }
}

