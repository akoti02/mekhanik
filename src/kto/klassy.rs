/// Образец со звёздочкой (`*` — любые знаки, `?` — один), без учёта регистра. Чистая (видно в тесте).
pub fn образец(шаблон: &str, текст: &str) -> bool {
    let ш: Vec<char> = шаблон.to_lowercase().chars().collect();
    let т: Vec<char> = текст.to_lowercase().chars().collect();
    образец_строчными(&ш, &т)
}

/// То же для уже строчных (справочник хранит строчными: сверка идёт на каждый новый процесс).
fn образец_строчными(ш: &[char], т: &[char]) -> bool {
    let (mut и, mut j) = (0usize, 0usize);
    let (mut звезда, mut откат) = (None::<usize>, 0usize);
    while j < т.len() {
        if и < ш.len() && (ш[и] == '?' || ш[и] == т[j]) { и += 1; j += 1; }
        else if и < ш.len() && ш[и] == '*' { звезда = Some(и); откат = j; и += 1; }
        else if let Some(з) = звезда { и = з + 1; откат += 1; j = откат; }
        else { return false; }
    }
    while и < ш.len() && ш[и] == '*' { и += 1; }
    и == ш.len()
}

#[derive(Clone, Debug, Default)]
struct Образцы(Vec<Vec<char>>);

impl Образцы {
    fn из(v: Option<&Value>) -> Образцы {
        Образцы(v.and_then(Value::as_array).into_iter().flatten().filter_map(Value::as_str)
            .map(|с| с.to_lowercase().replace('/', "\\").chars().collect()).collect())
    }
    fn пусто(&self) -> bool { self.0.is_empty() }
    fn любой(&self, текст_строчными: &str) -> bool {
        if self.0.is_empty() { return false; }
        let т: Vec<char> = текст_строчными.chars().collect();
        self.0.iter().any(|ш| образец_строчными(ш, &т))
    }
}

