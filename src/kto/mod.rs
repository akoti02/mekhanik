//! «Кто есть кто» — модуль «Механика», который ПОНИМАЕТ любую тяжёлую программу офлайн и без моделей ИИ (его слово
//! 13.11: предвосхищать и понимать, что это, — про ЛЮБЫЕ тяжёлые процессы, а не только сборки и Claude).
//!
//! Что внутри:
//! - `pasport` — личность процесса (номер + время создания + путь), паспорт файла офлайн (версия, издатель по подписи,
//!   библиотеки видеокарты), родословная с проверкой времени, сессии разработки, кэш по файлу;
//! - `klassy` — классы «чей» (он сам → его работа → БАРС → фон → система) и роды (сборка, САПР, рендер, расчёт,
//!   видеомонтаж, игра, ВМ, браузер, просмотр, обучение, сессия разработки, утилита, телеметрия); справочник — данными;
//!   тяжесть — по поведению; просмотр видео — НЕ тяжёлое; подпись словами;
//! - `profili` — профиль каждой программы по опыту (пики ОЗУ/видеопамяти/процессора, время до пика, ритм) с забыванием;
//! - `win` — только чтение Windows: ресурс версии, подпись, библиотеки, строка запуска, окно, видеопамять по процессам,
//!   имена видеокарт по LUID.
//!
//! # Как пользоваться (для свода)
//! `Картина` держит всё знание «кто есть кто». Свод кормит её снимком раз в такт (250 мс / 2 с):
//! ```ignore
//! let mut картина = Картина::новая();                 // при старте
//! картина.обновить(снимок);                           // каждый замер; снимок — опознание + поведение + внимание
//! if let Some(к) = картина.карточка(pid) { ... }      // решение и подпись по номеру процесса
//! for к in картина.карточки() { ... }                 // перебрать всё
//! ```
//! `Снимок` — то, что считают соседние пакеты: `otladka` (поведение: ядра, память, видеокарта), `vnimanie` (окно
//! впереди, звук, микрофон), `svyaz` (какие процессы — БАРС). `Картина` сама добирает офлайн-паспорт (кэш по файлу),
//! видеопамять по процессам и профили. Цена такта — доли процента ядра: дорогое (паспорт) делается один раз на файл.
//!
//! Лечение (`lechenie`) берёт из карточки `решение.чей`, `решение.тяжёлое`, `решение.нужно`, `морозить_можно`,
//! `неприкасаемый`; связь с БАРСом (`svyaz`) — `подпись` и «его работа занята» из перебора карточек.

#![allow(dead_code)]

pub mod klassy;
pub mod pasport;
pub mod profili;
pub mod win;

pub use klassy::{Защита, Решение, Род, ЧастьБарса, Чей};
pub use pasport::Личность;

use std::collections::{HashMap, HashSet};

/// Что свод знает о процессе на этот замер. Личность и путь — опознание; поведение считает `otladka`; внимание —
/// `vnimanie`; `барс` — `svyaz`. Чего нет (0/None) — считается неизвестным, не мешает.
#[derive(Clone, Debug, Default)]
pub struct ВходПроцесса {
    pub pid: u32,
    pub родитель: u32,
    /// Время создания (FILETIME); 0 — неизвестно (тогда родословная не отсекает по времени).
    pub создан: u64,
    pub сеанс: u32,
    pub имя: String,
    pub путь: Option<String>,
    /// Размер и время файла — для ключа кэша паспорта (0 — ключ только по пути).
    pub размер_файла: u64,
    pub время_файла: u64,

    // поведение за окно (otladka)
    pub ядер: f64,
    pub личная_мб: u64,
    /// Самый занятый движок счёта/3D любой видеокарты, %.
    pub гпу: f64,
    pub гпу_нв: f64,
    pub декодер: f64,
    pub кодер: f64,
    pub тяжёлое_недавно: bool,

    // внимание (vnimanie)
    pub окно: bool,
    pub впереди: bool,
    pub весь_экран: bool,
    pub звук: bool,
    pub микрофон: bool,

    // БАРС (svyaz)
    pub барс: Option<ЧастьБарса>,
    pub сам: bool,
}

/// Снимок машины на один замер.
#[derive(Clone, Debug, Default)]
pub struct Снимок {
    /// Местное время замера, мс (для профилей и забывания).
    pub когда_мс: u64,
    pub процессы: Vec<ВходПроцесса>,
}

/// Карточка процесса — ответ «Механику»: кто это, что делает, чем грузит, можно ли трогать.
#[derive(Clone, Debug)]
pub struct Карточка {
    pub личность: Личность,
    pub имя: String,
    pub решение: Решение,
    /// Словами: «Fusion 360 — САПР, NVIDIA, 6,1 ГБ видеопамяти».
    pub подпись: String,
    /// Выделенная видеопамять этого процесса, МБ.
    pub видео_мб: u64,
    pub видео_нв_мб: u64,
    /// Ключ профиля (стабилен при обновлениях программы).
    pub ключ_профиля: String,
    /// Ожидаемый пик по опыту (P95), МБ ОЗУ — для предвидения; `None` — опыта мало.
    pub ожидаемый_озу_мб: Option<u64>,
    pub ожидаемая_видеопамять_мб: Option<u64>,
}

struct ЖивойЗапуск {
    ключ: String,
    подпись: String,
    начало_мс: u64,
    последний_мс: u64,
    пик_озу: u64,
    время_пика_озу: u64,
    пик_видео: u64,
    пик_проц: f64,
    час: Option<u8>,
    видно_в_такт: bool,
}

/// 🟥 14.11 (пакет «цена»): стойкая («паспортная») часть карточки — то, что не меняется за жизнь процесса: признаки по
/// паспорту и справочнику, библиотеки, сессия/под разработкой/запущен им, родословная и ключ профиля. Дорогое (паспорт,
/// строка запуска, справочник, родословная) считаем раз на личность и не чаще раза в `ПОЛНОЕ_КАЖДЫЕ_МС`; лёгкое
/// (поведение, внимание, видеопамять, решение, подпись) — каждое окно поверх базы.
struct База {
    признаки: klassy::Признаки,
    предки: Vec<u32>,
    ключ_профиля: String,
    /// 🟥 14.11: свои флаги для пересборки только новым (окно разработки по справочнику; агент сессии разработки).
    разработка: bool,
    агент: bool,
}

/// 🟥 14.11 (пакет «цена»): полную («паспортную») часть карточки пересобираем новым процессам и не чаще, чем раз в
/// столько (его слово: «раз в 10–30 с»). Между пересборками топология родословной и классы разработки держатся прежними.
const ПОЛНОЕ_КАЖДЫЕ_МС: u64 = 15_000;

/// Вся осведомлённость «Механика»: паспорта (кэш), профили (опыт), карточки нынешних процессов, имена видеокарт.
pub struct Картина {
    спр: &'static klassy::Справочник,
    паспорта: pasport::КэшПаспортов,
    профили: profili::Профили,
    /// Строки запуска, прочитанные один раз на процесс (личность) — в них бывает личное, не храним их текст наружу.
    строки: HashMap<Личность, Option<String>>,
    /// Видеокарты по LUID (меняются редко — читаем изредка).
    карты: HashMap<String, win::Карта>,
    такты_без_карт: u32,
    живые: HashMap<Личность, ЖивойЗапуск>,
    карточки: HashMap<u32, Карточка>,
    /// Прошлые решения по номеру (для наследства обёрток): (решение, создан).
    прошлые: HashMap<u32, (Чей, Род, f32, u64)>,
    /// 🟥 14.11 (пакет «цена»): стойкая часть карточки по личности (пересобирается новым и раз в N с).
    базы: HashMap<Личность, База>,
    /// Когда (мс) последний раз пересобирали базы целиком.
    базы_когда: u64,
}

impl Default for Картина {
    fn default() -> Self { Картина::новая() }
}

impl Картина {
    pub fn новая() -> Картина {
        Картина {
            спр: klassy::Справочник::встроенный(),
            паспорта: pasport::КэшПаспортов::новый(512),
            профили: profili::путь_профилей().map(profili::Профили::загрузить).unwrap_or_else(profili::Профили::новые),
            строки: HashMap::new(),
            карты: HashMap::new(),
            такты_без_карт: u32::MAX, // прочитать видеокарты при первом такте
            живые: HashMap::new(),
            карточки: HashMap::new(),
            прошлые: HashMap::new(),
            базы: HashMap::new(),
            базы_когда: 0,
        }
    }

    pub fn карточка(&self, pid: u32) -> Option<&Карточка> { self.карточки.get(&pid) }
    pub fn карточки(&self) -> impl Iterator<Item = &Карточка> { self.карточки.values() }
    pub fn профили(&self) -> &profili::Профили { &self.профили }

    /// Обновить картину по снимку. 🟥 14.11 (пакет «цена»): дорогое (паспорт, строка запуска, справочник, родословная,
    /// классы разработки) — только новым процессам и раз в `ПОЛНОЕ_КАЖДЫЕ_МС` (стойкая «база»); лёгкое (поведение,
    /// внимание, видеопамять, решение и подпись) — каждое окно поверх базы.
    pub fn обновить(&mut self, снимок: &Снимок) {
        let сейчас = снимок.когда_мс;
        // видеокарты — изредка
        if self.такты_без_карт >= 600 || self.карты.is_empty() {
            let новые = win::видеокарты();
            if !новые.is_empty() { self.карты = новые; }
            self.такты_без_карт = 0;
        } else {
            self.такты_без_карт += 1;
        }
        let видеопамять = win::видеопамять();
        let все_окна = win::все_окна();

        // индекс для родословной (дёшево — проверку по времени делаем и на лёгком такте)
        let индекс: HashMap<u32, pasport::Узел> = снимок.процессы.iter()
            .map(|п| (п.pid, pasport::Узел { родитель: п.родитель, создан: п.создан })).collect();

        // 🟥 14.11 (пакет «цена»): пересобрать стойкие базы — новым процессам или раз в N с; иначе лёгкий такт по кэшу
        // 🟥 14.11 (живой замер 0.9.4: 4,3 % ядра): любой новый процесс пересобирал базы ВСЕХ (≈46 мс на 420), а сессии
        // Claude и БАРС рождают процессы почти каждое окно — полная пересборка шла почти всегда. Теперь новым — только их
        // базы (родословная старых от новых не зависит: родитель старше ребёнка), полная — раз в `ПОЛНОЕ_КАЖДЫЕ_МС`.
        let есть_новые = снимок.процессы.iter()
            .any(|п| !self.базы.contains_key(&Личность { pid: п.pid, создан: п.создан }));
        if self.базы.is_empty() || сейчас.saturating_sub(self.базы_когда) >= ПОЛНОЕ_КАЖДЫЕ_МС {
            self.построить_базы(снимок, &индекс, сейчас, true);
            self.базы_когда = сейчас;
        } else if есть_новые {
            self.построить_базы(снимок, &индекс, сейчас, false);
        }
        // забыть базы и строки умерших (личность с иным временем создания — уже другой процесс)
        let жива = |л: &Личность| индекс.get(&л.pid).map(|у| у.создан) == Some(л.создан)
            || (л.создан == 0 && индекс.contains_key(&л.pid));
        self.базы.retain(|л, _| жива(л));
        self.строки.retain(|л, _| жива(л));

        let mut новые_карточки: HashMap<u32, Карточка> = HashMap::with_capacity(снимок.процессы.len());
        let mut новые_прошлые: HashMap<u32, (Чей, Род, f32, u64)> = HashMap::new();
        let час = текущий_час();

        // 🟥 14.11 (живая проба перед включением распорядителя): дерево его приложения и защита по дереву — в этом же
        // такте (наследство решений опаздывает на такт на каждый уровень). Приложение — дерево от верхнего предка ниже
        // стоп-корня; окно впереди, звук или микрофон у ЛЮБОГО его процесса — всё приложение его (вкладки браузера —
        // дети главного процесса, у которого окно; звук браузера — в отдельной службе). Части БАРСа — своей защитой.
        let имена: HashMap<u32, &str> = снимок.процессы.iter().map(|п| (п.pid, п.имя.as_str())).collect();
        let спр = self.спр; // &'static — замыкание не держит self (ниже self.живые берётся на запись)
        let стоп = |pid: u32| имена.get(&pid).is_some_and(|и| спр.стоп_корень(и));
        let mut корни: HashMap<u32, u32> = HashMap::with_capacity(снимок.процессы.len());
        let mut свои_защиты: HashMap<u32, Защита> = HashMap::new();
        let mut его_корни: HashSet<u32> = HashSet::new();
        for п in &снимок.процессы {
            let Some(база) = self.базы.get(&Личность { pid: п.pid, создан: п.создан }) else { continue };
            let корень = pasport::корень_приложения(п.pid, &база.предки, стоп);
            корни.insert(п.pid, корень);
            if let Some(з) = база.признаки.запись.and_then(|(н, _)| спр.записи.get(н)).and_then(|з| з.защита) {
                свои_защиты.insert(п.pid, з);
            }
            let барс = п.барс.is_some() || база.признаки.барс.is_some();
            if !барс && (п.впереди || п.звук || п.микрофон) { его_корни.insert(корень); }
        }

        for п in &снимок.процессы {
            let личность = Личность { pid: п.pid, создан: п.создан };
            // 🟥 14.11 (пакет «цена»): стойкая часть — из кэша баз (её пересобирают новым и раз в N с); дорогого тут нет
            let Some(база) = self.базы.get(&личность) else { continue };
            let mut пр = база.признаки.clone();
            // 🟥 14.11: проверенный список БАРСа от сторожа (номер, путь и время создания по отметке БАРСа, с детьми) —
            // поверх справочника; «прочее» не стирает часть из справочника (судья, движок)
            if let Some(ч) = п.барс {
                пр.барс = Some(match (ч, пр.барс) { (ЧастьБарса::Прочее, Some(своя)) => своя, (ч, _) => ч });
            }
            пр.дерево_его = корни.get(&п.pid).is_some_and(|к| его_корни.contains(к));
            пр.защита_предка = база.предки.iter().take_while(|pid| !стоп(**pid))
                .find_map(|pid| свои_защиты.get(pid).copied());

            // наследство — решение ближайшего предка в прошлом такте (по родословной из базы; каждое окно)
            let наследство = база.предки.iter().find_map(|pid| self.прошлые.get(pid)
                .filter(|(_, _, _, создан)| индекс.get(pid).map(|у| у.создан) == Some(*создан))
                .map(|(ч, р, у, _)| (*ч, *р, *у)));

            // видеопамять процесса
            let видео_байт = видеопамять.всего.get(&п.pid).copied().unwrap_or(0);
            let нв_байт: u64 = видеопамять.по_картам.get(&п.pid).map(|карты| карты.iter()
                .filter(|(люид, _)| self.карты.get(*люид).map(|к| к.изготовитель == win::Изготовитель::NVIDIA).unwrap_or(false))
                .map(|(_, б)| *б).sum()).unwrap_or(0);
            let видео_мб = видео_байт >> 20;
            let видео_нв_мб = нв_байт >> 20;

            // заголовок окна → только «видео ли это» (сам заголовок не храним)
            let (окно_есть, заголовок_видео) = match все_окна.get(&п.pid) {
                Some((есть, Some(заг))) => (*есть, self.спр.видео_в_заголовке(заг)),
                Some((есть, None)) => (*есть, false),
                None => (false, false),
            };

            // поведение и внимание — из снимка (стойкое уже в базе)
            пр.наследство = наследство;
            пр.ядер = п.ядер;
            пр.личная_мб = п.личная_мб;
            пр.видео_мб = видео_мб;
            пр.видео_нв_мб = видео_нв_мб;
            пр.гпу = п.гпу;
            пр.гпу_нв = п.гпу_нв;
            пр.декодер = п.декодер;
            пр.кодер = п.кодер;
            пр.тяжёлое_недавно = п.тяжёлое_недавно;
            пр.окно = п.окно || окно_есть;
            пр.впереди = п.впереди;
            пр.весь_экран = п.весь_экран;
            пр.заголовок_видео = заголовок_видео;
            пр.звук = п.звук;
            пр.микрофон = п.микрофон;

            let решение = klassy::решить(&пр, self.спр);
            let метка = пр.запись.and_then(|(н, _)| self.спр.записи.get(н)).map(|з| з.подпись.clone()).unwrap_or_default();
            let подпись = klassy::подпись(&решение, &пр, (!метка.is_empty()).then_some(метка.as_str()), None);
            let ключ_профиля = база.ключ_профиля.clone();

            // профиль по опыту — для предвидения
            let профиль = self.профили.профиль(&ключ_профиля);
            let ожидаемый_озу_мб = профиль.and_then(|пр| пр.пик_озу_мб(сейчас));
            let ожидаемая_видеопамять_мб = профиль.and_then(|пр| пр.пик_видео_мб(сейчас));

            // учёт запуска для профиля (только своё тяжёлое/программы, не система)
            if !matches!(решение.чей, Чей::Система | Чей::Сам) {
                let зап = self.живые.entry(личность).or_insert_with(|| ЖивойЗапуск {
                    ключ: ключ_профиля.clone(), подпись: подпись.clone(), начало_мс: сейчас, последний_мс: сейчас,
                    пик_озу: 0, время_пика_озу: сейчас, пик_видео: 0, пик_проц: 0.0, час, видно_в_такт: true,
                });
                зап.последний_мс = сейчас;
                зап.видно_в_такт = true;
                if п.личная_мб > зап.пик_озу { зап.пик_озу = п.личная_мб; зап.время_пика_озу = сейчас; }
                зап.пик_видео = зап.пик_видео.max(видео_мб);
                зап.пик_проц = зап.пик_проц.max(п.ядер);
            }

            новые_прошлые.insert(п.pid, (решение.чей, решение.род, решение.уверенность, п.создан));
            новые_карточки.insert(п.pid, Карточка {
                личность, имя: п.имя.clone(), решение, подпись, видео_мб, видео_нв_мб, ключ_профиля,
                ожидаемый_озу_мб, ожидаемая_видеопамять_мб,
            });
        }

        // завершить профили исчезнувших запусков
        let ушли: Vec<Личность> = self.живые.iter()
            .filter(|(л, _)| индекс.get(&л.pid).map(|у| у.создан) != Some(л.создан))
            .map(|(л, _)| *л).collect();
        for л in ушли {
            if let Some(з) = self.живые.remove(&л) { self.записать_профиль(&з, сейчас); }
        }

        self.карточки = новые_карточки;
        self.прошлые = новые_прошлые;
    }

    /// 🟥 14.11 (пакет «цена»): пересобрать стойкие базы по снимку — паспорт (кэш по файлу), строка запуска (раз на
    /// личность), справочник, библиотеки, родословная (с проверкой времени), классы разработки и агенты сессий, ключ
    /// профиля. `все` — полная пересборка (раз в `ПОЛНОЕ_КАЖДЫЕ_МС`); иначе — только новым личностям (у старых всё
    /// стойкое прежнее: их родословная от новых не зависит). Поведение и решение считает уже лёгкий такт поверх.
    fn построить_базы(&mut self, снимок: &Снимок, индекс: &HashMap<u32, pasport::Узел>, сейчас: u64, все: bool) {
        let спр = self.спр;
        // имя по номеру — картой (до 14.11 — линейный поиск на каждого предка: квадрат на 420 процессах)
        let имена: HashMap<u32, &str> = снимок.процессы.iter().map(|п| (п.pid, п.имя.as_str())).collect();
        let имя = |pid: u32| имена.get(&pid).copied().unwrap_or("");
        let строить: Vec<&ВходПроцесса> = снимок.процессы.iter()
            .filter(|п| все || !self.базы.contains_key(&Личность { pid: п.pid, создан: п.создан })).collect();

        // окна разработки и агенты сессий: у старых — их флаги из баз, у строящихся — заново
        let mut dev_pids: HashSet<u32> = HashSet::new();
        let mut агенты: HashSet<u32> = HashSet::new();
        if !все {
            for п in &снимок.процессы {
                if let Some(б) = self.базы.get(&Личность { pid: п.pid, создан: п.создан }) {
                    if б.разработка { dev_pids.insert(п.pid); }
                    if б.агент { агенты.insert(п.pid); }
                }
            }
        }
        for п in &строить {
            let сверка = klassy::Сверка::новая(&п.имя, п.путь.as_deref(), None, None, None);
            if спр.найти(&сверка, &[]).and_then(|(н, _)| спр.записи.get(н)).is_some_and(|з| з.разработка) {
                dev_pids.insert(п.pid);
            }
            // строка запуска (один раз на личность) — только там, где она что-то решает: возможный агент, обёртка
            let личность = Личность { pid: п.pid, создан: п.создан };
            let строка = self.строки.entry(личность).or_insert_with(|| {
                let тёзка_агента = спр.агент_сессии(&п.имя, п.путь.as_deref(), None)
                    || спр.агент_сессии(&п.имя, None, Some(""));
                if тёзка_агента || спр.обёртка(&п.имя) {
                    win::строка_запуска(п.pid)
                } else { None }
            }).clone();
            if спр.агент_сессии(&п.имя, п.путь.as_deref(), строка.as_deref()) {
                агенты.insert(п.pid);
            }
        }

        let mut базы: HashMap<Личность, База> = if все { HashMap::with_capacity(снимок.процессы.len()) }
            else { std::mem::take(&mut self.базы) };
        for п in строить {
            let личность = Личность { pid: п.pid, создан: п.создан };
            // паспорт (кэш по файлу)
            let ключ_файла = match &п.путь {
                Some(путь) if п.размер_файла != 0 || п.время_файла != 0 =>
                    pasport::КлючФайла::новый(путь, п.размер_файла, п.время_файла),
                Some(путь) => pasport::КлючФайла::по_пути(путь),
                None => pasport::КлючФайла::по_пути(&format!("?{}", п.имя)),
            };
            let путь_строка = п.путь.clone();
            let pid = п.pid;
            let паспорт = self.паспорта.получить(ключ_файла, сейчас,
                || pasport::прочитать(путь_строка.as_deref(), pid, спр));

            let строка = self.строки.get(&личность).cloned().flatten();
            let mut пр = pasport::признаки_из_паспорта(п.pid, &п.имя, п.путь.as_deref(), &паспорт, строка.as_deref(), спр);

            // родословная с проверкой времени
            let предки = pasport::предки(п.pid, индекс, |pid| спр.стоп_корень(имя(pid)));
            let сессия = pasport::часть_сессии(п.pid, &предки, &агенты);
            let под_разработкой = предки.iter().any(|pid| dev_pids.contains(pid));
            let родитель_его = индекс.get(&п.pid).map(|у| у.родитель).map(|р|
                спр.запускатель(имя(р)) || dev_pids.contains(&р) || агенты.contains(&р))
                .unwrap_or(false);

            // стойкая часть признаков (без поведения, внимания и наследства — их докладывает лёгкий такт)
            пр.сеанс = п.сеанс;
            пр.сам = п.сам;
            пр.библиотеки = паспорт.библиотеки;
            пр.сессия = сессия;
            пр.под_разработкой = под_разработкой;
            пр.окно_помощника = dev_pids.contains(&п.pid);
            пр.запущен_им = родитель_его;

            let ключ_профиля = pasport::ключ_профиля(&п.имя, &паспорт);
            базы.insert(личность, База { признаки: пр, предки, ключ_профиля,
                разработка: dev_pids.contains(&п.pid), агент: агенты.contains(&п.pid) });
        }
        self.базы = базы;
    }

    fn записать_профиль(&mut self, з: &ЖивойЗапуск, сейчас: u64) {
        // запуск короче 3 с — обвязка (оболочка, grep): опыт не копим
        let длительность = (з.последний_мс.saturating_sub(з.начало_мс)) as f64 / 1000.0;
        if длительность < 3.0 && з.пик_озу < 512 { return; }
        let запуск = profili::Запуск {
            пик_озу_мб: з.пик_озу, пик_видео_мб: з.пик_видео, пик_проц_ядра: з.пик_проц,
            до_пика_с: (з.время_пика_озу.saturating_sub(з.начало_мс)) as f64 / 1000.0,
            длительность_с: длительность, час: з.час, когда_мс: з.последний_мс,
        };
        self.профили.записать(&з.ключ, &з.подпись, &запуск, сейчас);
    }

    /// Сохранить профили на диск (нечасто — например, раз в несколько минут и при остановке).
    pub fn сохранить_профили(&mut self) -> std::io::Result<bool> {
        self.профили.прибрать(текущие_мс());
        self.профили.сохранить()
    }
}


fn текущий_час() -> Option<u8> {
    use chrono::Timelike;
    Some(chrono::Local::now().hour() as u8)
}

fn текущие_мс() -> u64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|д| д.as_millis() as u64).unwrap_or(0)
}

