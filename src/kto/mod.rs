    /// Живой снимок текущих процессов через `okna` (только чтение). Для живой пробы.
    #[cfg(test)]
    fn снять_живьём(пауза_мс: u64) -> Снимок {
        use crate::okna;
        let все = okna::процессы(); // (pid, родитель, имя)
        let mut буф1 = Vec::new();
        let сн1 = okna::снимок(&mut буф1).unwrap_or_default();
        std::thread::sleep(std::time::Duration::from_millis(пауза_мс));
        let mut буф2 = Vec::new();
        let сн2 = okna::снимок(&mut буф2).unwrap_or_default();
        let передний = okna::передний_pid();
        let секунд = (пауза_мс as f64 / 1000.0).max(0.001);

        let процессы = все.iter().map(|&(pid, родитель, ref имя)| {
            let (п1, п2) = (сн1.get(&pid), сн2.get(&pid));
            let ядер = match (п1, п2) {
                (Some(а), Some(б)) => (б.время.saturating_sub(а.время)) as f64 / 1e7 / секунд,
                _ => 0.0,
            };
            let личная_мб = п2.map(|п| п.память >> 20).unwrap_or(0);
            ВходПроцесса {
                pid, родитель,
                создан: okna::создан(pid).unwrap_or(0),
                сеанс: okna::сеанс(pid).unwrap_or(1),
                имя: имя.clone(),
                путь: okna::путь_процесса(pid),
                ядер, личная_мб,
                впереди: передний == Some(pid),
                окно: false,
                ..Default::default()
            }
        }).collect();
        Снимок { когда_мс: текущие_мс(), процессы }
    }
