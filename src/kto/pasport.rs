//! Личность процесса и паспорт программы (офлайн).
//!
//! Личность — (номер, время создания, путь): номер мог достаться другому процессу, поэтому один номер без времени
//! создания ничего не значит (беда, что видели в журнале: «дети» чужих вкладок, «движки» из заставки).
//!
//! Паспорт программы — её данные на этом ПК: ресурс версии (продукт, фирма, описание), издатель по встроенной подписи
//! (офлайн, без проверки отзыва), загруженные библиотеки видеокарты, строка запуска, заголовок окна. Паспорт считается
//! ОДИН раз на файл (по пути, размеру и времени файла) и лежит в местном кэше: разбор тысяч рождений в час иначе
//! стоил бы дорого (его правило «цена — доли процента ядра»).
//!
//! Родословная и сессии разработки — по снимку (номер → родитель, время создания): родитель засчитывается, только если
//! родился не позже ребёнка. Корень дерева «его работы» — агент сессии (узнаётся справочником, не именем-тёзкой).

use super::klassy::{Признаки, Справочник, биб};
use super::win::{self, Версия};
use std::collections::{HashMap, HashSet};

/// Личность процесса — (номер, время создания). Путь — рядом, для паспорта.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Личность {
    pub pid: u32,
    /// Время создания (FILETIME); 0 — неизвестно.
    pub создан: u64,
}

/// Ключ файла для кэша паспорта: путь + размер + время файла. Меняется — паспорт перечитывается (обновление программы).
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct КлючФайла {
    pub путь: String,
    pub размер: u64,
    pub время: u64,
}

impl КлючФайла {
    pub fn новый(путь: &str, размер: u64, время: u64) -> КлючФайла {
        КлючФайла { путь: путь.to_lowercase().replace('/', "\\"), размер, время }
    }
    /// Ключ по одному пути (когда размер и время файла неизвестны): перечитываться будет только при смене пути.
    pub fn по_пути(путь: &str) -> КлючФайла { КлючФайла::новый(путь, 0, 0) }
}

/// Паспорт программы — статические данные о файле (кэшируются по `КлючФайла`).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Паспорт {
    pub версия: Версия,
    /// Издатель по подписи Authenticode (офлайн). `None` — не подписан или подпись не прошла.
    pub издатель: Option<String>,
    /// Биты найденных библиотек (см. `klassy::биб`).
    pub библиотеки: u32,
}

impl Паспорт {
    pub fn сверка(&self, файл: &str, путь: Option<&str>) -> super::klassy::Сверка {
        super::klassy::Сверка::новая(файл, путь, self.версия.продукт.as_deref(), self.издатель.as_deref(),
            self.версия.фирма.as_deref())
    }
}

/// Кэш паспортов по файлам (ограниченного размера; при переполнении выбрасывается давно не читанный).
pub struct КэшПаспортов {
    по_файлам: HashMap<КлючФайла, (Паспорт, u64)>,
    предел: usize,
}

impl КэшПаспортов {
    pub fn новый(предел: usize) -> КэшПаспортов { КэшПаспортов { по_файлам: HashMap::new(), предел: предел.max(16) } }
    pub fn сколько(&self) -> usize { self.по_файлам.len() }

    /// Паспорт файла из кэша или, если нет, прочитанный `читать` и запомненный. `сейчас_мс` — для вытеснения давнего.
    /// Логика кэша чистая (видно в тестах): `читать` можно подменить.
    pub fn получить<F: FnOnce() -> Паспорт>(&mut self, ключ: КлючФайла, сейчас_мс: u64, читать: F) -> Паспорт {
        if let Some((п, когда)) = self.по_файлам.get_mut(&ключ) {
            *когда = сейчас_мс;
            return п.clone();
        }
        let п = читать();
        if self.по_файлам.len() >= self.предел {
            if let Some(старый) = self.по_файлам.iter().min_by_key(|(_, (_, к))| *к).map(|(к, _)| к.clone()) {
                self.по_файлам.remove(&старый);
            }
        }
        self.по_файлам.insert(ключ, (п.clone(), сейчас_мс));
        п
    }
}

/// Прочитать паспорт файла (дорогой разовый вызов): ресурс версии, издатель, библиотеки по загруженным модулям `pid`.
/// Модули берутся по номеру процесса (они живые у ещё работающего процесса), версия и издатель — по файлу.
pub fn прочитать(путь: Option<&str>, pid: u32, спр: &Справочник) -> Паспорт {
    let версия = путь.map(win::версия).unwrap_or_default();
    let издатель = путь.and_then(win::издатель);
    let модули = win::библиотеки(pid);
    let библиотеки = спр.библиотеки(модули.iter().map(String::as_str));
    Паспорт { версия, издатель, библиотеки }
}

// ───────────────────────────── родословная ─────────────────────────────

/// Что нужно о процессе для родословной.
#[derive(Clone, Copy, Debug)]
pub struct Узел {
    pub родитель: u32,
    pub создан: u64,
}

/// Цепочка предков `pid` снизу вверх (не включая сам `pid`), с проверкой времени: родитель засчитывается, только если
/// родился не позже ребёнка (чужой номер-родитель моложе ребёнка — обрыв). `стоп` — на ком не идти дальше (проводник,
/// службы). До 32 колен (защита от кольца переиспользованных номеров). Чистая (видно в тестах).
pub fn предки(pid: u32, индекс: &HashMap<u32, Узел>, стоп: impl Fn(u32) -> bool) -> Vec<u32> {
    let mut путь = Vec::new();
    let mut виделись = HashSet::new();
    виделись.insert(pid);
    let mut текущий = pid;
    for _ in 0..32 {
        let Some(узел) = индекс.get(&текущий) else { break; };
        let родитель = узел.родитель;
        if родитель == 0 || родитель == текущий { break; }
        let Some(род_узел) = индекс.get(&родитель) else { break; };
        // переиспользованный номер: «родитель» моложе ребёнка — не родитель (беда из журнала)
        if узел.создан != 0 && род_узел.создан != 0 && род_узел.создан > узел.создан { break; }
        if !виделись.insert(родитель) { break; }
        путь.push(родитель);
        if стоп(родитель) { break; }
        текущий = родитель;
    }
    путь
}

/// Процесс — часть дерева сессии разработки: он сам агент или среди его проверенных предков есть агент.
/// Чистая (видно в тестах): `агенты` — номера процессов-агентов (их определяет `агент_ли` по справочнику).
pub fn часть_сессии(pid: u32, предки_pid: &[u32], агенты: &HashSet<u32>) -> bool {
    агенты.contains(&pid) || предки_pid.iter().any(|п| агенты.contains(п))
}

/// Ключ профиля — стабильный при обновлениях программы (папка `app-<версия>` меняется, продукт и имя файла — нет):
/// фирма и продукт, иначе имя файла. Чистая (видно в тесте).
pub fn ключ_профиля(файл: &str, п: &Паспорт) -> String {
    match (&п.версия.фирма, &п.версия.продукт) {
        (ф, Some(прод)) => format!("{}|{}", ф.as_deref().unwrap_or("").to_lowercase(), прод.to_lowercase()),
        (Some(ф), None) => format!("{}|{}", ф.to_lowercase(), файл.to_lowercase()),
        (None, None) => файл.to_lowercase(),
    }
}

/// Собрать базовые признаки процесса из паспорта и справочника (без поведения и внимания — их докладывает снимок).
/// `строка` — строка запуска (None, если не читали); используется для условий справочника по `cmd`.
pub fn признаки_из_паспорта(pid: u32, имя: &str, путь: Option<&str>, п: &Паспорт, строка: Option<&str>,
    спр: &Справочник) -> Признаки {
    let сверка = п.сверка(имя, путь);
    let строка_совпала = строка.map(|с| спр.строка_совпала(с)).unwrap_or_default();
    let запись = спр.найти(&сверка, &строка_совпала);
    let барс = запись.and_then(|(н, _)| спр.записи.get(н)).and_then(|з| з.барс);
    Признаки {
        pid,
        имя: имя.to_string(),
        путь: путь.map(str::to_string),
        продукт: п.версия.продукт.clone(),
        описание: п.версия.описание.clone(),
        запись,
        барс,
        библиотеки: п.библиотеки,
        ..Default::default()
    }
}

/// Нужна ли этому процессу дорогая дочитка паспорта (библиотеки ещё не видны, а он уже грузит или прожил): дёшево
/// сначала — паспорт только тяжёлым или долгоживущим (его правило §8.7). Чистая.
pub fn дочитать_библиотеки(п: &Паспорт, тяжёлый: bool, живёт_с: f64) -> bool {
    let уже = п.библиотеки & (биб::CUDA | биб::TORCH_CUDA | биб::OPTIX | биб::OPENGL_NV | биб::VULKAN | биб::D3D12) != 0;
    !уже && (тяжёлый || живёт_с >= 10.0)
}

#[cfg(test)]
mod тесты {
    use super::*;

    fn узлы(список: &[(u32, u32, u64)]) -> HashMap<u32, Узел> {
        список.iter().map(|&(pid, род, создан)| (pid, Узел { родитель: род, создан })).collect()
    }

    #[test]
    fn кэш_читает_один_раз_на_файл() {
        let mut кэш = КэшПаспортов::новый(16);
        let читано = std::cell::Cell::new(0);
        let ключ = КлючФайла::новый(r"C:\p\a.exe", 100, 200);
        let читать = || { читано.set(читано.get() + 1); Паспорт { издатель: Some("ООО".into()), ..Default::default() } };
        let п1 = кэш.получить(ключ.clone(), 1000, читать);
        let п2 = кэш.получить(ключ.clone(), 2000, || { читано.set(читано.get() + 1); Паспорт::default() });
        assert_eq!(читано.get(), 1, "второй раз — из кэша, не читаем");
        assert_eq!(п1, п2);
        assert_eq!(п1.издатель.as_deref(), Some("ООО"));
        // другой размер (обновление программы) — перечитываем
        let _ = кэш.получить(КлючФайла::новый(r"C:\p\a.exe", 999, 200), 3000,
            || { читано.set(читано.get() + 1); Паспорт::default() });
        assert_eq!(читано.get(), 2, "сменился размер — новый паспорт");
    }

    #[test]
    fn кэш_вытесняет_давний() {
        let mut кэш = КэшПаспортов::новый(16);
        for и in 0..20u32 {
            let ключ = КлючФайла::новый(&format!(r"C:\p\{и}.exe"), и as u64, 0);
            кэш.получить(ключ, и as u64, Паспорт::default);
        }
        assert!(кэш.сколько() <= 16, "кэш не растёт без предела: {}", кэш.сколько());
    }

    /// 🟥 Красный на старом коде (родословная по номеру без времени — `storozh::сборка_по`): python 25648 числился
    /// ребёнком номера 11112, а это Vivaldi, созданный ПОЗЖЕ. Теперь «родитель» моложе ребёнка — обрыв.
    #[test]
    fn переиспользованный_номер_не_родитель() {
        // python создан в 100, «родитель» 11112 создан в 200 (позже) — не настоящий родитель
        let и = узлы(&[(25648, 11112, 100), (11112, 500, 200), (500, 0, 50)]);
        assert!(предки(25648, &и, |_| false).is_empty(), "ложный родитель моложе ребёнка — обрыв");
        // настоящая цепочка (родители старше) проходит
        let и2 = узлы(&[(300, 200, 150), (200, 100, 80), (100, 0, 10)]);
        assert_eq!(предки(300, &и2, |_| false), vec![200, 100]);
    }

    #[test]
    fn родословная_стоп_и_кольцо() {
        // стоп на проводнике (100): дальше не идём
        let и = узлы(&[(400, 300, 300), (300, 100, 200), (100, 1, 100)]);
        assert_eq!(предки(400, &и, |pid| pid == 100), vec![300, 100]);
        // кольцо переиспользованных номеров не зацикливает
        let к = узлы(&[(1, 2, 100), (2, 1, 100)]);
        assert!(предки(1, &к, |_| false).len() <= 2);
    }

    #[test]
    fn часть_сессии_по_предку() {
        let агенты: HashSet<u32> = [900u32].into_iter().collect();
        assert!(часть_сессии(123, &[456, 900, 1], &агенты), "предок-агент → часть сессии");
        assert!(часть_сессии(900, &[], &агенты), "сам агент → часть сессии");
        assert!(!часть_сессии(123, &[456, 1], &агенты));
    }

    #[test]
    fn агент_узнаётся_справочником_не_тёзкой() {
        let спр = Справочник::встроенный();
        // окно-тёзка (claude.exe без пути агента и без строки) — НЕ агент
        assert!(!спр.агент_сессии("claude.exe", Some(r"C:\Users\u\AppData\Local\AnthropicClaude\app-5.1\claude.exe"), None));
        // по пути агента
        assert!(спр.агент_сессии("claude.exe", Some(r"C:\Users\u\AppData\Roaming\Claude\claude-code\2.1\h\claude.exe"), None));
        // по строке запуска
        assert!(спр.агент_сессии("claude.exe", None, Some("claude.exe --output-format stream-json --permission-mode x")));
        assert!(!спр.агент_сессии("vivaldi.exe", None, Some("--output-format stream-json")));
    }

    #[test]
    fn ключ_профиля_стабильный() {
        let п = Паспорт { версия: Версия { продукт: Some("Autodesk Fusion 360".into()),
            фирма: Some("Autodesk, Inc.".into()), ..Default::default() }, ..Default::default() };
        // путь с app-<версия> не входит в ключ — обновление программы ключ не меняет
        assert_eq!(ключ_профиля("fusion360.exe", &п), "autodesk, inc.|autodesk fusion 360");
        let пусто = Паспорт::default();
        assert_eq!(ключ_профиля("rustc.exe", &пусто), "rustc.exe");
    }

    #[test]
    fn дочитка_библиотек_только_нужным() {
        let пусто = Паспорт::default();
        assert!(!дочитать_библиотеки(&пусто, false, 2.0), "лёгкий и молодой — не дочитываем");
        assert!(дочитать_библиотеки(&пусто, true, 0.0), "тяжёлому — дочитать");
        assert!(дочитать_библиотеки(&пусто, false, 15.0), "долгожителю — дочитать");
        let с_куда = Паспорт { библиотеки: биб::CUDA, ..Default::default() };
        assert!(!дочитать_библиотеки(&с_куда, true, 99.0), "библиотеки уже известны — не дочитывать");
    }
}
