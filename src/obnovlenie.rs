/// Список имён папок-версий в каталоге (только те, что разбираются как версия).
fn версии_в(каталог: &PathBuf) -> Vec<String> {
    std::fs::read_dir(каталог)
        .into_iter()
        .flatten()
        .filter_map(Result::ok)
        .filter(|з| з.path().is_dir())
        .filter_map(|з| з.file_name().into_string().ok())
        .filter(|и| разобрать_версию(и).is_some())
        .collect()
}

fn прочитать_json(путь: &PathBuf) -> Option<Value> {
    serde_json::from_str(&std::fs::read_to_string(путь).ok()?).ok()
}

fn отвергнутые() -> Vec<String> {
    прочитать_json(&отвергнутые_путь())
        .and_then(|v| v.as_array().map(|а| а.iter().filter_map(|x| x.as_str().map(str::to_string)).collect()))
        .unwrap_or_default()
}

fn пометить_отвергнутой(версия: &str) {
    let mut список = отвергнутые();
    if !список.iter().any(|в| в == версия) {
        список.push(версия.to_string());
    }
    // 🟥 14.11 (аудит): нужно и после перезагрузки — с fsync (внезапные выключения этого ПК оставляли пустые файлы)
    let _ = crate::svyaz::записать_надёжно(&отвергнутые_путь(), &json!(список).to_string());
}

