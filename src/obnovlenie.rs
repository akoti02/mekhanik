/// SHA-256 своими силами (без крейтов — правило репозитория): целостность файла выпуска.
pub fn sha256(данные: &[u8]) -> [u8; 32] {
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
        0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
        0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
        0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
        0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
        0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
        0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
        0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
    ];
    let mut h: [u32; 8] = [
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
    ];
    let длина_бит = (данные.len() as u64).wrapping_mul(8);
    let mut м = данные.to_vec();
    м.push(0x80);
    while м.len() % 64 != 56 {
        м.push(0);
    }
    м.extend_from_slice(&длина_бит.to_be_bytes());
    for кусок in м.chunks(64) {
        let mut w = [0u32; 64];
        for i in 0..16 {
            w[i] = u32::from_be_bytes([кусок[i * 4], кусок[i * 4 + 1], кусок[i * 4 + 2], кусок[i * 4 + 3]]);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
        }
        let (mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh) =
            (h[0], h[1], h[2], h[3], h[4], h[5], h[6], h[7]);
        for i in 0..64 {
            let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
            let ch = (e & f) ^ ((!e) & g);
            let t1 = hh.wrapping_add(s1).wrapping_add(ch).wrapping_add(K[i]).wrapping_add(w[i]);
            let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let t2 = s0.wrapping_add(maj);
            hh = g;
            g = f;
            f = e;
            e = d.wrapping_add(t1);
            d = c;
            c = b;
            b = a;
            a = t1.wrapping_add(t2);
        }
        for (ячейка, знач) in h.iter_mut().zip([a, b, c, d, e, f, g, hh]) {
            *ячейка = ячейка.wrapping_add(знач);
        }
    }
    let mut итог = [0u8; 32];
    for i in 0..8 {
        итог[i * 4..i * 4 + 4].copy_from_slice(&h[i].to_be_bytes());
    }
    итог
}

/// SHA-256 строкой из 64 шестнадцатеричных знаков в нижнем регистре.
pub fn sha256_hex(данные: &[u8]) -> String {
    sha256(данные).iter().map(|б| format!("{б:02x}")).collect()
}

/// Сверить данные файла с содержимым `*.sha256` (первое «слово» — хэш; регистр не важен; формат `хэш *имя` тоже
/// подходит). `false` — не совпало или хэша нет.
pub fn проверить_sha(данные: &[u8], файл_sha: &str) -> bool {
    let Some(ожидаем) = файл_sha.split_whitespace().next() else { return false };
    let ожидаем = ожидаем.trim_start_matches('*').to_ascii_lowercase();
    ожидаем.len() == 64 && ожидаем == sha256_hex(данные)
}

/// Разобрать версию `major.minor.patch` (хвост после `-`, например коммит, отбрасываем). `None` — не версия.
pub fn разобрать_версию(с: &str) -> Option<(u64, u64, u64)> {
    let ядро = с.split(['-', '+']).next().unwrap_or(с);
    let mut ч = ядро.split('.');
    let a = ч.next()?.parse().ok()?;
    let b = ч.next()?.parse().ok()?;
    let c = ч.next()?.parse().ok()?;
    if ч.next().is_some() {
        return None;
    }
    Some((a, b, c))
}

/// `a` строго новее `b`? `None` — хотя бы одна не разбирается.
pub fn новее(a: &str, b: &str) -> Option<bool> {
    Some(разобрать_версию(a)? > разобрать_версию(b)?)
}

/// Выбрать лучший выпуск: самый новый из `кандидаты`, что строго новее `текущая` и не в `отвергнутые`.
/// `None` — брать нечего. Чистая: сверку SHA и наличие файлов делает вызывающий, сюда даёт готовый список версий.
pub fn лучший_выпуск(кандидаты: &[String], текущая: &str, отвергнутые: &[String]) -> Option<String> {
    кандидаты
        .iter()
        .filter(|в| !отвергнутые.iter().any(|о| о == *в))
        .filter(|в| новее(в, текущая) == Some(true))
        .max_by_key(|в| разобрать_версию(в).unwrap_or((0, 0, 0)))
        .cloned()
}

/// Какие версии оставить рядом: текущую и до `ПРЕЖНИХ` самых новых из остальных (для отката). Прочие — удалить.
pub fn хранимые(все: &[String], текущая: &str) -> Vec<String> {
    let mut прочие: Vec<&String> = все.iter().filter(|в| *в != текущая).collect();
    прочие.sort_by_key(|в| разобрать_версию(в).unwrap_or((0, 0, 0)));
    let mut держим: Vec<String> = Vec::new();
    if все.iter().any(|в| в == текущая) {
        держим.push(текущая.to_string());
    }
    for в in прочие.iter().rev().take(ПРЕЖНИХ) {
        держим.push((*в).clone());
    }
    держим
}

/// Версии, которые можно удалить (все, кроме `хранимые`).
pub fn удалить_лишние(все: &[String], текущая: &str) -> Vec<String> {
    let держим = хранимые(все, текущая);
    все.iter().filter(|в| !держим.iter().any(|д| д == *в)).cloned().collect()
}

/// Решение «откатить»: новая версия упала не меньше `ПОРОГ_ОТКАТА` раз за `ОКНО_ОТКАТА_МС`.
pub fn решить_откат(падения_мс: &[u64], сейчас: u64) -> bool {
    падения_мс.iter().filter(|т| сейчас.saturating_sub(**т) <= ОКНО_ОТКАТА_МС).count() >= ПОРОГ_ОТКАТА
}

/// Сдаться (сказать ему): падений за час не меньше `СДАТЬСЯ_ЗА_ЧАС`.
pub fn сдаться(падения_мс: &[u64], сейчас: u64) -> bool {
    падения_мс.iter().filter(|т| сейчас.saturating_sub(**т) <= 3_600_000).count() >= СДАТЬСЯ_ЗА_ЧАС
}

/// Пауза перед перезапуском упавшего Мозга: 1→2 с, 2→10 с, дальше 60 с (как в `samostoyatelnost.md` §3.3 Б2).
pub fn пауза_перезапуска(номер_падения: u32) -> Duration {
    Duration::from_secs(match номер_падения {
        0 | 1 => 2,
        2 => 10,
        _ => 60,
    })
}

/// 🟥 ЧИСТАЯ (видно в тесте): завис ли Мозг — процесс жив, но пульс (`barsu.json`: `pid`, `ms`) не идёт. 🟥 14.11
/// (аудит): время — БЕЗ СНА (QueryUnbiasedInterruptTime), а не стенные часы: после сна ноутбука дольше 1,5 мин пульс
/// «устаревал» на время сна, и здоровый, только проснувшийся Мозг снимался как зависший (и засчитывался падением —
/// вплоть до отката и «сдаюсь»). `наш` — в barsu.json номер нашего Мозга; `с_старта_бодр_мс` — бодрого времени с
/// запуска (в льготе не трогаем); `без_нового_бодр_мс` — бодрого времени с тех пор, как пульс последний раз МЕНЯЛСЯ.
pub fn завис(наш: bool, с_старта_бодр_мс: u64, без_нового_бодр_мс: u64) -> bool {
    if с_старта_бодр_мс < ЛЬГОТА_СТАРТА_МС {
        return false;
    }
    !наш || без_нового_бодр_мс > ПУЛЬС_СТАР_МС
}

