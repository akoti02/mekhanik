static ОБНОВИТЬСЯ: AtomicBool = AtomicBool::new(false);

/// Мозг просили переключиться на новую версию (читает `main` после выхода storozh).
pub fn обновиться_просили() -> bool {
    ОБНОВИТЬСЯ.load(Ordering::Relaxed)
}

/// Поток Мозга: раз в минуту искать свежий выпуск и ставить его. Поставил — просит выход (stop.flag) и помечает
/// «обновиться». Зовётся под смотрителем потоков (`zhizn::поток`).
pub fn сторожить() {
    loop {
        std::thread::sleep(Duration::from_secs(60));
        if crate::svyaz::просят_выйти() {
            return;
        }
        match поставить_свежий() {
            Ok(Some(в)) => {
                crate::svyaz::журнал("механик_обновление_готово", &json!({ "версия": в, "почему": "ставлю и перезапускаюсь" }));
                ОБНОВИТЬСЯ.store(true, Ordering::Relaxed);
                // попросить storozh всё отпустить и выйти — «запуск» поднимет новую версию из tekushchaya.json
                let _ = std::fs::File::create(данные().join("stop.flag"));
                return;
            }
            Ok(None) => {}
            Err(e) => crate::svyaz::журнал("механик_обновление_ошибка", &json!({ "err": e })),
        }
    }
}

/// Найти, проверить и поставить свежий выпуск. `Ok(Some(версия))` — поставлен; `Ok(None)` — брать нечего.
fn поставить_свежий() -> Result<Option<String>, String> {
    let текущая = env!("CARGO_PKG_VERSION");
    let выпуски = папка_выпусков();
    if !выпуски.exists() {
        return Ok(None);
    }
    // кандидаты: версия с целым exe и верным SHA
    let годные: Vec<String> = версии_в(&выпуски)
        .into_iter()
        .filter(|в| выпуск_цел(&выпуски.join(в)))
        .collect();
    let Some(версия) = лучший_выпуск(&годные, текущая, &отвергнутые()) else {
        return Ok(None);
    };
    let откуда = выпуски.join(&версия);
    let куда = папка_версий().join(&версия);
    std::fs::create_dir_all(&куда).map_err(|e| format!("не создать {}: {e}", куда.display()))?;
    let exe_откуда = откуда.join("mekhanik.exe");
    let exe_куда = куда.join("mekhanik.exe");
    std::fs::copy(&exe_откуда, &exe_куда).map_err(|e| format!("не скопировать exe: {e}"))?;
    // сверить ещё раз уже на месте — на случай сбоя копирования
    let данные_exe = std::fs::read(&exe_куда).map_err(|e| format!("не прочесть поставленный exe: {e}"))?;
    let файл_sha = std::fs::read_to_string(откуда.join("mekhanik.exe.sha256")).unwrap_or_default();
    if !проверить_sha(&данные_exe, &файл_sha) {
        let _ = std::fs::remove_dir_all(&куда);
        // 🟥 14.11 (аудит): пометить — иначе та же порченая копия перекладывалась бы раз в минуту без конца
        пометить_отвергнутой(&версия);
        return Err(format!("SHA-256 не совпал после установки {версия} — не ставлю"));
    }
    // 🟥 14.11 (аудит): самопроверка новой версии ДО закрепления (так и задумано, но не звалась): exe цел по SHA, но
    // может не встать на этом ПК — пусть сперва откроет датчики и назовёт версию
    if !самопроверка_прошла(&exe_куда) {
        let _ = std::fs::remove_dir_all(&куда);
        пометить_отвергнутой(&версия);
        return Err(format!("самопроверка {версия} не прошла — не ставлю, остаюсь на {текущая}"));
    }
    записать_указатель(&версия, Some(текущая));
    подчистить_версии(&версия);
    Ok(Some(версия))
}

/// 🟥 14.11 (аудит): запустить поставленный exe с `--proverka` и дождаться (до 20 с): код 0 — датчики открылись, версия
/// названа. Не запустился, упал или молчит — не прошла.
fn самопроверка_прошла(exe: &std::path::Path) -> bool {
    let Ok(mut дитя) = std::process::Command::new(exe).arg("--proverka").spawn() else { return false };
    let начало = std::time::Instant::now();
    loop {
        match дитя.try_wait() {
            Ok(Some(ст)) => return ст.success(),
            Ok(None) if начало.elapsed() < Duration::from_secs(20) => std::thread::sleep(Duration::from_millis(200)),
            _ => {
                let _ = дитя.kill();
                let _ = дитя.wait();
                return false;
            }
        }
    }
}

/// Папка выпуска цела: есть exe, есть `.sha256` и они совпадают.
fn выпуск_цел(папка: &PathBuf) -> bool {
    let Ok(данные_exe) = std::fs::read(папка.join("mekhanik.exe")) else { return false };
    let Ok(файл_sha) = std::fs::read_to_string(папка.join("mekhanik.exe.sha256")) else { return false };
    проверить_sha(&данные_exe, &файл_sha)
}

fn записать_указатель(версия: &str, прежняя: Option<&str>) {
    let mut тело = json!({ "versiya": версия });
    if let Some(п) = прежняя {
        if п != версия {
            тело["prezhnyaya"] = json!(п);
        }
    }
    let _ = std::fs::create_dir_all(программы());
    // 🟥 14.11 (аудит): указатель версии читает каждый вход — с fsync, иначе после внезапного выключения он мог
    // оказаться пустым: запуск брал бы версию пенька, откат терял бы прежнюю
    let _ = crate::svyaz::записать_надёжно(&указатель(), &тело.to_string());
}

/// Удалить версии, которые больше не храним (кроме текущей и двух прежних).
fn подчистить_версии(текущая: &str) {
    let все = версии_в(&папка_версий());
    for лишняя in удалить_лишние(&все, текущая) {
        // прежнюю для отката не трогаем — она в `хранимые`
        let _ = std::fs::remove_dir_all(папка_версий().join(&лишняя));
        crate::svyaz::журнал("механик_версия_убрана", &json!({ "версия": лишняя }));
    }
}

// ───────────────────────────── «запуск»: держит Мозг живым ─────────────────────────────

/// Текущая версия из указателя (или версия самого «запуска», если указателя нет — первый старт).
fn текущая_версия() -> String {
    прочитать_json(&указатель())
        .and_then(|v| v.get("versiya").and_then(Value::as_str).map(str::to_string))
        .unwrap_or_else(|| env!("CARGO_PKG_VERSION").to_string())
}

/// Путь к exe Мозга текущей версии; нет такой папки — свой exe (первый старт до установки версий).
fn exe_мозга(версия: &str) -> PathBuf {
    let по_версии = папка_версий().join(версия).join("mekhanik.exe");
    if по_версии.exists() {
        по_версии
    } else {
        std::env::current_exe().unwrap_or(по_версии)
    }
}

/// Откат на прежнюю версию: плохую пометить «не прижилась», указатель вернуть на прежнюю (если её exe цел).
/// `Some(прежняя)` — откатились; `None` — откатываться не на что.
fn откатить(плохая: &str) -> Option<String> {
    let прежняя = прочитать_json(&указатель())?
        .get("prezhnyaya")
        .and_then(Value::as_str)
        .map(str::to_string)?;
    if !папка_версий().join(&прежняя).join("mekhanik.exe").exists() {
        return None;
    }
    пометить_отвергнутой(плохая);
    записать_указатель(&прежняя, None);
    Some(прежняя)
}

/// «Запуск» (`mekhanik.exe --zapusk`): поднимает Мозг и держит его живым. Возвращает код выхода процесса «запуска».
pub fn запуск() -> i32 {
    let _ = std::fs::create_dir_all(данные());
    crate::svyaz::журнал("механик_запуск_сторож", &json!({ "pid": std::process::id() }));
    let mut падения: Vec<u64> = Vec::new();
    let mut подряд = 0u32;
    loop {
        if crate::svyaz::просят_выйти() {
            crate::svyaz::стоп_снят();
            crate::svyaz::журнал("механик_запуск_вышел", &json!({ "почему": "просили выйти до старта Мозга" }));
            return 0;
        }
        let версия = текущая_версия();
        let exe = exe_мозга(&версия);
        crate::svyaz::журнал("механик_мозг_старт", &json!({ "версия": версия, "exe": exe.display().to_string() }));
        let код = запустить_и_ждать(&exe);
        match код {
            Some(0) => {
                crate::svyaz::журнал("механик_мозг_вышел", &json!({ "почему": "его воля — до следующего входа не поднимаю" }));
                return 0;
            }
            Some(КОД_ОБНОВИТЬСЯ) => {
                crate::svyaz::журнал("механик_переключение", &json!({ "на": текущая_версия() }));
                падения.clear();
                подряд = 0;
            }
            Some(КОД_УЖЕ_РАБОТАЕТ) => {
                crate::svyaz::журнал("механик_мозг_уже_работает", &json!({}));
                return 0;
            }
            прочее => {
                let сейчас = crate::svyaz::сейчас_мс();
                падения.push(сейчас);
                падения.retain(|т| сейчас.saturating_sub(*т) <= 3_600_000);
                подряд += 1;
                crate::svyaz::журнал("механик_мозг_упал", &json!({ "код": прочее, "версия": версия,
                    "падений_за_10_мин": падения.iter().filter(|т| сейчас.saturating_sub(**т) <= ОКНО_ОТКАТА_МС).count() }));
                if решить_откат(&падения, сейчас) {
                    if let Some(прежняя) = откатить(&версия) {
                        crate::svyaz::журнал("механик_откат", &json!({ "с": версия, "на": прежняя, "почему": "3 падения за 10 мин" }));
                        падения.clear();
                        подряд = 0;
                        continue;
                    }
                    crate::svyaz::журнал("механик_откат_нельзя", &json!({ "версия": версия, "почему": "нет целой прежней версии" }));
                }
                if сдаться(&падения, сейчас) {
                    crate::svyaz::журнал("механик_сдаюсь", &json!({ "версия": версия, "почему": "5 падений за час" }));
                    let _ = crate::okna::уведомить("Механик не работает", "Пять падений за час. Нужна твоя рука: запусти «Механик» из «Пуск» или переустанови.");
                    // 🟥 чистый выход (0): задача входа (RestartOnFailure) не должна поднять сломанную версию снова.
                    return КОД_СДАЛСЯ;
                }
                std::thread::sleep(пауза_перезапуска(подряд));
            }
        }
    }
}

/// Пульс Мозга из `barsu.json`: (`pid`, `ms`). `None` — файла ещё нет или полей нет.
fn пульс_мозга() -> Option<(u32, u64)> {
    let v = прочитать_json(&данные().join("barsu.json"))?;
    let pid = v.get("pid").and_then(Value::as_u64)? as u32;
    let мс = v.get("ms").and_then(Value::as_u64)?;
    Some((pid, мс))
}

/// Запустить exe Мозга и держать его, пока жив И отвечает. Вернуть код выхода (`None` — без кода). 🟥 Не блокирующее
/// `status()`, а запуск + опрос: раз в 2 с смотрим, вышел ли процесс, и свеж ли его пульс (`barsu.json`). Жив, но
/// пульс устарел (взаимная блокировка, вечный цикл) — считаем зависанием: снимаем и возвращаем `КОД_ЗАВИС` (ветка
/// падения сделает откат/сдаётся). Пока просят выйти (обновление/его воля) — пульс не сторожим, ждём чистого выхода.
fn запустить_и_ждать(exe: &PathBuf) -> Option<i32> {
    let mut дитя = match std::process::Command::new(exe).spawn() {
        Ok(д) => д,
        Err(e) => {
            crate::svyaz::журнал("механик_мозг_не_запущен", &json!({ "exe": exe.display().to_string(), "err": e.to_string() }));
            // не запустился — считаем падением, но с паузой (пусть «запуск» не крутит впустую)
            std::thread::sleep(Duration::from_secs(5));
            return Some(-1);
        }
    };
    let pid = дитя.id();
    // 🟥 14.11 (аудит): бодрое время (без сна), и пульс — по его СМЕНЕ, а не по стенным часам в нём
    let бодро = || crate::okna::без_сна_мс().unwrap_or(0);
    let старт = бодро();
    let mut пульс_был: Option<u64> = None;
    let mut пульс_бодро = старт;
    loop {
        match дитя.try_wait() {
            Ok(Some(ст)) => return ст.code(),
            Ok(None) => {}
            Err(_) => return дитя.wait().ok().and_then(|ст| ст.code()),
        }
        let сейчас = бодро();
        let пульс = пульс_мозга();
        let наш = пульс.is_some_and(|(п, _)| п == pid);
        if let Some((п, мс)) = пульс {
            if п == pid && пульс_был != Some(мс) { пульс_был = Some(мс); пульс_бодро = сейчас; }
        }
        if !crate::svyaz::просят_выйти()
            && завис(наш, сейчас.saturating_sub(старт), сейчас.saturating_sub(пульс_бодро)) {
            crate::svyaz::журнал("механик_мозг_завис", &json!({ "pid": pid, "версия_exe": exe.display().to_string(),
                "почему": "процесс жив, но пульс barsu.json устарел — снимаю и поднимаю заново" }));
            let _ = дитя.kill();
            let _ = дитя.wait();
            return Some(КОД_ЗАВИС);
        }
        std::thread::sleep(Duration::from_secs(2));
    }
}

