    #[test]
    fn применить_события() {
        let mut с = Состояние::default();
        assert!(!с.замок && с.экран_горит() && с.от_сети.is_none());
        с.применить(&Событие::Замок);
        assert!(с.замок);
        с.применить(&Событие::Отпёрто);
        assert!(!с.замок);
        с.применить(&Событие::Экран(Экран::Погас));
        assert!(!с.экран_горит(), "экран погас — не горит");
        с.применить(&Событие::Экран(Экран::Притушен));
        assert!(с.экран_горит(), "притушен — всё ещё что-то показывает");
        с.применить(&Событие::Питание(Питание::Батарея));
        assert_eq!(с.от_сети, Some(false));
        с.применить(&Событие::Питание(Питание::Сеть));
        assert_eq!(с.от_сети, Some(true));
        с.применить(&Событие::Засыпает);
        assert!(с.спит);
        с.применить(&Событие::Проснулся);
        assert!(!с.спит);
        с.применить(&Событие::ОкноВперёд(123));
        assert_eq!(с.окно_pid, Some(123));
        с.применить(&Событие::Присутствие(Присутствие::Нет));
        assert_eq!(с.присутствие, Присутствие::Нет);
        // вход снимает замок
        с.замок = true;
        с.применить(&Событие::Вошёл);
        assert!(!с.замок);
    }

