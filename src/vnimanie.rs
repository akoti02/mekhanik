pub fn заставка_идёт() -> bool {
    // SPI_GETSCREENSAVERRUNNING = 0x0072
    let mut идёт: i32 = 0;
    unsafe { SystemParametersInfoW(0x0072, 0, &mut идёт as *mut i32 as *mut c_void, 0) };
    идёт != 0
}

