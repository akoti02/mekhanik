#[link(name = "shell32")]
extern "system" {
    fn SHQueryUserNotificationState(состояние: *mut i32) -> i32;
}

/// Чистая (видно в тесте): QUERY_USER_NOTIFICATION_STATE → во весь ли экран. QUNS_BUSY=3 (полноэкранное не-D3D,
/// обычно видео), QUNS_RUNNING_D3D_FULL_SCREEN=4 (игра); QUNS_PRESENTATION_MODE=5 — показ, тоже не мешать.
pub fn во_весь_экран_по(состояние: i32) -> bool {
    matches!(состояние, 3 | 4 | 5)
}

/// Сейчас что-то идёт во весь экран.
pub fn во_весь_экран() -> bool {
    let mut с: i32 = 0;
    unsafe { SHQueryUserNotificationState(&mut с) >= 0 && во_весь_экран_по(с) }
}

