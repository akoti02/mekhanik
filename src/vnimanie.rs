const HKCU: isize = 0x8000_0001u32 as i32 as isize;
const KEY_READ: u32 = 0x2_0019;

/// Чистая (видно в тесте): устройство занято сейчас — Windows ставит `LastUsedTimeStop` = 0, пока оно пишет, и реальное
/// время остановки, когда отпустило.
pub fn занято_по_метке(stop: u64) -> bool {
    stop == 0
}

/// Прочесть QWORD-значение ключа реестра.
fn прочесть_u64(ключ: isize, имя: &str) -> Option<u64> {
    let и = широкая(имя);
    let mut буф = [0u8; 8];
    let mut байт = 8u32;
    let mut тип = 0u32;
    let ст = unsafe { RegQueryValueExW(ключ, и.as_ptr(), std::ptr::null_mut(), &mut тип, буф.as_mut_ptr(), &mut байт) };
    // ERROR_SUCCESS = 0; REG_QWORD = 11
    (ст == 0 && тип == 11 && байт == 8).then(|| u64::from_le_bytes(буф))
}

/// Подключи реестра `путь` (под HKCU): есть ли хоть один с `LastUsedTimeStop` == 0. `вглубь` — зайти в `NonPackaged`
/// (там живут обычные программы, не из магазина) ещё на уровень.
fn занято_под(путь: &str, вглубь: bool) -> bool {
    let п = широкая(путь);
    let mut ключ: isize = 0;
    if unsafe { RegOpenKeyExW(HKCU, п.as_ptr(), 0, KEY_READ, &mut ключ) } != 0 {
        return false;
    }
    let mut занято = false;
    let mut индекс = 0u32;
    loop {
        let mut имя = [0u16; 256];
        let mut длина = имя.len() as u32;
        let ст = unsafe {
            RegEnumKeyExW(ключ, индекс, имя.as_mut_ptr(), &mut длина, std::ptr::null_mut(), std::ptr::null_mut(),
                std::ptr::null_mut(), std::ptr::null_mut())
        };
        if ст != 0 {
            break; // ERROR_NO_MORE_ITEMS = 259
        }
        индекс += 1;
        let имя_с = String::from_utf16_lossy(&имя[..длина as usize]);
        if вглубь && имя_с == "NonPackaged" {
            if занято_под(&format!("{путь}\\NonPackaged"), false) {
                занято = true;
                break;
            }
            continue;
        }
        let под_путь = широкая(&format!("{путь}\\{имя_с}"));
        let mut под: isize = 0;
        if unsafe { RegOpenKeyExW(HKCU, под_путь.as_ptr(), 0, KEY_READ, &mut под) } == 0 {
            let метка = прочесть_u64(под, "LastUsedTimeStop");
            unsafe { RegCloseKey(под) };
            if метка.is_some_and(занято_по_метке) {
                занято = true;
                break;
            }
        }
    }
    unsafe { RegCloseKey(ключ) };
    занято
}

