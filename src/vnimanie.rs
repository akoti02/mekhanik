    /// 🟥 14.11 (пакет «цена»): дорогое внимание (COM-звук, реестр) освежается не каждое окно, а раз в 10 с. Красный
    /// на старом коде: там `снять` звал звук/микрофон/камеру каждое окно — освежения «раз в 10 с» не было вовсе.
    #[test]
    fn дорогое_освежается_раз_в_10с() {
        // первый раз — надо (ещё не опрашивали)
        assert!(освежить_дорогое(None, ДОРОГОЕ_КАЖДЫЕ));
        // только что опросили — не надо
        assert!(!освежить_дорогое(Some(Instant::now()), ДОРОГОЕ_КАЖДЫЕ));
        // прошло больше порога — снова надо
        let давно = Instant::now().checked_sub(Duration::from_secs(11)).unwrap();
        assert!(освежить_дорогое(Some(давно), ДОРОГОЕ_КАЖДЫЕ));
        // ровно на пороге — надо
        assert!(освежить_дорогое(Instant::now().checked_sub(ДОРОГОЕ_КАЖДЫЕ), ДОРОГОЕ_КАЖДЫЕ));
    }

