// ───────────────────────────── кадры DWM (что он реально видит) ─────────────────────────────

/// DWM_TIMING_INFO (dwmapi.h), открытая «общая» часть — ровно 124 байта, упакована по 4 (проверено на этом ПК: именно
/// такой `cbSize` Windows 11 26H2 принимает, hr == 0; больший — отказ). Это сведения обо всём рабочем столе; полей
/// «пропущено/выброшено» в ней нет (они — для отдельного окна, что само правит композицию, и чужому процессу недоступны).
/// Нам нужен один счётчик — `cFramesLate`: сколько кадров показано поздно (рывки, «глюки»), то, что он реально видит.
#[allow(dead_code, non_snake_case)]
#[repr(C, packed(4))]
struct ВремяDwm {
    cbSize: u32,
    rateRefresh_num: u32,
    rateRefresh_den: u32,
    qpcRefreshPeriod: u64,
    rateCompose_num: u32,
    rateCompose_den: u32,
    qpcVBlank: u64,
    cRefresh: u64,
    cDXRefresh: u32,
    qpcCompose: u64,
    cFrame: u64,
    cDXPresent: u32,
    cRefreshFrame: u64,
    cFrameSubmitted: u64,
    cDXPresentSubmitted: u32,
    cFrameConfirmed: u64,
    cDXPresentConfirmed: u32,
    cRefreshConfirmed: u64,
    cDXRefreshConfirmed: u32,
    /// Кадры, показанные поздно (глюки): рывок на экране.
    cFramesLate: u64,
    cFramesOutstanding: u32,
}

#[link(name = "dwmapi")]
extern "system" {
    fn DwmGetCompositionTimingInfo(окно: isize, время: *mut ВремяDwm) -> i32;
}

/// Счётчик рывков рабочего стола (накопленный — разница двух снимков даёт рывки за промежуток).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Кадры {
    /// Кадры, показанные поздно (`cFramesLate`).
    pub поздно: u64,
}

/// Снять счётчик кадров DWM (рабочий стол в целом, без окна). `None` — DWM не ответил.
/// 🟥 Проба 13.11: на этом ПК (Windows 11 26H2) `DwmGetCompositionTimingInfo` из отдельного консольного процесса
/// отвечает отказом (hr 0x88980090) при любом `cbSize` — как и предупреждали отчёты («проверить стендом; поля могут
/// быть нулями — тогда не использовать»). Код верен (структура 124 байта — тот размер, что API проверяет), но счётчик
/// здесь недоступен. Перепроверить из настоящего окна Мозга (роль `--okno`); запасной путь — статистика кадров DXGI
/// (`IDXGIOutput::GetFrameStatistics`) или трасса DxgKrnl («лупа», волна В). `None` «Механик» переносит спокойно.
pub fn кадры() -> Option<Кадры> {
    let mut в: ВремяDwm = unsafe { std::mem::zeroed() };
    в.cbSize = std::mem::size_of::<ВремяDwm>() as u32; // 124
    // NULL hwnd — счётчики всего рабочего стола
    if unsafe { DwmGetCompositionTimingInfo(0, &mut в) } < 0 {
        return None;
    }
    // поле упаковано (невыровненное) — читаем копией, не ссылкой
    let поздно = unsafe { std::ptr::read_unaligned(std::ptr::addr_of!(в.cFramesLate)) };
    Some(Кадры { поздно })
}

/// Чистая (видно в тесте): сколько рывков случилось между двумя снимками (счётчик только растёт; сброс — не минус).
pub fn кадры_разница(пред: Кадры, тек: Кадры) -> Кадры {
    Кадры { поздно: тек.поздно.saturating_sub(пред.поздно) }
}

