fn широкая(с: &str) -> Vec<u16> {
    с.encode_utf16().chain(std::iter::once(0)).collect()
}

// ───────────────────────────── состояние по событиям ─────────────────────────────

/// Что «Механик» знает о ПК и сеансе из событий шины. Меняется мгновенно (`применить`), снимок внимания берёт отсюда
/// замок, экран, питание, сон и кто впереди — без опроса.
#[derive(Clone, Debug, PartialEq)]
pub struct Состояние {
    pub замок: bool,
    pub экран: Экран,
    pub присутствие: Присутствие,
    /// None — Windows ещё не сказала (до первого события питания).
    pub от_сети: Option<bool>,
    pub спит: bool,
    /// Номер процесса окна, что вышло вперёд последним (по событию); снимок всё равно перечитает передний напрямую.
    pub окно_pid: Option<u32>,
}

impl Default for Состояние {
    fn default() -> Состояние {
        Состояние {
            замок: false,
            экран: Экран::Горит,
            присутствие: Присутствие::Есть,
            от_сети: None,
            спит: false,
            окно_pid: None,
        }
    }
}

impl Состояние {
    /// Применить событие шины. Чистая (видно в тесте): без вызовов Windows.
    pub fn применить(&mut self, с: &Событие) {
        match с {
            Событие::Замок => self.замок = true,
            Событие::Отпёрто => self.замок = false,
            Событие::Экран(э) => self.экран = *э,
            Событие::Присутствие(п) => self.присутствие = *п,
            Событие::Питание(п) => self.от_сети = Some(*п == crate::sobytiya::Питание::Сеть),
            Событие::Засыпает => self.спит = true,
            Событие::Проснулся => self.спит = false,
            Событие::ОкноВперёд(pid) => self.окно_pid = Some(*pid),
            Событие::Вошёл => self.замок = false,
            // свёртывание, вход/выход, конец сеанса, заставка — на снимок внимания прямо не влияют
            _ => {}
        }
    }

    /// Экран что-то показывает (горит или притушен, но не погас).
    pub fn экран_горит(&self) -> bool {
        self.экран != Экран::Погас
    }
}

// ───────────────────────────── он за ПК ─────────────────────────────

/// Чистая (видно в тесте): он за ПК. Замок или погасший экран — его нет. Иначе: недавно трогал ввод, или что-то
/// звучит (музыка, созвон), или идёт его видео. `видео` даёт звонящий (у «Механика» и у БАРСа свои датчики декодера).
pub fn за_пк(без_ввода_с: u64, порог_с: u64, замок: bool, экран_горит: bool, звук: bool, видео: bool) -> bool {
    if замок || !экран_горит {
        return false;
    }
    без_ввода_с < порог_с || звук || видео
}

