//! 🟥 13.11 (волна 2а, ключ `vnimanie`): «его внимание» (И5, П6) — то, что он видит, слышит и трогает. Карта внимания:
//! переднее окно (номер + время создания, чтобы номер не путался с чужим процессом), во весь ли оно экран, какие
//! процессы сейчас звучат, занят ли микрофон или камера (созвон), от сети ли ПК, сколько секунд он не трогал мышь,
//! замок, экран, заставка. Всё это — неприкасаемо, как переднее окно: его видео в другом окне и его созвон — это тоже
//! «он сам», а не фон.
//!
//! Плюс кадры DWM (`DwmGetCompositionTimingInfo`) — что он РЕАЛЬНО видит: дёрнулась картинка или нет. Задержка запроса
//! экрана под видео бывает и без потери кадров — тогда он ничего не замечает.
//!
//! Состояние ПК и сеанса (замок, экран, питание, сон, окно впереди) «Механик» держит по событиям шины (`sobytiya.rs`):
//! `Состояние::применить` меняет его мгновенно. Остальное (звук, микрофон, камера, во весь экран, простой ввода, кадры)
//! — дешёвым опросом в миг снимка. Живые вызовы Windows — только чтение; над чужими процессами ничего не делаем.

// Пока сведение не подключило внимание к лечению/окну, часть функций «не используется» — ожидание, не мёртвый код.
#![allow(dead_code)]

