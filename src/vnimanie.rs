/// Номера процессов, у которых прямо сейчас играет звук (активная звуковая сессия на устройстве вывода по умолчанию).
/// Пусто — звука нет, или COM не дался (тогда звонящий просто не узнает о звуке — прежнее поведение). Только чтение.
pub fn звук_процессов() -> Vec<u32> {
    let мой = unsafe { CoInitializeEx(std::ptr::null_mut(), 0) }; // COINIT_MULTITHREADED
    let итог = unsafe { звук_внутри() };
    // S_OK (0) и S_FALSE (1) — мы инициализировали COM, нам и закрывать; RPC_E_CHANGED_MODE (<0) — не мы
    if мой >= 0 {
        unsafe { CoUninitialize() };
    }
    итог
}

unsafe fn звук_внутри() -> Vec<u32> {
    type Создать = unsafe extern "system" fn(*const u8, *mut c_void, u32, *const u8, *mut *mut c_void) -> i32;
    type ПоУмолчанию = unsafe extern "system" fn(*mut c_void, u32, u32, *mut *mut c_void) -> i32;
    type Включить = unsafe extern "system" fn(*mut c_void, *const u8, u32, *mut c_void, *mut *mut c_void) -> i32;
    type Перечислитель = unsafe extern "system" fn(*mut c_void, *mut *mut c_void) -> i32;
    type Сколько = unsafe extern "system" fn(*mut c_void, *mut i32) -> i32;
    type Взять = unsafe extern "system" fn(*mut c_void, i32, *mut *mut c_void) -> i32;
    type Спросить = unsafe extern "system" fn(*mut c_void, *const u8, *mut *mut c_void) -> i32;
    type Состояние = unsafe extern "system" fn(*mut c_void, *mut u32) -> i32;
    type Номер = unsafe extern "system" fn(*mut c_void, *mut u32) -> i32;

    let mut пиды = Vec::new();
    // CLSCTX_ALL = 0x17
    let mut перечень: *mut c_void = std::ptr::null_mut();
    if CoCreateInstance(CLSID_ПЕРЕЧЕНЬ.as_ptr(), std::ptr::null_mut(), 0x17, IID_ПЕРЕЧЕНЬ.as_ptr(), &mut перечень) < 0
        || перечень.is_null()
    {
        return пиды;
    }
    // IMMDeviceEnumerator::GetDefaultAudioEndpoint — 4; eRender=0, eConsole=0
    let mut устройство: *mut c_void = std::ptr::null_mut();
    if метод::<ПоУмолчанию>(перечень, 4)(перечень, 0, 0, &mut устройство) < 0 || устройство.is_null() {
        отпустить(перечень);
        return пиды;
    }
    // IMMDevice::Activate — 3
    let mut распорядитель: *mut c_void = std::ptr::null_mut();
    let hr = метод::<Включить>(устройство, 3)(устройство, IID_РАСПОРЯДИТЕЛЬ2.as_ptr(), 0x17, std::ptr::null_mut(),
        &mut распорядитель);
    if hr < 0 || распорядитель.is_null() {
        отпустить(устройство);
        отпустить(перечень);
        return пиды;
    }
    // IAudioSessionManager2::GetSessionEnumerator — 5
    let mut перечислитель: *mut c_void = std::ptr::null_mut();
    if метод::<Перечислитель>(распорядитель, 5)(распорядитель, &mut перечислитель) >= 0 && !перечислитель.is_null() {
        let mut сколько: i32 = 0;
        // IAudioSessionEnumerator::GetCount — 3
        if метод::<Сколько>(перечислитель, 3)(перечислитель, &mut сколько) >= 0 {
            for i in 0..сколько {
                let mut сессия: *mut c_void = std::ptr::null_mut();
                // GetSession — 4
                if метод::<Взять>(перечислитель, 4)(перечислитель, i, &mut сессия) < 0 || сессия.is_null() {
                    continue;
                }
                let mut сессия2: *mut c_void = std::ptr::null_mut();
                // IAudioSessionControl::QueryInterface(IAudioSessionControl2) — 0
                if метод::<Спросить>(сессия, 0)(сессия, IID_УПРАВЛЕНИЕ2.as_ptr(), &mut сессия2) >= 0 && !сессия2.is_null() {
                    let mut сост: u32 = 0;
                    // IAudioSessionControl::GetState — 3 (AudioSessionStateActive = 1)
                    let активна = метод::<Состояние>(сессия2, 3)(сессия2, &mut сост) >= 0 && сост == 1;
                    if активна {
                        let mut pid: u32 = 0;
                        // IAudioSessionControl2::GetProcessId — 14
                        if метод::<Номер>(сессия2, 14)(сессия2, &mut pid) >= 0 && pid != 0 && !пиды.contains(&pid) {
                            пиды.push(pid);
                        }
                    }
                    отпустить(сессия2);
                }
                отпустить(сессия);
            }
        }
        отпустить(перечислитель);
    }
    отпустить(распорядитель);
    отпустить(устройство);
    отпустить(перечень);
    пиды
}

// ───────────────────────────── снимок внимания ─────────────────────────────

/// Переднее окно: номер + время создания (номер мог достаться другому процессу — сверяем перед любым действием).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Окно {
    pub pid: u32,
    /// Время создания процесса (FILETIME); 0 — не прочли.
    pub создан: u64,
    /// Окно не отвечает (висит).
    pub висит: bool,
}

/// Общее состояние внимания — для лечения и для окна «Механика».
#[derive(Clone, Debug, PartialEq)]
pub struct Внимание {
    pub за_пк: bool,
    pub замок: bool,
    pub экран_горит: bool,
    pub заставка: bool,
    pub окно: Option<Окно>,
    pub во_весь_экран: bool,
    /// Процессы, чей звук играет (неприкасаемы).
    pub звук: Vec<u32>,
    pub микрофон: bool,
    pub камера: bool,
    /// None — Windows не сказала.
    pub от_сети: Option<bool>,
    pub без_ввода_с: u64,
}

/// Снять внимание: состояние по событиям (`сост`) + дешёвый опрос живого. `видео` даёт звонящий (декодер видео меряют
/// `storozh`/БАРС). Только чтение. Порог «за ПК» — `lechenie::ЗА_ПК_С` (120 с).
pub fn снять(сост: &Состояние, видео: bool) -> Внимание {
    let замок = сост.замок;
    let экран_горит = сост.экран_горит();
    let заставка = заставка_идёт();
    let без_ввода_с = okna::простой_ввода_с();
    let звук = звук_процессов();
    let окно = okna::передний_pid().map(|pid| Окно {
        pid,
        создан: okna::создан(pid).unwrap_or(0),
        висит: okna::висит_pid() == Some(pid),
    });
    let от_сети = сост.от_сети.or_else(okna::от_сети);
    Внимание {
        за_пк: за_пк(без_ввода_с, crate::lechenie::ЗА_ПК_С, замок, экран_горит, !звук.is_empty(), видео),
        замок,
        экран_горит,
        заставка,
        окно,
        во_весь_экран: во_весь_экран(),
        звук,
        микрофон: микрофон_занят(),
        камера: камера_занята(),
        от_сети,
        без_ввода_с: без_ввода_с.min(86_400),
    }
}

// ───────────────────────────── опрос с кэшем дорогого ─────────────────────────────

/// 🟥 14.11 (пакет «цена»): дорогое внимание (COM-звук, реестр микрофона/камеры) освежаем не чаще — его слово: «по
/// событию или раз в 10 с». Между опросами отдаём прошлый ответ.
const ДОРОГОЕ_КАЖДЫЕ: Duration = Duration::from_secs(10);

/// Чистая (видно в тесте): пора ли освежить дорогое — первый раз (`None`) или прошло не меньше `каждые`.
pub fn освежить_дорогое(дорогое_когда: Option<Instant>, каждые: Duration) -> bool {
    дорогое_когда.is_none_or(|т| т.elapsed() >= каждые)
}

/// Опрос внимания с кэшем дорогого. COM-звук и реестр микрофона/камеры стоят заметно, а меняются редко — освежаем их
/// не каждое окно (2 с), а раз в 10 с; дешёвое (замок, экран, заставка, окно впереди, во весь экран, простой ввода) —
/// каждый раз свежее. Только чтение.
pub struct Опрос {
    звук: Vec<u32>,
    микрофон: bool,
    камера: bool,
    дорогое_когда: Option<Instant>,
}

impl Default for Опрос {
    fn default() -> Опрос { Опрос::новый() }
}

impl Опрос {
    pub fn новый() -> Опрос { Опрос { звук: Vec::new(), микрофон: false, камера: false, дорогое_когда: None } }

    /// Снять внимание. То же, что свободная `снять`, но COM-звук и реестр микрофона/камеры — раз в `ДОРОГОЕ_КАЖДЫЕ`.
    pub fn снять(&mut self, сост: &Состояние, видео: bool) -> Внимание {
        if освежить_дорогое(self.дорогое_когда, ДОРОГОЕ_КАЖДЫЕ) {
            self.звук = звук_процессов();
            self.микрофон = микрофон_занят();
            self.камера = камера_занята();
            self.дорогое_когда = Some(Instant::now());
        }
        let замок = сост.замок;
        let экран_горит = сост.экран_горит();
        let без_ввода_с = okna::простой_ввода_с();
        let окно = okna::передний_pid().map(|pid| Окно {
            pid,
            создан: okna::создан(pid).unwrap_or(0),
            висит: okna::висит_pid() == Some(pid),
        });
        let от_сети = сост.от_сети.or_else(okna::от_сети);
        Внимание {
            за_пк: за_пк(без_ввода_с, crate::lechenie::ЗА_ПК_С, замок, экран_горит, !self.звук.is_empty(), видео),
            замок,
            экран_горит,
            заставка: заставка_идёт(),
            окно,
            во_весь_экран: во_весь_экран(),
            звук: self.звук.clone(),
            микрофон: self.микрофон,
            камера: self.камера,
            от_сети,
            без_ввода_с: без_ввода_с.min(86_400),
        }
    }
}

#[cfg(test)]
