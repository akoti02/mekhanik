/// Вид файла по происхождению (§7.3).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Вид {
    /// А — метка «из интернета» (браузер, мессенджер, расширение).
    Интернет,
    /// Б — без метки в «Загрузках» (записала его программа, скопировал сам).
    БезМетки,
    /// В — подпапка-проект (его работа): не уведомляем, кроме угроз.
    Работа,
}

/// Что нашли о файле (вход для решения).
#[derive(Clone, Debug, Default)]
pub struct Находки {
    pub род: Option<Род>,
    /// Маскировка: по имени одно, по содержимому опаснее.
    pub маскировка: Option<String>,
    /// Подпись (для запускаемых).
    pub подпись: Option<podpis::Подпись>,
    /// Угроза от Защитника.
    pub угроза: Option<Vec<String>>,
    /// Подвох в имени (bidi, двойное расширение).
    pub имя_опасно: Option<String>,
    /// Разбор PDF.
    pub pdf: Option<razbor::Пдф>,
    /// Взгляд в архив.
    pub архив: Option<razbor::ВзглядВАрхив>,
    /// Образец команды в тексте/субтитрах.
    pub команда: Option<String>,
    /// Защитник не смог — повторить позже.
    pub защитник_не_смог: bool,
}

/// Что сделать с файлом.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Итог {
    /// Чисто — оставить на месте.
    Чисто,
    /// Опасно — в карантин переносом.
    Карантин(String),
    /// Придержать до его «Вернуть».
    Придержать(String),
    /// Заметка в журнал, файл на месте.
    Заметка(String),
    /// Файл пропал посреди проверки — тихо.
    Пропал,
    /// Не проверен (Защитник не смог, нет памяти) — повторить позже.
    НеПроверен(String),
}

impl Итог {
    pub fn словом(&self) -> &'static str {
        match self {
            Итог::Чисто => "чисто",
            Итог::Карантин(_) => "карантин",
            Итог::Придержать(_) => "придержан",
            Итог::Заметка(_) => "заметка",
            Итог::Пропал => "пропал",
            Итог::НеПроверен(_) => "не проверен",
        }
    }
    pub fn причина(&self) -> &str {
        match self {
            Итог::Карантин(с) | Итог::Придержать(с) | Итог::Заметка(с) | Итог::НеПроверен(с) => с,
            _ => "",
        }
    }
}

/// Решение по находкам (§7.6). Чистая — всё видно в тестах. «Старое» (Отправка) часто придерживало лишнее;
/// тесты стерегут, где мы решаем иначе.
pub fn решить(вид: Вид, н: &Находки) -> Итог {
    // 1. Настоящая угроза Защитника — всегда карантин.
    if let Some(у) = &н.угроза {
        return Итог::Карантин(format!("Защитник нашёл угрозу: {}", у.join(", ")));
    }
    // 2. Маскировка (программа под видом видео/картинки/документа) — всегда карантин.
    if let Some(м) = &н.маскировка {
        return Итог::Карантин(м.clone());
    }
    // 3. Подвох в имени (перевёрнутое/двойное расширение) — карантин.
    if let Some(и) = &н.имя_опасно {
        return Итог::Карантин(format!("подвох в имени: {и}"));
    }
    // 4. Архив.
    if let Some(а) = &н.архив {
        let беда = if а.зашифрован {
            Some("архив под паролем — проверить содержимое нельзя".to_string())
        } else if а.бомба() {
            Some("архив-бомба (распакуется в десятки ГБ)".to_string())
        } else if !а.подвохи.is_empty() {
            Some(format!("подвох в именах внутри: {}", а.подвохи.join("; ")))
        } else if !а.запускаемые.is_empty() {
            Some(format!("внутри запускаемое: {}", а.запускаемые.join(", ")))
        } else {
            None
        };
        if let Some(б) = беда {
            return держать_или_заметка(вид, б);
        }
    }
    // 5. PDF.
    if let Some(п) = &н.pdf {
        if п.запуск {
            return держать_или_заметка(вид, "PDF запускает программу при открытии (/Launch)".into());
        }
        if п.вложение || п.скрипт {
            let что = if п.вложение { "вложенный файл" } else { "скрипт" };
            return Итог::Заметка(format!("в PDF {что} — безобидно для чтения, но знай"));
        }
    }
    // 6. Образец команды в тексте/субтитрах.
    if let Some(к) = &н.команда {
        return Итог::Заметка(format!("похоже на команду Windows («{к}») — не вставляй в Win+R"));
    }
    // 7. Запускаемый файл (программа, скрипт, ярлык, установщик, образ, библиотека, драйвер).
    if н.род.is_some_and(Род::запускается) {
        let род = н.род.unwrap();
        match вид {
            Вид::Интернет => {
                // программа с действительной подписью и чистая — отпустить; иначе придержать
                if род == Род::Программа && н.подпись.is_some_and(podpis::Подпись::действительна) {
                    return Итог::Чисто;
                }
                let подпись_текст = match н.подпись {
                    Some(podpis::Подпись::Сломана) => " (подпись не сходится)",
                    Some(podpis::Подпись::Нет) | None => " (без действительной подписи)",
                    Some(podpis::Подпись::Есть) => "",
                };
                return Итог::Придержать(format!("{} из интернета{}", род.словами(), подпись_текст));
            }
            // без метки и в папке-проекте — это обычные его файлы: только заметка
            Вид::БезМетки | Вид::Работа => {
                return Итог::Заметка(format!("{} (твой, без метки из интернета) — оставил на месте", род.словами()));
            }
        }
    }
    if н.защитник_не_смог {
        return Итог::НеПроверен("Защитник не смог — повторю позже".into());
    }
    Итог::Чисто
}

/// Для вида А — придержать; для Б/В — только заметка (его файлы работе не мешаем).
fn держать_или_заметка(вид: Вид, причина: String) -> Итог {
    match вид {
        Вид::Интернет => Итог::Придержать(причина),
        Вид::БезМетки | Вид::Работа => Итог::Заметка(причина),
    }
}

// ───────────────────────────── разбор одного файла ─────────────────────────────

/// Сколько читаем для разбора (PDF, текст, архив): остальное не нужно, диск не насилуем.
const ЧИТАТЬ_ДЛЯ_РАЗБОРА: u64 = 8 << 20;

fn прочитать_до(путь: &Path, предел: u64) -> Option<Vec<u8>> {
    use std::io::Read;
    let ф = std::fs::File::open(путь).ok()?;
    let mut буф = Vec::new();
    ф.take(предел).read_to_end(&mut буф).ok()?;
    Some(буф)
}

/// Собрать находки по файлу (чтение; подпись и Защитник — живые вызовы Windows). `exe_защитника` — путь MpCmdRun.
fn разобрать_файл(путь: &Path, вид: Вид, exe_защитника: Option<&Path>) -> Находки {
    let mut н = Находки::default();
    let имя = путь.file_name().and_then(|и| и.to_str()).unwrap_or("");
    let ext = vid::расширение(имя);
    let род = vid::род_по_расширению(&ext);
    н.род = Some(род);

    // подвох в имени
    let разбор_имени = vid::разобрать_имя(имя);
    if разбор_имени.опасно {
        н.имя_опасно = Some(разбор_имени.замечания.join("; "));
    }

    let длина = std::fs::metadata(путь).map(|м| м.len()).unwrap_or(0);
    let Some(данные) = прочитать_до(путь, ЧИТАТЬ_ДЛЯ_РАЗБОРА) else {
        return н;
    };
    let контейнер = razbor::sniff(&данные, длина);
    let настоящий = razbor::род_контейнера(контейнер);

    // маскировка: заявлено безобидное, а внутри опасное
    н.маскировка = vid::маскировка(&ext, настоящий);

    match контейнер {
        razbor::Контейнер::Pdf => {
            н.pdf = Some(razbor::разобрать_pdf(&данные));
        }
        razbor::Контейнер::Zip => {
            if let Some(записи) = razbor::записи_zip(&данные) {
                // docx/xlsx/pptx — ZIP: макросы по именам записей
                if razbor::office_макросы(&записи) {
                    н.род = Some(Род::ДокументМакросы);
                }
                // настоящий архив (не офисный документ по расширению) — заглянуть внутрь
                if род == Род::Архив {
                    н.архив = Some(razbor::взгляд_в_архив(&записи));
                }
            }
        }
        razbor::Контейнер::Ole => {
            if razbor::ole_макросы(&данные) {
                н.род = Some(Род::ДокументМакросы);
            }
        }
        razbor::Контейнер::Текст => {
            н.команда = razbor::найти_команду(&данные).map(str::to_string);
        }
        _ => {}
    }

    // подпись — для запускаемых
    if н.род.is_some_and(Род::запускается) {
        н.подпись = Some(podpis::проверить(путь));
    }

    // Защитник — для вида А и для запускаемых/архивов/документов (не для массы безобидных без метки)
    let звать_защитника = matches!(вид, Вид::Интернет)
        || н.род.is_some_and(Род::запускается)
        || род == Род::Архив
        || род == Род::Документ;
    if звать_защитника {
        if let Some(exe) = exe_защитника {
            match zashchitnik::проверить(exe, путь) {
                zashchitnik::Итог::Угроза(у) => н.угроза = Some(у),
                zashchitnik::Итог::НеСмог(_) => н.защитник_не_смог = true,
                zashchitnik::Итог::Чисто => {}
            }
        }
    }
    н
}

// ───────────────────────────── история для окна ─────────────────────────────

/// `%LOCALAPPDATA%\mekhanik\zagruzki\istoriya.json` — массив последних итогов для окна «Механика».
/// Схема записи: `{ "ts": строка-время, "imya": имя, "put": полный путь, "vid": "internet|bez_metki|rabota",
/// "sayt": сайт или null, "itog": "chisto|karantin|priderzhan|zametka|propal|ne_proveren",
/// "prichina": текст, "otpechatok": sha256 или null, "karantin_id": id или null }`.
const ИСТОРИЯ_МАКС: usize = 2000;

fn вид_словом(в: Вид) -> &'static str {
    match в {
        Вид::Интернет => "internet",
        Вид::БезМетки => "bez_metki",
        Вид::Работа => "rabota",
    }
}

fn записать_историю(запись: serde_json::Value) {
    let путь = karantin::папка_данных().join("istoriya.json");
    let _ = std::fs::create_dir_all(karantin::папка_данных());
    let mut список: Vec<serde_json::Value> = std::fs::read_to_string(&путь)
        .ok()
        .and_then(|т| serde_json::from_str(&т).ok())
        .unwrap_or_default();
    список.push(запись);
    if список.len() > ИСТОРИЯ_МАКС {
        let лишних = список.len() - ИСТОРИЯ_МАКС;
        список.drain(0..лишних);
    }
    let _ = crate::svyaz::записать(&путь, &serde_json::Value::Array(список).to_string());
}

