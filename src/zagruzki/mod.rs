//! Сторож «Загрузок» «Механика» — офлайн-проверка файлов, которые попадают в «Загрузки» (перенос из «Кино Киры —
//! Отправки», 13.11). Своя проверка (имя, сигнатура, PE, скрипты, макросы, PDF, архивы), подпись без сети, AMSI,
//! Защитник Windows местно. Без ClamAV, YARA и любой сети. Опасное — в карантин переносом; программы и скрипты без
//! действительной подписи — придержать до его «Вернуть»; чистое — оставить; один раз на файл (память отпечатков).
