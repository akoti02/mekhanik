/// Проба на стенде: `proba_zagruzki.json` `{ "until_ms": …, "papka": "…" }` — сторожить только эту папку, без
/// уведомлений и без строк БАРСу (его правило: проверочные копии молчат).
fn проба() -> Option<PathBuf> {
    let т = std::fs::read_to_string(crate::svyaz::папка().join("proba_zagruzki.json")).ok()?;
    let v: serde_json::Value = serde_json::from_str(&т).ok()?;
    let до = v.get("until_ms").and_then(serde_json::Value::as_u64)?;
    if до <= crate::svyaz::сейчас_мс() {
        return None;
    }
    v.get("papka").and_then(serde_json::Value::as_str).map(PathBuf::from)
}

/// Определить вид файла: метка из интернета (А), иначе папка-проект (В) или без метки (Б).
fn вид_файла(путь: &Path) -> (Вид, Option<String>) {
    if let Some(м) = metka::прочитать(путь) {
        if м.из_интернета() {
            return (Вид::Интернет, м.сайт());
        }
    }
    // папка-проект?
    if let Some(папка) = путь.parent() {
        let имена: Vec<String> = std::fs::read_dir(папка)
            .map(|д| д.filter_map(Result::ok).filter_map(|з| з.file_name().into_string().ok()).collect())
            .unwrap_or_default();
        if papki::похоже_на_проект(&имена) {
            return (Вид::Работа, None);
        }
    }
    (Вид::БезМетки, None)
}

/// Обработать один файл целиком: от ожидания докачки до записи итога. Возвращает итог (для журнала и истории).
fn обработать(путь: &Path, отпечатки: &mut karantin::Отпечатки, exe_защитника: Option<&Path>, тихо: bool) -> Итог {
    let имя = путь.file_name().and_then(|и| и.to_str()).unwrap_or("").to_string();
    if vid::мусор(&имя) {
        return Итог::Чисто;
    }
    // дождаться докачки (тихо дольше для папок-проектов не делаем здесь — простое ожидание)
    if !sledit::ждать_докачки(путь, Duration::from_secs(2), Duration::from_secs(600)) {
        if !путь.exists() {
            return Итог::Пропал;
        }
        // ещё качается (временное имя) — вернётся отдельным событием
        return Итог::НеПроверен("файл ещё не докачан".into());
    }

    let отпечаток = karantin::отпечаток_файла(путь);
    if let Some(о) = &отпечаток {
        // 🟥 возврат пишет «возвращённые» на диск из другого потока — подмешать свежие с диска, иначе только что
        // возвращённый из карантина файл не узнаётся и придерживается снова.
        let свежие = karantin::Отпечатки::загрузить();
        отпечатки.возвращённые.extend(свежие.возвращённые);
        отпечатки.чистые.extend(свежие.чистые);
        if отпечатки.знаем(о) {
            return Итог::Чисто; // уже решено — перенос и пересохранение не трогаем
        }
    }

    let (вид, сайт) = вид_файла(путь);
    let находки = разобрать_файл(путь, вид, exe_защитника);
    let итог = решить(вид, &находки);

    // действия
    match &итог {
        Итог::Карантин(причина) => {
            if !тихо {
                let id = karantin::в_карантин(путь, находки.род.unwrap_or(Род::Прочее), причина, сайт.clone(), отпечаток.clone());
                записать_итог(&имя, путь, вид, &сайт, &итог, &отпечаток, id.ok(), тихо);
                if !проба_тихо(тихо) {
                    crate::vid::уведомить_со_страницей("Опасный файл убран", &format!("{имя} — {причина}"),
                        crate::vid::Вид::Тревога, Some("zagruzki"));
                }
                return итог;
            }
        }
        Итог::Придержать(причина) => {
            if !тихо {
                let id = karantin::в_карантин(путь, находки.род.unwrap_or(Род::Прочее), причина, сайт.clone(), отпечаток.clone());
                записать_итог(&имя, путь, вид, &сайт, &итог, &отпечаток, id.ok(), тихо);
                if !проба_тихо(тихо) {
                    crate::vid::уведомить_со_страницей("Придержал до твоего слова", &format!("{имя} — {причина}"),
                        crate::vid::Вид::Внимание, Some("zagruzki"));
                }
                return итог;
            }
        }
        Итог::Чисто => {
            if let Some(о) = &отпечаток {
                отпечатки.чистые.insert(о.clone());
                let _ = отпечатки.сохранить();
            }
        }
        _ => {}
    }
    записать_итог(&имя, путь, вид, &сайт, &итог, &отпечаток, None, тихо);
    итог
}

fn проба_тихо(тихо: bool) -> bool {
    тихо
}

#[allow(clippy::too_many_arguments)]
fn записать_итог(
    имя: &str,
    путь: &Path,
    вид: Вид,
    сайт: &Option<String>,
    итог: &Итог,
    отпечаток: &Option<String>,
    карантин_id: Option<String>,
    тихо: bool,
) {
    let тело = json!({
        "ts": chrono::Local::now().to_rfc3339_opts(chrono::SecondsFormat::Millis, false),
        "imya": имя,
        "put": путь.to_string_lossy(),
        "vid": вид_словом(вид),
        "sayt": сайт,
        "itog": итог.словом(),
        "prichina": итог.причина(),
        "otpechatok": отпечаток,
        "karantin_id": карантин_id,
    });
    записать_историю(тело.clone());
    // в журнал: проба — только свой журнал; опасное/придержанное — и БАРСу
    if тихо {
        crate::svyaz::журнал("загрузка_проверена_проба", &тело);
        return;
    }
    match итог {
        Итог::Карантин(_) | Итог::Придержать(_) => crate::svyaz::журнал_барсу("загрузка_в_карантин", &тело),
        Итог::Пропал => crate::svyaz::журнал("загрузка_пропала", &тело),
        _ => crate::svyaz::журнал("загрузка_проверена", &тело),
    }
}

/// Вход сторожа: запустить слежку и обрабатывать файлы, пока не попросят выйти. Подключит сведение (поток, как
/// `videokarta::работать`). Проба на стенде (`proba_zagruzki.json`) сторожит только свою папку и молчит.
pub fn работать() {
    let _ = std::fs::create_dir_all(karantin::папка_данных());
    let mut отпечатки = karantin::Отпечатки::загрузить();
    let exe_защитника = zashchitnik::mpcmdrun();

    let тихо = проба().is_some();
    let корни = match проба() {
        Some(п) => vec![п],
        None => papki::целиком(),
    };
    if корни.is_empty() {
        crate::svyaz::журнал("сторож_загрузок_нет_папок", &json!({ "почему": "не нашёл папку «Загрузки»" }));
        return;
    }
    crate::svyaz::журнал(
        "сторож_загрузок_запущен",
        &json!({ "korni": корни.iter().map(|п| п.to_string_lossy()).collect::<Vec<_>>(),
            "zashchitnik": exe_защитника.is_some(), "proba": тихо }),
    );

    let (пер, прм) = mpsc::channel::<sledit::Событие>();
    let стоп = Arc::new(AtomicBool::new(false));
    sledit::следить(корни.clone(), пер.clone(), стоп.clone());

    // догнать то, что уже лежит (при запуске)
    for корень in &корни {
        обойти(корень, &пер);
    }

    loop {
        if crate::svyaz::просят_выйти() {
            стоп.store(true, Ordering::Relaxed);
            return;
        }
        match прм.recv_timeout(Duration::from_secs(2)) {
            Ok(sledit::Событие::Файл(путь)) => {
                let _ = обработать(&путь, &mut отпечатки, exe_защитника.as_deref(), тихо);
            }
            Ok(sledit::Событие::ОбойтиЗаново(корень)) => обойти(&корень, &пер),
            Err(mpsc::RecvTimeoutError::Timeout) => {}
            Err(mpsc::RecvTimeoutError::Disconnected) => return,
        }
    }
}

/// Обойти папку (не глубже нескольких уровней) и отправить файлы на проверку. Папки разработки пропускаем.
fn обойти(корень: &Path, пер: &mpsc::Sender<sledit::Событие>) {
    обойти_глубь(корень, пер, 0);
}

fn обойти_глубь(папка: &Path, пер: &mpsc::Sender<sledit::Событие>, уровень: u32) {
    if уровень > 6 || papki::исключён(папка) {
        return;
    }
    let Ok(читатель) = std::fs::read_dir(папка) else { return };
    for запись in читатель.filter_map(Result::ok) {
        let путь = запись.path();
        if путь.is_dir() {
            обойти_глубь(&путь, пер, уровень + 1);
        } else if !papki::исключён(&путь) {
            let _ = пер.send(sledit::Событие::Файл(путь));
        }
    }
}

/// Вернуть файл из карантина по id (его «Вернуть»). Обёртка для сведения/окна/команд `mekhanik:`.
pub fn вернуть(id: &str) -> std::io::Result<PathBuf> {
    let mut отпечатки = karantin::Отпечатки::загрузить();
    let путь = karantin::вернуть(id, &mut отпечатки)?;
    crate::svyaz::журнал("загрузка_возвращена", &json!({ "id": id, "put": путь.to_string_lossy(), "кто": "он" }));
    Ok(путь)
}

