//! Вид файла и подвохи в имени (перенос `FileRules.cs` из «Кино Киры — Отправки», 13.11).
//! Чистая работа над строками и первыми байтами — без сети, без диска: всё видно в тестах.
//! «Старое» для красного теста здесь — сторож «Отправки»: где он решал иначе, в тесте стоит пометка.

/// Род файла по расширению. Запускаемые роды (`запускается`) без метки «из интернета» всё равно
/// придерживаются по решению Артура: вредонос бывает и с купленной подписью.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Род {
    Видео,
    Картинка,
    Программа,
    Скрипт,
    Архив,
    ДокументМакросы,
    Ярлык,
    ОбразДиска,
    Установщик,
    Библиотека,
    Драйвер,
    Документ,
    Текст,
    Звук,
    Прочее,
}

impl Род {
    /// Запускаемые и «придерживаемые» виды: их уводят в карантин до решения Артура (§7.6).
    pub fn запускается(self) -> bool {
        matches!(
            self,
            Род::Программа
                | Род::Скрипт
                | Род::Ярлык
                | Род::ОбразДиска
                | Род::Установщик
                | Род::ДокументМакросы
                | Род::Библиотека
                | Род::Драйвер
        )
    }
    /// Текст вида, его можно показать Артуру.
    pub fn словами(self) -> &'static str {
        match self {
            Род::Видео => "видео",
            Род::Картинка => "картинка",
            Род::Программа => "программа",
            Род::Скрипт => "скрипт",
            Род::Архив => "архив",
            Род::ДокументМакросы => "документ с макросами",
            Род::Ярлык => "ярлык",
            Род::ОбразДиска => "образ диска",
            Род::Установщик => "установщик",
            Род::Библиотека => "библиотека программы",
            Род::Драйвер => "драйвер",
            Род::Документ => "документ",
            Род::Текст => "текст",
            Род::Звук => "звук",
            Род::Прочее => "файл",
        }
    }
}

/// Расширение файла в нижнем регистре вместе с точкой: «Фильм.MP4» → «.mp4». Нет — пустая строка.
pub fn расширение(имя: &str) -> String {
    // только последняя точка после последнего разделителя пути; имя приходит уже без пути
    match имя.rfind('.') {
        Some(0) | None => String::new(), // «.gitignore» — не расширение
        Some(т) => имя[т..].to_lowercase(),
    }
}

/// Род по расширению (с точкой, нижний регистр). Таблица — перенос `FileRules.DangerousExt`
/// и `HarmlessKnown`, с добавлениями под ПК Артура.
pub fn род_по_расширению(ext: &str) -> Род {
    match ext {
        ".mp4" | ".m4v" | ".mkv" | ".avi" | ".mov" | ".wmv" | ".ts" | ".mpg" | ".mpeg" | ".webm" | ".flv"
        | ".3gp" | ".m2ts" | ".vob" | ".rmvb" => Род::Видео,
        ".jpg" | ".jpeg" | ".png" | ".webp" | ".gif" | ".bmp" | ".tif" | ".tiff" | ".heic" | ".avif" => Род::Картинка,
        ".exe" | ".scr" | ".com" | ".pif" | ".cpl" | ".gadget" | ".apk" => Род::Программа,
        ".bat" | ".cmd" | ".ps1" | ".psm1" | ".psd1" | ".vbs" | ".vbe" | ".js" | ".jse" | ".wsf" | ".wsh"
        | ".hta" | ".sh" | ".py" | ".pyw" | ".pl" | ".rb" | ".jar" | ".ps2" | ".mshxml" | ".svg" => Род::Скрипт,
        ".zip" | ".rar" | ".7z" | ".cab" | ".tar" | ".gz" | ".tgz" | ".bz2" | ".xz" | ".arj" | ".lzh" | ".ace"
        | ".uue" | ".zst" => Род::Архив,
        ".docm" | ".xlsm" | ".pptm" | ".xll" | ".xlam" | ".ppam" | ".wll" => Род::ДокументМакросы,
        ".lnk" | ".url" | ".scf" | ".website" | ".settingcontent-ms" | ".library-ms" | ".search-ms" => Род::Ярлык,
        ".iso" | ".img" | ".vhd" | ".vhdx" | ".dmg" => Род::ОбразДиска,
        ".msi" | ".msp" | ".mst" | ".msix" | ".msixbundle" | ".appx" | ".appxbundle" | ".appinstaller"
        | ".application" | ".deb" | ".rpm" | ".reg" | ".inf" => Род::Установщик,
        ".dll" | ".ocx" => Род::Библиотека,
        ".sys" | ".drv" => Род::Драйвер,
        ".pdf" | ".doc" | ".docx" | ".rtf" | ".xls" | ".xlsx" | ".ppt" | ".pptx" | ".chm" | ".hlp" => Род::Документ,
        ".txt" | ".nfo" | ".md" | ".json" | ".xml" | ".ini" | ".log" | ".csv" | ".srt" | ".ass" | ".ssa" | ".sub"
        | ".vtt" | ".html" | ".htm" | ".mht" | ".xhtml" | ".r" | ".rmd" => Род::Текст,
        ".mp3" | ".aac" | ".ac3" | ".dts" | ".flac" | ".mka" | ".wav" | ".m4a" | ".ogg" | ".opus" => Род::Звук,
        _ => Род::Прочее,
    }
}

/// Служебные файлы Проводника и macOS: в папке пропускаем молча.
pub fn мусор(имя: &str) -> bool {
    имя.eq_ignore_ascii_case("desktop.ini")
        || имя.eq_ignore_ascii_case("thumbs.db")
        || имя.eq_ignore_ascii_case("ehthumbs.db")
        || имя == ".DS_Store"
        || имя.starts_with("._")
}

/// Недокачанный файл (ждём, пока докачается). Перенос `GuardRules`.
pub fn недокачан(имя: &str) -> bool {
    let e = расширение(имя);
    matches!(e.as_str(), ".crdownload" | ".part" | ".tmp" | ".!qb" | ".partial" | ".download" | ".opdownload")
        || имя.ends_with('~')
}

// ───────────────────────────── подвохи в имени ─────────────────────────────

/// Невидимый знак направления текста (bidi): им прячут настоящее расширение (знак U+202E
/// переворачивает хвост, и «фото[U+202E]gpj.exe» видно как «фотоexe.jpg»).
pub fn знак_направления(c: u32) -> bool {
    matches!(c, 0x202A..=0x202E | 0x2066..=0x2069 | 0x200E | 0x200F | 0x061C)
}

/// Управляющий знак в имени.
pub fn управляющий(c: u32) -> bool {
    c < 0x20 || c == 0x7F || (0x80..=0x9F).contains(&c)
}

/// Невидимый знак (пробел-невидимка, склейка), которым разводят глаз.
pub fn невидимый(c: u32) -> bool {
    matches!(
        c,
        0x2800   // пустой шрифт Брайля
        | 0xFFA0 | 0x115F | 0x1160 | 0x3164 // хангыль-заполнители
        | 0x200B | 0x200C | 0x200D          // нулевой ширины
        | 0x2060..=0x2064                   // слово-джойнеры
        | 0xFEFF | 0x180E | 0x00AD          // BOM, монгольский, мягкий перенос
    )
}

/// Итог разбора имени.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct РазборИмени {
    /// Настоящая опасность в самом имени (подделка расширения) — 🔴.
    pub опасно: bool,
    /// Что нашли (пусто — чисто).
    pub замечания: Vec<String>,
}

/// Внутреннее расширение «film.exe.mp4» → «.exe». Пробелы и точки по краям не считаем.
fn внутреннее_расширение(основа: &str) -> Option<String> {
    let s = основа.trim_end_matches([' ', '.']);
    let т = s.rfind('.')?;
    if т == 0 || т == s.len() - 1 {
        return None;
    }
    let e = &s[т..];
    if e.len() > 18 || e.contains(' ') {
        return None;
    }
    Some(e.to_lowercase())
}

/// Основа имени без расширения: «Король Лев.mkv» → «Король Лев».
fn основа(имя: &str) -> &str {
    match имя.rfind('.') {
        Some(0) | None => имя,
        Some(т) => &имя[..т],
    }
}

/// Шаг 2: подвохи в имени — bidi, управляющие и невидимые знаки, двойное расширение, пробелы перед расширением.
/// «Старое» (сторож «Отправки») ловит то же — тест стережёт, чтобы перенос ничего не потерял.
pub fn разобрать_имя(имя: &str) -> РазборИмени {
    let mut замечания = Vec::new();
    let mut опасно = false;

    for c in имя.chars() {
        let к = c as u32;
        if знак_направления(к) {
            замечания.push(format!("невидимый знак направления U+{к:04X} — так прячут настоящее расширение"));
            опасно = true;
            break;
        }
        if управляющий(к) {
            замечания.push(format!("управляющий знак U+{к:04X} в имени"));
            опасно = true;
            break;
        }
        if невидимый(к) {
            замечания.push(format!("невидимый знак U+{к:04X} в имени"));
            опасно = true;
            break;
        }
    }

    let ext = расширение(имя);
    let осн = основа(имя);
    if let Some(внутр) = внутреннее_расширение(осн) {
        let внутр_род = род_по_расширению(&внутр);
        // «.com» внутри имени — чаще адрес сайта («rutracker.com»), а не программа
        if внутр != ".com" && внутр_род.запускается() {
            замечания.push(format!("двойное расширение «{внутр}{ext}»: в имени прячется {}", внутр_род.словами()));
            опасно = true;
        } else if matches!(внутр_род, Род::Видео | Род::Картинка) && род_по_расширению(&ext).запускается() {
            let что = род_по_расширению(&ext).словами();
            let как = if внутр_род == Род::Видео { "видео" } else { "картинку" };
            замечания.push(format!("двойное расширение «{внутр}{ext}»: {что} притворяется под {как}"));
            опасно = true;
        }
    }

    // «Мультик.mp4          .exe» — настоящее расширение отодвинуто пробелами за край окна
    // 🟥 14.11 (аудит): считать СИМВОЛЫ — длина в байтах делала из трёх неразрывных пробелов «шесть»
    let хвост_пробелов = осн.chars().rev().take_while(|с| с.is_whitespace()).count();
    if хвост_пробелов >= 5 {
        замечания.push(format!("перед расширением {хвост_пробелов} пробелов — так прячут расширение за край окна"));
        опасно = true;
    }

    РазборИмени { опасно, замечания }
}

/// Маскировка: по расширению должно быть одно, а по первым байтам — другое, опаснее (§`DownloadGuard.Disguise`).
/// `ext` — расширение с точкой; `настоящий` — род по сигнатуре из `razbor::sniff`.
/// Возвращает причину, если программа/скрипт/образ притворяется безобидным видом.
pub fn маскировка(ext: &str, настоящий: Род) -> Option<String> {
    let заявлен = род_по_расширению(ext);
    // безобидным заявлен, а внутри — запускаемое или архив под видом картинки/видео/документа
    let заявлен_безобиден =
        matches!(заявлен, Род::Видео | Род::Картинка | Род::Документ | Род::Текст | Род::Звук | Род::Прочее);
    if заявлен_безобиден && (настоящий.запускается() || настоящий == Род::Программа) {
        return Some(format!(
            "по имени «{ext}» это {}, а по содержимому — {}: подделка",
            заявлен.словами(),
            настоящий.словами()
        ));
    }
    None
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn расширения_и_род() {
        assert_eq!(расширение("Фильм.MP4"), ".mp4");
        assert_eq!(расширение(".gitignore"), "", "скрытый файл без расширения");
        assert_eq!(расширение("без_точки"), "");
        assert_eq!(род_по_расширению(".exe"), Род::Программа);
        assert_eq!(род_по_расширению(".ps1"), Род::Скрипт);
        assert_eq!(род_по_расширению(".docm"), Род::ДокументМакросы);
        assert_eq!(род_по_расширению(".mkv"), Род::Видео);
        assert_eq!(род_по_расширению(".pdf"), Род::Документ);
        assert!(Род::Программа.запускается() && Род::Скрипт.запускается());
        assert!(!Род::Видео.запускается() && !Род::Архив.запускается());
    }

    #[test]
    fn недокачанное_и_мусор() {
        assert!(недокачан("кино.mp4.crdownload") && недокачан("x.part") && недокачан("y.tmp"));
        assert!(!недокачан("кино.mp4"));
        assert!(мусор("desktop.ini") && мусор("Thumbs.db") && мусор("._resource"));
        assert!(!мусор("лекция.pdf"));
    }

    #[test]
    fn имя_перевёрнутое_расширение() {
        // U+202E RIGHT-TO-LEFT OVERRIDE (в коде — экранированный): так прячут настоящее расширение
        let р = разобрать_имя("мульт\u{202E}fdp.exe");
        assert!(р.опасно, "старое (Отправка) тоже ловит bidi — перенос не должен потерять");
    }

    #[test]
    fn имя_двойное_расширение() {
        // запускаемое спрятано ВНУТРИ, снаружи — безобидное: «Отчёт.exe.pdf» (а честный «x.pdf.exe» ловит слой решения по роду)
        let р = разобрать_имя("Отчёт.exe.pdf");
        assert!(р.опасно && !р.замечания.is_empty());
        // видео-расширение внутри, запускаемое снаружи — программа притворяется видео
        assert!(разобрать_имя("Кино.mp4.scr").опасно);
        // «rutracker.com» — адрес, не программа: не опасно
        assert!(!разобрать_имя("rutracker.com.torrent").опасно, "«.com» внутри — адрес сайта, не программа");
        // чистое имя
        assert!(!разобрать_имя("Лекция 07-01.pdf").опасно);
    }

    #[test]
    fn имя_пробелы_перед_расширением() {
        assert!(разобрать_имя("Мультик.mp4          .exe").опасно);
        assert!(!разобрать_имя("Мультик .mp4").опасно, "один пробел — не подвох");
        // 🟥 14.11 (аудит): считаются символы, не байты — три неразрывных пробела (6 байт) не «шесть пробелов»
        assert!(!разобрать_имя("video\u{00A0}\u{00A0}\u{00A0}.mp4").опасно, "три неразрывных пробела — не подвох");
        assert!(разобрать_имя("video\u{00A0}\u{00A0}\u{00A0}\u{00A0}\u{00A0}.exe").опасно, "пять — подвох");
    }

    #[test]
    fn маскировка_программы_под_видео() {
        // расширение .mp4 (видео), а по байтам — программа Windows (PE)
        let п = маскировка(".mp4", Род::Программа);
        assert!(п.is_some(), "программа под видом видео — подделка (старое тоже ловит Disguise)");
        // .exe с содержимым-программой — не подделка (всё честно)
        assert!(маскировка(".exe", Род::Программа).is_none());
        // .pdf с содержимым-документом — честно
        assert!(маскировка(".pdf", Род::Документ).is_none());
    }
}
