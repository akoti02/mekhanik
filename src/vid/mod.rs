//! 🟥 13.11 ВИД «МЕХАНИКА» — роль окна (`mekhanik.exe --okno`): значок у часов, окно на 7 страниц, уведомления значком.
//! Его слова 13.11: вид (окно, значок); «чтобы Механик работал сам максимально просто и удобно — чтобы не было этого
//! говна, где мне каждый раз его пробуждать нужно». Программа прозрачная: значок виден, всё видно, остановить можно из
//! меню значка — никакой защиты от владельца.
//!
//! - Окно — отдельный процесс от Мозга (vid.md §4.2): упадёт свой код GDI — Мозг работает и лечит дальше; упадёт Мозг —
//!   окно видит («молчит») и, если сведение дало чем, поднимает его (`Настройка::поднять_мозг`).
//! - Без прав администратора, приоритет обычный (ставит себе сам: Мозг — «ниже обычного», окно унаследовало бы).
//! - Без сети: ни шрифтов, ни библиотек извне; только файлы `%LOCALAPPDATA%\mekhanik\` (схемы — `sostoyanie.rs`).
//! - Окно спрятано — работает только значок: раз в 2 с пять маленьких файлов, процессор ≈0, видеокарта — 0.
//! - Чего окно не умеет и уметь не будет: закрыть или убить чужой процесс, тронуть БАРС, писать БАРСу, менять
//!   настройки Windows. Его программы «Механик» не закрывает.
//!
//! Подключение (сведение, `main.rs`): `mod vid;` и до `okna::единственный()` — `if std::env::args().any(|а| а == "--okno")
//! { vid::работать_окно(); return; }` (у окна свой мьютекс `Local\mekhanik-okno`, `stop.flag` ему не снимать).

