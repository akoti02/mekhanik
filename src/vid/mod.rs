    #[test]
    fn подъём_по_правилам() {
        static ЗВАЛИ: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(0);
        fn поднять() -> Result<String, String> { ЗВАЛИ.fetch_add(1, Ordering::Relaxed); Ok("задачей".into()) }
        let н = Настройка { поднять_мозг: Some(поднять) };
        let общее = Общее::default();
        let mut п = Подъём::default();
        let молчит = Картина { мозг: Мозг { жизнь: ЖизньМозга::НеЗапущен, ..Default::default() }, ..Default::default() };
        assert!(!подъём_шаг(&mut п, &молчит, &н, &общее));
        assert_eq!(ЗВАЛИ.load(Ordering::Relaxed), 0, "только замолчал — ждём минуту");
        п.молчит_с = Some(Instant::now() - Duration::from_secs(61));
        assert!(!подъём_шаг(&mut п, &молчит, &н, &общее));
        assert_eq!((ЗВАЛИ.load(Ordering::Relaxed), п.попыток), (1, 1), "минута — поднять");
        assert!(!подъём_шаг(&mut п, &молчит, &н, &общее));
        assert_eq!(ЗВАЛИ.load(Ordering::Relaxed), 1, "не чаще раза в 5 мин");
        п.попыток = 3;
        assert!(подъём_шаг(&mut п, &молчит, &н, &общее), "три без толку — не поднимается");
        assert_eq!(общее.очередь.lock().unwrap().len(), 1, "и одно уведомление");
        assert!(подъём_шаг(&mut п, &молчит, &н, &общее));
        assert_eq!(общее.очередь.lock().unwrap().len(), 1, "не чаще раза в час");
        let жив = Картина { мозг: Мозг { жизнь: ЖизньМозга::Жив, ..Default::default() }, ..Default::default() };
        assert!(!подъём_шаг(&mut п, &жив, &н, &общее));
        assert_eq!(п.попыток, 0, "ожил — счёт заново");
        let стоп = Картина { мозг: Мозг { жизнь: ЖизньМозга::Остановлен, ..Default::default() }, ..Default::default() };
        п.молчит_с = Some(Instant::now() - Duration::from_secs(600));
        assert!(!подъём_шаг(&mut п, &стоп, &н, &общее));
        assert_eq!(ЗВАЛИ.load(Ordering::Relaxed), 1, "он остановил — не поднимаем");
        let без = Настройка::default();
        assert!(!подъём_шаг(&mut Подъём { молчит_с: Some(Instant::now() - Duration::from_secs(600)), ..Default::default() }, &молчит, &без, &общее),
            "сведение не дало чем поднять — только «молчит»");
    }

