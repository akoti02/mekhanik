/// Читает файлы и снимки для картины. Спрятано окно — только то, что нужно значку.
pub struct Читатель {
    вход: Option<u64>,
    журнал: ХвостЖурнала,
    прошлая: Картина,
    буф: Vec<u8>,
    снимок: Option<(Instant, crate::okna::Снимок)>,
    сеансы: HashMap<u32, bool>,
    свой_сеанс: Option<u32>,
    передний: Option<u32>,
    время_машины: Option<(u64, u64, u64)>,
}

impl Читатель {
    pub fn новый(вход: Option<u64>) -> Читатель {
        Читатель { вход, журнал: ХвостЖурнала::default(), прошлая: Картина::default(), буф: Vec::new(), снимок: None,
            сеансы: HashMap::new(), свой_сеанс: crate::okna::сеанс(std::process::id()), передний: None, время_машины: None }
    }

    pub fn собрать(&mut self, папка: &Path, видно: bool, страница: Страница) -> Картина {
        let сейчас = сейчас_мс();
        let mut к = std::mem::take(&mut self.прошлая);
        к.мс = сейчас;
        // всегда (значку): жив ли Мозг, его значок, своя просьба и его ответ, проба
        let отметка = std::fs::read_to_string(папка.join("barsu.json")).ok().and_then(|т| serde_json::from_str::<Value>(&т).ok());
        let отметка_мс = отметка.as_ref().and_then(|v| v.get("ms")).and_then(Value::as_u64).unwrap_or(0);
        к.просьба = прочитать_просьбу(папка);
        let выкладка = папка.join("stop.flag").exists() || папка.join(СТОП_ОКНА).exists();
        к.мозг = Мозг {
            жизнь: жизнь_мозга(отметка_мс, win32::мьютекс_есть(МЬЮТЕКС_МОЗГА), к.просьба.остановлен(self.вход), выкладка, сейчас),
            pid: отметка.as_ref().and_then(|v| v.get("pid")).and_then(Value::as_u64).map(|п| п as u32),
            версия: отметка.as_ref().and_then(|v| v.get("version")).and_then(Value::as_str).map(str::to_string),
            отметка_мс,
            тормозит: отметка.as_ref().and_then(|v| v.get("slow")).and_then(Value::as_bool).unwrap_or(false),
        };
        let читать = |имя: &str| std::fs::read_to_string(папка.join(имя)).ok();
        к.значок = читать(ЗНАЧОК).and_then(|т| serde_json::from_str::<Value>(&т).ok()).and_then(|v| Значок::из_json(&v));
        к.ответ = читать(ОТВЕТ).and_then(|т| serde_json::from_str::<Value>(&т).ok()).map(|v| Ответ::из_json(&v));
        к.проба = читать("proba.json").and_then(|т| serde_json::from_str::<Value>(&т).ok())
            .and_then(|v| v.get("until_ms").and_then(Value::as_u64)).is_some_and(|до| до > сейчас);
        if !видно { self.снимок = None; self.время_машины = None; return self.отдать(к); }
        // окно видно — всё для шапки и страницы
        к.сводка = читать(СВОДКА).and_then(|т| serde_json::from_str::<Value>(&т).ok()).and_then(|v| Сводка::из_json(&v));
        let (озу, озу_всего, выд, выд_предел) = win32::память_пк().map(|(а, б, в, г)| (Some(а), Some(б), Some(в), Some(г)))
            .unwrap_or((None, None, None, None));
        let цп = win32::время_машины();
        let цп_весь = match (self.время_машины, цп) { (Some(было), Some(стало)) => win32::занятость(было, стало), _ => к.свои.цп_весь };
        self.время_машины = цп;
        к.свои = Свои { озу_своб_мб: озу, озу_всего_мб: озу_всего, выделено_своб_мб: выд, выделено_предел_мб: выд_предел,
            c_своб_гб: crate::okna::диск_свободно_мб('C').map(|м| м / 1024), ввод_с: Some(crate::okna::простой_ввода_с()), цп_весь };
        к.держит = разобрать_держит(читать("izmeneniya.json").as_deref(), читать("zamershie.json").as_deref(), читать("razum_nizhe.json").as_deref());
        к.опыт = читать("opyt.json").map(|т| разобрать_опыт(&т, сейчас)).unwrap_or_default();
        к.окна_разработки = читать("nastroyki.json").map(|т| окна_разработки(&т)).unwrap_or_default();
        к.барс = читать("ot_barsa.json").and_then(|т| разобрать_барса(&т));
        self.журнал.обновить(папка, сейчас);
        к.события = self.журнал.события.clone();
        к.мозг_с_мс = к.события.iter().rev().find(|с| с.имя == "механик_запущен").map(|с| с.мс);
        let система = папка_системы();
        к.видеокарта = разобрать_видеокарту(std::fs::read_to_string(система.join("videokarta.json")).ok().as_deref(),
            std::fs::read_to_string(система.join("zazhim_itog.json")).ok().as_deref(), &к.события);
        match страница {
            Страница::Загрузки => {
                let з = папка.join("zagruzki");
                к.загрузки = std::fs::read_to_string(з.join("istoriya.json")).ok()
                    .and_then(|и| разобрать_загрузки(&и, std::fs::read_to_string(з.join("sostoyanie.json")).ok().as_deref()));
                к.сторож_отправки = сторож_отправки_с();
            }
            Страница::Барс => {
                к.сообщений_барсу = std::fs::read_dir(папка.join("soobshcheniya")).ok()
                    .map(|д| д.filter_map(Result::ok).filter(|ф| ф.path().extension().is_some_and(|р| р == "json")).count());
                let нужны: Vec<u32> = к.барс.as_ref().map(|б| б.все_pid()).unwrap_or_default();
                к.имена = Arc::new(crate::okna::процессы().into_iter().filter(|(п, _, _)| нужны.contains(п)).map(|(п, _, и)| (п, и)).collect());
            }
            Страница::КтоЕст => к.кто = self.кто_ест(&к).map(Arc::new).or(к.кто.take()),
            Страница::Настройки => {
                к.возраст = ["barsu.json", ЗНАЧОК, СВОДКА, "ot_barsa.json", ПРОСЬБА, ОТВЕТ, "izmeneniya.json"].into_iter()
                    .map(|и| (и, возраст_с(&папка.join(и)))).collect();
            }
            _ => {}
        }
        if страница != Страница::КтоЕст { self.снимок = None; }
        self.отдать(к)
    }

    fn отдать(&mut self, к: Картина) -> Картина { self.прошлая = к.clone(); к }

    /// «Кто ест»: свой снимок процессов (тот же, что у Мозга: `okna::снимок`), разница с прошлым — процессор и диск.
    fn кто_ест(&mut self, к: &Картина) -> Option<Vec<ГруппаКто>> {
        let свой = std::process::id();
        if let Some(п) = crate::okna::передний_pid().filter(|п| *п != свой) { self.передний = Some(п); }
        let снимок = crate::okna::снимок(&mut self.буф)?;
        let сейчас = Instant::now();
        let Some((когда, было)) = self.снимок.replace((сейчас, снимок)) else { return None };
        let (_, стало) = self.снимок.as_ref()?;
        let с = сейчас.duration_since(когда).as_secs_f64().max(0.2);
        let свой_сеанс = self.свой_сеанс;
        self.сеансы.retain(|п, _| стало.contains_key(п));
        let процессы: Vec<ПроцессОкна> = стало.iter().filter(|(п, _)| **п != 0).map(|(п, пр)| {
            let до = было.get(п).filter(|д| д.имя == пр.имя);
            let ядер = до.map(|д| пр.время.saturating_sub(д.время) as f64 / (с * 1e7)).unwrap_or(0.0);
            let диск = до.map(|д| пр.ввод_вывод.saturating_sub(д.ввод_вывод) as f64 / с / 1_048_576.0).unwrap_or(0.0);
            let свой_с = *self.сеансы.entry(*п).or_insert_with(|| crate::okna::сеанс(*п).is_some_and(|с| Some(с) == свой_сеанс && с != 0));
            ПроцессОкна { pid: *п, родитель: пр.родитель, имя: пр.имя.clone(), ядер, озу_мб: пр.рабочий >> 20, выделено_мб: пр.память >> 20,
                диск_мб_с: диск, свой_сеанс: свой_с }
        }).collect();
        let барс = к.барс.as_ref().map(|б| б.все_pid()).unwrap_or_default();
        let мозг: Vec<ПроцессМозга> = к.сводка.as_ref().filter(|с| sostoyanie::сейчас_мс().saturating_sub(с.мс) <= СВОДКА_СВЕЖА_МС)
            .map(|с| с.процессы.clone()).unwrap_or_default();
        Some(разложить(&процессы, &Окружение { передний: self.передний, барс: &барс, окна_разработки: &к.окна_разработки, свой_pid: свой },
            &мозг, &к.держит))
    }
}

/// Поднимать ли Мозг — счёт попыток рабочего потока.
#[derive(Default)]
struct Подъём { молчит_с: Option<Instant>, попыток: u32, прошлая: Option<Instant>, сказал: Option<Instant> }

fn рабочий(папка: PathBuf, общее: Arc<Общее>, настройка: Настройка, mut читатель: Читатель) {
    let mut живо_писали: Option<Instant> = None;
    let mut было_видно = false;
    let mut подъём = Подъём::default();
    let послать = |код: u32| { unsafe { win32::PostMessageW(общее.скрытое.load(Ordering::Relaxed), код, 0, 0) }; };
    loop {
        for _ in 0..(ШАГ.as_millis() / 100) {
            if общее.выход.load(Ordering::Relaxed) { return; }
            if общее.обновить_сейчас.swap(false, Ordering::Relaxed) { break; }
            std::thread::sleep(Duration::from_millis(100));
        }
        if общее.выход.load(Ordering::Relaxed) { return; }
        let видно = общее.видно.load(Ordering::Relaxed);
        let страница = Страница::ВСЕ.get(общее.страница.load(Ordering::Relaxed) as usize).copied().unwrap_or_default();
        // окно открыто — Мозг пишет сводку; спрятано — стереть отметку
        if видно {
            if живо_писали.is_none_or(|к| к.elapsed() >= ОКНО_ЖИВО_РАЗ_В) {
                let _ = записать(&папка.join(ОКНО_ЖИВО), &окно_живо_json(страница.ключ(), сейчас_мс()).to_string());
                живо_писали = Some(Instant::now());
            }
        } else if было_видно {
            let _ = std::fs::remove_file(папка.join(ОКНО_ЖИВО));
            живо_писали = None;
        }
        было_видно = видно;
        // выкладка просит окно выйти
        if папка.join(СТОП_ОКНА).exists() {
            записать_себе("окно_выходит", &json!({ "почему": "выкладка попросила (stop_okno.flag)" }));
            общее.выход.store(true, Ordering::Relaxed);
            послать(win32::WM_CLOSE);
            return;
        }
        let mut к = читатель.собрать(&папка, видно, страница);
        к.не_поднимается = подъём_шаг(&mut подъём, &к, &настройка, &общее);
        if let Ok(mut место) = общее.картина.lock() { *место = Some(к); }
        послать(okno::КАРТИНА_ГОТОВА);
        let очередь = забрать_очередь(&папка, сейчас_мс());
        if !очередь.is_empty() {
            if let Ok(mut о) = общее.очередь.lock() { о.extend(очередь); }
            послать(okno::ОЧЕРЕДЬ_ГОТОВА);
        }
    }
}

/// Мозг молчит минуту — поднять (если сведение дало чем), не чаще раза в 5 мин; три раза без толку — тревога и одно
/// уведомление в час. `true` — не поднимается.
fn подъём_шаг(п: &mut Подъём, к: &Картина, н: &Настройка, общее: &Общее) -> bool {
    let молчит = matches!(к.мозг.жизнь, ЖизньМозга::Молчит(_) | ЖизньМозга::НеЗапущен);
    if !молчит {
        if к.мозг.жизнь == ЖизньМозга::Жив && п.попыток > 0 { записать_себе("мозг_ожил", &json!({ "попыток": п.попыток })); }
        if к.мозг.жизнь == ЖизньМозга::Жив { п.попыток = 0; }
        п.молчит_с = None;
        return false;
    }
    let Some(поднять) = н.поднять_мозг else { return false };
    let с = п.молчит_с.get_or_insert_with(Instant::now).elapsed().as_secs();
    if поднять_ли(к.мозг.жизнь, с, п.попыток, п.прошлая.map(|к| к.elapsed().as_secs())) {
        п.попыток += 1;
        п.прошлая = Some(Instant::now());
        let итог = поднять();
        записать_себе("мозг_поднят", &json!({ "попытка": п.попыток, "молчал_с": с, "итог": match &итог { Ok(т) => т.clone(), Err(е) => format!("не вышло: {е}") } }));
    }
    let не_поднимается = п.попыток >= ПОПЫТОК_МАКС;
    if не_поднимается && п.сказал.is_none_or(|к| к.elapsed() >= НЕ_РАБОТАЕТ_РАЗ_В) {
        п.сказал = Some(Instant::now());
        if let Ok(mut о) = общее.очередь.lock() {
            о.push(Уведомление { мс: сейчас_мс(), заголовок: "Механик не работает".into(),
                текст: "Три попытки поднять его не помогли. Открой окно — там видно, что с ним.".into(), вид: Вид::Тревога,
                страница: Some(Страница::Настройки.ключ().into()) });
        }
        unsafe { win32::PostMessageW(общее.скрытое.load(Ordering::Relaxed), okno::ОЧЕРЕДЬ_ГОТОВА, 0, 0) };
    }
    не_поднимается
}

