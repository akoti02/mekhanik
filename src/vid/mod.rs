/// Исполнить пункт меню (или кнопку «Настроек»): записать желаемое в `prosba_okna.json` — Мозг исполнит сам и ответит.
pub fn исполнить_пункт(п: ПунктМеню) {
    let Some((папка, mut просьба, окно, скрытое, общее)) = okno::с_видом(|в| (в.папка.clone(), в.картина.просьба.clone(), в.окно,
        в.скрытое, в.общее.clone())) else { return };
    let сейчас = сейчас_мс();
    let мозг_есть = win32::мьютекс_есть(МЬЮТЕКС_МОЗГА);
    let (заметка, выйти) = match п {
        ПунктМеню::ПаузаЧас => {
            просьба.пауза_до_мс = сейчас + ПАУЗА.as_millis() as u64;
            (format!("Пауза до {} — Механик всё вернёт и никого не тронет", stranicy::время(просьба.пауза_до_мс)), false)
        }
        ПунктМеню::СнятьПаузу => { просьба.пауза_до_мс = 0; ("Пауза снята — Механик снова работает сам".to_string(), false) }
        ПунктМеню::Остановить => {
            let т = win32::широкая("Остановить Механик до следующего входа в Windows?\n\nВсё, что он поменял, он вернёт сам. \
                Значок у часов тоже уйдёт. Запустить снова — из меню «Пуск» или при следующем входе.");
            let з = win32::широкая("Механик");
            let ответ = unsafe { win32::MessageBoxW(окно, т.as_ptr(), з.as_ptr(), win32::MB_OKCANCEL | win32::MB_ICONQUESTION | win32::MB_DEFBUTTON2) };
            if ответ != win32::IDOK { return; }
            match win32::вход_сеанса_мс() {
                Some(в) => просьба.стоп_вход_мс = в,
                None => { okno::с_видом(|в| в.заметить("Не узнал время входа в Windows — остановить до входа не могу")); return; }
            }
            ("Останавливаю до следующего входа: Механик всё вернёт и выйдет".to_string(), true)
        }
        ПунктМеню::ПриВходе(да) => {
            просьба.при_входе = Some(да);
            (if да { "Попросил: запускать Механик при входе в Windows" } else { "Попросил: не запускать Механик при входе в Windows" }.to_string(), false)
        }
        ПунктМеню::Открыть | ПунктМеню::ЗакрытьОкно => return,
    };
    просьба.мс = сейчас;
    просьба.id = format!("{сейчас}-{}", НОМЕР.fetch_add(1, Ordering::Relaxed));
    let ок = записать(&папка.join(ПРОСЬБА), &просьба.в_json().to_string()).is_ok();
    записать_себе("просьба_окна", &json!({ "пункт": format!("{п:?}"), "записано": ок, "мозг_жив": мозг_есть, "просьба": просьба.в_json() }));
    okno::с_видом(|в| {
        в.картина.просьба = просьба.clone();
        в.обновить_значок();
        в.заметить(if ок { заметка } else { "Не вышло записать просьбу (prosba_okna.json)".into() });
        if выйти && ок { в.выход_с = Some(Instant::now()); }
    });
    if выйти && ок {
        // Мозга нет — выходим сразу; есть — ждём, пока он всё вернёт и выйдет
        if мозг_есть { okno::ждать_выхода_мозга(скрытое); } else { unsafe { win32::DestroyWindow(скрытое) }; }
    }
    общее.обновить_сейчас.store(true, Ordering::Relaxed);
}

