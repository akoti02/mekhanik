/// Вход роли `--okno` (сведение подключает в `main.rs`).
pub fn работать_окно() { работать_окно_с(Настройка::default()) }

pub fn работать_окно_с(настройка: Настройка) {
    let папка = crate::svyaz::папка();
    let _ = std::fs::create_dir_all(&папка);
    let аргументы: Vec<String> = std::env::args().collect();
    // `--otkryt` — его рука (ярлык «Пуск», второй запуск): показать окно; `--stranica=kto` — на какой странице
    let открыть = аргументы.iter().any(|а| а == "--otkryt");
    let страница = аргументы.iter().find_map(|а| а.strip_prefix("--stranica=")).and_then(Страница::из);
    if win32::занять_мьютекс(МЬЮТЕКС_ОКНА).is_none() {
        // окно уже есть — попросить его открыться (только если открыть просил он) и выйти
        if открыть { попросить_открыть(страница.map(|с| с.ключ()).unwrap_or("")); }
        return;
    }
    let вход = win32::вход_сеанса_мс();
    let mut просьба = прочитать_просьбу(&папка);
    if просьба.остановлен(вход) {
        if !открыть {
            // он остановил «Механик» до входа — и окно тоже стоит
            записать_себе("окно_не_запущено", &json!({ "почему": "остановлен тобой до следующего входа" }));
            return;
        }
        // он сам открыл окно — значит, хочет «Механик» обратно
        просьба.стоп_вход_мс = 0;
        просьба.мс = сейчас_мс();
        let _ = записать(&папка.join(ПРОСЬБА), &просьба.в_json().to_string());
        записать_себе("остановка_снята", &json!({ "почему": "он открыл окно сам" }));
    }
    win32::масштаб_по_монитору();
    win32::свой_приоритет_обычный();
    win32::имя_программы(crate::okna::ОТПРАВИТЕЛЬ);
    let (светлые, _) = win32::тема_светлая();
    let меню = win32::тёмное_меню(!светлые);
    let скрытое = okno::создать_скрытое();
    if скрытое == 0 { записать_себе("окно_не_запущено", &json!({ "почему": "не создалось скрытое окно значка" })); return; }
    let общее = Arc::new(Общее::default());
    общее.скрытое.store(скрытое, Ordering::Relaxed);
    let mut читатель = Читатель::новый(вход);
    let картина = читатель.собрать(&папка, false, Страница::Сейчас);
    let mut вид = okno::Вид::новый(папка.clone(), общее.clone(), скрытое);
    вид.картина = картина;
    let значок = вид.поставить_значок();
    okno::поставить_вид(вид);
    записать_себе("окно_запущено", &json!({ "pid": std::process::id(), "версия": env!("CARGO_PKG_VERSION"), "значок": значок,
        "тёмное_меню": меню, "открыть": открыть }));
    let (о, п, н) = (общее.clone(), папка.clone(), настройка.clone());
    let рабочий = std::thread::Builder::new().name("okno-rabochiy".into()).spawn(move || рабочий(п, о, н, читатель)).ok();
    okno::завести_таймеры(скрытое);
    let очередь = забрать_очередь(&папка, сейчас_мс());
    if !очередь.is_empty() {
        if let Ok(mut о) = общее.очередь.lock() { о.extend(очередь); }
        unsafe { win32::PostMessageW(скрытое, okno::ОЧЕРЕДЬ_ГОТОВА, 0, 0) };
    }
    if открыть { okno::показать_окно(страница); }
    okno::крутить_сообщения();
    общее.выход.store(true, Ordering::Relaxed);
    if let Some(р) = рабочий { let _ = р.join(); }
    let _ = std::fs::remove_file(папка.join(ОКНО_ЖИВО));
    okno::снять_вид();
    записать_себе("окно_вышло", &json!({}));
}

/// Второй запуск: найти окно значка и попросить открыться.
fn попросить_открыть(страница: &str) -> bool {
    let класс = win32::широкая(okno::КЛАСС_ЗНАЧКА);
    let h = unsafe { win32::FindWindowW(класс.as_ptr(), std::ptr::null()) };
    if h == 0 { return false; }
    let д = win32::ПереданныеДанные { метка: okno::МЕТКА_ОТКРЫТЬ, байт: страница.len() as u32, данные: страница.as_ptr() as *const _ };
    let mut итог = 0usize;
    // SMTO_ABORTIFHUNG = 2
    unsafe { win32::SendMessageTimeoutW(h, win32::WM_COPYDATA, 0, &д as *const _ as isize, 2, 2000, &mut итог) != 0 && итог != 0 }
}

// ───────────────────────────── уведомления ─────────────────────────────

static НОМЕР: AtomicU64 = AtomicU64::new(0);

/// 🟥 Уведомление Windows от «Механика» — пузырём значка у часов, а не PowerShell (так выглядят вредоносы). Звать можно
/// из любого процесса «Механика»: в окне — показывает сам; в Мозге — передаёт окну (`WM_COPYDATA`, ждёт не дольше 2 с);
/// окна нет — кладёт в очередь `uvedomleniya\` (окно покажет, когда поднимется). `true` — показано или отдано окну.
/// Правила тишины — у окна: проба и проверочные копии молчат, то же — не чаще раза в 10 мин, звук — только при нём.
pub fn уведомить(заголовок: &str, текст: &str, вид: Вид) -> bool { уведомить_со_страницей(заголовок, текст, вид, None) }

/// То же, с открытием страницы по щелчку (`zagruzki`, `videokarta`…).
pub fn уведомить_со_страницей(заголовок: &str, текст: &str, вид: Вид, страница: Option<&str>) -> bool {
    let у = Уведомление { мс: сейчас_мс(), заголовок: заголовок.to_string(), текст: текст.to_string(), вид,
        страница: страница.map(str::to_string) };
    if проверочная_копия() { return false; }
    if let Some((показано, почему)) = okno::с_видом(|в| в.сказать(&у)) {
        записать_себе("уведомление", &json!({ "заголовок": заголовок, "текст": текст, "вид": вид.ключ(), "показано": показано, "почему": почему }));
        return показано;
    }
    let класс = win32::широкая(okno::КЛАСС_ЗНАЧКА);
    let h = unsafe { win32::FindWindowW(класс.as_ptr(), std::ptr::null()) };
    if h != 0 {
        let тело = у.в_json().to_string();
        let д = win32::ПереданныеДанные { метка: okno::МЕТКА_УВЕДОМЛЕНИЯ, байт: тело.len() as u32, данные: тело.as_ptr() as *const _ };
        let mut итог = 0usize;
        if unsafe { win32::SendMessageTimeoutW(h, win32::WM_COPYDATA, 0, &д as *const _ as isize, 2, 2000, &mut итог) } != 0 {
            return итог != 0;
        }
    }
    в_очередь(&crate::svyaz::папка(), &у, НОМЕР.fetch_add(1, Ordering::Relaxed));
    false
}

/// Проверочная копия (тесты, сборка в `target`) — не уведомляет и в журнал «Механика» не пишет (его правило: проверочные
/// копии не шлют уведомлений).
pub fn проверочная_копия() -> bool {
    if cfg!(test) { return true; }
    let путь = std::env::current_exe().map(|п| п.to_string_lossy().to_lowercase()).unwrap_or_default();
    путь.contains("\\target\\") || путь.contains("\\wt-target\\") || путь.contains("\\deps\\")
}

/// Свой журнал окна (`okno_zhurnal.jsonl`): журнал Мозга пишет только Мозг.
pub fn записать_себе(событие: &str, данные: &Value) {
    if cfg!(test) { return; }
    use std::io::Write;
    let путь = crate::svyaz::папка().join(ЖУРНАЛ_ОКНА);
    if std::fs::metadata(&путь).is_ok_and(|м| м.len() > ЖУРНАЛ_ОКНА_МАКС) { let _ = std::fs::rename(&путь, путь.with_extension("jsonl.old")); }
    let строка = json!({ "ts": chrono::Local::now().to_rfc3339_opts(chrono::SecondsFormat::Millis, false), "event": событие, "data": данные });
    if let Ok(mut ф) = std::fs::OpenOptions::new().create(true).append(true).open(&путь) { let _ = ф.write_all(format!("{строка}\n").as_bytes()); }
}

