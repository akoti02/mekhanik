/// Знак гаечного ключа («Repair») в шрифтах значков Windows.
const ЗНАК: u16 = 0xE90F;

/// Доля пикселя [x, x+1] × [y, y+1] под кругом (сглаживание по расстоянию от центра пикселя).
fn под_кругом(x: f32, y: f32, cx: f32, cy: f32, р: f32) -> f32 {
    let д = ((x + 0.5 - cx).powi(2) + (y + 0.5 - cy).powi(2)).sqrt();
    (р - д + 0.5).clamp(0.0, 1.0)
}

/// Доля пикселя под прямоугольником (точно — пересечение площадей).
fn под_прямоугольником(x: f32, y: f32, л: f32, в: f32, п: f32, н: f32) -> f32 {
    let ш = ((x + 1.0).min(п) - x.max(л)).max(0.0);
    let вы = ((y + 1.0).min(н) - y.max(в)).max(0.0);
    ш * вы
}

/// Цвета точки (#RRGGBB) — ярче на тёмной панели, глубже на светлой.
fn цвет_точки(п: Показ, светлая: bool) -> Option<u32> {
    match (п, светлая) {
        (Показ::Работает, false) => Some(0x4EA1FF), (Показ::Работает, true) => Some(0x0969DA),
        (Показ::Внимание, false) => Some(0xF5C04E), (Показ::Внимание, true) => Some(0xD29A00),
        (Показ::Тревога, false) => Some(0xFF6B5E), (Показ::Тревога, true) => Some(0xCF222E),
        _ => None,
    }
}

/// Чистая (видно в тесте): собрать картинку значка из покрытия знака (0…255 на пиксель, `р`×`р`) — 32 бита ARGB, альфа
/// прямая (как в файле .ico).
pub fn собрать(покрытие: &[u8], р: usize, п: Показ, светлая_панель: bool) -> Vec<u32> {
    let s = р as f32;
    let знак: u32 = if светлая_панель { 0x1F1F1F } else { 0xFFFFFF };
    let бледность = if matches!(п, Показ::Молчит | Показ::Пауза) { 0.45 } else { 1.0 };
    let точка = цвет_точки(п, светлая_панель);
    let (cx, cy, рт) = (s * 0.73, s * 0.73, s * 0.23);
    let вырез = рт + (s * 0.09).max(1.0);
    // пауза: два столбика внизу справа
    let (ст_ш, ст_в, ст_зазор) = (s * 0.13, s * 0.44, s * 0.09);
    let ст_н = s;
    let ст_п2 = s;
    let ст_л2 = ст_п2 - ст_ш;
    let ст_п1 = ст_л2 - ст_зазор;
    let ст_л1 = ст_п1 - ст_ш;
    let ст_в0 = ст_н - ст_в;
    let отступ = (s * 0.09).max(1.0);
    let mut итог = vec![0u32; р * р];
    for y in 0..р {
        for x in 0..р {
            let (fx, fy) = (x as f32, y as f32);
            let mut а_з = покрытие.get(y * р + x).copied().unwrap_or(0) as f32 / 255.0 * бледность;
            let (mut цв, mut а_т) = (0u32, 0.0f32);
            if let Some(ц) = точка {
                а_з *= 1.0 - под_кругом(fx, fy, cx, cy, вырез);
                а_т = под_кругом(fx, fy, cx, cy, рт);
                цв = ц;
            } else if п == Показ::Пауза {
                let вырез_ст = под_прямоугольником(fx, fy, ст_л1 - отступ, ст_в0 - отступ, ст_п2 + отступ, ст_н + отступ);
                а_з *= 1.0 - вырез_ст;
                а_т = под_прямоугольником(fx, fy, ст_л1, ст_в0, ст_п1, ст_н) + под_прямоугольником(fx, fy, ст_л2, ст_в0, ст_п2, ст_н);
                цв = знак;
            }
            let а = а_т + а_з * (1.0 - а_т);
            if а <= 0.0 { continue; }
            let смесь = |к: u32| -> u32 {
                let (т, з) = (((цв >> к) & 0xFF) as f32, ((знак >> к) & 0xFF) as f32);
                (((т * а_т + з * а_з * (1.0 - а_т)) / а).round() as u32).min(255)
            };
            итог[y * р + x] = ((а * 255.0).round() as u32).min(255) << 24 | смесь(16) << 16 | смесь(8) << 8 | смесь(0);
        }
    }
    итог
}

/// Нарисовать знак в памяти (белым по чёрному, оттенки серого) — покрытие 0…255. Нет ни одного шрифта значков — буква «М».
pub fn покрытие_знака(р: i32) -> Option<Vec<u8>> {
    unsafe {
        let dc = CreateCompatibleDC(0);
        if dc == 0 { return None; }
        let з = ЗаголовокРисунка { размер: 40, ширина: р, высота: -р, плоскостей: 1, бит: 32, сжатие: 0, байт: 0, _x: 0, _y: 0,
            _цветов: 0, _важных: 0 };
        let mut биты: *mut c_void = std::ptr::null_mut();
        let рис = CreateDIBSection(dc, &з, 0, &mut биты, 0, 0);
        if рис == 0 || биты.is_null() { DeleteDC(dc); return None; }
        let было = SelectObject(dc, рис);
        SetBkMode(dc, 1);
        SetTextColor(dc, 0x00FF_FFFF);
        let mut нашли = false;
        for (имя, знак, доля) in [("Segoe Fluent Icons", ЗНАК, 1.0f32), ("Segoe MDL2 Assets", ЗНАК, 1.0), ("Segoe UI Semibold", 'М' as u16, 0.95)] {
            let и = широкая(имя);
            // ANTIALIASED_QUALITY = 4 (оттенки серого, не ClearType: из них берём альфу)
            let шр = CreateFontW(-((р as f32 * доля).round() as i32), 0, 0, 0, if знак == ЗНАК { 400 } else { 600 }, 0, 0, 0, 1, 0, 0, 4, 0, и.as_ptr());
            if шр == 0 { continue; }
            let было_ш = SelectObject(dc, шр);
            let mut номер: u16 = 0;
            // GGI_MARK_NONEXISTING_GLYPHS = 1: нет знака — 0xFFFF
            let есть = GetGlyphIndicesW(dc, &знак, 1, &mut номер, 1) != 0xFFFF_FFFF && номер != 0xFFFF;
            if есть {
                let текст = [знак, 0];
                let mut п = Прям { лев: 0, верх: 0, прав: р, низ: р };
                DrawTextW(dc, текст.as_ptr(), 1, &mut п, DT_CENTER | DT_VCENTER | DT_SINGLELINE | DT_NOPREFIX | DT_NOCLIP);
                нашли = true;
            }
            SelectObject(dc, было_ш);
            DeleteObject(шр);
            if нашли { break; }
        }
        GdiFlush();
        let пиксели = std::slice::from_raw_parts(биты as *const u32, (р * р) as usize);
        let покрытие: Vec<u8> = пиксели.iter().map(|п| ((п >> 16) & 0xFF).max((п >> 8) & 0xFF).max(п & 0xFF) as u8).collect();
        SelectObject(dc, было);
        DeleteObject(рис);
        DeleteDC(dc);
        нашли.then_some(покрытие)
    }
}

/// Значок Windows из картинки ARGB.
pub fn значок_из(пиксели: &[u32], р: i32) -> Ручка {
    unsafe {
        let з = ЗаголовокРисунка { размер: 40, ширина: р, высота: -р, плоскостей: 1, бит: 32, сжатие: 0, байт: 0, _x: 0, _y: 0,
            _цветов: 0, _важных: 0 };
        let mut биты: *mut c_void = std::ptr::null_mut();
        let цвет = CreateDIBSection(0, &з, 0, &mut биты, 0, 0);
        if цвет == 0 || биты.is_null() { return 0; }
        std::ptr::copy_nonoverlapping(пиксели.as_ptr(), биты as *mut u32, (р * р) as usize);
        // маска: при 32 битах с альфой Windows её не смотрит, но она должна быть
        let маска_байт = vec![0u8; ((р + 15) / 16 * 2 * р) as usize];
        let маска = CreateBitmap(р, р, 1, 1, маска_байт.as_ptr() as *const c_void);
        let с = СведенияЗначка { значок: 1, x: 0, y: 0, маска, цвет };
        let h = CreateIconIndirect(&с);
        DeleteObject(маска);
        DeleteObject(цвет);
        h
    }
}

/// Значок для состояния нужного размера (`SM_CXSMICON` по масштабу); не вышло — 0 (тогда Windows покажет пустое место).
pub fn нарисовать(р: i32, п: Показ, светлая_панель: bool) -> Ручка {
    let р = р.clamp(16, 256);
    let покрытие = покрытие_знака(р).unwrap_or_else(|| vec![0; (р * р) as usize]);
    значок_из(&собрать(&покрытие, р as usize, п, светлая_панель), р)
}

