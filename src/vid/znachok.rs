#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ПунктМеню { Открыть, ПаузаЧас, СнятьПаузу, Остановить, ПриВходе(bool), ЗакрытьОкно }

pub struct ВидМеню { pub пауза_до: Option<u64>, pub при_входе: Option<bool>, pub окно_открыто: bool }

/// Чистая (видно в тесте): пункты меню — (номер, слова, флаги, что делает); разделитель — номер 0.
pub fn пункты(в: &ВидМеню) -> Vec<(usize, String, u32, Option<ПунктМеню>)> {
    let mut п = vec![(1, "Открыть Механик".to_string(), MF_STRING, Some(ПунктМеню::Открыть)), (0, String::new(), MF_SEPARATOR, None)];
    match в.пауза_до {
        Some(до) => п.push((2, format!("Снять паузу (пауза до {})", время(до)), MF_STRING, Some(ПунктМеню::СнятьПаузу))),
        None => п.push((2, "Пауза на час".into(), MF_STRING, Some(ПунктМеню::ПаузаЧас))),
    }
    п.push((3, "Остановить до входа".into(), MF_STRING, Some(ПунктМеню::Остановить)));
    // галочка — запуск при входе выключен; нажатие переключает
    let выключен = в.при_входе == Some(false);
    п.push((4, "Не запускать при входе".into(), MF_STRING | if выключен { MF_CHECKED } else { 0 }, Some(ПунктМеню::ПриВходе(выключен))));
    п.push((0, String::new(), MF_SEPARATOR, None));
    п.push((5, "Закрыть окно".into(), MF_STRING | if в.окно_открыто { 0 } else { MF_GRAYED }, Some(ПунктМеню::ЗакрытьОкно)));
    п
}

/// Показать меню у точки; вернуть выбранное (`None` — щёлкнул мимо).
pub fn показать_меню(окно: Ручка, x: i32, y: i32, в: &ВидМеню) -> Option<ПунктМеню> {
    let п = пункты(в);
    unsafe {
        let меню = CreatePopupMenu();
        if меню == 0 { return None; }
        for (номер, слова, флаги, _) in &п {
            let ш = широкая(слова);
            AppendMenuW(меню, *флаги, *номер, if *флаги & MF_SEPARATOR != 0 { std::ptr::null() } else { ш.as_ptr() });
        }
        SetMenuDefaultItem(меню, 1, 0);
        // без этого меню не закрывается щелчком мимо
        SetForegroundWindow(окно);
        let выбор = TrackPopupMenuEx(меню, TPM_RETURNCMD | TPM_NONOTIFY | TPM_RIGHTBUTTON, x, y, окно, std::ptr::null());
        PostMessageW(окно, 0, 0, 0);
        DestroyMenu(меню);
        п.into_iter().find(|(н, _, _, _)| *н == выбор as usize && выбор != 0).and_then(|(_, _, _, д)| д)
    }
}

