/// Что показывает значок.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum Показ { #[default] Спокойно, Работает, Внимание, Тревога, Молчит, Пауза }

impl Показ {
    fn тяжесть(self) -> u8 {
        match self { Показ::Спокойно => 0, Показ::Работает => 1, Показ::Внимание => 2, Показ::Тревога => 3, Показ::Молчит | Показ::Пауза => 4 }
    }
}

impl From<Состояние> for Показ {
    fn from(с: Состояние) -> Показ {
        match с { Состояние::Спокойно => Показ::Спокойно, Состояние::Работает => Показ::Работает,
            Состояние::Внимание => Показ::Внимание, Состояние::Тревога => Показ::Тревога }
    }
}

/// Чистая (видно в тесте): что показать и строка состояния — по старшинству: Мозг молчит / остановлен → не поднимается
/// (тревога) → пауза → что говорит Мозг (`znachok.json`) → без значка Мозга — по `barsu.json` (тормозит или работает).
pub fn показ(к: &Картина, сейчас: u64) -> (Показ, String) {
    if к.не_поднимается {
        return (Показ::Тревога, "Механик не работает — три попытки поднять не помогли".into());
    }
    match к.мозг.жизнь {
        ЖизньМозга::Остановлен => return (Показ::Молчит, "Механик остановлен тобой до следующего входа в Windows".into()),
        ЖизньМозга::Выкладка => return (Показ::Молчит, "Механик обновляется — подожди минуту".into()),
        ЖизньМозга::НеЗапущен => return (Показ::Молчит, "Механик не запущен".into()),
        ЖизньМозга::Молчит(с) => return (Показ::Молчит, format!("Механик молчит {}", super::stranicy::длительность(с))),
        ЖизньМозга::Жив => {}
    }
    if к.просьба.пауза_идёт(сейчас) {
        // честно: пауза — когда Мозг подтвердил (`otvet_okna.json`); иначе — только попросили
        let подтвердил = к.ответ.as_ref().is_some_and(|о| о.пауза_до_мс == к.просьба.пауза_до_мс);
        return (Показ::Пауза, if подтвердил { format!("Пауза до {} — всё вернул и никого не трогаю", время(к.просьба.пауза_до_мс)) }
            else { format!("Пауза до {} запрошена — жду, когда Механик подтвердит", время(к.просьба.пауза_до_мс)) });
    }
    match &к.значок {
        Some(з) => {
            let строка = if з.строка.is_empty() { match з.состояние {
                Состояние::Спокойно => "Всё спокойно".to_string(), Состояние::Работает => "Работаю сам".to_string(),
                Состояние::Внимание => "Нужно внимание".to_string(), Состояние::Тревога => "Нужна твоя рука".to_string() } }
                else { з.строка.clone() };
            (з.состояние.into(), строка)
        }
        None if к.мозг.тормозит => (Показ::Работает, "Тормозит — Механик разбирается сам".into()),
        None => (Показ::Спокойно, "Механик работает".into()),
    }
}

/// Чистая (видно в тесте): подсказка значка — «Механик · строка» и итоги дня; длиннее поля (127 знаков) — режет
/// `win32::в_поле`.
pub fn подсказка(к: &Картина, строка: &str) -> String {
    let mut п = format!("Механик · {строка}");
    if let Some(с) = к.значок.as_ref().and_then(|з| з.сегодня.as_ref()) {
        п += &format!("\nСегодня: {}, лечил {}{}", super::stranicy::число(с.тормозов, ["тормоз", "тормоза", "тормозов"]),
            с.вылечил, if с.всё_вернул { ", всё вернул" } else { "" });
    }
    п
}

/// Выдержка цвета: к тревожнее — если держится 4 с (тревога, «молчит» и пауза — сразу); обратно — после 10 с; картинка
/// меняется не чаще раза в 5 с (кроме сразу). Тормоз короче этого значок не красит (средина тормоза — 10 с).
#[derive(Clone, Debug)]
pub struct Выдержка { pub показано: Показ, показано_мс: u64, хочет: Показ, хочет_с_мс: u64 }

pub const К_ТРЕВОЖНЕЕ_МС: u64 = 4_000;
pub const К_СПОКОЙНЕЕ_МС: u64 = 10_000;
pub const НЕ_ЧАЩЕ_МС: u64 = 5_000;

impl Выдержка {
    pub fn новая(п: Показ, сейчас: u64) -> Выдержка { Выдержка { показано: п, показано_мс: сейчас, хочет: п, хочет_с_мс: сейчас } }
    /// Шаг: `вход` — что говорят данные. `true` — показанное сменилось (перерисовать значок).
    pub fn шаг(&mut self, вход: Показ, сейчас: u64) -> bool {
        if вход != self.хочет { self.хочет = вход; self.хочет_с_мс = сейчас; }
        if вход == self.показано { return false; }
        let держится = сейчас.saturating_sub(self.хочет_с_мс);
        let с_прошлой = сейчас.saturating_sub(self.показано_мс);
        let сразу = matches!(вход, Показ::Тревога | Показ::Молчит | Показ::Пауза) || matches!(self.показано, Показ::Молчит | Показ::Пауза);
        let можно = сразу || с_прошлой >= НЕ_ЧАЩЕ_МС && if вход.тяжесть() > self.показано.тяжесть() { держится >= К_ТРЕВОЖНЕЕ_МС }
            else { держится >= К_СПОКОЙНЕЕ_МС };
        if можно { self.показано = вход; self.показано_мс = сейчас; }
        можно
    }
}

