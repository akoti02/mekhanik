    #[test]
    fn картинка_значка() {
        let р = 24usize;
        // знак — квадрат в середине, полное покрытие
        let mut покр = vec![0u8; р * р];
        for y in 4..20 { for x in 4..20 { покр[y * р + x] = 255; } }
        let спокойно = собрать(&покр, р, Показ::Спокойно, false);
        assert_eq!(спокойно[10 * р + 10], 0xFFFF_FFFF, "белый знак на тёмной панели");
        assert_eq!(спокойно[0], 0, "вне знака — прозрачно");
        assert_eq!(собрать(&покр, р, Показ::Спокойно, true)[10 * р + 10], 0xFF1F_1F1F, "тёмный — на светлой");
        let тревога = собрать(&покр, р, Показ::Тревога, false);
        let ц = (0.73 * р as f32) as usize;
        assert_eq!(тревога[ц * р + ц] & 0x00FF_FFFF, 0xFF6B5E, "в середине точки — её цвет");
        assert_eq!(тревога[ц * р + ц] >> 24, 255);
        // вырез: между знаком и точкой — прозрачно (знак там был): пиксель (10, 17) — в 7 точках от центра точки,
        // она — 5,5, вырез — 7,7
        assert_eq!(покр[ц * р + 10], 255, "знак там есть");
        assert!(тревога[ц * р + 10] >> 24 < 64, "вырез вокруг точки: альфа {}", тревога[ц * р + 10] >> 24);
        let молчит = собрать(&покр, р, Показ::Молчит, false);
        assert_eq!(молчит[10 * р + 10] >> 24, 115, "молчит — бледный знак (45 %)");
        let пауза = собрать(&покр, р, Показ::Пауза, false);
        assert_eq!(пауза[(р - 2) * р + (р - 2)] >> 24, 255, "столбик паузы в углу");
        assert_ne!(пауза, молчит, "пауза отличима от «молчит»");
        for п in [Показ::Работает, Показ::Внимание] {
            assert_ne!(собрать(&покр, р, п, false)[ц * р + ц], тревога[ц * р + ц], "у каждого состояния свой цвет");
        }
    }

