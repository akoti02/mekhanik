/// Сообщение значка окну (версия 4: в `l` — событие и номер значка, в `w` — где).
pub const СООБЩЕНИЕ_ЗНАЧКА: u32 = WM_APP + 1;
const НОМЕР: u32 = 1;

pub struct Лоток { окно: Ручка, pub добавлен: bool }

impl Лоток {
    pub fn новый(окно: Ручка) -> Лоток { Лоток { окно, добавлен: false } }

    /// Поставить значок (и после перезапуска Проводника — `TaskbarCreated`).
    pub fn добавить(&mut self, иконка: Ручка, подсказка: &str) -> bool {
        let mut д = ДанныеЗначка::новые(self.окно, НОМЕР);
        д.флаги = NIF_MESSAGE | NIF_ICON | NIF_TIP | NIF_SHOWTIP;
        д.сообщение = СООБЩЕНИЕ_ЗНАЧКА;
        д.значок = иконка;
        д.подсказка = в_поле::<128>(подсказка);
        let mut ок = unsafe { Shell_NotifyIconW(NIM_ADD, &д) } != 0;
        if !ок {
            // значок остался от прежнего окна (упало) — заменить
            unsafe { Shell_NotifyIconW(NIM_DELETE, &д) };
            ок = unsafe { Shell_NotifyIconW(NIM_ADD, &д) } != 0;
        }
        if ок {
            д.версия = NOTIFYICON_VERSION_4;
            unsafe { Shell_NotifyIconW(NIM_SETVERSION, &д) };
        }
        self.добавлен = ок;
        ок
    }

    pub fn обновить(&mut self, иконка: Option<Ручка>, подсказка: &str) -> bool {
        if !self.добавлен { return false; }
        let mut д = ДанныеЗначка::новые(self.окно, НОМЕР);
        д.флаги = NIF_TIP | NIF_SHOWTIP;
        if let Some(и) = иконка { д.флаги |= NIF_ICON; д.значок = и; }
        д.подсказка = в_поле::<128>(подсказка);
        unsafe { Shell_NotifyIconW(NIM_MODIFY, &д) != 0 }
    }

    /// Пузырь значка (в Windows 10 и 11 — уведомление Windows от имени «Механик»).
    pub fn сказать(&self, заголовок: &str, текст: &str, вид: super::sostoyanie::Вид, звук: bool) -> bool {
        if !self.добавлен { return false; }
        let mut д = ДанныеЗначка::новые(self.окно, НОМЕР);
        д.флаги = NIF_INFO;
        д.заголовок = в_поле::<64>(заголовок);
        д.текст = в_поле::<256>(if текст.is_empty() { " " } else { текст });
        д.флаги_текста = match вид { super::sostoyanie::Вид::Сведение => NIIF_INFO, super::sostoyanie::Вид::Внимание => NIIF_WARNING,
            super::sostoyanie::Вид::Тревога => NIIF_ERROR } | NIIF_RESPECT_QUIET_TIME | if звук { 0 } else { NIIF_NOSOUND };
        unsafe { Shell_NotifyIconW(NIM_MODIFY, &д) != 0 }
    }

    pub fn убрать(&mut self) {
        if !self.добавлен { return; }
        let д = ДанныеЗначка::новые(self.окно, НОМЕР);
        unsafe { Shell_NotifyIconW(NIM_DELETE, &д) };
        self.добавлен = false;
    }
}

impl Drop for Лоток { fn drop(&mut self) { self.убрать(); } }

/// Разобрать сообщение значка версии 4: (событие, x, y).
pub fn событие_значка(w: usize, l: isize) -> (u32, i32, i32) {
    ((l as usize & 0xFFFF) as u32, (w & 0xFFFF) as u16 as i16 as i32, ((w >> 16) & 0xFFFF) as u16 as i16 as i32)
}

