/// Всё, что нужно странице кроме картины.
pub struct Обстановка<'а> { pub сейчас: u64, pub мерка: &'а dyn Мерка, pub м: f32 }

pub fn страница(с: Страница, к: &Картина, ш: i32, о: &Обстановка) -> Раскладка {
    let mut л = Лист::новый(ш, о.м, о.мерка);
    match с {
        Страница::Сейчас => сейчас(&mut л, к, о.сейчас),
        Страница::КтоЕст => кто_ест(&mut л, к, о.сейчас),
        Страница::ЧтоСделал => что_сделал(&mut л, к, о.сейчас),
        Страница::Видеокарта => видеокарта(&mut л, к, о.сейчас),
        Страница::Загрузки => загрузки(&mut л, к, о.сейчас),
        Страница::Барс => барс(&mut л, к, о.сейчас),
        Страница::Настройки => настройки(&mut л, к, о.сейчас),
    }
    л.готово()
}

/// Сводка свежая — верим; старая или нет — `None` (окно пишет «нет данных», а не старые числа).
fn сводка(к: &Картина, сейчас: u64) -> Option<&Сводка> {
    к.сводка.as_ref().filter(|с| сейчас.saturating_sub(с.мс) <= СВОДКА_СВЕЖА_МС)
}

const НЕТ_СВОДКИ: &str = "Мозг не прислал сводку (sejchas.json)";

fn держит_строки(к: &Картина, сейчас: u64) -> Vec<(String, Тон)> {
    let mut в = Vec::new();
    for и in &к.держит.изменения {
        в.push((format!("{}: {}{} — верну, когда затихнет 2 мин или ты её откроешь", и.имя, что_изменил(&и.что),
            if и.разработка { " (программа разработки)" } else { "" }), Тон::Работаю));
    }
    if !к.держит.замершие.is_empty() {
        let сколько = к.держит.замершие_с_мс.map(|с| format!(" уже {}", длительность(сейчас.saturating_sub(с) / 1000))).unwrap_or_default();
        в.push((format!("придержал {} на миг{сколько} — это пауза, не сбой; отпущу сам (до 2 мин)",
            число(к.держит.замершие.len() as u64, ["процесс", "процесса", "процессов"])), Тон::Вернул));
    }
    if let Some(pid) = к.держит.разум_ниже {
        в.push((format!("разум БАРСа (процесс {pid}) думает в промежутках, пока идут твои сборки"), Тон::Работаю));
    }
    if let Some(с) = сводка(к, сейчас) {
        if с.копия_медленнее { в.push(("копия ПК на Box — медленнее, пока идёт видео".into(), Тон::Приглушённый)); }
        if с.сборкам_ниже > 0 {
            в.push((format!("сборкам и тестам процессор — во вторую очередь ({})", с.сборкам_ниже), Тон::Приглушённый));
        }
    }
    в
}

fn сейчас(л: &mut Лист, к: &Картина, сейчас: u64) {
    л.заголовок("Сейчас", None);
    let св = сводка(к, сейчас);
    // нужна его рука
    let mut рука: Vec<(String, Тон)> = к.значок.iter().flat_map(|з| з.причины.iter())
        .filter(|п| matches!(п.состояние, Состояние::Внимание | Состояние::Тревога))
        .map(|п| (п.текст.clone(), if п.состояние == Состояние::Тревога { Тон::Тревога } else { Тон::Внимание })).collect();
    let c_гб = св.and_then(|с| с.сейчас.c_своб_гб).or(к.свои.c_своб_гб);
    if рука.is_empty() {
        if let Some(г) = c_гб.filter(|г| *г < 25) {
            рука.push((format!("диск C: свободно {г} ГБ — что удалить, решаешь ты; «Механик» ничего не удаляет"), Тон::Внимание));
        }
    }
    if !рука.is_empty() {
        let mut кар = Карточка::новая("Нужна твоя рука").точка(if рука.iter().any(|(_, т)| *т == Тон::Тревога) { Тон::Тревога } else { Тон::Внимание });
        for (т, тон) in рука { кар = кар.строка(т, тон); }
        л.сетка(vec![кар], 9999);
    }
    // шесть карточек
    let н = св.map(|с| &с.сейчас);
    let экран = match н.filter(|н| !н.гпу_мс.is_empty()) {
        Some(н) => {
            let mut в = н.гпу_мс.clone();
            в.sort_by(f64::total_cmp);
            let (средина, макс) = (в[в.len() / 2], в[в.len() - 1]);
            let тон = if макс >= 50.0 || средина >= 16.0 { Тон::Внимание } else { Тон::Норма };
            Карточка::новая(&format!("Экран{}", св.and_then(|с| с.экран_имя.as_deref()).map(|и| format!(" ({})", короче_адаптер(и))).unwrap_or_default()))
                .точка(тон).крупно(format!("{} мс", дробь(средина, 0)), Тон::Текст)
                .строка(format!("наибольшее {} мс за 2 с · норма до 16", дробь(макс, 0)), Тон::Приглушённый)
        }
        None => Карточка::новая("Экран").точка(Тон::Слабый).крупно("нет данных", Тон::Слабый).строка(НЕТ_СВОДКИ, Тон::Слабый),
    };
    let цп_весь = н.and_then(|н| н.цп_весь).or(к.свои.цп_весь);
    let mut процессор = Карточка::новая("Процессор");
    процессор = match цп_весь { Some(д) => процессор.точка(Тон::Норма).крупно(format!("занят {} %", дробь(д * 100.0, 0)), Тон::Текст),
        None => процессор.точка(Тон::Слабый).крупно("нет данных", Тон::Слабый) };
    процессор = match н.and_then(|н| н.цп_опоздал_мс) {
        Some(о) if о >= 100.0 => процессор.точка(Тон::Внимание).строка(format!("твоим программам не хватает процессора: поток опоздал на {} мс", дробь(о, 0)), Тон::Внимание),
        Some(о) => процессор.строка(format!("поток просыпается вовремя ({} мс)", дробь(о, 0)), Тон::Приглушённый),
        None => процессор.строка("опоздание потока — нет данных", Тон::Слабый),
    };
    let озу = н.and_then(|н| н.озу_своб_мб.zip(н.озу_всего_мб)).or(к.свои.озу_своб_мб.zip(к.свои.озу_всего_мб));
    let выделено = н.and_then(|н| н.выделено_своб_мб.zip(н.выделено_предел_мб)).or(к.свои.выделено_своб_мб.zip(к.свои.выделено_предел_мб));
    let mut память = Карточка::новая("Память");
    память = match озу {
        Some((с, в)) => память.точка(if с < 1024 { Тон::Тревога } else if с < 3072 { Тон::Внимание } else { Тон::Норма })
            .крупно(format!("свободно {} из {}", объём(с), объём(в)), Тон::Текст),
        None => память.точка(Тон::Слабый).крупно("нет данных", Тон::Слабый),
    };
    if let Some((с, п)) = выделено {
        let тон = if с < 2048 { Тон::Тревога } else if с < 2560 { Тон::Внимание } else { Тон::Приглушённый };
        память = память.строка(format!("выделено {} из {} (свободно {})", объём(п.saturating_sub(с)), объём(п), объём(с)), тон);
    }
    let mut диск = Карточка::новая("Диск");
    диск = match c_гб {
        Some(г) => диск.точка(if г < 25 { Тон::Внимание } else { Тон::Норма }).крупно(format!("C: свободно {г} ГБ"), Тон::Текст),
        None => диск.точка(Тон::Слабый).крупно("нет данных", Тон::Слабый),
    };
    диск = match н.and_then(|н| н.диск_занят) {
        Some(д) => диск.строка(format!("занят {} % (тормоз — от 90 %)", дробь(д, 0)), if д >= 90.0 { Тон::Внимание } else { Тон::Приглушённый }),
        None => диск.строка("занятость — нет данных", Тон::Слабый),
    };
    let нв = карточка_nvidia(к, сейчас);
    let mut ты = Карточка::новая("Ты за ПК");
    let ввод = н.and_then(|н| н.ввод_с).or(к.свои.ввод_с);
    let видео = н.and_then(|н| н.видео).or(к.барс.as_ref().and_then(|б| б.видео));
    ты = match ввод {
        Some(в) => ты.точка(if в < 120 || видео == Some(true) { Тон::Норма } else { Тон::Слабый })
            .крупно(if в < 2 { "ввод только что".to_string() } else { format!("ввод {}", назад(в)) }, Тон::Текст),
        None => ты.точка(Тон::Слабый).крупно("нет данных", Тон::Слабый),
    };
    if видео == Some(true) { ты = ты.строка("играет видео — ради него разум БАРСа не уступает", Тон::Приглушённый); }
    ты = ты.строка("лечу тормоза, только когда ты за ПК", Тон::Слабый);
    л.сетка(vec![экран, процессор, память, диск, нв, ты], 250);
    // тормоз и лечение сейчас
    if let Some(т) = св.and_then(|с| с.тормоз.as_ref()) {
        л.раздел("Тормозит сейчас");
        л.пункт(&format!("{}: {}", длительность(сейчас.saturating_sub(т.с_мс) / 1000),
            т.признаки.iter().map(|п| класс_словами(п)).collect::<Vec<_>>().join(", ")), Тон::Внимание, Тон::Текст);
        if !т.причина.is_empty() { л.абзац(&запятые(&т.причина), Шрифт::Мелкий, Тон::Приглушённый); }
        if let Some(л_) = св.and_then(|с| с.лечение.as_ref()) {
            л.пункт(&format!("делаю: {} ({})", ступень_словами(&л_.ступень), л_.кому), Тон::Работаю, Тон::Текст);
        }
    }
    л.раздел("Сейчас держу");
    let д = держит_строки(к, сейчас);
    if д.is_empty() { л.абзац("ничего — всё вернул", Шрифт::Обычный, Тон::Приглушённый); }
    for (т, тон) in д { л.пункт(&т, тон, Тон::Текст); }
    л.раздел("Последнее");
    let сл = случаи(&к.события);
    if сл.is_empty() { л.абзац("в журнале пока ничего (или журнала нет)", Шрифт::Обычный, Тон::Слабый); }
    for с in сл.iter().rev().take(3) {
        let (а, б, в, тон) = случай_словами(с);
        л.пункт(&а, тон, Тон::Текст);
        if !б.is_empty() { л.абзац(&б, Шрифт::Мелкий, Тон::Приглушённый); }
        л.абзац(&в, Шрифт::Мелкий, тон);
    }
    if let Some(с) = св.filter(|с| !с.график.is_empty()) {
        л.раздел(&format!("Экран за {}", длительность(с.график.len() as u64 * с.график_шаг_с.max(1))));
        график(л, &с.график);
    }
}

/// Столбики ожидания экрана (наибольшее за окно), шкала — до 100 мс; выше 50 — жёлтым, выше 100 — красным.
fn график(л: &mut Лист, ряд: &[f64]) {
    let в = л.px(60);
    let ш = л.ш;
    let н = ряд.len().max(1) as i32;
    let шаг = (ш / н).max(1);
    л.р.фигуры.push(Фигура::Плашка { п: Прям::новый(0, л.y, ш, в), тон: Тон::Карточка, рамка: Some(Тон::Рамка), радиус: л.px(6) });
    for (и, з) in ряд.iter().enumerate() {
        let h = ((з.min(100.0) / 100.0) * (в - л.px(8)) as f64).round().max(1.0) as i32;
        let тон = if *з >= 100.0 { Тон::Тревога } else if *з >= 50.0 { Тон::Внимание } else { Тон::Работаю };
        let x = и as i32 * шаг + 1;
        л.р.фигуры.push(Фигура::Плашка { п: Прям::новый(x, л.y + в - л.px(4) - h, (шаг - 1).max(1), h), тон, рамка: None, радиус: 0 });
    }
    л.y += в + л.px(4);
    л.р.текст.push(format!("экран, мс: {}", ряд.iter().map(|з| дробь(*з, 0)).collect::<Vec<_>>().join(" ")));
}

fn короче_адаптер(и: &str) -> String {
    и.replace("(R)", "").replace("(TM)", "").replace("  ", " ").replace(" GPU", "").trim().to_string()
}

fn карточка_nvidia(к: &Картина, сейчас: u64) -> Карточка {
    let mut кар = Карточка::новая("Видеокарта NVIDIA");
    if let Some(н) = сводка(к, сейчас).and_then(|с| с.нвидиа.as_ref()) {
        let зажата = н.зажата_с.is_some();
        кар = кар.точка(if зажата { Тон::Тревога } else { Тон::Норма });
        кар = match (н.предел_вт, н.обычный_вт) {
            (Some(п), Some(о)) => кар.крупно(format!("{} из {} Вт{}", дробь(п, 0), дробь(о, 0),
                н.ступень.as_ref().map(|с| format!(" · {с}")).unwrap_or_default()), if зажата { Тон::Тревога } else { Тон::Текст }),
            _ => кар.крупно("не мерю — видеокарта спит", Тон::Приглушённый),
        };
        if let Some(с) = н.зажата_с { кар = кар.строка(format!("зажата {} — лечу сам", длительность(с)), Тон::Тревога); }
        кар = кар.строка(format!("{}{}", match н.от_сети { Some(true) => "от сети", Some(false) => "от батареи", None => "питание — не знаю" },
            н.видеопамять_мб.map(|в| format!(" · видеопамять {}", объём(в))).unwrap_or_default()), Тон::Приглушённый);
        return кар;
    }
    match &к.видеокарта.замер {
        Some((п, о, ст, вп, зажата, мс)) => {
            кар = кар.точка(if *зажата { Тон::Внимание } else { Тон::Норма });
            if let (Some(п), Some(о)) = (п, о) {
                кар = кар.крупно(format!("{} из {} Вт{}", дробь(*п, 0), дробь(*о, 0), ст.as_ref().map(|с| format!(" · {с}")).unwrap_or_default()), Тон::Текст);
            }
            кар = кар.строка(format!("последний замер в {}{}{}", время(*мс), вп.map(|в| format!(" · видеопамять {}", объём(в))).unwrap_or_default(),
                if *зажата { " · была зажата" } else { "" }), Тон::Приглушённый);
            кар
        }
        None => кар.точка(Тон::Слабый).крупно("нет данных", Тон::Слабый).строка("замеров в журнале нет (меряю только от сети и когда она занята)", Тон::Слабый),
    }
}

fn кто_ест(л: &mut Лист, к: &Картина, сейчас: u64) {
    let св = сводка(к, сейчас);
    let цп = св.and_then(|с| с.сейчас.цп_весь).or(к.свои.цп_весь);
    let озу = к.свои.озу_своб_мб.zip(к.свои.озу_всего_мб);
    let подпись = format!("процессор {} · в ОЗУ занято {}{}",
        цп.map(|д| format!("{} %", дробь(д * 100.0, 0))).unwrap_or_else(|| "—".into()),
        озу.map(|(с, в)| format!("{} из {}", объём(в.saturating_sub(с)), объём(в))).unwrap_or_else(|| "—".into()),
        if св.is_some() { "" } else { " · классы — по своим правилам окна (Мозг сводку не прислал)" });
    л.заголовок("Кто ест", Some(подпись));
    let Some(группы) = к.кто.as_ref() else {
        л.абзац("считаю… первый снимок процессов — через 2 с", Шрифт::Обычный, Тон::Приглушённый);
        return;
    };
    // важность: что он смотрит первым — процессор, ОЗУ и что «Механик» сделал; выделено и экран — первыми долой, если узко
    let столбцы = [("Кто", 0, 9), ("Проц.", 70, 8), ("ОЗУ", 80, 7), ("Выделено", 90, 1), ("Диск", 76, 3), ("Экран", 64, 2),
        ("NVIDIA", 70, 4), ("Механик", 220, 6)];
    let mut строки: Vec<(Vec<String>, Тон, bool, bool)> = Vec::new();
    let доля = |я: f64| if я < 0.05 { "0".to_string() } else { format!("{} яд.", дробь(я, 1)) };
    let диск = |д: f64| if д < 0.5 { String::new() } else { format!("{} МБ/с", дробь(д, 0)) };
    let проц = |п: Option<f64>| п.filter(|п| *п >= 0.5).map(|п| format!("{} %", дробь(п, 0))).unwrap_or_default();
    for г in группы.iter() {
        let и = &г.итог;
        // заголовок группы — строкой на всю ширину: «Твои программы в фоне» в узкий столбец не влезает
        let диск_г = диск(и.диск_мб_с);
        строки.push((vec![format!("{} — {} · процессор {} · в ОЗУ {}{}", и.имя,
            число(и.штук as u64, ["процесс", "процесса", "процессов"]), доля(и.ядер), объём(и.озу_мб),
            if диск_г.is_empty() { String::new() } else { format!(" · диск {диск_г}") })], Тон::Текст, true, false));
        for с in г.строки.iter().take(8) {
            let имя = if с.штук > 1 { format!("{} ×{}", с.имя, с.штук) } else { с.имя.clone() };
            let имя = match &с.род { Some(р) => format!("{имя} — {р}"), None => имя };
            строки.push((vec![имя, доля(с.ядер), объём(с.озу_мб), объём(с.выделено_мб), диск(с.диск_мб_с), проц(с.экран), проц(с.нвидиа),
                с.метка.clone().unwrap_or_default()], Тон::Текст, false, true));
        }
        if г.строки.len() > 8 {
            строки.push((vec![format!("ещё {}", число((г.строки.len() - 8) as u64, ["программа", "программы", "программ"]))],
                Тон::Слабый, false, true));
        }
    }
    л.таблица(&столбцы, &строки);
    л.пробел(10);
    л.абзац("Кнопки «Завершить» нет и не будет — «Механик» твои программы не закрывает и не убивает. Порядок: ты → твоя \
        работа → БАРС (думает в промежутках) → фон.", Шрифт::Мелкий, Тон::Слабый);
}

fn что_сделал(л: &mut Лист, к: &Картина, сейчас: u64) {
    л.заголовок("Что сделал", Some("Тормоз → что сделал → чем кончилось → когда вернул. О тормозах «Механик» не уведомляет — \
        всё здесь.".into()));
    л.раздел("Сейчас держу");
    let д = держит_строки(к, сейчас);
    if д.is_empty() { л.абзац("ничего — всё вернул", Шрифт::Обычный, Тон::Приглушённый); }
    for (т, тон) in д { л.пункт(&т, тон, Тон::Текст); }
    let и = итоги(&к.события, полночь_мс(сейчас));
    л.раздел("Сегодня");
    л.абзац(&format!("{} (при тебе {}) · вылечил {} · прошло после действия {} · прошло само {} · лечить было нечего {} · вернул {}",
        число(и.тормозов, ["тормоз", "тормоза", "тормозов"]), и.при_нём, и.вылечил, и.прошло_после, и.само, и.нечего, и.вернул),
        Шрифт::Обычный, Тон::Текст);
    л.раздел("Случаи (новые сверху)");
    let сл = случаи(&к.события);
    if сл.is_empty() { л.абзац("в журнале за двое суток случаев нет (или журнала нет)", Шрифт::Обычный, Тон::Слабый); }
    for с in сл.iter().rev().take(30) {
        let (а, б, в, тон) = случай_словами(с);
        л.пункт(&format!("{} {}", дата_день(с.начало_мс, сейчас), а), тон, Тон::Текст);
        if !б.is_empty() { л.абзац(&б, Шрифт::Мелкий, Тон::Приглушённый); }
        л.абзац(&в, Шрифт::Мелкий, тон);
        л.пробел(4);
    }
    л.раздел("Опыт: что помогает");
    if к.опыт.is_empty() { л.абзац("опыта ещё нет (opyt.json)", Шрифт::Обычный, Тон::Слабый); }
    for о in &к.опыт {
        let т = format!("{} · {} — помогло {} из {}{}", класс_словами(&о.класс), ступень_словами(&о.ступень), о.помогло, о.раз,
            if о.выключена { " — сутки не беру: шесть раз без пользы" } else { "" });
        л.пункт(&т, if о.выключена { Тон::Слабый } else if о.помогло > 0 { Тон::Норма } else { Тон::Приглушённый }, Тон::Текст);
    }
    л.раздел("Сам «Механик»");
    let час = сводка(к, сейчас).and_then(|с| с.час.as_ref()).and_then(|ч| ч.доля_ядра)
        .or_else(|| к.события.iter().rev().find(|с| с.имя == "сторож_тормозов_час").and_then(|с| с.д.get("доля_ядра_проц")).and_then(|д| д.as_f64()));
    л.абзац(&format!("версия {} · работает {} · цена за час {}", к.мозг.версия.clone().unwrap_or_else(|| "—".into()),
        к.мозг_с_мс.map(|с| длительность(сейчас.saturating_sub(с) / 1000)).unwrap_or_else(|| "—".into()),
        час.map(|ч| format!("{} % одного ядра", дробь(ч, 2))).unwrap_or_else(|| "—".into())), Шрифт::Обычный, Тон::Приглушённый);
}

