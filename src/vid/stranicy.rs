#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Шрифт { Заголовок, Крупный, Обычный, Жирный, Мелкий, Знаки }

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Тон { Фон, Карточка, Рамка, Текст, Приглушённый, Слабый, Норма, Работаю, Внимание, Тревога, Вернул, Выбор, Наведение }

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Ровно { Лево, Центр, Право }

#[derive(Clone, Debug, PartialEq)]
pub enum Фигура {
    /// Закрашенный прямоугольник (скруглённый, если радиус > 0), с рамкой или без.
    Плашка { п: Прям, тон: Тон, рамка: Option<Тон>, радиус: i32 },
    /// Одна строка текста в прямоугольнике (не влезла — «…»).
    Текст { п: Прям, т: String, шрифт: Шрифт, тон: Тон, ровно: Ровно },
    Точка { x: i32, y: i32, р: i32, тон: Тон },
}

impl Фигура {
    #[cfg(test)]
    pub fn прям(&self) -> Прям {
        match self {
            Фигура::Плашка { п, .. } | Фигура::Текст { п, .. } => *п,
            Фигура::Точка { x, y, р, .. } => Прям { лев: x - р, верх: y - р, прав: x + р, низ: y + р },
        }
    }
}

