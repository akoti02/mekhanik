/// Чистая (видно в тесте): «1 тормоз», «3 тормоза», «5 тормозов».
pub fn число(н: u64, формы: [&str; 3]) -> String {
    let (д, с) = (н % 10, н % 100);
    let ф = if д == 1 && с != 11 { формы[0] } else if (2..=4).contains(&д) && !(12..=14).contains(&с) { формы[1] } else { формы[2] };
    format!("{н} {ф}")
}

/// Чистая (видно в тесте): дробь с запятой — «0,66», «3,9».
pub fn дробь(x: f64, знаков: usize) -> String { format!("{x:.знаков$}").replace('.', ",") }

/// Чистая (видно в тесте): объём из МБ — «8,7 ГБ», «512 МБ», «120 ГБ».
pub fn объём(мб: u64) -> String {
    if мб < 1000 { return format!("{мб} МБ"); }
    let гб = мб as f64 / 1024.0;
    if гб < 100.0 { format!("{} ГБ", дробь(гб, 1)) } else { format!("{} ГБ", гб.round() as u64) }
}

/// Чистая (видно в тесте): длительность — «40 с», «5 мин», «1 ч 17 мин», «2 сут 3 ч».
pub fn длительность(с: u64) -> String {
    match с {
        0..=59 => format!("{с} с"),
        60..=3599 => format!("{} мин", с / 60),
        3600..=86_399 => if с % 3600 / 60 == 0 { format!("{} ч", с / 3600) } else { format!("{} ч {} мин", с / 3600, с % 3600 / 60) },
        _ => if с % 86_400 / 3600 == 0 { format!("{} сут", с / 86_400) } else { format!("{} сут {} ч", с / 86_400, с % 86_400 / 3600) },
    }
}

pub fn назад(с: u64) -> String { if с < 2 { "только что".into() } else { format!("{} назад", длительность(с)) } }

/// Время его часами: «20:14».
pub fn время(мс: u64) -> String {
    use chrono::TimeZone;
    chrono::Local.timestamp_millis_opt(мс as i64).single().map(|т| т.format("%H:%M").to_string()).unwrap_or_else(|| "—".into())
}

/// «13.11 20:14».
pub fn дата_время(мс: u64) -> String {
    use chrono::TimeZone;
    chrono::Local.timestamp_millis_opt(мс as i64).single().map(|т| т.format("%d.%m %H:%M").to_string()).unwrap_or_else(|| "—".into())
}

/// Чистая (видно в тесте): точка между цифрами — запятой («6.2 ядра» → «6,2 ядра»): строки Мозга пишут точку.
pub fn запятые(т: &str) -> String {
    let з: Vec<char> = т.chars().collect();
    з.iter().enumerate().map(|(н, &с)| {
        let цифра = |к: Option<&char>| к.is_some_and(|к| к.is_ascii_digit());
        if с == '.' && н > 0 && цифра(з.get(н - 1)) && цифра(з.get(н + 1)) { ',' } else { с }
    }).collect()
}

/// Чистая (видно в тесте): ступень лечения — словами для окна (vid.md §9).
pub fn ступень_словами(с: &str) -> String {
    let (ступень, кому) = с.split_once(": ").map(|(а, б)| (а, Some(б))).unwrap_or((с, None));
    let слова = match ступень {
        "сборки замереть" => "придержал сборки до 2 мин (пауза, не сбой)",
        "выжать память простаивающих" => "освободил ОЗУ у простаивающих программ",
        "выгрузить простаивающий 27B" => "попросил БАРС выгрузить простаивающий разум",
        "фону — процессор ниже" => "процессор ему — во вторую очередь",
        "фону — диск и память ниже" | "фону — диск ниже" => "диск ему — в последнюю очередь",
        "фону — видеокарта ниже" => "видеокарта ему — во вторую очередь",
        д => д,
    };
    match кому { Some(к) => format!("{слова} ({})", запятые(к)), None => слова.to_string() }
}

