/// Чистая (видно в тесте): случай одной-тремя строками (время · длительность · что было; причина; что сделал и итог).
pub fn случай_словами(сл: &Случай) -> (String, String, String, Тон) {
    let mut первая = время(сл.начало_мс);
    if сл.заранее { первая += " · заранее, до тормоза: запас памяти таял"; }
    else {
        первая += &format!(" · тормоз{}", сл.длилось_с.map(|с| format!(" {}", длительность(с))).unwrap_or_default());
        if сл.при_нём == Some(false) { первая += " · без тебя"; }
    }
    let признаки: Vec<&str> = сл.признаки.iter().map(|п| класс_словами(п)).collect();
    if !признаки.is_empty() { первая += &format!(" · {}", признаки.join(", ")); }
    let (итог, тон) = исход_словами(сл);
    let mut третья = if сл.сделано.is_empty() { итог } else {
        format!("сделал: {} → {итог}", сл.сделано.iter().map(|с| ступень_словами(с)).collect::<Vec<_>>().join("; "))
    };
    for (мс, кому) in &сл.вернул { третья += &format!(" → вернул в {}: {}", время(*мс), кому); }
    (первая, запятые(&сл.причина), третья, тон)
}

