    fn проверить(р: &Раскладка, ш: i32, что: &str) {
        assert!(!р.фигуры.is_empty(), "{что}: пусто");
        for ф in &р.фигуры {
            let п = ф.прям();
            assert!(п.лев >= 0 && п.прав <= ш, "{что}: фигура за краем ({п:?}) при ширине {ш}: {ф:?}");
            assert!(п.верх >= 0 && п.низ <= р.высота, "{что}: фигура ниже листа ({п:?}, высота {}): {ф:?}", р.высота);
        }
        // кнопки не налезают друг на друга
        for (н, (а, _)) in р.кнопки.iter().enumerate() {
            for (б, _) in &р.кнопки[н + 1..] { assert!(!а.пересекает(б), "{что}: кнопки налезают {а:?} {б:?}"); }
        }
        // тексты не налезают друг на друга
        let тексты: Vec<&Фигура> = р.фигуры.iter().filter(|ф| matches!(ф, Фигура::Текст { .. })).collect();
        for (н, а) in тексты.iter().enumerate() {
            for б in &тексты[н + 1..] {
                assert!(!а.прям().пересекает(&б.прям()), "{что}: тексты налезают {а:?} и {б:?}");
            }
        }
    }

    #[test]
    fn узкая_таблица_теряет_неважное() {
        let мерка = Мерка7(1.0);
        let столбцы = [("Кто", 0, 9), ("Проц.", 70, 8), ("ОЗУ", 80, 7), ("Выделено", 90, 1), ("Диск", 76, 3), ("Экран", 64, 2),
            ("NVIDIA", 70, 4), ("Механик", 210, 6)];
        let номера = |ш: i32| Лист::новый(ш, 1.0, &мерка).столбцы_влезают(&столбцы).into_iter().map(|(н, _)| н).collect::<Vec<_>>();
        assert_eq!(номера(1200), vec![0, 1, 2, 3, 4, 5, 6, 7], "широко — все");
        assert_eq!(номера(704), vec![0, 1, 2, 4, 6, 7], "окно по умолчанию — без «Выделено» и «Экран»");
        assert_eq!(номера(560), vec![0, 1, 2, 7], "узко — «Механик» держится дольше диска и NVIDIA");
        assert_eq!(номера(400), vec![0, 1, 2]);
        assert_eq!(номера(100), vec![0], "совсем узко — только «Кто»");
        let ш: i32 = Лист::новый(704, 1.0, &мерка).столбцы_влезают(&столбцы).iter().map(|(_, ш)| ш).sum();
        assert_eq!(ш, 704, "ширины в сумме — ровно лист");
    }

