/// Строка шапки справа: «Механик 1 ч 17 мин · БАРС 2 с · права ✓».
pub fn метки_шапки(к: &Картина, сейчас: u64) -> String {
    let мозг = match к.мозг.жизнь {
        ЖизньМозга::Жив => format!("Механик {}", к.мозг_с_мс.or(к.сводка.as_ref().and_then(|с| с.с_мс))
            .map(|с| длительность(сейчас.saturating_sub(с) / 1000)).unwrap_or_else(|| "работает".into())),
        ЖизньМозга::Молчит(с) => format!("Механик молчит {}", длительность(с)),
        ЖизньМозга::НеЗапущен => "Механик не запущен".into(),
        ЖизньМозга::Остановлен => "Механик остановлен".into(),
        ЖизньМозга::Выкладка => "Механик обновляется".into(),
    };
    let барс = match &к.барс {
        Some(б) if б.отметка_мс > 0 => format!("БАРС {}", назад(сейчас.saturating_sub(б.отметка_мс) / 1000)),
        _ => "БАРСа нет".into(),
    };
    let права = if к.видеокарта.установлено.is_some() { "права ✓" } else { "права —" };
    format!("{мозг} · {барс} · {права}")
}

/// Вторая строка шапки — итоги дня (от Мозга, а нет — по журналу).
pub fn итоги_шапки(к: &Картина, сейчас: u64) -> String {
    let (тормозов, вылечил, само, нечего, всё) = match к.значок.as_ref().and_then(|з| з.сегодня.as_ref()) {
        Some(с) => (с.тормозов, с.вылечил, с.само, с.нечего, с.всё_вернул),
        None => { let и = итоги(&к.события, полночь_мс(сейчас)); (и.тормозов, и.вылечил, и.само, и.нечего, к.держит.пусто()) }
    };
    format!("Сегодня: {} (вылечил {вылечил}, прошло само {само}, лечить было нечего {нечего}){}",
        число(тормозов, ["тормоз", "тормоза", "тормозов"]), if всё { ", всё вернул" } else { ", кое-что держу" })
}

pub fn тон_показа(п: Показ) -> Тон {
    match п { Показ::Спокойно => Тон::Норма, Показ::Работает => Тон::Работаю, Показ::Внимание => Тон::Внимание,
        Показ::Тревога => Тон::Тревога, Показ::Молчит | Показ::Пауза => Тон::Слабый }
}

/// Шапка окна: точка цвета значка и строка состояния, справа — метки; ниже — итоги дня (или `заметка` — что окно только
/// что сделало по его нажатию, пока она свежая).
pub fn шапка(к: &Картина, ш: i32, м: f32, мерка: &dyn Мерка, сейчас: u64, заметка: Option<&str>) -> Раскладка {
    let px = |d: i32| (d as f32 * м).round() as i32;
    let mut р = Раскладка::default();
    let (п, строка) = показ(к, сейчас);
    let вж = мерка.высота(Шрифт::Жирный);
    let вм = мерка.высота(Шрифт::Мелкий);
    let y1 = px(14);
    р.фигуры.push(Фигура::Точка { x: px(22), y: y1 + вж / 2, р: px(6), тон: тон_показа(п) });
    let метки = метки_шапки(к, сейчас);
    let ш_меток = (мерка.ширина(&метки, Шрифт::Мелкий) + px(4)).min(ш / 2);
    let mut x_меток = ш - px(16) - ш_меток;
    if к.проба || к.сводка.as_ref().is_some_and(|с| с.сейчас.проба) {
        let шп = мерка.ширина("ПРОБА", Шрифт::Мелкий) + px(12);
        x_меток -= шп + px(8);
        let пп = Прям::новый(x_меток + ш_меток + px(8), y1, шп, вж);
        р.фигуры.push(Фигура::Плашка { п: пп, тон: Тон::Внимание, рамка: None, радиус: px(4) });
        р.фигуры.push(Фигура::Текст { п: пп, т: "ПРОБА".into(), шрифт: Шрифт::Мелкий, тон: Тон::Фон, ровно: Ровно::Центр });
    }
    р.фигуры.push(Фигура::Текст { п: Прям::новый(px(38), y1, (x_меток - px(38) - px(12)).max(px(40)), вж), т: строка.clone(),
        шрифт: Шрифт::Жирный, тон: Тон::Текст, ровно: Ровно::Лево });
    р.фигуры.push(Фигура::Текст { п: Прям::новый(x_меток, y1, ш_меток, вж), т: метки.clone(), шрифт: Шрифт::Мелкий,
        тон: Тон::Приглушённый, ровно: Ровно::Право });
    let итог = заметка.map(str::to_string).unwrap_or_else(|| итоги_шапки(к, сейчас));
    р.фигуры.push(Фигура::Текст { п: Прям::новый(px(38), y1 + вж + px(4), ш - px(54), вм), т: итог.clone(), шрифт: Шрифт::Мелкий,
        тон: if заметка.is_some() { Тон::Работаю } else { Тон::Приглушённый }, ровно: Ровно::Лево });
    р.высота = y1 + вж + px(4) + вм + px(14);
    р.фигуры.push(Фигура::Плашка { п: Прям::новый(0, р.высота - px(1).max(1), ш, px(1).max(1)), тон: Тон::Рамка, рамка: None, радиус: 0 });
    р.текст = vec![строка, метки, итог];
    р
}

/// Меню страниц слева: знак + слово; выбранная — с полосой; под мышью — подсветка.
pub fn меню_страниц(текущая: Страница, наведена: Option<Страница>, верх: i32, ш: i32, м: f32, мерка: &dyn Мерка,
                    знаки: bool) -> Раскладка {
    let px = |d: i32| (d as f32 * м).round() as i32;
    let mut р = Раскладка::default();
    let в = px(36);
    let mut y = верх + px(10);
    for с in Страница::ВСЕ {
        let п = Прям::новый(px(8), y, ш - px(16), в);
        if с == текущая {
            р.фигуры.push(Фигура::Плашка { п, тон: Тон::Выбор, рамка: None, радиус: px(6) });
            р.фигуры.push(Фигура::Плашка { п: Прям::новый(px(8), y + px(9), px(3), в - px(18)), тон: Тон::Работаю, рамка: None, радиус: px(2) });
        } else if наведена == Some(с) {
            р.фигуры.push(Фигура::Плашка { п, тон: Тон::Наведение, рамка: None, радиус: px(6) });
        }
        let тон = if с == текущая { Тон::Текст } else { Тон::Приглушённый };
        let x_слова = if знаки {
            р.фигуры.push(Фигура::Текст { п: Прям::новый(px(22), y, px(20), в), т: с.знак().to_string(), шрифт: Шрифт::Знаки,
                тон, ровно: Ровно::Центр });
            px(52)
        } else { px(22) };
        let _ = мерка;
        р.фигуры.push(Фигура::Текст { п: Прям::новый(x_слова, y, ш - x_слова - px(10), в), т: с.слово().into(),
            шрифт: if с == текущая { Шрифт::Жирный } else { Шрифт::Обычный }, тон, ровно: Ровно::Лево });
        р.кнопки.push((п, Действие::Страница(с)));
        y += в + px(2);
    }
    р.высота = y;
    р
}

