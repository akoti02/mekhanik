/// Что делать на шаге уступки.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Уступить { Замереть, Держать, Отпустить, НеМы, Ничего }

/// Чистая (видно в тесте): решение на шаге по ожиданию работы экрана `мс`. `замерли` — наши процессы стоят уже
/// `шагов` шагов; `считаем` — БАРС считает или идёт сборка; `можно` — не в паузе «не мы»; `доля` — сколько времени за
/// 10 с они стояли.
pub fn уступить(мс: f64, замерли: bool, шагов: u32, считаем: bool, можно: bool, доля: f64) -> Уступить {
    if замерли {
        if мс < УСТУПКА_МС { return Уступить::Отпустить; }
        // экран опоздал и после 2 с замерших — виноваты не они: отпускаем и не держим
        if шагов >= ДЕРЖАТЬ_ШАГОВ { return Уступить::НеМы; }
        // половину времени стояли — пусть поработают (думают дальше, медленнее)
        if доля >= ДОЛЯ_ЗАМЕРШИХ { return Уступить::Отпустить; }
        return Уступить::Держать;
    }
    if мс >= УСТУПКА_МС && считаем && можно && доля < ДОЛЯ_ЗАМЕРШИХ { Уступить::Замереть } else { Уступить::Ничего }
}

/// Перерыв шага: ПК спал (сколько секунд) или «Механик» стоял, не получив процессора.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Перерыв { Сон(u64), Стоял(u64) }

/// Чистая (видно в тесте): шаг длился `шаг_мс`, а время без сна за него ушло на `без_сна_мс` (`None` — не узнать).
/// Шаг короче `ШАГ_ПЕРЕРЫВ` — не перерыв.
pub fn перерыв(шаг_мс: u64, без_сна_мс: Option<u64>) -> Option<Перерыв> {
    if шаг_мс < ШАГ_ПЕРЕРЫВ.as_millis() as u64 { return None; }
    Some(match без_сна_мс {
        Some(б) if шаг_мс.saturating_sub(б) >= 3_000 => Перерыв::Сон(шаг_мс.saturating_sub(б) / 1000),
        _ => Перерыв::Стоял(шаг_мс / 1000),
    })
}

/// Чистая (видно в тесте): 🟥 27.10 (его порядок 26.10) — опустить разум 27B ниже сборок (`Some(true)`), вернуть ему
/// его приоритет (`Some(false)`) или ничего. Сборки заняты, а он не ждёт ответа разума (его слово) — опустить; сборки
/// затихли на `РАЗУМ_ВЕРНУТЬ_ТИХО` — вернуть. На круг его слова БАРС поднимает движок сам (и потом возвращает прежний).
pub fn разум_ниже(сборки_ядер: f64, слово: bool, опущен: bool, тихо: Option<Duration>) -> Option<bool> {
    let заняты = сборки_ядер >= СБОРКИ_ЗАНЯТЫ_ЯДЕР;
    match (опущен, заняты) {
        (false, true) if !слово => Some(true),
        (true, false) if тихо.is_some_and(|т| т >= РАЗУМ_ВЕРНУТЬ_ТИХО) => Some(false),
        _ => None,
    }
}

/// Чистая (видно в тесте): приоритет процессора сборке — ниже обычного, только вниз: стоит выше — `Some`, уже ниже
/// (свой самый низкий у сборщика) — не трогаем.
pub fn приоритет_сборки(сейчас: u32) -> Option<u32> {
    (ранг_приоритета(сейчас) > ранг_приоритета(ПРИОРИТЕТ_СБОРОК)).then_some(ПРИОРИТЕТ_СБОРОК)
}

/// Чистая (видно в тесте): верх процессов по доле адаптера экрана — (имя, %, БАРС ли), от `порог` %.
pub fn верх_экрана(доли: &HashMap<u32, f64>, все: &[(u32, u32, String)], наши: &HashSet<u32>, сколько: usize, порог: f64)
    -> Vec<(String, f64, bool)> {
    let mut в: Vec<(u32, f64)> = доли.iter().filter(|(pid, д)| **pid != 0 && **д >= порог).map(|(p, д)| (*p, *д)).collect();
    в.sort_by(|а, б| б.1.total_cmp(&а.1));
    в.into_iter().take(сколько).map(|(pid, д)| (все.iter().find(|(п, _, _)| *п == pid).map(|(_, _, и)| и.clone())
        .unwrap_or_else(|| format!("процесс {pid}")), (д * 10.0).round() / 10.0, наши.contains(&pid))).collect()
}

/// Окна разработки: всё, что запущено из них (кроме них самих), — сборки и тесты. Список — у каждой машины свой:
/// `%LOCALAPPDATA%\mekhanik\nastroyki.json`, ключ `dev_windows` (имена программ); нет файла — только по имени сборщика.
static ОКНА_РАЗРАБОТКИ: std::sync::OnceLock<Vec<String>> = std::sync::OnceLock::new();

fn окна_разработки() -> &'static [String] {
    ОКНА_РАЗРАБОТКИ.get_or_init(|| std::fs::read_to_string(svyaz::папка().join("nastroyki.json")).ok()
        .and_then(|т| serde_json::from_str::<Value>(&т).ok())
        .and_then(|v| v.get("dev_windows").and_then(Value::as_array).map(|м| м.iter()
            .filter_map(|x| x.as_str().map(str::to_string)).collect()))
        .unwrap_or_default())
}

/// Сборка или тест — имя из `СБОРКИ` или потомок окна разработки.
pub fn сборка(pid: u32, все: &[(u32, u32, String)]) -> bool { сборка_по(pid, все, окна_разработки()) }

/// Чистая (видно в тесте): сборка или тест — имя из `СБОРКИ` или потомок окна из `окна` (до 8 колен), кроме процессов
/// самого окна. `все` — (номер, родитель, имя).
pub fn сборка_по(pid: u32, все: &[(u32, u32, String)], окна: &[String]) -> bool {
    let окно = |и: &str| окна.iter().any(|о| о.eq_ignore_ascii_case(и));
    let Some((_, родитель, имя)) = все.iter().find(|(п, _, _)| *п == pid) else { return false };
    if окно(имя) { return false; }
    if СБОРКИ.iter().any(|с| имя.eq_ignore_ascii_case(с)) { return true; }
    let mut р = *родитель;
    for _ in 0..8 {
        let Some((_, дальше, имя_р)) = все.iter().find(|(п, _, _)| *п == р) else { return false };
        if окно(имя_р) { return true; }
        if *дальше == р || *дальше == 0 { return false; }
        р = *дальше;
    }
    false
}

