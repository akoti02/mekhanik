/// Кандидаты лечения за окно — без неприкасаемых. Сборки и прочие программы разработки — с пометкой: их берёт только
/// ступень диска (26.10), и тогда, когда окно разработки впереди (`lechenie::трогать_можно`).
#[allow(clippy::too_many_arguments)]
fn кандидаты(было: &okna::Снимок, стало: &okna::Снимок, секунд: f64, гпу: &HashMap<u32, f64>, все: &[(u32, u32, String)],
             барс_н: &HashSet<u32>, передние: &HashSet<u32>, передний: Option<u32>, передний_имя: Option<&str>,
             свой_сеанс: Option<u32>) -> Vec<Кандидат> {
    let с = секунд.max(0.5);
    стало.iter().filter(|(pid, _)| **pid > 4).filter_map(|(pid, п)| {
        let б = было.get(pid)?;
        let свой = свой_сеанс.is_some() && okna::сеанс(*pid) == свой_сеанс;
        let разработка = сборка(*pid, все);
        if !lechenie::трогать_можно(*pid, &п.имя, разработка, передние, передний, передний_имя, барс_н, свой) { return None; }
        Some(Кандидат { pid: *pid, имя: п.имя.clone(), ядер: п.время.saturating_sub(б.время) as f64 / 1e7 / с,
            диск_мб_с: п.ввод_вывод.saturating_sub(б.ввод_вывод) as f64 / 1_048_576.0 / с,
            гпу: гпу.get(pid).copied().unwrap_or(0.0), рабочий_мб: п.рабочий >> 20, разработка })
    }).collect()
}

/// Сделать ступень (кроме выгрузки 27B — у неё ответ БАРСа): кого словами и подробности; `None` — неприменима.
fn применить(ст: Ступень, класс: Класс, л: &mut Лечение, кандидаты: &[Кандидат], сборки: &[(u32, String)],
             сборки_замерли: &mut Option<(Instant, Vec<u32>)>) -> Option<(String, Value)> {
    match ст {
        Ступень::Сборки => {
            if сборки_замерли.is_some() { return None; }
            let цели: Vec<u32> = сборки.iter().filter(|(_, и)| морозить_сборку(и)).map(|(p, _)| *p).collect();
            let з = заморозить_все(&цели);
            if з.is_empty() { return None; }
            let n = з.len();
            let кто: Vec<&str> = сборки.iter().filter(|(p, _)| з.contains(p)).map(|(_, и)| и.as_str()).collect();
            let подробно = json!({ "процессов": n, "кто": кто });
            *сборки_замерли = Some((Instant::now(), з));
            Some((format!("{n} сборщиков"), подробно))
        }
        Ступень::Выжать => {
            let цели = lechenie::цели(ст, кандидаты, &HashSet::new(), &л.выжимали);
            let (mut кого, mut мб) = (Vec::new(), 0u64);
            for (pid, имя) in цели {
                if okna::выжать(pid) {
                    л.выжимали.insert(pid, Instant::now());
                    мб += кандидаты.iter().find(|к| к.pid == pid).map(|к| к.рабочий_мб).unwrap_or(0);
                    кого.push(имя);
                }
            }
            if кого.is_empty() { return None; }
            Some((format!("{} простаивающих программ, ≈{} МБ ОЗУ", кого.len(), мб), json!({ "кого": кого, "рабочий_мб": мб })))
        }
        Ступень::ВыгрузитьРазум => None,
        Ступень::ПриоритетФона | Ступень::ДискФона | Ступень::ВидеокартаФона => {
            let уже: HashSet<(u32, Ступень)> = л.книга.записи.iter().map(|з| (з.pid, з.что)).collect();
            let (pid, имя) = lechenie::цели(ст, кандидаты, &уже, &л.выжимали).into_iter().next()?;
            let создан = okna::создан(pid)?;
            let (было, стало): (i64, i64) = match ст {
                Ступень::ПриоритетФона => {
                    let сейчас = okna::приоритет_сейчас(pid)?;
                    if ранг_приоритета(сейчас) <= ранг_приоритета(lechenie::НИЖЕ_ОБЫЧНОГО) { return None; }
                    let (б, с) = okna::приоритет(pid, lechenie::НИЖЕ_ОБЫЧНОГО)?;
                    (б as i64, с as i64)
                }
                // 🟥 26.10: и приоритет памяти — его чтение не вытесняет из памяти экран и его программы
                Ступень::ДискФона => {
                    let (б, с) = okna::очередь_диска(pid, Some(lechenie::ДИСК_ОЧЕНЬ_НИЗКО))?;
                    let п = okna::память_процесса(pid, Some(lechenie::ПАМЯТЬ_ОЧЕНЬ_НИЗКО));
                    (lechenie::было_диска(б, п.map(|(б, _)| б)), lechenie::было_диска(с, п.map(|(_, с)| с)))
                }
                _ => { let (б, с) = okna::понизить_видеокарту(pid, ОЧЕРЕДЬ_НИЖЕ)?; (б as i64, с as i64) }
            };
            if было == стало { return None; }
            let к = кандидаты.iter().find(|к| к.pid == pid);
            let разработка = к.is_some_and(|к| к.разработка);
            л.книга.добавить(Запись { pid, создан, имя: имя.clone(), что: ст, было, класс, разработка });
            let mut подробно = json!({ "pid": pid, "было": было, "стало": стало, "ядер": к.map(|к| (к.ядер * 10.0).round() / 10.0),
                "диск_мб_с": к.map(|к| к.диск_мб_с.round()), "видеокарта_проц": к.map(|к| к.гпу.round()),
                "разработка": разработка });
            if ст == Ступень::ДискФона {
                let ((дб, пб), (дс, пс)) = (lechenie::разобрать_диск(было), lechenie::разобрать_диск(стало));
                подробно["очередь_диска"] = json!(format!("{дб} → {дс}"));
                подробно["память"] = json!(match (пб, пс) { (Some(а), Some(б)) => format!("{а} → {б}"), _ => "не далась".into() });
            }
            Some((имя, подробно))
        }
    }
}

