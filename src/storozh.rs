/// 🟥 волна 2б: ЧЁРНЫЙ ЯЩИК — своим потоком под смотрителем `zhizn` (кадр раз в секунду, кольцо 10 мин, сброс на диск
/// раз в 5 с). При старте разбирает внезапное выключение по журналу Windows. Тело само крутит цикл (смотритель `zhizn`
/// перезапускает лишь при панике), поэтому журнал не засоряется.
fn запустить_ящик(вход: std::sync::Arc<std::sync::Mutex<ЯщикВход>>) {
    crate::zhizn::поток("yashchik", Duration::from_secs(1), move || {
        let папка = crate::yashchik::папка_ящика();
        if let Some(п) = &папка {
            if let Ok(Some((причина, когда))) = crate::yashchik::разобрать_падение(п, crate::yashchik::события_выключения) {
                журнал("механик_падение_пк", &json!({ "причина": причина.слово(), "когда_мс": когда }));
            }
        }
        let mut ящик = crate::yashchik::Ящик::новый(папка);
        loop {
            let сейчас = svyaz::сейчас_мс();
            if svyaz::просят_выйти() { let _ = ящик.сбросить(сейчас); return; }
            let (доступно, _, зачислено_своб) = okna::память();
            let общ = вход.lock().map(|г| г.clone()).unwrap_or_default();
            ящик.кадр(crate::yashchik::Кадр {
                когда_мс: сейчас, от_сети: okna::от_сети().unwrap_or(false), заряд: 0,
                доступно_мб: доступно.unwrap_or(0), зачислено_своб_мб: зачислено_своб.unwrap_or(0),
                видеопамять_нв_своб_мб: общ.видеопамять_нв_своб_мб, диск_занят: общ.диск_занят,
                передний_pid: okna::передний_pid().unwrap_or(0), за_пк: общ.за_пк, советов: общ.советов, верх: общ.верх,
            });
            if ящик.сброс_пора(сейчас) { let _ = ящик.сбросить(сейчас); }
            std::thread::sleep(Duration::from_secs(1));
        }
    });
}

