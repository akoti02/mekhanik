#[derive(Clone, Debug, PartialEq)]
pub struct Процесс { pub имя: String, pub ядер: f64, pub промахов_с: f64, pub память_мб: u64, pub диск_мб_с: f64, pub наш: bool }

/// Чистая (видно в тесте): виновник тормоза словами и БАРС ли он — `(барс, словами)`. `работа_барса` — что БАРС делал;
/// `экран` — верх процессов по адаптеру экрана (`верх_экрана`).
pub fn виновник(п: &[Признак], работа_барса: &[String], процессы: &[Процесс], диск_занят: Option<f64>,
                экран: &[(String, f64, bool)]) -> (bool, String) {
    let на_видеокарте = |р: &String| !р.contains("судья экрана") && !р.contains("судья векторов");
    let мой_гпу: Vec<&String> = работа_барса.iter().filter(|р| на_видеокарте(р)).collect();
    let mut части = Vec::new();
    let mut барс = false;
    let mut память_сказана = false;
    for пр in п {
        match пр {
            Признак::Память { .. } | Признак::Зачислено(_) if память_сказана => {}
            // 🟥 27.10: 71 из 130 тормозов видеокарты звучали «грузил не БАРС» без имени — называем, кто грузил адаптер экрана
            Признак::Видеокарта { .. } => if мой_гпу.is_empty() {
                match экран.first() {
                    Some((и, д, true)) => { барс = true; части.push(format!("видеокарту экрана грузил БАРС: {и} — {д:.0} %")); }
                    Some((и, д, false)) => части.push(format!("видеокарту грузил не БАРС: на экране больше всех — {и} {д:.0} %")),
                    None => части.push("видеокарту грузил не БАРС (его движки на ней не работали; на адаптере экрана никто \
                        не выше 5 %)".to_string()),
                }
            } else {
                барс = true;
                let чужой = экран.first().filter(|(_, _, наш)| !наш)
                    .map(|(и, д, _)| format!("; на экране больше всех — {и} {д:.0} %")).unwrap_or_default();
                части.push(format!("видеокарту грузил БАРС: {}{чужой}", мой_гпу.iter().map(|s| s.as_str()).collect::<Vec<_>>().join(", ")));
            },
            Признак::Процессор(_) => if let Some(т) = процессы.iter().max_by(|а, б| а.ядер.total_cmp(&б.ядер)) {
                барс |= т.наш;
                части.push(format!("процессор: {} — {:.1} ядра{}", т.имя, т.ядер, if т.наш { " (БАРС)" } else { "" }));
            },
            Признак::Память { .. } | Признак::Зачислено(_) => {
                память_сказана = true;
                let наша: u64 = процессы.iter().filter(|р| р.наш).map(|р| р.память_мб).sum();
                let т = процессы.iter().filter(|р| !р.наш).max_by_key(|р| р.память_мб);
                let подкачка = процессы.iter().max_by(|а, б| а.промахов_с.total_cmp(&б.промахов_с)).filter(|р| р.промахов_с >= 50.0);
                барс |= т.is_none_or(|т| наша > т.память_мб * 2);
                части.push(format!("память: у БАРСа {:.1} ГБ{}{}", наша as f64 / 1024.0,
                    т.map(|т| format!(", больше всех из прочих — {} {:.1} ГБ", т.имя, т.память_мб as f64 / 1024.0)).unwrap_or_default(),
                    подкачка.map(|р| format!("; с диска подкачивал {} ({:.0} стр/с)", р.имя, р.промахов_с)).unwrap_or_default()));
            }
            Признак::Драйверы(_) => части.push("драйверы устройств (не БАРС)".into()),
            Признак::Висит(кто) => части.push(format!("зависло окно {кто}")),
        }
    }
    // 🟥 26.10 12:57–13:28: экран ждал 500 мс при 100 % диска от поиска по всей домашней папке, а виновник звучал только
    // «видеокарту грузил не БАРС» — называем и того, кто держит диск
    if let Some(д) = диск_занят.filter(|д| *д >= lechenie::ДИСК_ЗАНЯТ) {
        let т = процессы.iter().filter(|р| р.диск_мб_с >= lechenie::ПОЖИРАТЕЛЬ_ДИСК_МБ_С)
            .max_by(|а, б| а.диск_мб_с.total_cmp(&б.диск_мб_с));
        match т {
            Some(т) => {
                барс |= т.наш;
                части.push(format!("диск занят {д:.0} %: {} — {:.0} МБ/с{}", т.имя, т.диск_мб_с, if т.наш { " (БАРС)" } else { "" }));
            }
            None => части.push(format!("диск занят {д:.0} % (кто — не видно: подкачка или система)")),
        }
    }
    (барс, части.join("; "))
}

fn процессы_окна(было: &okna::Снимок, стало: &okna::Снимок, секунд: f64, наши: &HashSet<u32>) -> Vec<Процесс> {
    let mut в: Vec<Процесс> = стало.iter().filter(|(pid, _)| **pid != 0).filter_map(|(pid, п)| {
        let б = было.get(pid)?;
        Some(Процесс { имя: п.имя.clone(), ядер: п.время.saturating_sub(б.время) as f64 / 1e7 / секунд.max(0.5),
            промахов_с: п.промахи.saturating_sub(б.промахи) as f64 / секунд.max(0.5), память_мб: п.память >> 20,
            диск_мб_с: п.ввод_вывод.saturating_sub(б.ввод_вывод) as f64 / 1_048_576.0 / секунд.max(0.5),
            наш: наши.contains(pid) })
    }).collect();
    в.sort_by(|а, б| б.ядер.total_cmp(&а.ядер));
    в
}

fn кратко(п: &[Процесс], ключ: fn(&Процесс) -> f64, сколько: usize, порог: f64) -> Vec<Value> {
    let mut в: Vec<&Процесс> = п.iter().filter(|р| ключ(р) >= порог).collect();
    в.sort_by(|а, б| ключ(б).total_cmp(&ключ(а)));
    в.into_iter().take(сколько).map(|р| json!({ "имя": р.имя, "ядер": (р.ядер * 10.0).round() / 10.0,
        "промахов_с": р.промахов_с.round(), "память_мб": р.память_мб, "диск_мб_с": р.диск_мб_с.round(), "барс": р.наш })).collect()
}

