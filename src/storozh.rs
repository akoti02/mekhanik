/// Поток-страховщик (TIME_CRITICAL): раз в 100 мс смотрит `тик` (когда решения последний раз обновляли часы от `начало`);
/// молчат дольше `СТРАХОВЩИК_МС` — отпускает замороженных по файлу и ставит флаг `спасено`, чтобы главный поток не
/// отпускал их второй раз. Выходит, когда выкладка просит выйти.
fn запустить_страховщика(начало: Instant, тик: std::sync::Arc<std::sync::atomic::AtomicU64>,
                         спасено: std::sync::Arc<std::sync::atomic::AtomicBool>) {
    use std::sync::atomic::Ordering::Relaxed;
    let _ = std::thread::Builder::new().name("mekh-strahovshchik".into()).spawn(move || {
        let сон = okna::Сон::новый();
        okna::приоритет_потока(okna::ПОТОК_КРИТИЧНЫЙ);
        okna::поток_без_эко();
        let mut спасали_на = u64::MAX;
        loop {
            сон.спать(Duration::from_millis(100));
            if svyaz::просят_выйти() { return; }
            let сейчас = начало.elapsed().as_millis() as u64;
            let т = тик.load(Relaxed);
            // первый тик ещё не поставлен (0) — ждём; молчат дольше 1 с и это новое молчание — спасаем
            if т != 0 && пора_спасать(т, сейчас) && т != спасали_на {
                спасали_на = т;
                let n = спасти_замороженных();
                if n > 0 {
                    спасено.store(true, Relaxed);
                    журнал("механик_страховщик", &json!({ "отпущено": n,
                        "почему": "решения молчали дольше 1 с (повисла проба видеокарты) — отпустил замороженных" }));
                }
            }
        }
    });
}

