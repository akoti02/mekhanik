/// 🟥 14.11 (пакет «цена»): учёт цены сторожа по кускам одного окна. Копим время каждого куска за час (наносекунды,
/// монотонные часы — куски главного окна считают без снов, так что это и есть цена процессору); в часовую строку
/// `сторож_тормозов_час` кладём мкс на кусок. Какой кусок дороже — видно сразу, а стенд `examples/cena.rs` меряет те же
/// куски по отдельности. Накопители сбрасываются каждый час вместе с остальными часовыми счётчиками.
#[derive(Clone, Default)]
struct ЦенаКусков {
    снимок_нс: u128,
    видеокарта_нс: u128,
    внимание_нс: u128,
    kto_нс: u128,
    предвидение_нс: u128,
    арбитр_нс: u128,
    мост_нс: u128,
    лечение_нс: u128,
    окно_нс: u128,
    ящик_нс: u128,
}

impl ЦенаКусков {
    /// Мкс на кусок за час (округление до десятых) — для часовой строки.
    fn в_мкс(&self) -> Value {
        let м = |нс: u128| ((нс as f64 / 1000.0) * 10.0).round() / 10.0;
        json!({ "снимок": м(self.снимок_нс), "видеокарта": м(self.видеокарта_нс), "внимание": м(self.внимание_нс),
            "kto": м(self.kto_нс), "предвидение": м(self.предвидение_нс), "арбитр": м(self.арбитр_нс),
            "мост": м(self.мост_нс), "лечение": м(self.лечение_нс), "окно": м(self.окно_нс), "ящик": м(self.ящик_нс) })
    }
}

/// 🟥 14.11 (пакет «цена»): замерить кусок окна — время потока до и после (здесь монотонные часы: куски идут без снов,
/// так что это и есть цена процессору), прибавить к накопителю `нс`. Возвращает, что вернул кусок.
#[inline]
fn замерить<T>(нс: &mut u128, f: impl FnOnce() -> T) -> T {
    let т = Instant::now();
    let r = f();
    *нс += т.elapsed().as_nanos();
    r
}

/// 🟥 волна 2б: верх процессов для чёрного ящика — класс `kto`, память рабочего набора и видеопамять NVIDIA; до 8.
fn верх_ящика(картина: &Картина, снимок: &okna::Снимок) -> Vec<crate::yashchik::Верх> {
    let mut в: Vec<crate::yashchik::Верх> = картина.карточки().map(|к| {
        let мб = снимок.get(&к.личность.pid).map(|п| п.рабочий >> 20).unwrap_or(0);
        crate::yashchik::Верх { класс: к.решение.чей.слово().to_string(), имя: к.имя.clone(), мб, ядер: 0.0,
            видео_нв_мб: к.видео_нв_мб }
    }).collect();
    в.sort_by(|а, б| (б.видео_нв_мб, б.мб).cmp(&(а.видео_нв_мб, а.мб)));
    в.truncate(8);
    в
}

