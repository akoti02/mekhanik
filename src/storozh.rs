/// Признак тормоза.
#[derive(Clone, Debug, PartialEq)]
pub enum Признак { Видеокарта { макс: f64, средина: f64 }, Процессор(f64), Память { доступно: u64, подкачка: f64 },
    Зачислено(u64), Драйверы(f64), Висит(String) }

impl Признак {
    fn слово(&self) -> String {
        let ч = |x: f64| format!("{x:.0}");
        match self {
            Признак::Видеокарта { макс, средина } => format!("видеокарта: экран ждал до {} мс (обычно {} мс)", ч(*макс), ч(*средина)),
            Признак::Процессор(мс) => format!("процессор: программа ждала {} мс", ч(*мс)),
            Признак::Память { доступно, подкачка } => format!("память: доступно {} МБ, подкачка с диска {} стр/с", доступно, ч(*подкачка)),
            Признак::Зачислено(своб) => format!("зачисленная память на пределе: свободно {своб} МБ (Windows растит файл подкачки, \
                программам может не хватить)"),
            Признак::Драйверы(п) => format!("драйверы: прерывания {} % процессора", ч(*п)),
            Признак::Висит(кто) => format!("окно {кто} не отвечает"),
        }
    }
    fn вид(&self) -> &'static str {
        match self { Признак::Видеокарта { .. } => "видеокарта", Признак::Процессор(_) => "процессор",
            Признак::Память { .. } => "память", Признак::Зачислено(_) => "зачисленная", Признак::Драйверы(_) => "драйверы",
            Признак::Висит(_) => "окно" }
    }
}

/// Чистая (видно в тесте): признаки тормоза в окне.
pub fn признаки(о: &Окно) -> Vec<Признак> {
    let mut п = Vec::new();
    if !о.гпу.is_empty() {
        let mut г = о.гпу.clone();
        г.sort_by(f64::total_cmp);
        let макс = г[г.len() - 1];
        let средина = г[г.len() / 2];
        if макс >= ГПУ_МАКС_МС || средина >= ГПУ_СРЕДИНА_МС { п.push(Признак::Видеокарта { макс, средина }); }
    }
    if о.цп_опоздал >= ЦП_ОПОЗДАЛ_МС { п.push(Признак::Процессор(о.цп_опоздал)); }
    if let Some(д) = о.доступно_мб {
        let подкачка = о.подкачка_с.unwrap_or(0.0);
        if д < ДОСТУПНО_МАЛО_МБ || (д < ПОДКАЧКА_ДОСТУПНО_МБ && подкачка >= ПОДКАЧКА_ГРОЗА) {
            п.push(Признак::Память { доступно: д, подкачка });
        }
    }
    // 🟥 24.10 20:43 живьём: 27B поднялся снова — свободно зачисленной 290 МБ из 52,7 ГБ; в такие минуты Windows
    // отказывает программам в памяти (журнал Windows: «мало виртуальной памяти»)
    if let Some(с) = о.зачислено_своб_мб.filter(|с| *с < ЗАЧИСЛЕНО_МАЛО_МБ) { п.push(Признак::Зачислено(с)); }
    if о.драйверы_проц.is_some_and(|д| д >= ДРАЙВЕРЫ_ПРОЦ) { п.push(Признак::Драйверы(о.драйверы_проц.unwrap_or(0.0))); }
    if let Some(кто) = &о.висит { п.push(Признак::Висит(кто.clone())); }
    п
}

/// Тормоз начался или кончился.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Смена { Начался, Кончился }

/// Счёт окон: начало — признак в этом окне и хотя бы в двух из трёх последних; конец — `ЧИСТЫХ_ДО_КОНЦА` чистых подряд.
#[derive(Clone, Debug, Default)]
pub struct Счёт { последние: VecDeque<bool>, идёт: bool, чистых: u32 }

impl Счёт {
    pub fn шаг(&mut self, есть: bool) -> Option<Смена> {
        self.последние.push_back(есть);
        if self.последние.len() > 3 { self.последние.pop_front(); }
        if self.идёт {
            self.чистых = if есть { 0 } else { self.чистых + 1 };
            if self.чистых >= ЧИСТЫХ_ДО_КОНЦА { self.идёт = false; self.чистых = 0; return Some(Смена::Кончился); }
            return None;
        }
        if есть && self.последние.iter().filter(|x| **x).count() >= 2 {
            self.идёт = true;
            self.чистых = 0;
            return Some(Смена::Начался);
        }
        None
    }
}

