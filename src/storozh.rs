/// Построить снимок для `kto::Картина` из данных окна сторожа (только чтение). `все` — (pid, родитель, имя); поведение —
/// из снимков `okna`; видеокарта — доля счёта/3D (`гпу`) и декодер (`декодер`) по процессам; присутствие — передний pid,
/// во весь ли экран, какие процессы звучат; `барс_н` — процессы БАРСа (их часть берём из `svyaz::Барс`). Видеопамять,
/// паспорт файла и окна `Картина` добирает сама. Зовётся только когда снимок нужен (тормоз/лечение) — цена ограничена.
/// 🟥 14.11 (пакет «цена»): путь программы и сеанс процесса не меняются за его жизнь, а добывались живым `OpenProcess`
/// каждому процессу каждое окно (≈300 открытий ручек на 2 с). Читаем раз на личность (номер + время создания) и держим
/// в `пути_сеансы`; новому процессу — читаем, умершему — забываем. Ключ с временем отсекает чужой процесс, получивший
/// номер умершего (ему прочтётся заново).
#[allow(clippy::too_many_arguments)]
fn kto_снимок(когда_мс: u64, все: &[(u32, u32, String)], снимок: &okna::Снимок, снимок_был: &okna::Снимок, секунд: f64,
              гпу: &HashMap<u32, f64>, декодер: &HashMap<u32, f64>, барс_н: &HashSet<u32>, б: &Барс,
              передний: Option<u32>, весь_экран: bool, звук: &[u32], мой: u32,
              пути_сеансы: &mut HashMap<kto::Личность, (Option<String>, u32)>) -> kto::Снимок {
    let с = секунд.max(0.5);
    let mut живые: HashSet<kto::Личность> = HashSet::with_capacity(все.len());
    let процессы = все.iter().map(|&(pid, родитель, ref имя)| {
        let п = снимок.get(&pid);
        let создан = п.map(|p| p.создан).unwrap_or(0);
        let личность = kto::Личность { pid, создан };
        живые.insert(личность);
        // путь и сеанс неизменны за жизнь процесса — дорогой OpenProcess только новой личности
        let (путь, сеанс) = {
            let зап = пути_сеансы.entry(личность)
                .or_insert_with(|| (okna::путь_процесса(pid), okna::сеанс(pid).unwrap_or(1)));
            (зап.0.clone(), зап.1)
        };
        let ядер = match (снимок_был.get(&pid), п) {
            (Some(a), Some(c)) => c.время.saturating_sub(a.время) as f64 / 1e7 / с,
            _ => 0.0,
        };
        let барс = if !барс_н.contains(&pid) { None } else {
            Some(if б.окно == Some(pid) { kto::ЧастьБарса::Окно }
                else if б.голова == Some(pid) { kto::ЧастьБарса::Голова }
                else if б.разум_pid == Some(pid) { kto::ЧастьБарса::Разум }
                else if путь.as_deref().is_some_and(разум_по_пути) { kto::ЧастьБарса::Разум }
                else { kto::ЧастьБарса::Прочее })
        };
        kto::ВходПроцесса {
            pid, родитель,
            создан,
            сеанс,
            имя: имя.clone(),
            путь,
            ядер,
            личная_мб: п.map(|p| p.рабочий >> 20).unwrap_or(0),
            гпу: гпу.get(&pid).copied().unwrap_or(0.0),
            декодер: декодер.get(&pid).copied().unwrap_or(0.0),
            впереди: передний == Some(pid),
            весь_экран: передний == Some(pid) && весь_экран,
            звук: звук.contains(&pid),
            барс,
            сам: pid == мой,
            ..Default::default()
        }
    }).collect();
    // забыть пути/сеансы процессов, которых уже нет (и тех, чей номер достался другому — у личности иное время)
    пути_сеансы.retain(|л, _| живые.contains(л));
    kto::Снимок { когда_мс, процессы }
}

