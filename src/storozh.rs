    /// 🟥 13.11 (слепое пятно NVIDIA): его тяжёлое 3D/счёт на NVIDIA — по классу `kto` (его работа/он сам, тяжёлое, нужна
    /// NVIDIA или держит её видеопамять). Красный на старом: функции не было — сторож видел только Intel (проба на нём) и
    /// покой на NVIDIA (игра/27B делят её). Фон и БАРС сюда не идут; его работа без NVIDIA — тоже нет.
    #[test]
    fn его_тяжёлое_на_nvidia_узнаётся() {
        let реш = |чей, тяжёлое, nvidia| Решение { чей, род: kto::Род::Расчёт, уверенность: 0.8, уверенность_рода: 0.8,
            тяжёлое, нужно: kto::klassy::Нужда { nvidia, видеопамять: false, озу: false, процессор: тяжёлое },
            морозить_можно: false, неприкасаемый: false, часть_барса: None, защита: None, почему: Vec::new() };
        // игра/счёт его работы на NVIDIA (нужна nvidia)
        assert!(его_тяжёлое_на_nvidia_по(&реш(Чей::ЕгоРабота, true, true), 0));
        // держит видеопамять NVIDIA, хоть флаг nvidia и не стоял
        assert!(его_тяжёлое_на_nvidia_по(&реш(Чей::ЕгоРабота, true, false), 2048));
        // он сам (игра впереди) — тоже уступаем
        assert!(его_тяжёлое_на_nvidia_по(&реш(Чей::Он, true, true), 0));
        // его работа без NVIDIA (сборка на процессоре) — нет
        assert!(!его_тяжёлое_на_nvidia_по(&реш(Чей::ЕгоРабота, true, false), 0));
        // фон на NVIDIA — не его тяжёлое (ему NVIDIA не бережём)
        assert!(!его_тяжёлое_на_nvidia_по(&реш(Чей::Фон, true, true), 4096));
        // БАРС на NVIDIA (27B) — это и есть тот, кто уступает, не причина уступки
        assert!(!его_тяжёлое_на_nvidia_по(&реш(Чей::Барс, true, true), 8192));
        // не тяжёлое (просмотр уже отсеян классом) — нет
        assert!(!его_тяжёлое_на_nvidia_по(&реш(Чей::ЕгоРабота, false, true), 1024));
    }

