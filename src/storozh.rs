/// Что делать на шаге уступки.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Уступить { Замереть, Отпустить, НеМы, Ничего }

/// Чистая (видно в тесте): решение на шаге по ожиданию работы экрана `мс`. `замерли` — наши процессы стояли весь шаг
/// замера; `считаем` — БАРС считает или идёт сборка; `можно` — не в паузе «не мы».
pub fn уступить(мс: f64, замерли: bool, считаем: bool, можно: bool) -> Уступить {
    if замерли {
        // экран опоздал и при замерших — виноваты не они: отпускаем и не держим
        return if мс >= УСТУПКА_МС { Уступить::НеМы } else { Уступить::Отпустить };
    }
    if мс >= УСТУПКА_МС && считаем && можно { Уступить::Замереть } else { Уступить::Ничего }
}

/// Окна разработки: всё, что запущено из них (кроме них самих), — сборки и тесты. Список — у каждой машины свой:
/// `%LOCALAPPDATA%\mekhanik\nastroyki.json`, ключ `dev_windows` (имена программ); нет файла — только по имени сборщика.
static ОКНА_РАЗРАБОТКИ: std::sync::OnceLock<Vec<String>> = std::sync::OnceLock::new();

fn окна_разработки() -> &'static [String] {
    ОКНА_РАЗРАБОТКИ.get_or_init(|| std::fs::read_to_string(svyaz::папка().join("nastroyki.json")).ok()
        .and_then(|т| serde_json::from_str::<Value>(&т).ok())
        .and_then(|v| v.get("dev_windows").and_then(Value::as_array).map(|м| м.iter()
            .filter_map(|x| x.as_str().map(str::to_string)).collect()))
        .unwrap_or_default())
}

/// Сборка или тест — имя из `СБОРКИ` или потомок окна разработки.
pub fn сборка(pid: u32, все: &[(u32, u32, String)]) -> bool { сборка_по(pid, все, окна_разработки()) }

/// Чистая (видно в тесте): сборка или тест — имя из `СБОРКИ` или потомок окна из `окна` (до 8 колен), кроме процессов
/// самого окна. `все` — (номер, родитель, имя).
pub fn сборка_по(pid: u32, все: &[(u32, u32, String)], окна: &[String]) -> bool {
    let окно = |и: &str| окна.iter().any(|о| о.eq_ignore_ascii_case(и));
    let Some((_, родитель, имя)) = все.iter().find(|(п, _, _)| *п == pid) else { return false };
    if окно(имя) { return false; }
    if СБОРКИ.iter().any(|с| имя.eq_ignore_ascii_case(с)) { return true; }
    let mut р = *родитель;
    for _ in 0..8 {
        let Some((_, дальше, имя_р)) = все.iter().find(|(п, _, _)| *п == р) else { return false };
        if окно(имя_р) { return true; }
        if *дальше == р || *дальше == 0 { return false; }
        р = *дальше;
    }
    false
}

