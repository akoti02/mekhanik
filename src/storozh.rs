/// Чистая (видно в тесте): процессы и их дети до четырёх колен — без окна БАРСа и его детей (WebView2 рисует ему экран);
/// системные (dwm, заставка…) исключены всегда; ребёнок — только если родитель создан раньше (`создан`: номер → время).
pub fn движки_с_детьми(все: &[(u32, u32, String)], движки: &[u32], окно: u32, создан: &HashMap<u32, u64>) -> Vec<u32> {
    let систем: HashSet<u32> = все.iter().filter(|(_, _, и)| системный(и)).map(|(p, _, _)| *p).collect();
    let mut свои: HashSet<u32> = движки.iter().copied().filter(|p| *p != окно && *p != 0 && !систем.contains(p)).collect();
    for _ in 0..4 {
        let дети: Vec<u32> = все.iter().filter(|(pid, родитель, _)| *pid != окно && !свои.contains(pid)
            && свои.contains(родитель) && !систем.contains(pid)
            && родитель_годен(создан.get(родитель).copied(), создан.get(pid).copied()))
            .map(|(pid, _, _)| *pid).collect();
        if дети.is_empty() { break; }
        свои.extend(дети);
    }
    let mut в: Vec<u32> = свои.into_iter().collect();
    в.sort_unstable();
    в
}

/// Чистая (видно в тесте): все процессы БАРСа с детьми до четырёх колен (окно с WebView2, голова, движки); системные
/// никогда не БАРС; ребёнок — только если родитель создан раньше.
pub fn барс_с_детьми(все: &[(u32, u32, String)], б: &Барс, создан: &HashMap<u32, u64>) -> HashSet<u32> {
    let систем: HashSet<u32> = все.iter().filter(|(_, _, и)| системный(и)).map(|(p, _, _)| *p).collect();
    let mut свои: HashSet<u32> = б.движки.iter().copied().chain(б.окно).chain(б.голова)
        .filter(|p| *p != 0 && !систем.contains(p)).collect();
    for _ in 0..4 {
        let дети: Vec<u32> = все.iter().filter(|(pid, родитель, _)| !свои.contains(pid) && свои.contains(родитель)
            && !систем.contains(pid) && родитель_годен(создан.get(родитель).copied(), создан.get(pid).copied()))
            .map(|(pid, _, _)| *pid).collect();
        if дети.is_empty() { break; }
        свои.extend(дети);
    }
    свои
}

