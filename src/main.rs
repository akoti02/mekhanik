//! «МЕХАНИК» — отдельное приложение против тормозов ПК Артура (25.10, Р-193; имя и лечение — Р-194). Его слова: «…сделал
//! отдельно от Bars, но при этом… чтобы Bars знал об этой системе, а этой системой знал Bars… чтобы у меня компьютер не
//! буксил, не тормозил и не зависал»; «…как только оно будет видеть какие-то зависания, то оно будет само разбираться,
//! идентифицировать проблему и дальше оптимизировать компьютер… без каких-либо подачек от меня».
//! 🟥 25.10 (Р-195): ПОЛНОСТЬЮ ОТДЕЛЬНОЕ от БАРСа — своя папка, свой git, свой установщик, своя документация; удалят
//! БАРС — «Механик» живёт и лечит дальше, а сказать ему что-то сам может уведомлением Windows.
//! 🟥 13.11 (волна 2а, пакет «жизнь»): РОЛИ одного exe (`zhizn.rs`, `obnovlenie.rs`):
//!   - без ключа — **Мозг**: обычный приоритет без экономного режима, ловушка паники, смотритель потоков (замер,
//!     видеокарта, обновление), подъём окна; работает, пока не попросят выйти;
//!   - `--okno` — **окно** (значок у часов): вход `vid::работать_окно` появится при сведении (ясное место ниже);
//!   - `--proverka` — **самопроверка**: открыть датчики, прочесть файлы, назвать версию (ею пользуется самообновление);
//!   - `--zapusk` — **«запуск»**: задача входа зовёт его; поднимает Мозг и держит живым (падение — перезапуск, новая
//!     версия упала 3 раза за 10 мин — откат).
#![cfg_attr(not(test), windows_subsystem = "windows")]
// имена по-русски, как в БАРСе: «р» и «p», «с» и «c» рядом — не путаница
#![allow(confusable_idents, mixed_script_confusables)]

use serde_json::json;

mod kopiya;
mod lechenie;
mod obnovlenie;
mod okna;
mod storozh;
mod svyaz;
mod videokarta;
mod zhizn;

fn main() {
    let роль = std::env::args().nth(1);
    match роль.as_deref() {
        Some("--zapusk") => std::process::exit(obnovlenie::запуск()),
        Some("--proverka") => std::process::exit(if самопроверка() { 0 } else { 1 }),
        Some("--okno") => окно(),
        _ => мозг(),
    }
}

/// Мозг: сторож тормозов со всем вокруг. Не возвращается, пока не попросят выйти; тогда либо обновляемся (код для
/// «запуска»), либо выходим по воле владельца.
fn мозг() {
    let _ = std::fs::create_dir_all(svyaz::папка());
    zhizn::ловушка_паники();
    // один Мозг на сеанс; другой уже работает — не плодим (код скажет «запуску» не поднимать ещё один)
    if !okna::единственный() {
        svyaz::журнал("механик_уже_работает", &json!({ "pid": std::process::id() }));
        std::process::exit(obnovlenie::КОД_УЖЕ_РАБОТАЕТ);
    }
    // выкладка, которая просила выйти прежний «Механик», уже дождалась его — её просьба не к нам
    svyaz::стоп_снят();
    // имя «Механик» в уведомлениях Windows (когда БАРСа нет, говорит сам)
    okna::зарегистрировать_отправителя();
    // 🟥 обычная жизнь: обычный приоритет процесса, экономный режим выключен
    zhizn::обычная_жизнь();
    // 🟥 13.11: зажим видеокарты — своим потоком под смотрителем (nvidia-smi идёт до секунды, а шаг сторожа 250 мс)
    zhizn::поток("videokarta", std::time::Duration::from_secs(60), || videokarta::работать());
    // 🟥 самообновление — своим потоком под смотрителем: раз в минуту ищет свежий выпуск, ставит и просит перезапуск
    zhizn::поток("obnovlenie", std::time::Duration::from_secs(60), obnovlenie::сторожить);
    // 🟥 поднять окно (значок у часов), если его нет и владелец не на паузе (до сведения — только отметка)
    zhizn::поднять_окно();
    // замер и лечение — на этом потоке; вернётся, когда попросят выйти (stop.flag: всех отпустит)
    storozh::работать();
    // storozh вернулся: либо самообновление попросило перезапуск, либо воля владельца (его «Остановить»)
    if obnovlenie::обновиться_просили() {
        svyaz::журнал("механик_выход_на_обновление", &json!({}));
        std::process::exit(obnovlenie::КОД_ОБНОВИТЬСЯ);
    }
    svyaz::журнал("механик_выход_воля_владельца", &json!({}));
    std::process::exit(0);
}

/// Окно — значок у часов и меню (роль `--okno`).
/// 🟥 МЕСТО ДЛЯ СВЕДЕНИЯ: здесь пакет `vid` покажет окно — `vid::работать_окно()` (значок с состояниями, меню «Пауза
/// на час / Остановить до входа / Не запускать при входе / Открыть журнал / Вернуть прежнюю версию / Удалить», подъём
/// Мозга через `zhizn::поднять_мозг()`, уведомления о питании). До сведения — заглушка: отметить и выйти, чтобы Мозг не
/// считал окно поднятым и чтобы `--okno` ничего не ломал.
fn окно() {
    let _ = std::fs::create_dir_all(svyaz::папка());
    zhizn::ловушка_паники();
    // ЗАМЕНИТЬ ПРИ СВЕДЕНИИ на: vid::работать_окно();
    svyaz::журнал("механик_окно_заглушка", &json!({ "почему": "vid::работать_окно появится при сведении" }));
}

/// Самопроверка (роль `--proverka`): датчики живы, файлы на месте, версия названа. Ею пользуется самообновление
/// перед закреплением новой версии. `true` — всё цело.
fn самопроверка() -> bool {
    let _ = std::fs::create_dir_all(svyaz::папка());
    let счётчики = okna::Счётчики::открыть().is_some();
    let mut буф = vec![0u8; 2 << 20];
    let снимок = okna::снимок(&mut буф).is_some();
    let память = okna::память().0.is_some();
    let видеокарта = okna::Видеокарта::открыть().is_ok();
    let папка = svyaz::папка().exists();
    let версия = env!("CARGO_PKG_VERSION");
    // видеокарта экрана (Intel Arc) бывает занята на миг — её сбой не валит проверку; остальное обязательно
    let цело = счётчики && снимок && память && папка;
    svyaz::журнал(
        "механик_проверка",
        &json!({ "версия": версия, "счётчики": счётчики, "снимок": снимок, "память": память,
            "видеокарта": видеокарта, "папка": папка, "цело": цело }),
    );
    цело
}
