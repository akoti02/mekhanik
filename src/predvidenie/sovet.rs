//! Совет — не действие, а предложение распорядителю/лечению (его порядок: он → его работа → БАРС → фон). Предвидение
//! только советует «освободи столько-то до пика у того-то»; исполняет и возвращает — `lechenie`/распорядитель.
//!
//! 🟥 Для Просмотра (фильмы, сериалы, видео) совета уступки нет НИКОГДА (его слово 13.11): ради видео разум БАРСа не
//! уступает, и фон под него не жмём. Просмотр не бывает тяжёлым (`kto`), поэтому поводом не станет; плюс явная защита в
//! `mod.rs` при сборе кандидатов.

use super::prognoz::Уровень;

/// Что советуем. `Свободно` — не уступка, а «всё спокойно до момента `до_мс`» (для `quiet_until_ms` БАРСу).
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ВидСовета {
    /// Освободить видеопамять NVIDIA (главный рычаг — попросить БАРС выгрузить простаивающий 27B до пика).
    ОсвободитьВидеопамять,
    /// Освободить ОЗУ/зачисленную (выгрузить простаивающий 27B, выжать простаивающих).
    ОсвободитьПамять,
    /// Фон — на экономные ядра, диск и память ниже (мягко, безвредно).
    ФонУступает,
    /// Разуму — не начинать фоновый ход/подъём 27B перед пиком его работы.
    РазумОтложить,
    /// Всё спокойно до этого момента (мс эпохи) — тихие часы для БАРСа.
    Свободно { до_мс: u64 },
}

impl ВидСовета {
    pub fn ключ(&self) -> &'static str {
        match self {
            ВидСовета::ОсвободитьВидеопамять => "free_vram",
            ВидСовета::ОсвободитьПамять => "free_ram",
            ВидСовета::ФонУступает => "background_yield",
            ВидСовета::РазумОтложить => "mind_hold",
            ВидСовета::Свободно { .. } => "clear",
        }
    }
    /// Уступка ли это (то, чего ради Просмотра не делаем). `Свободно` — не уступка.
    pub fn уступка(&self) -> bool { !matches!(self, ВидСовета::Свободно { .. }) }
}

/// Кому адресован совет — личность процесса (номер + время создания). `pid = 0` — ни к кому (общий фон или «спокойно»).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Кому { pub pid: u32, pub создан: u64 }

impl Кому {
    pub fn есть(&self) -> bool { self.pid != 0 }
}

/// Совет распорядителю.
#[derive(Clone, Debug)]
pub struct Совет {
    pub вид: ВидСовета,
    /// Кому (процесс), которого касается уступка: фон, который жмём, или разум, который просим выгрузить. `None` — общий.
    pub кому: Option<Кому>,
    /// Словами, для его журнала и значка: «cargo возьмёт ~7 ГБ за ~40 с — фон на экономные ядра».
    pub почему: String,
    pub уверенность: f32,
    /// Через сколько секунд ожидается пик/беда (срочность).
    pub до_пика_с: Option<f64>,
}

/// Какой ресурс под угрозой.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Ресурс { Озу, Зачисленная, ВидеопамятьНВ }

impl Ресурс {
    pub fn слово(self) -> &'static str {
        match self {
            Ресурс::Озу => "памяти (ОЗУ)", Ресурс::Зачисленная => "зачисленной памяти",
            Ресурс::ВидеопамятьНВ => "видеопамяти NVIDIA",
        }
    }
}

/// Контекст для слов совета: ради кого (подпись тяжёлой программы) и его личность-разум (кого просить выгрузить).
pub struct Повод<'a> {
    pub ради: &'a str,
    pub разум: Option<Кому>,
    pub фон: Option<Кому>,
    pub до_пика_с: Option<f64>,
    pub уверенность: f32,
}

/// Чистое ядро: по ресурсу и уровню тревоги собрать советы. Мягко — только фон и «разум отложить»; сильно — добавить
/// освобождение (видеопамять или память) у разума. Видно в тестах; `mod.rs` добавляет гистерезис, бюджет и контроль.
pub fn советы_по_уровню(ресурс: Ресурс, уровень: Уровень, повод: &Повод) -> Vec<Совет> {
    let mut в = Vec::new();
    if уровень == Уровень::Нет { return в; }

    let слова_ресурса = ресурс.слово();
    let ради = if повод.ради.is_empty() { "его работа".to_string() } else { повод.ради.to_string() };

    // мягко: фон уступает + разум не начинает нового хода
    в.push(Совет {
        вид: ВидСовета::ФонУступает,
        кому: повод.фон,
        почему: format!("{ради}: скоро не хватит {слова_ресурса} — фон на экономные ядра заранее"),
        уверенность: повод.уверенность,
        до_пика_с: повод.до_пика_с,
    });
    в.push(Совет {
        вид: ВидСовета::РазумОтложить,
        кому: повод.разум,
        почему: format!("{ради}: перед пиком — разуму не начинать фоновый ход"),
        уверенность: повод.уверенность,
        до_пика_с: повод.до_пика_с,
    });

    if уровень == Уровень::Сильно {
        let вид = if ресурс == Ресурс::ВидеопамятьНВ {
            ВидСовета::ОсвободитьВидеопамять
        } else {
            ВидСовета::ОсвободитьПамять
        };
        let чем = if ресурс == Ресурс::ВидеопамятьНВ { "видеопамять NVIDIA" } else { "память" };
        в.push(Совет {
            вид,
            кому: повод.разум,
            почему: format!("{ради}: {чем} вот-вот кончится — выгрузить простаивающий 27B до пика"),
            уверенность: повод.уверенность,
            до_пика_с: повод.до_пика_с,
        });
    }
    в
}

#[cfg(test)]
mod тесты {
    use super::*;

    fn повод() -> Повод<'static> {
        Повод { ради: "cargo (сборка)", разум: Some(Кому { pid: 42, создан: 100 }),
            фон: Some(Кому { pid: 7, создан: 5 }), до_пика_с: Some(40.0), уверенность: 0.8 }
    }

    #[test]
    fn нет_тревоги_нет_советов() {
        assert!(советы_по_уровню(Ресурс::Озу, Уровень::Нет, &повод()).is_empty());
    }

    #[test]
    fn мягко_только_фон_и_отложить() {
        let с = советы_по_уровню(Ресурс::Зачисленная, Уровень::Мягко, &повод());
        let виды: Vec<_> = с.iter().map(|x| x.вид.клон_ключ()).collect();
        assert!(виды.contains(&"background_yield"));
        assert!(виды.contains(&"mind_hold"));
        assert!(!виды.contains(&"free_ram"), "мягко — без выгрузки");
    }

    #[test]
    fn сильно_добавляет_освобождение() {
        let с = советы_по_уровню(Ресурс::Зачисленная, Уровень::Сильно, &повод());
        assert!(с.iter().any(|x| x.вид == ВидСовета::ОсвободитьПамять));
        let вид_видео = советы_по_уровню(Ресурс::ВидеопамятьНВ, Уровень::Сильно, &повод());
        assert!(вид_видео.iter().any(|x| x.вид == ВидСовета::ОсвободитьВидеопамять));
    }

    #[test]
    fn советы_адресованы_и_со_словами() {
        let с = советы_по_уровню(Ресурс::ВидеопамятьНВ, Уровень::Сильно, &повод());
        let осв = с.iter().find(|x| x.вид == ВидСовета::ОсвободитьВидеопамять).unwrap();
        assert_eq!(осв.кому, Some(Кому { pid: 42, создан: 100 }));
        assert!(осв.почему.contains("cargo"));
        assert_eq!(осв.до_пика_с, Some(40.0));
    }

    #[test]
    fn просмотр_не_уступка() {
        assert!(ВидСовета::ФонУступает.уступка());
        assert!(ВидСовета::ОсвободитьВидеопамять.уступка());
        assert!(!ВидСовета::Свободно { до_мс: 1 }.уступка());
    }
}

// вспомогательное для теста — краткий ключ вида
impl ВидСовета {
    #[cfg(test)]
    fn клон_ключ(&self) -> &'static str { self.ключ() }
}
