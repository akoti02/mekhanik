//! Поводы предвидеть (разбор §3.2, §3.7, его слово «предвосхищать»): три повода узнаются по переменам между снимками,
//! до всякого тормоза:
//! 1) **запуск** тяжёлой программы — новая личность (номер + время создания) в снимке, которой не было;
//! 2) **его окно вышло вперёд** — переднее окно сменилось на программу, чей профиль «3D на NVIDIA» (игра, САПР): БАРС
//!    уступает видеокарту заранее, не дожидаясь задержки экрана на Intel, которой не будет;
//! 3) **рост** зачисленной памяти и видеопамяти — по наклону ряда (считает `ryad` в `mod.rs`).
//!
//! Чисто (видно в тестах): `Наблюдатель` хранит прошлый набор личностей и прошлее окно и по новому снимку говорит, что
//! изменилось. Рост — отдельной функцией по наклону.

use super::sovet::Кому;
use std::collections::HashSet;

/// Вид повода.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ВидПовода {
    /// Новая тяжёлая программа запустилась.
    Запуск,
    /// Его окно вышло вперёд (игра/САПР на NVIDIA — уступить видеокарту заранее).
    ОкноВперёд,
    /// Быстрый рост потребления ресурса (наклон).
    РостРесурса,
}

/// Повод с адресатом (личность) и словами.
#[derive(Clone, Debug)]
pub struct Повод {
    pub вид: ВидПовода,
    pub кому: Кому,
    pub подпись: String,
}

/// Наблюдатель перемен между снимками. Хранит набор живых личностей и прошлее переднее окно.
#[derive(Clone, Debug, Default)]
pub struct Наблюдатель {
    живые: HashSet<(u32, u64)>,
    окно: Option<(u32, u64)>,
    первый: bool,
}

impl Наблюдатель {
    pub fn новый() -> Наблюдатель { Наблюдатель { живые: HashSet::new(), окно: None, первый: true } }

    /// Шаг: `процессы` — нынешние (личность, подпись, повод_окна), где `повод_окна` = true, если этот процесс стоит
    /// уступки по выходу вперёд (игра/САПР на NVIDIA, решает `mod.rs` по роду). `окно_впереди` — чьё окно сейчас.
    /// Возвращает поводы «запуск» (для новых) и «окно вперёд» (если переднее сменилось на достойного уступки).
    /// Первый шаг после старта не выдаёт «запусков» (все процессы «старые» — иначе буря ложных поводов).
    pub fn шаг(&mut self, процессы: &[(Кому, String, bool)], окно_впереди: Option<(Кому, bool)>) -> Vec<Повод> {
        let mut поводы = Vec::new();
        let нынешние: HashSet<(u32, u64)> = процессы.iter().map(|(к, _, _)| (к.pid, к.создан)).collect();

        if !self.первый {
            for (к, подпись, _) in процессы {
                if !self.живые.contains(&(к.pid, к.создан)) {
                    поводы.push(Повод { вид: ВидПовода::Запуск, кому: *к, подпись: подпись.clone() });
                }
            }
        }

        // окно вперёд: сменилось и достойно уступки
        if let Some((к, достоин)) = окно_впереди {
            let сменилось = self.окно != Some((к.pid, к.создан));
            if сменилось && достоин {
                let подпись = процессы.iter().find(|(п, _, _)| p_eq(p_of(п), к))
                    .map(|(_, с, _)| с.clone()).unwrap_or_default();
                поводы.push(Повод { вид: ВидПовода::ОкноВперёд, кому: к, подпись });
            }
            self.окно = Some((к.pid, к.создан));
        } else {
            self.окно = None;
        }

        self.живые = нынешние;
        self.первый = false;
        поводы
    }
}

fn p_of(к: &Кому) -> Кому { *к }
fn p_eq(а: Кому, б: Кому) -> bool { а.pid == б.pid && а.создан == б.создан }

/// Рост-повод: падение свободного ресурса быстрее `порог_мб_с` (модуль наклона) — повод «рост потребления».
/// (Свободное падает — значит потребление растёт.) Возвращает модуль скорости, если он выше порога.
pub fn рост_повод(наклон_своб_в_сек: f64, порог_мб_с: f64) -> Option<f64> {
    let скорость = (-наклон_своб_в_сек).max(0.0);
    (скорость >= порог_мб_с).then_some(скорость)
}

#[cfg(test)]
mod тесты {
    use super::*;

    fn к(pid: u32, создан: u64) -> Кому { Кому { pid, создан } }

    #[test]
    fn первый_шаг_без_запусков_потом_ловит_новых() {
        let mut н = Наблюдатель::новый();
        let п1 = н.шаг(&[(к(1, 10), "rustc".into(), false)], None);
        assert!(п1.is_empty(), "первый шаг — все старые");
        // запустился новый cargo
        let п2 = н.шаг(&[(к(1, 10), "rustc".into(), false), (к(2, 20), "cargo".into(), false)], None);
        assert_eq!(п2.len(), 1);
        assert_eq!(п2[0].вид, ВидПовода::Запуск);
        assert_eq!(п2[0].кому, к(2, 20));
        // ничего нового — без повода
        let п3 = н.шаг(&[(к(1, 10), "rustc".into(), false), (к(2, 20), "cargo".into(), false)], None);
        assert!(п3.is_empty());
    }

    #[test]
    fn номер_переиспользован_считается_запуском() {
        let mut н = Наблюдатель::новый();
        н.шаг(&[(к(5, 100), "a".into(), false)], None);
        // тот же pid, другое время создания — это другая программа, повод «запуск»
        let п = н.шаг(&[(к(5, 200), "b".into(), false)], None);
        assert_eq!(п.len(), 1);
        assert_eq!(п[0].кому, к(5, 200));
    }

    #[test]
    fn окно_вперёд_только_достойного() {
        let mut н = Наблюдатель::новый();
        // игра вышла вперёд (достоин уступки)
        let п = н.шаг(&[(к(9, 1), "игра на NVIDIA".into(), true)], Some((к(9, 1), true)));
        assert!(п.iter().any(|x| x.вид == ВидПовода::ОкноВперёд));
        // то же окно впереди — повода нет
        let п2 = н.шаг(&[(к(9, 1), "игра на NVIDIA".into(), true)], Some((к(9, 1), true)));
        assert!(!п2.iter().any(|x| x.вид == ВидПовода::ОкноВперёд));
        // вперёд вышел блокнот (не достоин) — повода нет
        let п3 = н.шаг(&[(к(3, 1), "блокнот".into(), false)], Some((к(3, 1), false)));
        assert!(!п3.iter().any(|x| x.вид == ВидПовода::ОкноВперёд));
    }

    #[test]
    fn рост_повод_по_наклону() {
        assert_eq!(рост_повод(-120.0, 100.0), Some(120.0)); // падает 120 МБ/с
        assert_eq!(рост_повод(-20.0, 100.0), None); // медленно
        assert_eq!(рост_повод(50.0, 100.0), None); // растёт свободное — не повод
    }
}
