//! Прогноз запаса: «через N секунд не хватит». Соединяет две вещи (из разбора `predvoskhishchenie.md` §3.5):
//! 1) наклон ряда за 10–30 с — что уже происходит;
//! 2) ожидаемый прирост по профилю только что запущенной программы — то, чего ещё нет в ряду, но вот-вот будет
//!    (настоящее «пред-»).
//! Пороги беды — по журналу этого ПК (§3.5), уточняются повтором. Без моделей: вычитание и деление.

#![allow(dead_code)] // часть набора ждёт подключения сводом/следующими неделями — не мёртвый код

use super::ryad::время_до_конца;

/// Пороги одного ресурса (МБ): где «беда», где поднимать мягкую и сильную тревогу, и защита «много — не паниковать».
#[derive(Clone, Copy, Debug)]
pub struct Пороги {
    /// Ниже этого — уже беда (Windows отказывает, CUDA падает, подкачка молотит).
    pub беда_мб: f64,
    /// Мягкая тревога: прогноз ниже этого через `мягко_через_с`.
    pub мягко_мб: f64,
    pub мягко_через_с: f64,
    /// Сильная тревога: прогноз ниже этого через `сильно_через_с`.
    pub сильно_мб: f64,
    pub сильно_через_с: f64,
    /// Свободно больше этого — сильную тревогу не поднимаем при любом наклоне (его «много памяти — не дёргать»).
    pub защита_много_мб: f64,
}

/// ОЗУ доступно: беда < 2 ГБ при подкачке; мягко < 3,5 ГБ/60 с; сильно < 2,5 ГБ/30 с; защита 8 ГБ.
pub fn пороги_озу() -> Пороги {
    Пороги { беда_мб: 2000.0, мягко_мб: 3500.0, мягко_через_с: 60.0, сильно_мб: 2500.0, сильно_через_с: 30.0,
        защита_много_мб: 8000.0 }
}

/// Зачисленная свободно: беда < 1,5 ГБ; мягко < 4 ГБ/60 с; сильно < 2,5 ГБ/30 с; защита 12 ГБ.
pub fn пороги_зачисленной() -> Пороги {
    Пороги { беда_мб: 1500.0, мягко_мб: 4000.0, мягко_через_с: 60.0, сильно_мб: 2500.0, сильно_через_с: 30.0,
        защита_много_мб: 12000.0 }
}

/// Видеопамять NVIDIA свободно: беда < 0,5 ГБ; мягко < 2 ГБ/60 с; сильно < 1 ГБ/30 с; защита 4 ГБ.
pub fn пороги_видеопамяти_нв() -> Пороги {
    Пороги { беда_мб: 500.0, мягко_мб: 2000.0, мягко_через_с: 60.0, сильно_мб: 1000.0, сильно_через_с: 30.0,
        защита_много_мб: 4000.0 }
}

/// Запас через `т_с` секунд: что свободно сейчас, минус то, что ещё доберёт запущенная программа по профилю, минус то,
/// что утечёт по нынешнему наклону. `наклон_в_сек` — прирост свободного в секунду (при падении он отрицателен).
pub fn запас_через(свободно_мб: f64, ожидаемый_прирост_мб: f64, наклон_в_сек: f64, т_с: f64) -> f64 {
    let утечка = (-наклон_в_сек).max(0.0) * т_с;
    свободно_мб - ожидаемый_прирост_мб.max(0.0) - утечка
}

/// Ожидаемый прирост потребления программы: сколько она ещё возьмёт сверх того, что держит сейчас, до своего пика.
/// Считается только в фазе запуска (с начала меньше времени до пика). `пик` и `сейчас` — её потребление, МБ.
pub fn ещё_возьмёт(пик_p95_мб: u64, сейчас_у_неё_мб: u64) -> f64 {
    (пик_p95_мб as f64 - сейчас_у_неё_мб as f64).max(0.0)
}

/// Уровень тревоги по ресурсу.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Уровень { Нет, Мягко, Сильно }

/// Решить уровень тревоги по ресурсу: свободно сейчас, ожидаемый прирост (профиль), наклон (ряд), пороги.
/// Защита «много свободно» срезает сильную тревогу; при наклоне ≈0 и достаточном запасе — «Нет».
pub fn уровень(свободно_мб: f64, ожидаемый_прирост_мб: f64, наклон_в_сек: f64, п: &Пороги) -> Уровень {
    // уже беда или вот-вот (прирост профиля сам по себе заводит за порог) — сильно
    let запас_сильно = запас_через(свободно_мб, ожидаемый_прирост_мб, наклон_в_сек, п.сильно_через_с);
    let запас_мягко = запас_через(свободно_мб, ожидаемый_прирост_мб, наклон_в_сек, п.мягко_через_с);

    if свободно_мб < п.защита_много_мб && запас_сильно < п.сильно_мб.max(п.беда_мб) {
        return Уровень::Сильно;
    }
    if запас_мягко < п.мягко_мб {
        return Уровень::Мягко;
    }
    Уровень::Нет
}

/// Через сколько секунд ресурс дойдёт до беды (для `до_пика_с` в совете и для сортировки срочности).
pub fn до_беды_с(свободно_мб: f64, наклон_в_сек: f64, п: &Пороги) -> Option<f64> {
    время_до_конца(свободно_мб, п.беда_мб, наклон_в_сек)
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn запас_учитывает_профиль_и_наклон() {
        // свободно 9 ГБ, программа доберёт 5 ГБ, падаем 50 МБ/с, через 30 с
        let з = запас_через(9000.0, 5000.0, -50.0, 30.0);
        assert_eq!(з, 9000.0 - 5000.0 - 1500.0);
    }

    #[test]
    fn запуск_тяжёлой_заводит_сильную_тревогу_до_падения() {
        // 🟥 суть «пред-»: ряд ещё ровный (наклон 0), но cargo только запущен и по профилю возьмёт 7 ГБ.
        // На старом пороге уровня (только «сколько сейчас свободно») тревоги бы не было — 6 ГБ это много.
        let п = пороги_зачисленной();
        let без_профиля = уровень(6000.0, 0.0, 0.0, &п);
        assert_eq!(без_профиля, Уровень::Нет, "без ожидаемого прироста 6 ГБ — спокойно");
        let с_профилем = уровень(6000.0, 7000.0, 0.0, &п);
        assert_eq!(с_профилем, Уровень::Сильно, "профиль обещает −7 ГБ — сильно, до пика");
    }

    #[test]
    fn много_свободно_не_паникуем() {
        let п = пороги_озу();
        // 20 ГБ свободно, резкое падение — но защита «много» не даёт сильной тревоги
        assert_eq!(уровень(20000.0, 0.0, -200.0, &п), Уровень::Нет);
    }

    #[test]
    fn падение_без_запуска_даёт_мягко_потом_сильно() {
        let п = пороги_озу();
        // 4 ГБ, падаем 30 МБ/с: через 60 с будет 3,5-1,8=... → мягко
        assert_eq!(уровень(4000.0, 0.0, -30.0, &п), Уровень::Мягко);
        // 2,8 ГБ, падаем 40 МБ/с: через 30 с 2800-1200=1600 < 2500 → сильно
        assert_eq!(уровень(2800.0, 0.0, -40.0, &п), Уровень::Сильно);
    }

    #[test]
    fn до_беды_секунды() {
        let п = пороги_озу(); // беда 2000
        assert_eq!(до_беды_с(4000.0, -100.0, &п), Some(20.0));
        assert_eq!(до_беды_с(4000.0, 10.0, &п), None);
    }
}
