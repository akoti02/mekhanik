//! 🟥 ПРЕДВИДЕНИЕ — «Механик» 1.0, волна 2б (ключ `predvidenie`). Его слово 13.11: предвосхищать и понимать ЛЮБУЮ
//! тяжёлую нагрузку БЕЗ моделей ИИ и ПОЛНОСТЬЮ офлайн — только дешёвый счёт. Этот слой советует освободить ресурс ДО
//! пика, а не после: по поводу (запуск программы, его окно вперёд, рост памяти/видеопамяти), по профилю программы из
//! `kto` (сколько возьмёт и за сколько) и по наклону рядов — предвидит «через N с не хватит» и даёт советы.
//!
//! Совет — не действие (его порядок: он → его работа → БАРС → фон): исполняет и возвращает распорядитель/`lechenie`.
//! 🟥 Для Просмотра (видео) совета уступки нет НИКОГДА — ради видео разум БАРСа не уступает (его слово 13.11).
//!
//! Цена — доли процента ядра (≤ 0,2 %): всё — вычитание, деление и наклон по короткому ряду (`ryad`).
//!
//! # Как свод подключает (к `storozh`/`main`)
//! ```ignore
//! let mut предв = Предвидение::новая();                 // при старте Мозга
//! // каждый такт сторожа (решения — в окне 2 с): собрать Вход из kto::Картина, vnimanie, svyaz
//! let советы = предв.шаг(&вход);
//! // исполнить советы лечением/распорядителем; БАРСу — через svyaz::барсу_предвидение (quiet_until = предв.тихо_до_мс)
//! ```
//! `Вход` свод набивает так: свободная память/зачисленная — из замера; видеопамять NVIDIA свободная — `videokarta`/
//! `kto::win`; `тяжёлые` — карточки `kto` с `решение.тяжёлое` и профилями (`ожидаемый_озу_мб`, `ожидаемая_видеопамять_мб`,
//! `до_пика_с`); `разум` — личность 27B из `svyaz::картина`; `разум_простаивает` — 27B загружен, простой ≥ 60 с и не его
//! слово (`svyaz::не_просить_выгрузку`); `тормоз_памяти_только_что` — из `lechenie`; `тень` — первую неделю true.

#![allow(dead_code)]

