//! Честная проверка предвидения (его правило «опыт честный, с контрольной группой»): каждое предсказание потом
//! сверяется с тем, что вышло — «предсказал → сбылось / не сбылось»; точность по правилу копится с забыванием
//! (полужизнь 7 дней); в контрольных 10 % случаев совет НАРОЧНО не даётся — чтобы видеть, как часто обходится само;
//! правило с низкой точностью сильных действий не делает.

use std::collections::HashMap;

/// Полужизнь опыта проверки — как у профилей (7 дней).
pub const ПОЛУЖИЗНЬ_МС: f64 = 7.0 * 24.0 * 3600.0 * 1000.0;
/// Доля контрольных «не советовать».
pub const ДОЛЯ_КОНТРОЛЯ: f64 = 0.10;
/// Порог точности, ниже которого сильные советы по правилу сутки не даём.
pub const ПОРОГ_ТОЧНОСТИ: f64 = 0.50;
/// Сколько исходов нужно, чтобы доверять точности (иначе — «опыта мало», сильно можно только в тени).
pub const ИСХОДОВ_ДЛЯ_ДОВЕРИЯ: f64 = 5.0;

fn вес(сейчас: u64, момент: u64) -> f64 {
    0.5_f64.powf((сейчас.saturating_sub(момент)) as f64 / ПОЛУЖИЗНЬ_МС)
}

/// «Сбылось ли»: настоящий пик не ниже 70 % предсказанного (его правило «сбылось = пик ≥ 70 % обещанного»).
pub fn сбылось(настоящий_пик: f64, предсказанный_пик: f64) -> bool {
    предсказанный_пик <= 0.0 || настоящий_пик >= 0.70 * предсказанный_пик
}

/// Детерминированный выбор контрольных ≈10 % по ключу эпизода (без генератора — чтобы повтор был воспроизводим).
pub fn контрольный(ключ_эпизода: &str) -> bool {
    // простой хэш FNV-1a
    let mut h: u64 = 0xcbf29ce484222325;
    for b in ключ_эпизода.bytes() { h ^= b as u64; h = h.wrapping_mul(0x100000001b3); }
    (h % 1000) < (ДОЛЯ_КОНТРОЛЯ * 1000.0) as u64
}

/// Один исход: сбылось (1) или ложно (0), когда наблюдали.
#[derive(Clone, Copy, Debug)]
struct Исход { сбылось: bool, когда_мс: u64 }

/// Накопленная точность по правилам (ключ правила — например «запуск/зачисленная» или подпись программы).
#[derive(Clone, Debug, Default)]
pub struct Проверка {
    исходы: HashMap<String, Vec<Исход>>,
}

impl Проверка {
    pub fn новая() -> Проверка { Проверка::default() }

    /// Записать итог предсказания по правилу.
    pub fn записать(&mut self, правило: &str, сбылось: bool, когда_мс: u64) {
        let v = self.исходы.entry(правило.to_string()).or_default();
        v.push(Исход { сбылось, когда_мс });
        if v.len() > 128 { v.remove(0); }
    }

    /// Взвешенная точность правила и взвешенное число исходов на `сейчас`. `None` — исходов нет совсем.
    pub fn точность(&self, правило: &str, сейчас_мс: u64) -> Option<(f64, f64)> {
        let v = self.исходы.get(правило)?;
        let mut сумма = 0.0;
        let mut верных = 0.0;
        for и in v {
            let w = вес(сейчас_мс, и.когда_мс);
            сумма += w;
            if и.сбылось { верных += w; }
        }
        (сумма > 0.0).then_some((верных / сумма, сумма))
    }

    /// Можно ли по правилу давать сильный совет: нет опыта (None → можно, но вызывающий держит в тени), или точность
    /// не ниже порога при достаточном числе исходов. Правило, часто ложное, сильно не советует.
    pub fn сильно_можно(&self, правило: &str, сейчас_мс: u64) -> bool {
        match self.точность(правило, сейчас_мс) {
            None => true,
            Some((_, сколько)) if сколько < ИСХОДОВ_ДЛЯ_ДОВЕРИЯ => true,
            Some((доля, _)) => доля >= ПОРОГ_ТОЧНОСТИ,
        }
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn сбылось_порог_70() {
        assert!(сбылось(7000.0, 9000.0)); // 7000 ≥ 0.7·9000=6300
        assert!(!сбылось(5000.0, 9000.0)); // 5000 < 6300
        assert!(сбылось(10.0, 0.0)); // без предсказания — не считаем ложным
    }

    #[test]
    fn контрольные_около_десяти_процентов() {
        let n = 5000;
        let к = (0..n).filter(|i| контрольный(&format!("эпизод-{i}"))).count();
        let доля = к as f64 / n as f64;
        assert!((доля - 0.10).abs() < 0.03, "контрольных ≈10 %: {доля}");
    }

    #[test]
    fn плохое_правило_не_советует_сильно() {
        let mut п = Проверка::новая();
        let сейчас = 1_000_000u64;
        // 6 ложных подряд
        for _ in 0..6 { п.записать("запуск/видеопамять", false, сейчас); }
        assert!(!п.сильно_можно("запуск/видеопамять", сейчас));
        // доброе правило — можно
        for _ in 0..6 { п.записать("запуск/зачисленная", true, сейчас); }
        assert!(п.сильно_можно("запуск/зачисленная", сейчас));
        // неизвестное — можно (в тень вынесет вызывающий)
        assert!(п.сильно_можно("новое", сейчас));
    }

    #[test]
    fn старые_исходы_забываются() {
        let mut п = Проверка::новая();
        let день = 24 * 3600 * 1000u64;
        // давно — 10 ложных; недавно — 10 верных
        for _ in 0..10 { п.записать("r", false, 0); }
        for _ in 0..10 { п.записать("r", true, 42 * день); }
        let (доля, _) = п.точность("r", 42 * день).unwrap();
        assert!(доля > 0.9, "давние ложные почти не весят: {доля}");
    }
}
