//! Дешёвая математика предвидения без моделей ИИ (его слово 13.11: «никакой модели ИИ… только счёт»): наклон ряда
//! (метод наименьших квадратов и устойчивый Тейла — Сена), сглаживание Холта и «через сколько секунд кончится».
//! Всё — чистые функции и крошечные состояния (видно в тестах), счёт — доли микросекунды на шаг.
//!
//! Ряды короткие (окно 10 и 30 с при 1 Гц — до 30 точек), поэтому можно считать прямо по точкам, без хитрых структур.

#![allow(dead_code)] // часть набора ждёт подключения сводом/следующими неделями — не мёртвый код

use std::collections::VecDeque;

/// Наклон прямой `x = a·t + b` методом наименьших квадратов: `t` — секунды, `x` — величина (МБ и т. п.).
/// Возвращает `a` (прирост величины в секунду) или `None`, если точек меньше двух или все `t` совпали.
pub fn наклон_мнк(точки: &[(f64, f64)]) -> Option<f64> {
    let n = точки.len() as f64;
    if точки.len() < 2 { return None; }
    let (mut st, mut sx, mut stt, mut stx) = (0.0, 0.0, 0.0, 0.0);
    for &(t, x) in точки {
        st += t; sx += x; stt += t * t; stx += t * x;
    }
    let знам = n * stt - st * st;
    if знам.abs() < f64::EPSILON { return None; }
    Some((n * stx - st * sx) / знам)
}

/// Корень из среднего квадрата остатков прямой МНК — насколько ряд ложится на прямую (мера «это тренд, а не рывок»).
pub fn разброс_мнк(точки: &[(f64, f64)]) -> Option<f64> {
    if точки.len() < 3 { return None; }
    let a = наклон_мнк(точки)?;
    let n = точки.len() as f64;
    let (st, sx): (f64, f64) = точки.iter().fold((0.0, 0.0), |(st, sx), &(t, x)| (st + t, sx + x));
    let b = (sx - a * st) / n;
    let сумма: f64 = точки.iter().map(|&(t, x)| { let r = x - (a * t + b); r * r }).sum();
    Some((сумма / n).sqrt())
}

/// Наклон Тейла — Сена: медиана наклонов всех пар точек. Устойчив к одиночным рывкам (его правило «одиночный скачок не
/// тянет прогноз»). Для коротких рядов (12 точек → 66 пар) — копейки.
pub fn наклон_тейла_сена(точки: &[(f64, f64)]) -> Option<f64> {
    if точки.len() < 2 { return None; }
    let mut наклоны: Vec<f64> = Vec::with_capacity(точки.len() * точки.len() / 2);
    for i in 0..точки.len() {
        for j in (i + 1)..точки.len() {
            let (t1, x1) = точки[i];
            let (t2, x2) = точки[j];
            let dt = t2 - t1;
            if dt.abs() > f64::EPSILON { наклоны.push((x2 - x1) / dt); }
        }
    }
    if наклоны.is_empty() { return None; }
    наклоны.sort_by(|а, б| а.partial_cmp(б).unwrap_or(std::cmp::Ordering::Equal));
    let m = наклоны.len();
    Some(if m % 2 == 1 { наклоны[m / 2] } else { (наклоны[m / 2 - 1] + наклоны[m / 2]) / 2.0 })
}

/// «Через сколько секунд величина упадёт до порога беды» при текущем наклоне. `None` — величина уже ниже порога или
/// наклон не отрицательный (ничего не кончается). Та же формула, что у Prometheus `predict_linear`.
pub fn время_до_конца(значение: f64, порог: f64, наклон_в_сек: f64) -> Option<f64> {
    if значение <= порог { return Some(0.0); }
    if наклон_в_сек >= -f64::EPSILON { return None; }
    Some((значение - порог) / (-наклон_в_сек))
}

/// Двойное сглаживание Холта: уровень и тренд. При 1 Гц α ≈ 0,5, β ≈ 0,2 (из разбора). Прогноз через `к` шагов —
/// `l + к·t`. Память — два числа.
#[derive(Clone, Debug)]
pub struct Холт {
    альфа: f64,
    бета: f64,
    l: f64,
    t: f64,
    было: u8, // 0 — пусто, 1 — одно наблюдение, 2 — установлено
}

impl Холт {
    pub fn новый(альфа: f64, бета: f64) -> Холт {
        Холт { альфа: альфа.clamp(0.0, 1.0), бета: бета.clamp(0.0, 1.0), l: 0.0, t: 0.0, было: 0 }
    }

    /// Наблюдать очередное значение; вернуть (уровень, тренд в шаг).
    pub fn наблюсти(&mut self, x: f64) -> (f64, f64) {
        match self.было {
            0 => { self.l = x; self.t = 0.0; self.было = 1; }
            1 => { self.t = x - self.l; self.l = x; self.было = 2; }
            _ => {
                let прежн = self.l;
                self.l = self.альфа * x + (1.0 - self.альфа) * (self.l + self.t);
                self.t = self.бета * (self.l - прежн) + (1.0 - self.бета) * self.t;
            }
        }
        (self.l, self.t)
    }

    /// Прогноз величины через `шагов` шагов (при 1 Гц шаг = 1 с).
    pub fn прогноз(&self, шагов: f64) -> Option<f64> {
        if self.было < 2 { return None; }
        Some(self.l + self.t * шагов)
    }

    pub fn тренд(&self) -> Option<f64> { (self.было >= 2).then_some(self.t) }
}

/// Скользящее окно значений во времени (мс) для наклона. Держит последние `окно_мс` миллисекунд.
#[derive(Clone, Debug)]
pub struct Окно {
    точки: VecDeque<(u64, f64)>,
    окно_мс: u64,
}

impl Окно {
    pub fn новое(окно_мс: u64) -> Окно { Окно { точки: VecDeque::new(), окно_мс } }

    /// Добавить значение на момент `t_мс`; выбросить всё старше окна.
    pub fn добавить(&mut self, t_мс: u64, значение: f64) {
        if !значение.is_finite() { return; }
        self.точки.push_back((t_мс, значение));
        while let Some(&(t, _)) = self.точки.front() {
            if t_мс.saturating_sub(t) > self.окно_мс { self.точки.pop_front(); } else { break; }
        }
    }

    pub fn пусто(&self) -> bool { self.точки.is_empty() }
    pub fn сколько(&self) -> usize { self.точки.len() }
    pub fn последнее(&self) -> Option<f64> { self.точки.back().map(|&(_, x)| x) }
    pub fn охват_с(&self) -> f64 {
        match (self.точки.front(), self.точки.back()) {
            (Some(&(a, _)), Some(&(b, _))) => (b.saturating_sub(a)) as f64 / 1000.0,
            _ => 0.0,
        }
    }

    fn в_секундах(&self) -> Vec<(f64, f64)> {
        let Some(&(t0, _)) = self.точки.front() else { return Vec::new(); };
        self.точки.iter().map(|&(t, x)| ((t.saturating_sub(t0)) as f64 / 1000.0, x)).collect()
    }

    /// Наклон величины в секунду по методу наименьших квадратов. `None` — мало точек или мал охват.
    pub fn наклон(&self) -> Option<f64> {
        if self.точки.len() < 3 || self.охват_с() < 3.0 { return None; }
        наклон_мнк(&self.в_секундах())
    }

    /// Устойчивый наклон (Тейла — Сена) — для «битых» рядов.
    pub fn наклон_устойчивый(&self) -> Option<f64> {
        if self.точки.len() < 3 || self.охват_с() < 3.0 { return None; }
        наклон_тейла_сена(&self.в_секундах())
    }

    /// Разброс остатков вокруг прямой МНК (мера «это тренд»).
    pub fn разброс(&self) -> Option<f64> { разброс_мнк(&self.в_секундах()) }
}

/// Согласованный наклон двух окон (например, 10 с и 30 с): берём, только если оба падают (наклон < 0) и близки по
/// величине — одиночный скачок в одном окне не тянет прогноз (его правило). Возвращаем более пологий (осторожный).
pub fn согласованный_наклон(короткое: &Окно, длинное: &Окно) -> Option<f64> {
    let к = короткое.наклон()?;
    let д = длинное.наклон()?;
    if к >= 0.0 || д >= 0.0 { return None; }
    // близки по величине: отношение не больше ~3×
    let (мин, макс) = if к.abs() < д.abs() { (к.abs(), д.abs()) } else { (д.abs(), к.abs()) };
    if макс > мин * 3.0 { return None; }
    // осторожнее — меньший по модулю наклон (конец наступит позже → не паниковать зря)
    Some(if к.abs() < д.abs() { к } else { д })
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn наклон_прямой_точный() {
        // x = -100·t + 5000: ровно −100 МБ/с
        let точки: Vec<(f64, f64)> = (0..10).map(|i| (i as f64, 5000.0 - 100.0 * i as f64)).collect();
        let a = наклон_мнк(&точки).unwrap();
        assert!((a + 100.0).abs() < 1e-6, "наклон {a}");
    }

    #[test]
    fn тейл_сен_устойчив_к_рывку() {
        // ровное падение −50/с, но одна точка — резкий выброс вверх
        let mut точки: Vec<(f64, f64)> = (0..12).map(|i| (i as f64, 6000.0 - 50.0 * i as f64)).collect();
        точки[6].1 += 3000.0; // рывок
        let мнк = наклон_мнк(&точки).unwrap();
        let тс = наклон_тейла_сена(&точки).unwrap();
        assert!((тс + 50.0).abs() < 5.0, "Тейл-Сен держит −50: {тс}");
        assert!(мнк > тс, "МНК рывок утащил вверх: мнк={мнк}, тс={тс}");
    }

    #[test]
    fn время_до_конца_считается() {
        // 2500 МБ, порог 1000, падаем 100 МБ/с → 15 с
        assert_eq!(время_до_конца(2500.0, 1000.0, -100.0), Some(15.0));
        // не падаем — не кончится
        assert_eq!(время_до_конца(2500.0, 1000.0, 5.0), None);
        // уже ниже порога — ноль
        assert_eq!(время_до_конца(500.0, 1000.0, -10.0), Some(0.0));
    }

    #[test]
    fn холт_ловит_тренд() {
        let mut х = Холт::новый(0.5, 0.2);
        for i in 0..10 { х.наблюсти(5000.0 - 100.0 * i as f64); }
        let т = х.тренд().unwrap();
        assert!(т < -50.0 && т > -150.0, "тренд около −100: {т}");
        assert!(х.прогноз(5.0).unwrap() < х.прогноз(0.0).unwrap(), "прогноз падает вперёд");
    }

    #[test]
    fn окно_выбрасывает_старое() {
        let mut о = Окно::новое(10_000);
        for с in 0..20 { о.добавить(с * 1000, 100.0); }
        assert!(о.охват_с() <= 10.0, "охват в пределах окна: {}", о.охват_с());
        assert!(о.сколько() <= 11);
    }

    #[test]
    fn согласие_окон_гасит_одиночный_скачок() {
        // 27.10 22:43–23:08: доступно 4,2 → 1,5 ГБ за 25 мин ≈ −1,8 МБ/с — устойчивое падение
        let mut к = Окно::новое(10_000);
        let mut д = Окно::новое(30_000);
        for с in 0..31u64 {
            let v = 4200.0 - 1.8 * с as f64;
            к.добавить(с * 1000, v);
            д.добавить(с * 1000, v);
        }
        let н = согласованный_наклон(&к, &д).expect("оба падают согласно");
        assert!(н < 0.0);
        // плоский ряд с одной вспышкой — согласия нет
        let mut к2 = Окно::новое(10_000);
        let mut д2 = Окно::новое(30_000);
        for с in 0..31u64 {
            let v = if с == 15 { 3000.0 } else { 4000.0 };
            к2.добавить(с * 1000, v);
            д2.добавить(с * 1000, v);
        }
        assert!(согласованный_наклон(&к2, &д2).is_none(), "плоский ряд с одной вспышкой — без тревоги");
    }
}
