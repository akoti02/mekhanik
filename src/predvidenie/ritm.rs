//! Ритм дня: когда он за ПК и когда идёт его тяжёлое — 96 корзин по 15 минут × 7 дней недели, по МЕСТНОМУ времени ПК
//! (он ездит, пояс в журнале менялся −04/−05 — учимся по его стенным часам). С забыванием (полужизнь ≈3 недели).
//!
//! Зачем (разбор §3.8): «тихие часы» для БАРСа — где он почти никогда не за ПК и почти нет тяжёлого (по журналу ≈03:00–
//! 08:00): тяжёлое мышление 27B — туда. Отсюда же `quiet_until_ms` — до какого мига впереди будет спокойно.
//! Только мягко: по одной привычке ничего не выгружается — она лишь двигает пороги и подсказывает тихие часы.

use chrono::{Datelike, Local, TimeZone, Timelike};

/// Полужизнь привычки, мс (≈3 недели).
pub const ПОЛУЖИЗНЬ_МС: f64 = 21.0 * 24.0 * 3600.0 * 1000.0;
const КОРЗИН_В_ДЕНЬ: usize = 96; // 24 ч × 4
const ВСЕГО: usize = КОРЗИН_В_ДЕНЬ * 7;
const ЧЕТВЕРТЬ_МС: u64 = 15 * 60 * 1000;

fn вес(сейчас: u64, момент: u64) -> f64 {
    0.5_f64.powf((сейчас.saturating_sub(момент)) as f64 / ПОЛУЖИЗНЬ_МС)
}

/// Одна корзина недели: взвешенные счётчики «наблюдений», «он за ПК», «тяжёлое идёт», затухающие во времени.
#[derive(Clone, Copy, Debug, Default)]
struct Корзина {
    последний_мс: u64,
    всего: f64,
    за_пк: f64,
    тяжёлое: f64,
}

impl Корзина {
    fn затухание(&mut self, сейчас: u64) {
        if self.последний_мс == 0 { return; }
        let в = вес(сейчас, self.последний_мс);
        self.всего *= в;
        self.за_пк *= в;
        self.тяжёлое *= в;
    }
    fn отметить(&mut self, сейчас: u64, за_пк: bool, тяжёлое: bool) {
        self.затухание(сейчас);
        self.последний_мс = сейчас;
        self.всего += 1.0;
        if за_пк { self.за_пк += 1.0; }
        if тяжёлое { self.тяжёлое += 1.0; }
    }
    fn доля_за_пк(&self) -> Option<f64> { (self.всего > 0.0).then(|| self.за_пк / self.всего) }
    fn доля_тяжёлое(&self) -> Option<f64> { (self.всего > 0.0).then(|| self.тяжёлое / self.всего) }
}

/// Индекс корзины недели по местному времени момента (мс эпохи UTC → местное).
pub fn корзина_для(момент_мс: u64) -> usize {
    let секунды = (момент_мс / 1000) as i64;
    let местное = Local.timestamp_opt(секунды, 0).single()
        .unwrap_or_else(|| Local.timestamp_opt(0, 0).unwrap());
    let день = местное.weekday().num_days_from_monday() as usize; // 0 — пн
    let четверть = (местное.hour() as usize * 60 + местное.minute() as usize) / 15;
    (день % 7) * КОРЗИН_В_ДЕНЬ + четверть.min(КОРЗИН_В_ДЕНЬ - 1)
}

/// Начало следующей четверти часа после `момент_мс` (для шага вперёд по корзинам).
fn следующая_четверть(момент_мс: u64) -> u64 {
    (момент_мс / ЧЕТВЕРТЬ_МС + 1) * ЧЕТВЕРТЬ_МС
}

/// Весь ритм недели.
#[derive(Clone)]
pub struct Ритм {
    корзины: Vec<Корзина>,
}

impl Default for Ритм {
    fn default() -> Self { Ритм::новый() }
}

impl Ритм {
    pub fn новый() -> Ритм { Ритм { корзины: vec![Корзина::default(); ВСЕГО] } }

    /// Отметить наблюдение (раз в несколько секунд достаточно): был ли он за ПК и шло ли тяжёлое прямо сейчас.
    pub fn отметить(&mut self, момент_мс: u64, за_пк: bool, тяжёлое: bool) {
        let и = корзина_для(момент_мс);
        self.корзины[и].отметить(момент_мс, за_пк, тяжёлое);
    }

    /// Доля «он за ПК» в корзине текущего момента (с забыванием на `сейчас`). `None` — наблюдений мало.
    pub fn доля_за_пк(&self, момент_мс: u64, сейчас_мс: u64) -> Option<f64> {
        let и = корзина_для(момент_мс);
        let mut к = self.корзины[и];
        к.затухание(сейчас_мс);
        (к.всего >= 3.0).then_some(()).and_then(|_| к.доля_за_пк())
    }

    pub fn доля_тяжёлое(&self, момент_мс: u64, сейчас_мс: u64) -> Option<f64> {
        let и = корзина_для(момент_мс);
        let mut к = self.корзины[и];
        к.затухание(сейчас_мс);
        (к.всего >= 3.0).then_some(()).and_then(|_| к.доля_тяжёлое())
    }

    /// Тихая ли корзина момента: он почти никогда не за ПК (<10 %) и почти нет тяжёлого (<5 %). `None` — мало опыта
    /// (не утверждаем ни тихо, ни шумно).
    pub fn тихо_в(&self, момент_мс: u64, сейчас_мс: u64) -> Option<bool> {
        let за = self.доля_за_пк(момент_мс, сейчас_мс)?;
        let тяж = self.доля_тяжёлое(момент_мс, сейчас_мс)?;
        Some(за < 0.10 && тяж < 0.05)
    }

    /// До какого мига впереди будет спокойно для БАРСа: если сейчас тихо — конец непрерывной тихой полосы (начало
    /// первой не-тихой корзины), но не дальше чем на `предел_ч` вперёд. `None` — сейчас не тихо или опыта мало.
    pub fn тихо_до_мс(&self, сейчас_мс: u64, предел_ч: u64) -> Option<u64> {
        if self.тихо_в(сейчас_мс, сейчас_мс) != Some(true) { return None; }
        let край = сейчас_мс + предел_ч * 3600 * 1000;
        let mut т = следующая_четверть(сейчас_мс);
        let mut конец = т;
        while т <= край {
            match self.тихо_в(т, сейчас_мс) {
                Some(true) => { конец = следующая_четверть(т); т = конец; }
                _ => break, // не-тихо или неизвестно — полоса кончилась
            }
        }
        Some(конец.min(край))
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    // Собрать мс для конкретного местного дня/часа через те же часы ПК, что и в коде.
    fn мс_местного(день_смещение: i64, час: u32, минута: u32) -> u64 {
        use chrono::Duration;
        let сегодня = Local::now().date_naive();
        let д = сегодня + Duration::days(день_смещение);
        let время = д.and_hms_opt(час, минута, 0).unwrap();
        Local.from_local_datetime(&время).single().unwrap().timestamp() as u64 * 1000
    }

    #[test]
    fn корзина_различает_время() {
        let утро = корзина_для(мс_местного(0, 3, 10));
        let вечер = корзина_для(мс_местного(0, 20, 10));
        assert_ne!(утро, вечер);
        assert!(утро < ВСЕГО && вечер < ВСЕГО);
    }

    #[test]
    fn тихие_и_шумные_корзины_и_quiet_until() {
        // Детерминированно: две разные корзины (ночь и +13 ч) на свежих метках, чтобы вес не упал.
        let mut р = Ритм::новый();
        let ночь = 1_700_000_000_000u64; // фиксированный миг
        let день = ночь + 13 * 3600 * 1000; // другой час → другая корзина
        // в корзину «ночь» — 10 наблюдений «его нет, тяжёлого нет» (все в одной четверти часа — в пределах 9 с)
        for i in 0..10u64 { р.отметить(ночь.saturating_sub(i * 1000), false, false); }
        // в корзину «день» — «он за ПК и тяжёлое»
        for i in 0..10u64 { р.отметить(день.saturating_sub(i * 1000), true, true); }
        assert_eq!(р.тихо_в(ночь, ночь), Some(true), "ночная корзина тиха");
        assert_eq!(р.тихо_в(день, день), Some(false), "дневная корзина шумна");
        // quiet_until: сейчас тихо → возвращает миг впереди (конец тихой полосы), больше «сейчас»
        let до = р.тихо_до_мс(ночь, 8).expect("сейчас тихо — есть quiet_until");
        assert!(до > ночь);
        // в шумной корзине quiet_until нет
        assert_eq!(р.тихо_до_мс(день, 8), None);
    }

    #[test]
    fn мало_опыта_молчим() {
        let р = Ритм::новый();
        let сейчас = Local::now().timestamp() as u64 * 1000;
        assert_eq!(р.тихо_в(сейчас, сейчас), None);
        assert_eq!(р.тихо_до_мс(сейчас, 8), None);
    }
}
