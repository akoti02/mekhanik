/// Чистая (видно в тесте): разобрать `ot_barsa.json`; отметка старше `БАРС_СВЕЖ_МС` — БАРСа нет. Протокол v0 (без
/// `proto`) и v1: незнакомые поля пропускаются, нет поля — «не знаю».
pub fn разобрать_барс(текст: &str, сейчас: u64) -> Барс {
    let v: Value = serde_json::from_str(текст.trim_start_matches('\u{feff}')).unwrap_or_default();
    let когда = v.get("ms").and_then(Value::as_u64).unwrap_or(0);
    if когда == 0 || сейчас.saturating_sub(когда) > БАРС_СВЕЖ_МС { return Барс::default(); }
    let номер = |к: &str| v.get(к).and_then(Value::as_u64).map(|п| п as u32).filter(|п| *п != 0);
    let номера = |к: &str| v.get(к).and_then(Value::as_array).into_iter().flatten()
        .filter_map(|x| x.as_u64().map(|п| п as u32)).filter(|п| *п != 0).collect::<Vec<_>>();
    let режим = v.get("mode").and_then(Value::as_str).map(str::to_string);
    let печатает = режим.as_deref() == Some("ПЕЧАТАЕТ");
    let слово_барса = v.get("word").and_then(Value::as_bool);
    Барс {
        жив: true, окно: номер("window"), голова: номер("head"), движки: номера("engines"), счёт: номера("compute"),
        работа: v.get("work").and_then(Value::as_array).into_iter().flatten()
            .filter_map(|x| x.as_str().map(str::to_string)).collect(),
        разум_загружен: v.get("mind_loaded").and_then(Value::as_bool).unwrap_or(false),
        разум_простой_с: v.get("mind_idle_s").and_then(Value::as_u64),
        видео: v.get("video").and_then(Value::as_bool).unwrap_or(false),
        режим,
        разум_pid: номер("mind_pid"),
        слово: слово_барса == Some(true) || печатает,
        протокол: v.get("proto").and_then(Value::as_u64).unwrap_or(0) as u32,
        состояние: Состояние::Свеж,
        слово_барса,
        печатает,
        разум_выключен: v.pointer("/mind/off").and_then(Value::as_bool).unwrap_or(false),
        сигналы_дойдут: v.get("signals_ok").and_then(Value::as_bool),
    }
}

/// 🟥 25.10 (Р-195): когда БАРС последний раз был жив (мс эпохи) — для совместимости; «нет давно» — по картине.
static БАРС_ВИДЕН_МС: AtomicU64 = AtomicU64::new(0);
/// Время без сна при первом чтении картины (БАРСа не видели вовсе — «нет давно» считаем отсюда).
static СТАРТ_БЕЗ_СНА: OnceLock<Option<u64>> = OnceLock::new();
/// БАРСа нет дольше — говорить самому (уведомлением Windows).
const БАРСА_НЕТ_МС: u64 = 10 * 60 * 1000;
static КАРТИНА: Mutex<Option<Картина>> = Mutex::new(None);

/// Прочитать отметку БАРСа и обновить картину (сторож — раз в 2 с).
pub fn прочитать_барс() -> Барс {
    let без_сна = crate::okna::без_сна_мс();
    let _ = СТАРТ_БЕЗ_СНА.get_or_init(|| без_сна);
    let текст = std::fs::read_to_string(папка().join("ot_barsa.json")).ok();
    let флаг = флаг_разума();
    let (б, строки) = {
        let mut г = замок(&КАРТИНА);
        let к = г.get_or_insert_with(Картина::default);
        let б = к.шаг(текст.as_deref(), сейчас_мс(), без_сна, флаг, &kartina_barsa::Windows);
        (б, std::mem::take(&mut к.строки))
    };
    for (событие, данные) in строки { журнал(событие, &данные); }
    if б.жив { БАРС_ВИДЕН_МС.store(сейчас_мс(), Ordering::Relaxed); }
    б
}

/// Картина БАРСа без нового чтения (последний итог `прочитать_барс`; не читали — «нет»).
pub fn картина() -> Барс { замок(&КАРТИНА).as_ref().map(|к| к.итог().clone()).unwrap_or_default() }

/// Чистая (видно в тесте): БАРСа нет давно — с последней встречи (или с нашего старта, если не видели вовсе). 🟥 13.11:
/// времена — без сна (08.11 после сна 6,7 ч отметка БАРСа 4 с была «старой» — ушло ложное «БАРСа нет дольше 10 мин»).
pub fn барса_нет_давно_по(видели: u64, старт: u64, сейчас: u64) -> bool {
    сейчас.saturating_sub(if видели == 0 { старт } else { видели }) >= БАРСА_НЕТ_МС
}

/// БАРС удалён или не свеж дольше 10 мин времени без сна — говорить самому.
fn барса_нет_давно() -> bool {
    let г = замок(&КАРТИНА);
    let Some(к) = г.as_ref() else { return false };
    match к.состояние() {
        Состояние::Свеж => false,
        Состояние::Удалён => true,
        _ => match (crate::okna::без_сна_мс(), СТАРТ_БЕЗ_СНА.get().copied().flatten()) {
            (Some(сейчас), Some(старт)) => барса_нет_давно_по(к.видели_без_сна().unwrap_or(0), старт, сейчас),
            _ => false,
        },
    }
}

/// Флаг «разум выключен его словом» (только читаем; проверка не чаще раза в 10 с). Путь — `mind_off_flag` в
