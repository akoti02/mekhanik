static НОМЕР: AtomicU64 = AtomicU64::new(0);
/// Просьбы и сигналы, что ждут БАРСа: номер → до какого мига годны.
static ЖДЁМ: Mutex<BTreeMap<String, u64>> = Mutex::new(BTreeMap::new());
/// Пора подмести старое (сутки) — `убрать_старые` раз в 10 мин; метёт поток записи.
static ПОДМЕСТИ_СТАРОЕ: AtomicBool = AtomicBool::new(true);

/// Положить сообщение БАРСу (конверт: `id`, `proto`, `ms`); вернуть номер. `важное` (сигнал, просьба) — и при полной
/// очереди, строки журнала — нет. БАРС удалён — не кладём ничего.
fn положить(mut тело: Value, важное: bool) -> Option<String> {
    if замок(&КАРТИНА).as_ref().is_some_and(|к| к.состояние() == Состояние::Удалён) { return None; }
    let сейчас = сейчас_мс();
    let номер = format!("{}-{}", сейчас, НОМЕР.fetch_add(1, Ordering::Relaxed));
    if let Some(о) = тело.as_object_mut() {
        о.insert("id".into(), json!(номер));
        о.insert("proto".into(), json!(ПРОТОКОЛ));
        о.insert("ms".into(), json!(сейчас));
    }
    let з = Задание::Файл { путь: папка().join("soobshcheniya").join(format!("{номер}.json")), текст: тело.to_string(), надёжно: false };
    if важное { zhurnal::важное(з); } else if !zhurnal::потом(з) { return None; }
    Some(номер)
}

/// Подмести (поток записи, раз в 5 с): просьбы и сигналы, чей срок вышел, а БАРС их не взял, — стереть (вернувшись, он
/// не исполнит просьбу без нынешней причины и не разбудит разум старым сигналом); поздний ответ — стереть; строк
/// журнала, что ждут БАРСа, больше `СООБЩЕНИЙ_МАКС` — стереть самые старые; раз в 10 мин — всё старше суток.
pub fn подмести() {
    let сейчас = сейчас_мс();
    let папка_с = папка().join("soobshcheniya");
    let просрочено: Vec<(String, u64)> = замок(&ЖДЁМ).iter().filter(|(_, до)| сейчас > **до).map(|(н, до)| (н.clone(), *до)).collect();
    for (номер, до) in просрочено {
        let ф = папка_с.join(format!("{номер}.json"));
        if std::fs::remove_file(&ф).is_ok() {
            журнал("механик_сообщение_просрочено", &json!({ "id": номер, "смысл": "БАРС не взял за срок — стёрто: без нынешней причины не исполнять" }));
        }
        if сейчас > до.saturating_add(60_000) {
            замок(&ЖДЁМ).remove(&номер);
            let _ = std::fs::remove_file(папка().join("otvety").join(format!("{номер}.json")));
        }
    }
    let Ok(д) = std::fs::read_dir(&папка_с) else { return };
    let mut файлы: Vec<PathBuf> = д.filter_map(Result::ok).map(|ф| ф.path()).filter(|п| п.extension().is_some_and(|р| р == "json")).collect();
    let старое = ПОДМЕСТИ_СТАРОЕ.swap(false, Ordering::Relaxed);
    if файлы.len() <= СООБЩЕНИЙ_МАКС && !старое { return; }
    файлы.sort_by_key(|п| имя_по_порядку(п));
    let mut лишних = файлы.len().saturating_sub(СООБЩЕНИЙ_МАКС);
    for ф in &файлы {
        if лишних == 0 && !старое { break; }
        let v: Value = std::fs::read_to_string(ф).ok().and_then(|т| serde_json::from_str(&т).ok()).unwrap_or_default();
        let строка = v.get("kind").and_then(Value::as_str) == Some("log");
        let просрочено = v.get("until_ms").and_then(Value::as_u64).is_some_and(|до| сейчас > до);
        let суток = ф.metadata().and_then(|м| м.modified()).ok().and_then(|т| т.elapsed().ok())
            .is_some_and(|в| в > Duration::from_secs(24 * 3600));
        if (лишних > 0 && строка) || (старое && (просрочено || суток)) {
            if std::fs::remove_file(ф).is_ok() && строка && лишних > 0 { лишних -= 1; }
        }
    }
    if старое {
        if let Ok(д) = std::fs::read_dir(папка().join("otvety")) {
            for ф in д.filter_map(Result::ok) {
                let суток = ф.metadata().and_then(|м| м.modified()).ok().and_then(|т| т.elapsed().ok())
                    .is_some_and(|в| в > Duration::from_secs(24 * 3600));
                if суток { let _ = std::fs::remove_file(ф.path()); }
            }
        }
    }
}

/// Имя сообщения `<мс>-<n>.json` → (мс, n) — порядок (строкой «-10» встал бы раньше «-9»).
fn имя_по_порядку(п: &Path) -> (u64, u64) {
    let и = п.file_stem().map(|с| с.to_string_lossy().to_string()).unwrap_or_default();
    let mut ч = и.split('-').map(|x| x.parse::<u64>().unwrap_or(u64::MAX));
    (ч.next().unwrap_or(u64::MAX), ч.next().unwrap_or(0))
}

