//! 🟥 13.11 (волна 2б, ключ `arbitr`): МОСТ С БАРСОМ v1. «Механик» — единственный распорядитель железа; БАРС слушается
//! его сигналов (`barsu.json`). Этот модуль собирает заготовку предвидения для `barsu.json` и кладёт её через СЕТТЕР
//! `svyaz::барсу_предвидение` (сам файл пишет `svyaz::отметить` раз в 2 с — он же заполняет `his`, `his_idle_s`,
//! `gpu_clamped`, `mind_off_seen`; мост даёт `his_heavy`, `quiet_until_ms`, `verdict`).
//!
//! 🟥 СХЕМА ВЕРДИКТА (её получит БАРС). Вердикт — что можно разуму 27B сейчас:
//! - `dodumat` (думать дальше) — ПО УМОЛЧАНИЮ: процесс 27B уступает ПРОЦЕССОР (экономный режим и малые ядра — ставит
//!   `tablica`/`rychagi`); судьи не тронуты; видеокарту разум держит;
//! - `otlozhit_hod` (отложить ход) — ТОЛЬКО когда видеокарты NVIDIA или памяти не хватает НА ОБОИХ (его тяжёлое на
//!   NVIDIA либо тесно с памятью). Ход его слова (он печатает) так не откладывается никогда;
//! - `vygruzit_27b` (выгрузить 27B) — ТОЛЬКО если 27B простаивает и место нужно его работе (та же теснота, но разум
//!   не считает — выгрузить полезнее, чем держать и откладывать);
//! - 🟥 просмотр видео — НЕ повод ни для `otlozhit_hod`, ни для `vygruzit_27b`;
//! - 🟥 при ходе ЕГО СЛОВА разуму — ТОЛЬКО `dodumat` (`с_учётом_слова`). Слово — настоящий `mind_word` БАРСа, а НЕ
//!   режим «ПЕЧАТАЕТ» (любой ввод): печатать код в RStudio при тесной памяти — не слово, ход откладывается как надо.
//!
//! 🟥 О проводе: `svyaz` пишет вердикт полями `{gpu, cpu: mozhno|chut|nelzya, why}` (его схема `barsu.json` v1,
//! закреплена в своде). Наш трёхчастный вердикт ложится на неё так: `dodumat`→`gpu=mozhno, cpu=chut`;
//! `otlozhit_hod`→`gpu=nelzya, cpu=chut`; `vygruzit_27b`→`gpu=nelzya, cpu=mozhno` (27B простаивает — процессор свободен).
//! БАРС откладывает ход, когда `gpu=nelzya` (как и велит его правило). Само слово вердикта и причина — в `why` словами;
//! выгрузку (как и сейчас) делает лечение просьбой `unload_mind`, мост её не шлёт.

#![allow(dead_code)]

use super::tablica::Положение;
use crate::kto::{Карточка, Род};
use crate::svyaz;

/// Порог простоя 27B (с), с которого выгрузить полезнее, чем откладывать (как у лечения).
pub const ПРОСТОЙ_27B_С: u64 = 60;

/// Трёхчастный вердикт «Механика» разуму 27B.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Вердикт {
    /// Думать дальше (27B уступает только процессор).
    Додумать,
    /// Отложить ход разума (видеокарты/памяти не хватает на обоих).
    ОтложитьХод,
    /// Выгрузить простаивающий 27B (место нужно его работе).
    Выгрузить27B,
}

impl Вердикт {
    pub fn ключ(self) -> &'static str {
        match self {
            Вердикт::Додумать => "dodumat",
            Вердикт::ОтложитьХод => "otlozhit_hod",
            Вердикт::Выгрузить27B => "vygruzit_27b",
        }
    }
}

/// Что знаем о разуме для вердикта (из картины БАРСа, `svyaz::картина`).
#[derive(Clone, Copy, Debug, Default)]
pub struct Разум {
    pub печатает: bool,
    pub загружен: bool,
    /// Секунд простоя 27B (`None` — считает или не загружен).
    pub простой_с: Option<u64>,
}

/// 🟥 ЧИСТАЯ (видно в тестах): вердикт по положению и состоянию разума. `его_тяжёлое` — короткая подпись виновника для
/// причины («его Blender держит 6,2 ГБ видеопамяти»), либо пусто. Ход ЕГО СЛОВА поверх этого учитывает `с_учётом_слова`
/// (по настоящему `mind_word`); само `печатает` (любой ввод) ход НЕ защищает — иначе набор текста при тесной памяти
/// держал бы 27B и уводил ПК в подкачку.
pub fn вердикт(положение: Положение, разум: &Разум, его_тяжёлое: &str) -> (Вердикт, String) {
    let _ = разум.печатает; // присутствие (ввод) — не повод для «додумать»; ход слова учитывает `с_учётом_слова`
    let тесно = matches!(положение, Положение::ТяжёлоеNvidia | Положение::МалоПамяти);
    if !тесно {
        return (Вердикт::Додумать, "думать дальше: 27B уступает процессор (экономный режим, малые ядра); \
            видеокарта и память свободны для обоих".into());
    }
    let хвост = if его_тяжёлое.is_empty() { String::new() } else { format!(" ({его_тяжёлое})") };
    let простаивает = разум.загружен && разум.простой_с.is_some_and(|с| с >= ПРОСТОЙ_27B_С);
    if простаивает {
        let с = разум.простой_с.unwrap_or(0);
        (Вердикт::Выгрузить27B, format!("27B простаивает {с} с, место нужно его работе{хвост} — лучше выгрузить, чем держать"))
    } else {
        (Вердикт::ОтложитьХод, format!("видеокарте NVIDIA или памяти не хватает на обоих — отложить ход разума{хвост}"))
    }
}

/// 🟥 ЧИСТАЯ (видно в тестах): учесть ход ЕГО СЛОВА поверх вердикта. Идёт настоящее слово разуму (`mind_word` БАРСа,
/// а не просто «печатает») — ход НЕ откладываем никогда: `ОтложитьХод`/`Выгрузить27B` становятся `Додумать`.
/// `Додумать` остаётся как есть. Слова нет — вердикт не трогаем (теснота решает по памяти/видеокарте).
pub fn с_учётом_слова(в: Вердикт, почему: String, слово_разуму: bool) -> (Вердикт, String) {
    if слово_разуму && в != Вердикт::Додумать {
        return (Вердикт::Додумать, "идёт его слово разуму — ход его слова не откладываем никогда".into());
    }
    (в, почему)
}

/// Перевести наш вердикт в вердикт провода `svyaz` ({gpu, cpu, why}).
fn в_svyaz_вердикт(в: Вердикт, почему: String) -> svyaz::Вердикт {
    use svyaz::Можно::*;
    let (gpu, cpu) = match в {
        Вердикт::Додумать => (Можно, Чуть),
        Вердикт::ОтложитьХод => (Нельзя, Чуть),
        Вердикт::Выгрузить27B => (Нельзя, Можно),
    };
    svyaz::Вердикт { видеокарта: gpu, ядра: cpu, почему }
}

/// Род для провода `barsu.json` (словарь `svyaz`: `sborka/sapr/render/raschet/montazh/igra/vm/browser/prosmotr/
/// obuchenie/claude/utility/telemetry/unknown`; по нему БАРС и отсеивает `prosmotr`).
pub fn род_ключ(р: Род) -> &'static str {
    match р {
        Род::Сборка => "sborka", Род::Сапр => "sapr", Род::Рендер3д => "render", Род::Расчёт => "raschet",
        Род::ВидеоМонтаж => "montazh", Род::Игра => "igra", Род::Вм => "vm", Род::Браузер => "browser",
        Род::Просмотр => "prosmotr", Род::Обучение => "obuchenie", Род::Claude => "claude",
        Род::Утилита => "utility", Род::Телеметрия => "telemetry", Род::Неизвестно => "unknown",
    }
}

/// Собрать `svyaz::Тяжёлое` из карточки его работы (просмотр сюда не попадает — он не тяжёлое).
pub fn тяжёлое_из(к: &Карточка, с_мс: u64) -> svyaz::Тяжёлое {
    let mut нужно = Vec::new();
    if к.решение.нужно.nvidia { нужно.push(svyaz::Нужно::Nvidia); }
    if к.решение.нужно.видеопамять { нужно.push(svyaz::Нужно::Видеопамять); }
    if к.решение.нужно.озу { нужно.push(svyaz::Нужно::Озу); }
    if к.решение.нужно.процессор { нужно.push(svyaz::Нужно::Ядра); }
    svyaz::Тяжёлое {
        род: род_ключ(к.решение.род).into(),
        нужно,
        pid: к.личность.pid,
        создан: к.личность.создан,
        с_мс,
        пик_мб: к.ожидаемый_озу_мб,
        подпись: к.подпись.clone(),
    }
}

/// 🟥 Положить заготовку предвидения в `barsu.json` через сеттер `svyaz` (его допишет `svyaz::отметить`).
pub fn в_барс(тяжёлое: Vec<svyaz::Тяжёлое>, тихо_до_мс: Option<u64>, в: Вердикт, почему: String) {
    svyaz::барсу_предвидение(svyaz::ДляБарса {
        тяжёлое: Some(тяжёлое),
        тихо_до_мс,
        вердикт: Some(в_svyaz_вердикт(в, почему)),
    });
}

#[cfg(test)]
mod тесты {
    use super::*;

    fn разум(печатает: bool, загружен: bool, простой: Option<u64>) -> Разум {
        Разум { печатает, загружен, простой_с: простой }
    }

    /// 🟥 Видео — НИКОГДА не повод: при просмотре вердикт — думать дальше.
    #[test]
    fn видео_никогда_не_откладывает() {
        let (в, _) = вердикт(Положение::Видео, &разум(false, true, Some(300)), "");
        assert_eq!(в, Вердикт::Додумать);
    }

    /// 🟥 КРАСНО НА СТАРОМ: просто «печатает» (любой ввод) при тесной памяти НЕ держит ход — иначе 27B не выгрузить и
    /// ПК уходит в подкачку. Старое давало Додумать по разум.печатает; теперь — ОтложитьХод.
    #[test]
    fn печатает_не_держит_ход_при_тесноте() {
        let (в, _) = вердикт(Положение::МалоПамяти, &разум(true, true, None), "его RStudio");
        assert_eq!(в, Вердикт::ОтложитьХод, "печатает — присутствие, не слово: при тесноте ход откладываем");
    }

    /// 🟥 Ход ЕГО СЛОВА (настоящий mind_word) поверх вердикта — ТОЛЬКО dodumat, даже когда тесно с видеокартой.
    #[test]
    fn его_слово_только_додумать() {
        let (в0, п0) = вердикт(Положение::ТяжёлоеNvidia, &разум(false, true, Some(999)), "его игра");
        assert_ne!(в0, Вердикт::Додумать, "без слова при тесноте — не додумать");
        let (в, почему) = с_учётом_слова(в0, п0, true);
        assert_eq!(в, Вердикт::Додумать);
        assert!(почему.contains("слов"), "{почему}");
        // слова нет — вердикт оставлен как есть
        let (в2, _) = с_учётом_слова(Вердикт::ОтложитьХод, "x".into(), false);
        assert_eq!(в2, Вердикт::ОтложитьХод);
    }

    /// По умолчанию (за ПК, его тяжёлое на процессоре) — думать дальше, уступает только процессор.
    #[test]
    fn по_умолчанию_додумать() {
        assert_eq!(вердикт(Положение::ЗаПк, &разум(false, true, None), "").0, Вердикт::Додумать);
        assert_eq!(вердикт(Положение::ТяжёлоеПроцессор, &разум(false, true, None), "его сборка").0, Вердикт::Додумать);
    }

    /// 🟥 Отложить ход — только по видеокарте NVIDIA или памяти, и только когда 27B не простаивает.
    #[test]
    fn отложить_ход_по_видеокарте() {
        let (в, почему) = вердикт(Положение::ТяжёлоеNvidia, &разум(false, true, None), "его Blender");
        assert_eq!(в, Вердикт::ОтложитьХод);
        assert!(почему.contains("Blender"), "{почему}");
        // мало памяти — тоже отложить
        assert_eq!(вердикт(Положение::МалоПамяти, &разум(false, true, Some(10)), "").0, Вердикт::ОтложитьХод);
    }

    /// 🟥 Выгрузить 27B — только если он загружен и простаивает ≥ порога, и место нужно его работе.
    #[test]
    fn выгрузить_только_простаивающий() {
        let (в, _) = вердикт(Положение::ТяжёлоеNvidia, &разум(false, true, Some(ПРОСТОЙ_27B_С)), "его игра");
        assert_eq!(в, Вердикт::Выгрузить27B);
        // загружен, но считает (простой None) — не выгружаем, откладываем
        assert_eq!(вердикт(Положение::ТяжёлоеNvidia, &разум(false, true, None), "").0, Вердикт::ОтложитьХод);
        // не загружен — откладываем (выгружать нечего)
        assert_eq!(вердикт(Положение::МалоПамяти, &разум(false, false, None), "").0, Вердикт::ОтложитьХод);
    }

    /// Провод: dodumat→gpu можно; otlozhit/vygruzit→gpu нельзя.
    #[test]
    fn провод_вердикта() {
        use svyaz::Можно::*;
        assert_eq!(в_svyaz_вердикт(Вердикт::Додумать, String::new()).видеокарта, Можно);
        assert_eq!(в_svyaz_вердикт(Вердикт::ОтложитьХод, String::new()).видеокарта, Нельзя);
        let вг = в_svyaz_вердикт(Вердикт::Выгрузить27B, String::new());
        assert_eq!((вг.видеокарта, вг.ядра), (Нельзя, Можно));
    }

    #[test]
    fn род_для_провода() {
        assert_eq!(род_ключ(Род::Просмотр), "prosmotr"); // по нему БАРС отсеивает видео из his_heavy
        assert_eq!(род_ключ(Род::Сборка), "sborka");
        assert_eq!(род_ключ(Род::Игра), "igra");
    }
}
