//! 🟥 13.11 (волна 2б, ключ `arbitr`): ТАБЛИЦА ПОЛОЖЕНИЙ «кто — что». Его слово: «Механик» держит каждой группе
//! процессов её набор настроек ЗАРАНЕЕ (по положению ПК), а лечение остаётся тому, что таблица не предусмотрела
//! (1 048 эпизодов «лечить нечего» — тормоз уже есть, а рычага нет: `izobretatel_proizvoditelnost.md` §5.0).
//!
//! Таблица — чистая (видно в тестах): `положение ПК × группа → уровни`. Уровни — только обратимые рычаги его сеанса
//! без прав: приоритет процесса, экономный режим (EcoQoS), набор ядер (малые/все), приоритет памяти и диска.
//! Самих рычагов тут нет — их ставит `rychagi`; тут только РЕШЕНИЕ, что кому поставить.
//!
//! 🟥 Его порядок (13.11): он сам → его работа → БАРС (думает в промежутках) → фон. Поэтому:
//! - его окну и его работе — НИКОГДА ограничений (ни в одном положении);
//! - судьям БАРСа — НИКОГДА не трогать (сила принуждения его правил, 27.10);
//! - голове и окну БАРСа — НИКОГДА не трогать (держат связь);
//! - разум 27B может уступать ПРОЦЕССОР (экономный режим + малые ядра), пока он работает; ход разума откладывается
//!   не тут, а вердиктом (`most`), и только по видеокарте/памяти;
//! - 🟥 просмотр видео — НЕ повод ни для чего: ради фильма разум не уступает никогда (его решение 13.11);
//! - 🟥 пока он печатает разуму (его слово) — разум не трогать вовсе.

// Часть рычагов включит сведение (лечение/окно возьмут уровни отсюда) — пока «не используется» местами.
#![allow(dead_code)]

/// Положение ПК — то, по чему «Механик» выбирает настройки заранее (события и замер дают его `arbitr`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Положение {
    /// Он за ПК, тяжёлого ничего не идёт.
    ЗаПк,
    /// Его тяжёлое грузит процессор (сборка, расчёт, ВМ…).
    ТяжёлоеПроцессор,
    /// Его тяжёлое грузит видеокарту NVIDIA (игра, рендер, обучение, счёт на CUDA).
    ТяжёлоеNvidia,
    /// Памяти мало — на обоих (он + БАРС) не хватает.
    МалоПамяти,
    /// Он смотрит видео (фильм, сериал, ролик) — НЕ тяжёлое.
    Видео,
    /// Его нет за ПК (2 мин без ввода, замок или погасший экран).
    ЕгоНет,
}

impl Положение {
    pub fn ключ(self) -> &'static str {
        match self {
            Положение::ЗаПк => "za_pk",
            Положение::ТяжёлоеПроцессор => "his_cpu",
            Положение::ТяжёлоеNvidia => "his_nvidia",
            Положение::МалоПамяти => "low_ram",
            Положение::Видео => "video",
            Положение::ЕгоНет => "away",
        }
    }
    pub fn слово(self) -> &'static str {
        match self {
            Положение::ЗаПк => "он за ПК, тяжёлого нет",
            Положение::ТяжёлоеПроцессор => "его тяжёлое на процессоре",
            Положение::ТяжёлоеNvidia => "его тяжёлое на видеокарте NVIDIA",
            Положение::МалоПамяти => "памяти мало",
            Положение::Видео => "он смотрит видео",
            Положение::ЕгоНет => "его нет за ПК",
        }
    }
}

/// Группа процессов в его порядке.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Группа {
    /// Его окно впереди и его дерево — никогда не трогать.
    ЕгоОкно,
    /// Его работа (любое тяжёлое, что он запустил; сессии разработки и сборки) — никогда не трогать.
    ЕгоРабота,
    /// Разум 27B (и прочие движки счёта БАРСа) — может уступать процессор.
    Разум27B,
    /// Судьи БАРСа — НЕ трогать никогда (сила принуждения).
    СудьиБарса,
    /// Голова и окно БАРСа — НЕ трогать никогда (держат связь).
    ГоловаОкноБарса,
    /// Фон своего сеанса (утилиты, обновлялки, мессенджеры, копия ПК, фоновые вкладки).
    Фон,
}

/// Приоритет процессора, который ставит таблица. Повышать чужое «Механик» не вправе — только оставить или понизить.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Приоритет {
    /// Не менять — пусть будет как ставит Windows/БАРС/лечение.
    Оставить,
    /// Ниже обычного (BELOW_NORMAL): фону, пока идёт его тяжёлое.
    НижеОбычного,
}

/// Набор ядер, на которых держать процесс.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Ядра {
    /// Все ядра (не ограничивать).
    Все,
    /// Только малые и самые экономные (E + LP-E) — большие ядра остаются его окну и работе. Карту ядер даёт
    /// `GetSystemCpuSetInformation` по классам эффективности (`rychagi`), номера не зашиты.
    Малые,
}

/// Уровни — что поставить одному процессу в его положении. Только обратимое. `память`/`диск`: `None` — не трогать;
/// `Some(n)` — поставить уровень n (память 1 — очень низкий … 5 — обычный; диск 0 — очень низко, 1 — низко, 2 — обычно).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Уровни {
    pub приоритет: Приоритет,
    pub эко: bool,
    pub ядра: Ядра,
    pub память: Option<u32>,
    pub диск: Option<u32>,
}

/// Приоритет памяти «низкий» (его страницы Windows отдаёт другим первыми) — фону, пока тесно или идёт его тяжёлое.
pub const ПАМЯТЬ_НИЗКО: u32 = 2;
/// Очередь диска «низко».
pub const ДИСК_НИЗКО: u32 = 1;

impl Уровни {
    /// Ничего не менять — так живут его окно, его работа, судьи, голова и окно БАРСа ВСЕГДА.
    pub const fn без_изменений() -> Уровни {
        Уровни { приоритет: Приоритет::Оставить, эко: false, ядра: Ядра::Все, память: None, диск: None }
    }
    /// Таблица для этой группы в этом положении ничего не ставит (и ранее поставленное надо снять).
    pub fn ограничений_нет(&self) -> bool {
        self.приоритет == Приоритет::Оставить && !self.эко && self.ядра == Ядра::Все
            && self.память.is_none() && self.диск.is_none()
    }
}

/// 🟥 ЧИСТАЯ (видно в тестах): таблица «кто — что». `печатает` — он печатает разуму (его слово идёт): разум не трогаем.
///
/// | группа \\ положение | за ПК | его проц. | его NVIDIA | мало памяти | видео | его нет |
/// |---|---|---|---|---|---|---|
/// | его окно, его работа | — | — | — | — | — | — |
/// | судьи БАРСа | — | — | — | — | — | — |
/// | голова/окно БАРСа | — | — | — | — | — | — |
/// | разум 27B | эко+малые | эко+малые | эко+малые | эко+малые | — | — |
/// | фон | эко | эко+малые+↓приор.+↓память+↓диск | то же | эко+↓память+↓диск | эко | — |
///
/// («—» — без изменений; разум при `печатает` — тоже «—».)
pub fn решить(положение: Положение, группа: Группа, печатает: bool) -> Уровни {
    use Положение::*;
    match группа {
        // его порядок: его окно и работа — никогда ограничений; судьи, голова и окно БАРСа — никогда не трогать
        Группа::ЕгоОкно | Группа::ЕгоРабота | Группа::СудьиБарса | Группа::ГоловаОкноБарса => Уровни::без_изменений(),

        Группа::Разум27B => {
            // его слово (печатает) — разум не трогаем вовсе; видео — не повод; его нет — пусть БАРС думает в полную силу
            if печатает || матч_без_уступки(положение) {
                Уровни::без_изменений()
            } else {
                // уступает ПРОЦЕССОР: экономный режим и малые ядра. Память не трогаем (риск подкачки его хода —
                // этим ведает лечение просьбой), ход на видеокарте откладывает вердикт, а не таблица.
                Уровни { приоритет: Приоритет::Оставить, эко: true, ядра: Ядра::Малые, память: None, диск: None }
            }
        }

        Группа::Фон => match положение {
            ЕгоНет => Уровни::без_изменений(), // его нет — фон (его же агенты и ночные сборки) идёт в полную силу
            Видео | ЗаПк => Уровни { приоритет: Приоритет::Оставить, эко: true, ядра: Ядра::Все, память: None, диск: None },
            ТяжёлоеПроцессор | ТяжёлоеNvidia => Уровни {
                приоритет: Приоритет::НижеОбычного, эко: true, ядра: Ядра::Малые,
                память: Some(ПАМЯТЬ_НИЗКО), диск: Some(ДИСК_НИЗКО),
            },
            МалоПамяти => Уровни {
                приоритет: Приоритет::Оставить, эко: true, ядра: Ядра::Все,
                память: Some(ПАМЯТЬ_НИЗКО), диск: Some(ДИСК_НИЗКО),
            },
        },
    }
}

/// Положения, где разум уступать НЕ должен: видео (не тяжёлое) и «его нет» (пусть думает полно).
fn матч_без_уступки(п: Положение) -> bool {
    matches!(п, Положение::Видео | Положение::ЕгоНет)
}

#[cfg(test)]
mod тесты {
    use super::*;

    const ВСЕ_ПОЛОЖЕНИЯ: [Положение; 6] = [
        Положение::ЗаПк, Положение::ТяжёлоеПроцессор, Положение::ТяжёлоеNvidia,
        Положение::МалоПамяти, Положение::Видео, Положение::ЕгоНет,
    ];

    /// 🟥 Его окну и его работе — НИКОГДА ограничений, ни в одном положении, печатает он или нет.
    #[test]
    fn его_окно_и_работа_никогда_не_ограничены() {
        for п in ВСЕ_ПОЛОЖЕНИЯ {
            for печатает in [false, true] {
                assert!(решить(п, Группа::ЕгоОкно, печатает).ограничений_нет(), "окно {п:?}");
                assert!(решить(п, Группа::ЕгоРабота, печатает).ограничений_нет(), "работа {п:?}");
            }
        }
    }

    /// 🟥 Судей БАРСа — НЕ трогать никогда.
    #[test]
    fn судьи_никогда() {
        for п in ВСЕ_ПОЛОЖЕНИЯ {
            assert!(решить(п, Группа::СудьиБарса, false).ограничений_нет(), "судьи {п:?}");
            assert!(решить(п, Группа::СудьиБарса, true).ограничений_нет(), "судьи {п:?} печатает");
        }
    }

    /// 🟥 Голову и окно БАРСа — НЕ трогать никогда.
    #[test]
    fn голова_и_окно_барса_никогда() {
        for п in ВСЕ_ПОЛОЖЕНИЯ {
            assert!(решить(п, Группа::ГоловаОкноБарса, false).ограничений_нет(), "голова/окно {п:?}");
        }
    }

    /// 🟥 Видео — не повод: разум НЕ уступает, даже когда занят процессор по положению.
    #[test]
    fn видео_разум_не_уступает() {
        assert!(решить(Положение::Видео, Группа::Разум27B, false).ограничений_нет(),
            "смотрит видео — разум думает в полную силу");
    }

    /// 🟥 Его слово (печатает) — разум НЕ трогаем ни в каком положении.
    #[test]
    fn его_слово_разум_не_трогаем() {
        for п in ВСЕ_ПОЛОЖЕНИЯ {
            assert!(решить(п, Группа::Разум27B, true).ограничений_нет(), "печатает, {п:?} — разум не трогать");
        }
    }

    /// Пока он работает (не печатает, не видео, не «его нет») — разум уступает процессор: эко + малые ядра.
    #[test]
    fn разум_уступает_процессор_пока_он_работает() {
        for п in [Положение::ЗаПк, Положение::ТяжёлоеПроцессор, Положение::ТяжёлоеNvidia, Положение::МалоПамяти] {
            let у = решить(п, Группа::Разум27B, false);
            assert!(у.эко && у.ядра == Ядра::Малые, "{п:?}: разум — эко и малые ядра");
            assert!(у.память.is_none(), "{п:?}: память разума не трогаем (риск подкачки хода)");
            assert_eq!(у.приоритет, Приоритет::Оставить, "{п:?}: приоритет разума — дело БАРСа/лечения");
        }
        // его нет — разум в полную силу
        assert!(решить(Положение::ЕгоНет, Группа::Разум27B, false).ограничений_нет());
    }

    /// Фон уступает большие ядра его тяжёлому.
    #[test]
    fn фон_под_его_тяжёлым() {
        let у = решить(Положение::ТяжёлоеПроцессор, Группа::Фон, false);
        assert!(!у.ограничений_нет());
        assert!(у.эко && у.ядра == Ядра::Малые && у.приоритет == Приоритет::НижеОбычного);
        assert_eq!((у.память, у.диск), (Some(ПАМЯТЬ_НИЗКО), Some(ДИСК_НИЗКО)));
        // то же на его NVIDIA
        assert_eq!(решить(Положение::ТяжёлоеNvidia, Группа::Фон, false), у);
    }

    /// Он за ПК без тяжёлого — фону только экономный режим (большие ядра не запираем, память не трогаем).
    #[test]
    fn фон_за_пк_только_эко() {
        let у = решить(Положение::ЗаПк, Группа::Фон, false);
        assert!(у.эко && у.ядра == Ядра::Все && у.память.is_none() && у.диск.is_none());
        assert_eq!(у.приоритет, Приоритет::Оставить);
    }

    /// Его нет — фон не ограничиваем (его ночные сборки и агенты идут в полную силу).
    #[test]
    fn фон_без_него_свободен() {
        assert!(решить(Положение::ЕгоНет, Группа::Фон, false).ограничений_нет());
    }

    /// Мало памяти — фону память и диск низко, но ядра не запираем (узкое место — память, не ядра).
    #[test]
    fn мало_памяти_фон_отдаёт_память() {
        let у = решить(Положение::МалоПамяти, Группа::Фон, false);
        assert_eq!((у.память, у.диск, у.ядра), (Some(ПАМЯТЬ_НИЗКО), Some(ДИСК_НИЗКО), Ядра::Все));
    }
}
