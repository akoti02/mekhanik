    fn запись_ядра(id: u32, класс: u8) -> [u8; 32] {
        let mut з = [0u8; 32];
        з[0..4].copy_from_slice(&32u32.to_le_bytes()); // Size
        з[4..8].copy_from_slice(&0u32.to_le_bytes()); // Type = CpuSet
        з[8..12].copy_from_slice(&id.to_le_bytes()); // Id
        з[18] = класс; // EfficiencyClass
        з
    }

