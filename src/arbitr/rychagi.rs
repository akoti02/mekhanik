/// Что «Механик» поставил одному процессу — чтобы вернуть прежнее. `память_был`/`диск_был`/`приоритет_был` — значения
/// ДО нашего вмешательства (их и возвращаем); эко и ядра возвращаем снятием (к выбору Windows).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct Запись {
    эко: bool,
    малые: bool,
    память_был: Option<u32>,
    диск_был: Option<u32>,
    приоритет_был: Option<u32>,
}

impl Запись {
    fn пусто(&self) -> bool {
        !self.эко && !self.малые && self.память_был.is_none() && self.диск_был.is_none() && self.приоритет_был.is_none()
    }
}

/// Рычаги и книга возврата. Один на Мозг.
pub struct Рычаги {
    применено: HashMap<Личность, Запись>,
    малые: Vec<u32>,
    наш_сеанс: u32,
    путь: std::path::PathBuf,
}

impl Рычаги {
    /// При старте: снять с Windows карту ядер; прочитать книгу прошлого запуска и ВЕРНУТЬ всё, что осталось после
    /// падения (эко, ядра, память, диск, приоритет), затем начать с чистой книги.
    pub fn новый() -> Рычаги {
        let наш_сеанс = okna::сеанс(std::process::id()).unwrap_or(1);
        let мут = Рычаги {
            применено: HashMap::new(),
            малые: малые_ядра_системы(),
            наш_сеанс,
            путь: svyaz::папка().join("arbitr_vozvrat.json"),
        };
        мут.вернуть_прошлый_запуск();
        мут
    }

    /// Вернуть всё, что осталось в книге прошлого запуска (после падения «Механика» рычаги не сброшены).
    fn вернуть_прошлый_запуск(&self) {
        let Some(записи) = std::fs::read_to_string(&self.путь).ok()
            .and_then(|т| serde_json::from_str::<Value>(&т).ok())
            .and_then(|v| v.get("zapisi").and_then(|з| з.as_array()).cloned()) else { return };
        let mut вернул = 0u32;
        for з in &записи {
            let pid = з.get("pid").and_then(Value::as_u64).unwrap_or(0) as u32;
            let создан = з.get("created").and_then(Value::as_u64).unwrap_or(0);
            if pid == 0 { continue; }
            // процесс ещё жив и это тот самый (время создания совпало) — вернуть прежнее
            if okna::создан(pid).unwrap_or(0) != создан { continue; }
            let зап = Запись {
                эко: з.get("eco").and_then(Value::as_bool).unwrap_or(false),
                малые: з.get("cores").and_then(Value::as_bool).unwrap_or(false),
                память_был: з.get("mem_was").and_then(Value::as_u64).map(|n| n as u32),
                диск_был: з.get("disk_was").and_then(Value::as_u64).map(|n| n as u32),
                приоритет_был: з.get("prio_was").and_then(Value::as_u64).map(|n| n as u32),
            };
            вернуть_процесс(pid, &зап);
            вернул += 1;
        }
        if !записи.is_empty() {
            svyaz::журнал("арбитр_возврат_после_старта",
                &json!({ "в_книге": записи.len(), "вернул_живым": вернул,
                    "смысл": "рычаги прошлого запуска сняты (после падения книга оставалась)" }));
        }
        let _ = std::fs::remove_file(&self.путь);
    }

    /// Сохранить книгу надёжно (переживает внезапное выключение): возврат при следующем старте.
    fn сохранить(&self) {
        let записи: Vec<Value> = self.применено.iter().filter(|(_, з)| !з.пусто()).map(|(л, з)| json!({
            "pid": л.pid, "created": л.создан, "eco": з.эко, "cores": з.малые,
            "mem_was": з.память_был, "disk_was": з.диск_был, "prio_was": з.приоритет_был,
        })).collect();
        let _ = svyaz::записать_надёжно(&self.путь, &json!({ "proto": 1, "zapisi": записи }).to_string());
    }

    /// Поставить процессу уровни по таблице. Только его сеанс; не его сеанс — снять прежнее и выйти. `Уровни` без
    /// ограничений — снять прежнее. Идемпотентно (меняем только то, что отличается от уже применённого).
    pub fn применить(&mut self, личность: Личность, у: &Уровни) {
        let pid = личность.pid;
        if okna::сеанс(pid) != Some(self.наш_сеанс) {
            self.снять(личность);
            return;
        }
        if у.ограничений_нет() {
            self.снять(личность);
            return;
        }
        let малые = std::mem::take(&mut self.малые);
        let mut зап = self.применено.get(&личность).copied().unwrap_or_default();

        // экономный режим
        if у.эко && !зап.эко {
            if эко(pid, true).is_some() { зап.эко = true; }
        } else if !у.эко && зап.эко {
            эко(pid, false);
            зап.эко = false;
        }
        // набор ядер
        let нужны_малые = matches!(у.ядра, Ядра::Малые) && !малые.is_empty();
        if нужны_малые && !зап.малые {
            if набор_ядер(pid, &малые).is_some() { зап.малые = true; }
        } else if !нужны_малые && зап.малые {
            набор_ядер(pid, &[]);
            зап.малые = false;
        }
        // приоритет памяти
        match у.память {
            Some(ур) if зап.память_был.is_none() => {
                if let Some((был, _)) = okna::память_процесса(pid, Some(ур)) { зап.память_был = Some(был); }
            }
            None if зап.память_был.is_some() => {
                okna::память_процесса(pid, зап.память_был);
                зап.память_был = None;
            }
            _ => {}
        }
        // очередь диска
        match у.диск {
            Some(ур) if зап.диск_был.is_none() => {
                if let Some((был, _)) = okna::очередь_диска(pid, Some(ур)) { зап.диск_был = Some(был); }
            }
            None if зап.диск_был.is_some() => {
                okna::очередь_диска(pid, зап.диск_был);
                зап.диск_был = None;
            }
            _ => {}
        }
        // приоритет процессора (только понизить — ниже обычного)
        match у.приоритет {
            Приоритет::НижеОбычного if зап.приоритет_был.is_none() => {
                if let Some(был) = okna::приоритет_сейчас(pid) {
                    if окна_приоритет(pid, НИЖЕ_ОБЫЧНОГО) { зап.приоритет_был = Some(был); }
                }
            }
            Приоритет::Оставить if зап.приоритет_был.is_some() => {
                окна_приоритет(pid, зап.приоритет_был.unwrap_or(ОБЫЧНЫЙ));
                зап.приоритет_был = None;
            }
            _ => {}
        }

        self.малые = малые;
        if зап.пусто() {
            self.применено.remove(&личность);
        } else {
            self.применено.insert(личность, зап);
        }
        self.сохранить();
    }

    /// Снять всё поставленное одному процессу (вернуть прежнее).
    pub fn снять(&mut self, личность: Личность) {
        if let Some(зап) = self.применено.remove(&личность) {
            вернуть_процесс(личность.pid, &зап);
            self.сохранить();
        }
    }

    /// 🟥 Вернуть ВСЁ (при смене положения на «без ограничений», при выходе Мозга). После — книга пуста.
    pub fn вернуть_всё(&mut self) {
        let все: Vec<(Личность, Запись)> = self.применено.drain().collect();
        for (л, з) in все {
            вернуть_процесс(л.pid, &з);
        }
        self.сохранить();
    }

    /// Забыть процессы, которых уже нет в снимке (умерли — возвращать нечего). Книгу не трогаем для живых.
    pub fn прибрать(&mut self, живые: &std::collections::HashSet<Личность>) {
        let было = self.применено.len();
        self.применено.retain(|л, _| живые.contains(л));
        if self.применено.len() != было {
            self.сохранить();
        }
    }

    /// Сколько процессов сейчас под рычагами (для журнала/окна).
    pub fn под_рычагами(&self) -> usize {
        self.применено.len()
    }

    /// Малые наборы ядер (для живой пробы/окна); пусто — карта не снялась или не гибрид.
    pub fn малые_ядра(&self) -> &[u32] {
        &self.малые
    }
}

/// Вернуть процессу прежнее по записи книги (эко/ядра — снять, память/диск/приоритет — восстановить значение).
fn вернуть_процесс(pid: u32, зап: &Запись) {
    if зап.эко {
        эко(pid, false);
    }
    if зап.малые {
        набор_ядер(pid, &[]);
    }
    if let Some(ур) = зап.память_был {
        okna::память_процесса(pid, Some(ур));
    }
    if let Some(ур) = зап.диск_был {
        okna::очередь_диска(pid, Some(ур));
    }
    if let Some(кл) = зап.приоритет_был {
        окна_приоритет(pid, кл);
    }
}

/// Поставить приоритет процессора (обёртка над `okna::приоритет`, которая возвращает (был, стал)).
fn окна_приоритет(pid: u32, класс: u32) -> bool {
    okna::приоритет(pid, класс).is_some()
}

