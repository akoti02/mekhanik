//! 🟥 13.11 (волна 2б, ключ `arbitr`): РЫЧАГИ таблицы положений и КНИГА ВОЗВРАТА. Ставит процессам его сеанса то, что
//! решила `tablica` (`Уровни`), и помнит, что поменял, чтобы вернуть — при смене положения, при выходе и при старте
//! после падения (`izobretatel_proizvoditelnost.md` §5.0: «всё обратимо; всё записывается в книгу возврата»).
//!
//! 🟥 Правила его (обязательны):
//! - только процессы ЕГО сеанса; система (сеанс 0), его окно, его работа, судьи, голова и окно БАРСа — не трогаем
//!   (это решает таблица: им `Уровни::без_изменений`, и сюда они приходят «снять»);
//! - только обратимое и только без прав администратора: приоритет (ниже обычного), экономный режим (EcoQoS),
//!   набор ядер (малые), приоритет памяти и диска. Повышать чужое не вправе — только оставить/понизить и вернуть;
//! - процесс не открылся (повышенные права, защищённый) — молча пропустить: подкрутить его «Механик» и не должен.
//!
//! Карта ядер — `GetSystemCpuSetInformation` по классам эффективности (номера ядер не зашиты: на этом ПК большие
//! 0,1,10–13; малые 2–9; самые экономные 14,15 — но берём по `EfficiencyClass`). «Малые» = все, кроме самого
//! производительного класса (E + LP-E, 10 из 16 — как И-4).
//!
//! Живые вызовы Windows тут настоящие (меняют чужие процессы), поэтому в тестах — только разбор карты ядер (чисто) и
//! живая проба на СВОЁМ дочернем процессе (`#[ignore]`). Над чужими процессами в тестах ничего не делаем.

