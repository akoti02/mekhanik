// ── биты доступа и константы ──
/// PROCESS_QUERY_LIMITED_INFORMATION | PROCESS_SET_INFORMATION | PROCESS_SET_LIMITED_INFORMATION | PROCESS_QUERY_INFORMATION
const ДОСТУП: u32 = 0x1000 | 0x0200 | 0x2000 | 0x0400;
/// ProcessPowerThrottling.
const ДРОССЕЛЬ: u32 = 4;
/// PROCESS_POWER_THROTTLING_EXECUTION_SPEED.
const СКОРОСТЬ: u32 = 1;
/// BELOW_NORMAL_PRIORITY_CLASS и NORMAL (возврат, если прежнего не знаем).
const НИЖЕ_ОБЫЧНОГО: u32 = 0x4000;
const ОБЫЧНЫЙ: u32 = 0x20;

#[repr(C)]
struct ДроссельПитания {
    версия: u32,
    маска_управления: u32,
    маска_состояния: u32,
}

/// Экономный режим процесса: `вкл=true` — EcoQoS (малые ядра и экономная частота от Windows), `вкл=false` — СНЯТЬ
/// политику (маска управления 0 — вернуть к выбору Windows по умолчанию). `None` — не открыть/отказ.
fn эко(pid: u32, вкл: bool) -> Option<bool> {
    let h = unsafe { OpenProcess(ДОСТУП, 0, pid) };
    if h == 0 { return None; }
    let д = ДроссельПитания {
        версия: 1,
        маска_управления: if вкл { СКОРОСТЬ } else { 0 },
        маска_состояния: if вкл { СКОРОСТЬ } else { 0 },
    };
    let ок = unsafe {
        SetProcessInformation(h, ДРОССЕЛЬ, &д as *const _ as *const c_void,
            std::mem::size_of::<ДроссельПитания>() as u32)
    } != 0;
    unsafe { CloseHandle(h) };
    ок.then_some(вкл)
}

/// Прочитать экономный режим процесса (для живой пробы): `Some(true)` — EcoQoS включён.
fn эко_читать(pid: u32) -> Option<bool> {
    let h = unsafe { OpenProcess(ДОСТУП, 0, pid) };
    if h == 0 { return None; }
    let mut д = ДроссельПитания { версия: 0, маска_управления: 0, маска_состояния: 0 };
    let ок = unsafe {
        GetProcessInformation(h, ДРОССЕЛЬ, &mut д as *mut _ as *mut c_void,
            std::mem::size_of::<ДроссельПитания>() as u32)
    } != 0;
    unsafe { CloseHandle(h) };
    ок.then(|| д.маска_управления & СКОРОСТЬ != 0 && д.маска_состояния & СКОРОСТЬ != 0)
}

/// Поставить процессу набор ядер (CpuSet Id). Пусто — снять (вернуть все ядра). `None` — не открыть/отказ.
fn набор_ядер(pid: u32, наборы: &[u32]) -> Option<()> {
    let h = unsafe { OpenProcess(ДОСТУП, 0, pid) };
    if h == 0 { return None; }
    let (ук, n) = if наборы.is_empty() { (std::ptr::null(), 0) } else { (наборы.as_ptr(), наборы.len() as u32) };
    let ок = unsafe { SetProcessDefaultCpuSets(h, ук, n) } != 0;
    unsafe { CloseHandle(h) };
    ок.then_some(())
}

/// Сколько наборов ядер стоит у процесса сейчас (для живой пробы).
fn наборов_у(pid: u32) -> Option<u32> {
    let h = unsafe { OpenProcess(ДОСТУП, 0, pid) };
    if h == 0 { return None; }
    let mut нужно: u32 = 0;
    let mut буф = [0u32; 64];
    unsafe { GetProcessDefaultCpuSets(h, буф.as_mut_ptr(), буф.len() as u32, &mut нужно) };
    unsafe { CloseHandle(h) };
    Some(нужно)
}

