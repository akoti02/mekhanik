/// 🟥 ЧИСТАЯ (видно в тесте): разобрать буфер `GetSystemCpuSetInformation` → (CpuSet Id, класс эффективности) каждого
/// логического процессора. Запись SYSTEM_CPU_SET_INFORMATION: `Size`(u32,смещ.0), `Type`(u32,смещ.4); при `Type==0`
/// (CpuSet) — `Id`(u32,смещ.8) и `EfficiencyClass`(u8,смещ.18). Идём по полю `Size` (записи разной длины — переживём).
pub fn разобрать_наборы(буф: &[u8]) -> Vec<(u32, u8)> {
    let mut в = Vec::new();
    let mut i = 0usize;
    while i + 8 <= буф.len() {
        let размер = u32::from_le_bytes([буф[i], буф[i + 1], буф[i + 2], буф[i + 3]]) as usize;
        if размер < 8 || i + размер > буф.len() { break; }
        let тип = u32::from_le_bytes([буф[i + 4], буф[i + 5], буф[i + 6], буф[i + 7]]);
        if тип == 0 && размер >= 19 {
            let id = u32::from_le_bytes([буф[i + 8], буф[i + 9], буф[i + 10], буф[i + 11]]);
            let класс = буф[i + 18];
            в.push((id, класс));
        }
        i += размер;
    }
    в
}

/// 🟥 ЧИСТАЯ (видно в тесте): «малые» наборы — все, кроме самого производительного класса эффективности (большие P
/// — наибольший класс; E и LP-E — меньшие). Один класс (не гибрид) — пусто (ограничивать нечем).
pub fn малые_наборы(ядра: &[(u32, u8)]) -> Vec<u32> {
    let Some(&макс) = ядра.iter().map(|(_, к)| к).max() else { return Vec::new() };
    if ядра.iter().all(|(_, к)| *к == макс) { return Vec::new(); }
    ядра.iter().filter(|(_, к)| *к < макс).map(|(id, _)| *id).collect()
}

/// Снять карту ядер с Windows и вернуть «малые» наборы (один раз, кэшируется у `Рычаги`).
fn малые_ядра_системы() -> Vec<u32> {
    let mut длина: u32 = 0;
    // первый вызов — узнать длину
    unsafe { GetSystemCpuSetInformation(std::ptr::null_mut(), 0, &mut длина, 0, 0) };
    if длина == 0 || длина > 1 << 20 { return Vec::new(); }
    let mut буф = vec![0u8; длина as usize];
    let mut записано: u32 = 0;
    if unsafe { GetSystemCpuSetInformation(буф.as_mut_ptr(), длина, &mut записано, 0, 0) } == 0 {
        return Vec::new();
    }
    малые_наборы(&разобрать_наборы(&буф[..записано as usize]))
}

