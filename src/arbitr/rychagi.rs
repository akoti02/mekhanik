    /// 🟥 Живая проба (только на СВОЁМ дочернем процессе): запустить ping, поставить эко и малые ядра, проверить
    /// чтением, вернуть, закрыть. Запуск из своей папки: `cargo test arbitr::rychagi -- --ignored --nocapture`.
    #[test]
    #[ignore]
    fn живьём_свой_процесс() {
        use std::process::Command;
        let mut дитя = Command::new("cmd").args(["/c", "ping", "127.0.0.1", "-n", "30"])
            .spawn().expect("запустить своё ping");
        let pid = дитя.id();
        std::thread::sleep(std::time::Duration::from_millis(400));
        let малые = малые_ядра_системы();
        eprintln!("малых наборов ядер: {} ({:?})", малые.len(), малые);

        let до_эко = эко_читать(pid);
        let до_наборов = наборов_у(pid);
        eprintln!("до: эко={до_эко:?}, наборов={до_наборов:?}");

        assert!(эко(pid, true).is_some(), "эко поставилось");
        if !малые.is_empty() {
            assert!(набор_ядер(pid, &малые).is_some(), "набор ядер поставился");
        }
        okna::память_процесса(pid, Some(crate::arbitr::tablica::ПАМЯТЬ_НИЗКО));

        let после_эко = эко_читать(pid);
        let после_наборов = наборов_у(pid);
        eprintln!("после: эко={после_эко:?}, наборов={после_наборов:?}");
        // 🟥 Чтение эко (GetProcessInformation ProcessPowerThrottling) на этом ПК (Windows 11 26H2) недоступно —
        // как и кадры DWM (`vnimanie`). Поэтому проверяем УСПЕХ установки (выше `эко(pid, true).is_some()`), а
        // readback — если дался. Набор ядер читается надёжно.
        if let Some(вкл) = после_эко { assert!(вкл, "если эко читается — оно включено"); }
        if !малые.is_empty() {
            assert_eq!(после_наборов, Some(малые.len() as u32), "набор ядер читается");
        }

        // вернуть
        assert!(эко(pid, false).is_some(), "эко снято");
        набор_ядер(pid, &[]);
        okna::память_процесса(pid, Some(5));
        let верн_эко = эко_читать(pid);
        eprintln!("возврат: эко={верн_эко:?}, наборов={:?}", наборов_у(pid));
        if let Some(вкл) = верн_эко { assert!(!вкл, "если эко читается — оно снято"); }
        assert_eq!(наборов_у(pid), Some(0), "ядра возвращены (наборов 0)");

        let _ = дитя.kill();
        let _ = дитя.wait();
    }
