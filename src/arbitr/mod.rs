    /// word, иначе включённый распорядитель замедлил бы ход его слова; с полем — только по mind_word (набор текста в
    /// другом окне — не повод не уступать); отметка устарела (БАРСа нет) — таблица решает сама.
    #[test]
    fn разум_не_трогать_без_mind_word_по_word() {
        let ms = 1_794_621_434_977u64;
        let б = |т: String| svyaz::разобрать_барс(&т, ms);
        assert!(разум_не_трогать(&б(format!(r#"{{"ms":{ms},"word":true}}"#))), "word без mind_word — не трогать");
        assert!(разум_не_трогать(&б(format!(r#"{{"ms":{ms},"mode":"ПЕЧАТАЕТ"}}"#))), "печатает разуму — не трогать");
        assert!(!разум_не_трогать(&б(format!(r#"{{"ms":{ms},"word":false}}"#))), "слова нет — таблица решает");
        assert!(!разум_не_трогать(&б(format!(r#"{{"ms":{ms},"word":true,"mind_word":false}}"#))),
            "чистый признак есть: печатает в другом окне, хода слова нет — разум уступает");
        assert!(разум_не_трогать(&б(format!(r#"{{"ms":{ms},"word":false,"mind_word":true}}"#))), "ход его слова");
        assert!(!разум_не_трогать(&svyaz::разобрать_барс(&format!(r#"{{"ms":{ms},"word":true}}"#), ms + 60_000)),
            "отметка старее 15 с — БАРСа нет");
    }

