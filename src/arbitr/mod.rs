use crate::{okna, svyaz};
use std::collections::HashSet;
use tablica::{Группа, Положение, Уровни};

/// Совет предвидения арбитру (сведение наполнит из `predvidenie`). Арбитр учитывает их в положении и в `his_heavy`.
#[derive(Clone, Debug)]
pub enum СоветАрбитру {
    /// Его тяжёлое отпустит примерно к этому мигу (местное мс) — в `quiet_until_ms`.
    ТихоДо(u64),
    /// Предвидение: процесс вот-вот станет тяжёлым — учесть ДО пика (как его работу) в положении и в `his_heavy`.
    СкороТяжёлое {
        pid: u32,
        создан: u64,
        род: Род,
        нужда: Нужда,
        пик_мб: Option<u64>,
        подпись: String,
    },
}

/// Арбитр: таблица положений + рычаги + мост. Один на Мозг.
pub struct Арбитр {
    рычаги: rychagi::Рычаги,
    /// Последнее положение (для журнала/окна и чтобы заметить смену).
    положение: Положение,
}

impl Default for Арбитр {
    fn default() -> Арбитр {
        Арбитр::новый()
    }
}

impl Арбитр {
    pub fn новый() -> Арбитр {
        Арбитр {
            рычаги: rychagi::Рычаги::новый(),
            положение: Положение::ЗаПк,
        }
    }

    pub fn положение(&self) -> Положение {
        self.положение
    }
    pub fn под_рычагами(&self) -> usize {
        self.рычаги.под_рычагами()
    }

    /// 🟥 Шаг арбитра: понять положение, расставить рычаги по таблице, заполнить мост с БАРСом.
    pub fn шаг(&mut self, картина: &Картина, внимание: &Внимание, советы: &[СоветАрбитру]) {
        let сейчас = svyaz::сейчас_мс();
        let б = svyaz::картина();
        let печатает = б.жив && б.печатает;

        // память: тесно — на обоих не хватает
        let (доступно, _, зачислено) = okna::память();
        let мало_памяти = svyaz::память_тесна(доступно, зачислено);

        // его тяжёлое сейчас (карточки) + прогноз (советы)
        let (нужды, подпись_виновника, мут_тяжёлое) = self.его_тяжёлое(картина, советы, сейчас);

        // смотрит ли он видео (его окно рода «просмотр»)
        let смотрит_видео = картина.карточки()
            .any(|к| к.решение.род == Род::Просмотр && к.решение.чей == Чей::Он);

        let положение = определить_положение(внимание.за_пк, мало_памяти, нужды, смотрит_видео);
        self.положение = положение;

        // расставить рычаги по таблице
        let mut живые: HashSet<crate::kto::Личность> = HashSet::new();
        for к in картина.карточки() {
            живые.insert(к.личность);
            match группа_карточки(к) {
                Some(группа) => {
                    let у = tablica::решить(положение, группа, печатает);
                    self.применить_рычаги(к, &у);
                }
                None => self.рычаги.снять(к.личность), // система/сам — не трогаем (и снять, если было фоном)
            }
        }
        // умершие — забыть (возвращать нечего)
        self.рычаги.прибрать(&живые);

        // мост с БАРСом: его тяжёлое, прогноз тишины, вердикт
        let тихо_до = советы.iter().find_map(|с| match с {
            СоветАрбитру::ТихоДо(мс) => Some(*мс),
            _ => None,
        });
        let разум = most::Разум {
            печатает,
            загружен: б.жив && б.разум_загружен,
            простой_с: if б.жив { б.разум_простой_с } else { None },
        };
        let (вердикт, почему) = most::вердикт(положение, &разум, &подпись_виновника);
        most::в_барс(мут_тяжёлое, тихо_до, вердикт, почему);
    }

    /// Поставить рычаги карточке (только там, где таблица что-то решает; `rychagi` сам отсекает не его сеанс и
    /// снимает при «без ограничений»).
    fn применить_рычаги(&mut self, к: &Карточка, у: &Уровни) {
        self.рычаги.применить(к.личность, у);
    }

    /// Его тяжёлое сейчас: что ему нужно (nvidia/процессор), подпись виновника для причины вердикта, и список для
    /// `his_heavy`. Просмотр видео в `his_heavy` не попадает (он не тяжёлое — `kto` его так и не метит).
    fn его_тяжёлое(&self, картина: &Картина, советы: &[СоветАрбитру], сейчас: u64)
        -> (Нужды, String, Vec<svyaz::Тяжёлое>)
    {
        let mut нужды = Нужды::default();
        let mut подпись = String::new();
        let mut список = Vec::new();
        for к in картина.карточки() {
            if к.решение.чей == Чей::ЕгоРабота && к.решение.тяжёлое {
                нужды.nvidia |= к.решение.нужно.nvidia;
                нужды.процессор |= к.решение.нужно.процессор;
                if подпись.is_empty() { подпись = к.подпись.clone(); }
                список.push(most::тяжёлое_из(к, сейчас));
            }
        }
        // прогноз предвидения: то, что вот-вот станет тяжёлым, — учесть заранее (действие ДО пика)
        for с in советы {
            if let СоветАрбитру::СкороТяжёлое { pid, создан, род, нужда, пик_мб, подпись: п } = с {
                нужды.nvidia |= нужда.nvidia;
                нужды.процессор |= нужда.процессор;
                if подпись.is_empty() { подпись = п.clone(); }
                let mut н = Vec::new();
                if нужда.nvidia { н.push(svyaz::Нужно::Nvidia); }
                if нужда.видеопамять { н.push(svyaz::Нужно::Видеопамять); }
                if нужда.озу { н.push(svyaz::Нужно::Озу); }
                if нужда.процессор { н.push(svyaz::Нужно::Ядра); }
                список.push(svyaz::Тяжёлое {
                    род: most::род_ключ(*род).into(), нужно: н, pid: *pid, создан: *создан,
                    с_мс: сейчас, пик_мб: *пик_мб, подпись: п.clone(),
                });
            }
        }
        (нужды, подпись, список)
    }

    /// 🟥 Вернуть всё поставленное (при выходе Мозга и когда положение сменилось на «ничего не ставим»).
    pub fn вернуть(&mut self) {
        self.рычаги.вернуть_всё();
    }
}

/// Чего не хватает его тяжёлому — для выбора положения.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct Нужды {
    nvidia: bool,
    процессор: bool,
}

/// 🟥 ЧИСТАЯ (видно в тесте): положение ПК по тому, что видно. Порядок важности: его нет → мало памяти → его тяжёлое
/// на NVIDIA → его тяжёлое на процессоре → смотрит видео → за ПК.
fn определить_положение(за_пк: bool, мало_памяти: bool, нужды: Нужды, смотрит_видео: bool) -> Положение {
    if !за_пк {
        Положение::ЕгоНет
    } else if нужды.nvidia {
        Положение::ТяжёлоеNvidia
    } else if мало_памяти {
        Положение::МалоПамяти
    } else if нужды.процессор {
        Положение::ТяжёлоеПроцессор
    } else if смотрит_видео {
        Положение::Видео
    } else {
        Положение::ЗаПк
    }
}

/// 🟥 ЧИСТАЯ (видно в тесте): какая группа у карточки. Система и сам «Механик» — вне таблицы (`None`, не трогаем).
/// Движки счёта БАРСа (кроме судей, окна, головы) — в группу разума (уступают процессор, как 27B); прочие части
/// БАРСа — к голове/окну (не трогаем).
pub fn группа_карточки(к: &Карточка) -> Option<Группа> {
    match к.решение.чей {
        Чей::Он => Some(Группа::ЕгоОкно),
        Чей::ЕгоРабота => Some(Группа::ЕгоРабота),
        Чей::Фон => Some(Группа::Фон),
        Чей::Система | Чей::Сам => None,
        Чей::Барс => Some(match к.решение.часть_барса {
            Some(ЧастьБарса::Судья) => Группа::СудьиБарса,
            Some(ЧастьБарса::Окно) | Some(ЧастьБарса::Голова) | Some(ЧастьБарса::Прочее) | None => Группа::ГоловаОкноБарса,
            Some(ЧастьБарса::Разум) | Some(ЧастьБарса::Движок) => Группа::Разум27B,
        }),
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn положение_по_важности() {
        let нет = Нужды::default();
        let nv = Нужды { nvidia: true, процессор: false };
        let cpu = Нужды { nvidia: false, процессор: true };
        // его нет — первее всего
        assert_eq!(определить_положение(false, true, nv, true), Положение::ЕгоНет);
        // NVIDIA важнее памяти и процессора
        assert_eq!(определить_положение(true, true, nv, false), Положение::ТяжёлоеNvidia);
        assert_eq!(определить_положение(true, true, cpu, false), Положение::МалоПамяти);
        assert_eq!(определить_положение(true, false, cpu, true), Положение::ТяжёлоеПроцессор);
        // 🟥 видео — только когда тяжёлого нет
        assert_eq!(определить_положение(true, false, нет, true), Положение::Видео);
        assert_eq!(определить_положение(true, false, нет, false), Положение::ЗаПк);
    }

    fn карточка(чей: Чей, часть: Option<ЧастьБарса>) -> Карточка {
        use crate::kto::klassy::Решение;
        Карточка {
            личность: crate::kto::Личность { pid: 1, создан: 1 },
            имя: "x".into(),
            решение: Решение {
                чей, род: Род::Неизвестно, уверенность: 1.0, уверенность_рода: 1.0, тяжёлое: false,
                нужно: Нужда::default(), морозить_можно: false, неприкасаемый: false, часть_барса: часть, почему: vec![],
            },
            подпись: "x".into(), видео_мб: 0, видео_нв_мб: 0, ключ_профиля: "x".into(),
            ожидаемый_озу_мб: None, ожидаемая_видеопамять_мб: None,
        }
    }

    #[test]
    fn группы_процессов() {
        assert_eq!(группа_карточки(&карточка(Чей::Он, None)), Some(Группа::ЕгоОкно));
        assert_eq!(группа_карточки(&карточка(Чей::ЕгоРабота, None)), Some(Группа::ЕгоРабота));
        assert_eq!(группа_карточки(&карточка(Чей::Фон, None)), Some(Группа::Фон));
        assert_eq!(группа_карточки(&карточка(Чей::Система, None)), None);
        assert_eq!(группа_карточки(&карточка(Чей::Сам, None)), None);
        // 🟥 судьи БАРСа — своя группа (их таблица не трогает никогда)
        assert_eq!(группа_карточки(&карточка(Чей::Барс, Some(ЧастьБарса::Судья))), Some(Группа::СудьиБарса));
        assert_eq!(группа_карточки(&карточка(Чей::Барс, Some(ЧастьБарса::Окно))), Some(Группа::ГоловаОкноБарса));
        assert_eq!(группа_карточки(&карточка(Чей::Барс, Some(ЧастьБарса::Голова))), Some(Группа::ГоловаОкноБарса));
        assert_eq!(группа_карточки(&карточка(Чей::Барс, Some(ЧастьБарса::Разум))), Some(Группа::Разум27B));
        assert_eq!(группа_карточки(&карточка(Чей::Барс, Some(ЧастьБарса::Движок))), Some(Группа::Разум27B));
        // прочее/неизвестное у БАРСа — к голове/окну (осторожно, не трогаем)
        assert_eq!(группа_карточки(&карточка(Чей::Барс, Some(ЧастьБарса::Прочее))), Some(Группа::ГоловаОкноБарса));
        assert_eq!(группа_карточки(&карточка(Чей::Барс, None)), Some(Группа::ГоловаОкноБарса));
    }

    /// 🟥 Судьи БАРСа: какое бы ни было положение, таблица даёт им «без изменений» (связка группы и таблицы).
    #[test]
    fn судьи_никогда_не_трогаются() {
        let к = карточка(Чей::Барс, Some(ЧастьБарса::Судья));
        let группа = группа_карточки(&к).unwrap();
        for п in [Положение::ЗаПк, Положение::ТяжёлоеПроцессор, Положение::ТяжёлоеNvidia, Положение::МалоПамяти,
            Положение::Видео, Положение::ЕгоНет] {
            assert!(tablica::решить(п, группа, false).ограничений_нет(), "судьи {п:?}");
        }
    }
}
