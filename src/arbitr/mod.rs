//! 🟥 13.11 (волна 2б, ключ `arbitr`): АРБИТР — распорядитель железа по таблице положений. «Механик» — единственный
//! распорядитель железа (его слово 13.11): по положению ПК он держит каждой группе процессов её настройки ЗАРАНЕЕ,
//! а лечение остаётся тому, что таблица не предусмотрела.
//!
//! Устройство:
//! - `tablica` — чистая таблица «положение × группа → уровни» (его порядок: он → его работа → БАРС → фон; его окну,
//!   работе, судьям, голове и окну БАРСа — никогда ограничений);
//! - `rychagi` — обратимые рычаги его сеанса без прав (приоритет, EcoQoS, малые ядра, память, диск) + книга возврата;
//! - `most` — мост с БАРСом v1: его тяжёлое, прогноз тишины и вердикт (`dodumat`/`otlozhit_hod`/`vygruzit_27b`) в
//!   `barsu.json` через сеттер `svyaz`.
//!
//! # Как пользоваться (для свода)
//! ```ignore
//! let mut арбитр = Арбитр::новый();                       // при старте (вернёт рычаги прошлого запуска)
//! арбитр.шаг(&картина, &внимание, &советы);               // каждый замер (250 мс / 2 с)
//! // при выходе Мозга и смене на «без ограничений»:
//! арбитр.вернуть();
//! ```
//! `картина` (`kto`) — кто есть кто; `внимание` (`vnimanie`) — он за ПК, замок, экран; `советы` — подсказки
//! предвидения (сведение переложит в них прогноз `predvidenie`): куда класть прогноз тишины и что станет тяжёлым.

#![allow(dead_code)]

