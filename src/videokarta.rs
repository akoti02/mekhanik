/// Замер nvidia-smi: предел мощности сейчас и обычный, Вт, и ступень частот (P0…P12).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Замер { pub предел: Option<u32>, pub обычный: Option<u32>, pub ступень: Option<String> }

/// Чистая (видно в тесте): строка `nvidia-smi --query-gpu=enforced.power.limit,power.default_limit,pstate
/// --format=csv,noheader,nounits` — «33.00, 80.00, P5»; «[N/A]» или нет поля — `None`; видеокарт несколько — первая.
pub fn разобрать(s: &str) -> Замер {
    let поля: Vec<&str> = s.lines().next().unwrap_or("").split(',').map(str::trim).collect();
    let вт = |i: usize| поля.get(i).and_then(|x| x.parse::<f64>().ok()).filter(|в| в.is_finite() && *в > 0.0)
        .map(|в| в.round() as u32);
    let ступень = поля.get(2)
        .filter(|x| x.len() >= 2 && x.len() <= 3 && x.starts_with('P') && x[1..].chars().all(|c| c.is_ascii_digit()))
        .map(|x| x.to_string());
    Замер { предел: вт(0), обычный: вт(1), ступень }
}

/// Чистая: зажата ли — от сети предел ниже `ДОЛЯ` обычного. `None` — судить не по чему: от батареи (низкий предел там
/// — обычное дело), питание неизвестно или драйвер молчит о пределе (молчание — не довод).
pub fn зажата(з: &Замер, от_сети: Option<bool>) -> Option<bool> {
    match (з.предел, з.обычный, от_сети) {
        (Some(п), Some(о), Some(true)) if о > 0 => Some((п as f64) < (о as f64) * ДОЛЯ),
        _ => None,
    }
}

/// Память зажима: с какого мига зажата, сказано ли «зажата» в журнал и когда последний раз было по чему судить.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Зажим { pub с: Instant, pub сказано: bool, pub судили: Instant }

/// Чистая (видно в тесте): шаг памяти «видеокарта зажата». Возвращает новую память и строку журнала: «зажата» — после
/// `ДОЛЬШЕ` подряд, один раз; «отпущена» — когда предел вернулся, и только если «зажата» было сказано. Судить не по чему
/// (`None`) — память как была, строк нет; но несказанный зажим без довода дольше `ПЕРЕРЫВ` забывается (минута — подряд).
pub fn шаг_зажима(было: Option<Зажим>, сейчас_зажата: Option<bool>, сейчас: Instant) -> (Option<Зажим>, Option<&'static str>) {
    let перерыв = |з: &Зажим| !з.сказано && сейчас.saturating_duration_since(з.судили) > ПЕРЕРЫВ;
    match (было, сейчас_зажата) {
        (Some(з), None) if перерыв(&з) => (None, None),
        (п, None) => (п, None),
        (None, Some(false)) => (None, None),
        (None, Some(true)) => (Some(Зажим { с: сейчас, сказано: false, судили: сейчас }), None),
        (Some(з), Some(true)) if перерыв(&з) => (Some(Зажим { с: сейчас, сказано: false, судили: сейчас }), None),
        (Some(з), Some(true)) if !з.сказано && сейчас.saturating_duration_since(з.с) >= ДОЛЬШЕ =>
            (Some(Зажим { сказано: true, судили: сейчас, ..з }), Some("видеокарта_зажата")),
        (Some(з), Some(true)) => (Some(Зажим { судили: сейчас, ..з }), None),
        (Some(з), Some(false)) => (None, з.сказано.then_some("видеокарта_отпущена")),
    }
}

/// Память лечения за эпизод зажима: сколько раз просили задачу и когда последний раз.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Лечение { pub просили: u32, pub когда: Option<Instant> }

/// Чистая (видно в тесте): просить ли лечение на этом шаге. `зажим` — память `шаг_зажима` после шага, `сейчас_зажата` —
/// `зажата` этого шага. Просим, когда зажим сказан (минуту подряд от сети) и видеокарта зажата сейчас; повтор — не раньше
/// `ЛЕЧИТЬ_СНОВА`, не больше `ЛЕЧИТЬ_РАЗ` за эпизод; от батареи и при молчании драйвера — не просим; зажим кончился —
/// память с нуля.
pub fn шаг_лечения(было: Лечение, зажим: Option<Зажим>, сейчас_зажата: Option<bool>, сейчас: Instant)
    -> (Лечение, bool) {
    let Some(з) = зажим else { return (Лечение::default(), false) };
    if !з.сказано || сейчас_зажата != Some(true) || было.просили >= ЛЕЧИТЬ_РАЗ { return (было, false); }
    if было.когда.is_some_and(|т| сейчас.saturating_duration_since(т) < ЛЕЧИТЬ_СНОВА) { return (было, false); }
    (Лечение { просили: было.просили + 1, когда: Some(сейчас) }, true)
}

