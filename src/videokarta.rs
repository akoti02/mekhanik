/// Не снялось — сказать ему не чаще.
const СКАЗАТЬ_РАЗ_В: Duration = Duration::from_secs(6 * 3600);

/// Замер nvidia-smi: предел мощности сейчас и обычный, Вт, и ступень частот (P0…P12).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Замер { pub предел: Option<u32>, pub обычный: Option<u32>, pub ступень: Option<String> }

/// Чистая (видно в тесте): строка `nvidia-smi --query-gpu=enforced.power.limit,power.default_limit,pstate
/// --format=csv,noheader,nounits` — «33.00, 80.00, P5»; «[N/A]» или нет поля — `None`; видеокарт несколько — первая.
pub fn разобрать(s: &str) -> Замер {
    let поля: Vec<&str> = s.lines().next().unwrap_or("").split(',').map(str::trim).collect();
    let вт = |i: usize| поля.get(i).and_then(|x| x.parse::<f64>().ok()).filter(|в| в.is_finite() && *в > 0.0)
        .map(|в| в.round() as u32);
    let ступень = поля.get(2)
        .filter(|x| x.len() >= 2 && x.len() <= 3 && x.starts_with('P') && x[1..].chars().all(|c| c.is_ascii_digit()))
        .map(|x| x.to_string());
    Замер { предел: вт(0), обычный: вт(1), ступень }
}

/// Чистая: зажата ли — от сети предел ниже `ДОЛЯ` обычного. `None` — судить не по чему: от батареи (низкий предел там
/// — обычное дело), питание неизвестно или драйвер молчит о пределе (молчание — не довод).
pub fn зажата(з: &Замер, от_сети: Option<bool>) -> Option<bool> {
    match (з.предел, з.обычный, от_сети) {
        (Some(п), Some(о), Some(true)) if о > 0 => Some((п as f64) < (о as f64) * ДОЛЯ),
        _ => None,
    }
}

/// Чистая (видно в тесте): шаг памяти «видеокарта зажата». `было` — (с какого мига зажата, сказано ли в журнал).
/// Возвращает новую память и строку журнала: «зажата» — после `ДОЛЬШЕ` подряд, один раз; «отпущена» — когда предел
/// вернулся, и только если «зажата» было сказано. Судить не по чему (`None`) — память как была, строк нет.
pub fn шаг_зажима(было: Option<(Instant, bool)>, сейчас_зажата: Option<bool>, сейчас: Instant)
    -> (Option<(Instant, bool)>, Option<&'static str>) {
    match (было, сейчас_зажата) {
        (п, None) => (п, None),
        (None, Some(false)) => (None, None),
        (None, Some(true)) => (Some((сейчас, false)), None),
        (Some((с, false)), Some(true)) if сейчас.saturating_duration_since(с) >= ДОЛЬШЕ =>
            (Some((с, true)), Some("видеокарта_зажата")),
        (Some(п), Some(true)) => (Some(п), None),
        (Some((_, сказано)), Some(false)) => (None, сказано.then_some("видеокарта_отпущена")),
    }
}

/// Память лечения за эпизод зажима: сколько раз просили задачу и когда последний раз.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Лечение { pub просили: u32, pub когда: Option<Instant> }

/// Чистая (видно в тесте): просить ли лечение на этом шаге. `зажим` — память `шаг_зажима` после шага, `сейчас_зажата` —
/// `зажата` этого шага. Просим, когда зажим сказан (минуту подряд от сети) и видеокарта зажата сейчас; повтор — не раньше
/// `ЛЕЧИТЬ_СНОВА`, не больше `ЛЕЧИТЬ_РАЗ` за эпизод; от батареи и при молчании драйвера — не просим; зажим кончился —
/// память с нуля.
pub fn шаг_лечения(было: Лечение, зажим: Option<(Instant, bool)>, сейчас_зажата: Option<bool>, сейчас: Instant)
    -> (Лечение, bool) {
    let Some((_, сказано)) = зажим else { return (Лечение::default(), false) };
    if !сказано || сейчас_зажата != Some(true) || было.просили >= ЛЕЧИТЬ_РАЗ { return (было, false); }
    if было.когда.is_some_and(|т| сейчас.saturating_duration_since(т) < ЛЕЧИТЬ_СНОВА) { return (было, false); }
    (Лечение { просили: было.просили + 1, когда: Some(сейчас) }, true)
}

/// Итог задачи лечения (`zazhim_itog.json`, пишет `zazhim-lechit.ps1`).
#[derive(Clone, Debug, PartialEq)]
pub struct Итог { pub итог: String, pub шаг: u64, pub до: Option<u64>, pub после: Option<u64>, pub проба: bool }

/// Чистая (видно в тесте): итог задачи; не JSON или без `itog` — `None`.
pub fn разобрать_итог(т: &str) -> Option<Итог> {
    let v: Value = serde_json::from_str(т.trim().trim_start_matches('\u{feff}')).ok()?;
    let итог = v.get("itog")?.as_str()?.to_string();
    Some(Итог { итог, шаг: v.get("shag").and_then(Value::as_u64).unwrap_or(0),
        до: v.get("predel_do").and_then(Value::as_u64), после: v.get("predel_posle").and_then(Value::as_u64),
        проба: v.get("proba").and_then(Value::as_bool).unwrap_or(false) })
}

/// Чистая: итог словами — для журнала.
pub fn смысл_итога(итог: &str) -> &'static str {
    match итог {
        "snyat" => "зажим снят: предел мощности вернулся",
        "ne_snyat" => "лесенка не сняла зажим: снимет шнур (вынуть на 10 с и вставить) или перезагрузка",
        "ne_nuzhno" => "задача померила сама: зажима нет — ничего не трогала",
        "chasto" => "лечили меньше 8 мин назад — пропуск",
        "proba" => "проба установщика: перезапуск без зажима",
        _ => "итог задачи лечения",
    }
}

/// Папка задачи лечения — `C:\ProgramData\Mekhanik` (пишут только система и администраторы, читают все).
pub fn папка_лечения() -> PathBuf {
    std::env::var_os("ProgramData").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(r"C:\ProgramData")).join("Mekhanik")
}

/// Лечение установлено — метка установщика.
fn установлено() -> bool { папка_лечения().join("videokarta.json").exists() }

/// Итог задачи: когда записан и текст.
fn итог_файла() -> Option<(SystemTime, String)> {
    let путь = папка_лечения().join("zazhim_itog.json");
    let когда = std::fs::metadata(&путь).and_then(|м| м.modified()).ok()?;
    Some((когда, std::fs::read_to_string(&путь).ok()?))
}

/// nvidia-smi из System32 — без окна и не дольше 5 с (драйвер обновляется — может молчать); `None` — молчит или нет его.
fn замерить() -> Option<Замер> {
    use std::io::Read;
    use std::os::windows::process::CommandExt;
    use std::process::{Command, Stdio};
    let путь = std::env::var_os("SystemRoot").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(r"C:\Windows"))
        .join(r"System32\nvidia-smi.exe");
    // CREATE_NO_WINDOW: «Механик» без окна, nvidia-smi иначе открыл бы своё
    let mut р = Command::new(путь)
        .args(["--query-gpu=enforced.power.limit,power.default_limit,pstate", "--format=csv,noheader,nounits"])
        .stdin(Stdio::null()).stdout(Stdio::piped()).stderr(Stdio::null()).creation_flags(0x0800_0000).spawn().ok()?;
    let до = Instant::now() + Duration::from_secs(5);
    loop {
        match р.try_wait() {
            Ok(Some(_)) => break,
            Ok(None) if Instant::now() < до => std::thread::sleep(Duration::from_millis(50)),
            _ => { let _ = р.kill(); let _ = р.wait(); return None; }
        }
    }
    let mut т = String::new();
    р.stdout.take()?.read_to_string(&mut т).ok()?;
    Some(разобрать(&т))
}

/// 🟥 Проба (`proba_zazhim.json` `{"until_ms": …}` — до какого мига): видеокарта будто зажата (33 из 80 Вт от сети) —
/// проверить всю цепочку «поймал → попросил → задача померила сама → итог» без настоящего зажима. Задача мерит настоящую
/// видеокарту: зажима нет — ничего не трогает (`ne_nuzhno`). На пробе БАРСу ничего не пишется (ни строк, ни сигналов) —
/// только свой журнал. Свой файл, не `proba.json`: стенд сторожа тормозов (лечить, будто он за ПК) она не включает.
fn проба_зажима() -> bool {
    std::fs::read_to_string(svyaz::папка().join("proba_zazhim.json")).ok()
        .and_then(|т| serde_json::from_str::<Value>(&т).ok())
        .and_then(|v| v.get("until_ms").and_then(Value::as_u64)).is_some_and(|до| до > svyaz::сейчас_мс())
}

/// Строка журнала: на пробе — только своя, иначе и БАРСу.
fn в_журнал(проба: bool, событие: &str, данные: &Value) {
    if проба { журнал(событие, &json!({ "проба": true, "данные": данные })) } else { журнал_барсу(событие, данные) }
}

/// Поток сторожа зажима (`main.rs`). Упал — через минуту снова (сторож тормозов от этого не зависит).
pub fn работать() {
    loop {
        if std::panic::catch_unwind(круги).is_ok() { return; }
        журнал("видеокарта_сторож_упал", &json!({ "смысл": "поток сторожа зажима упал — через минуту снова" }));
        std::thread::sleep(Duration::from_secs(60));
    }
}

