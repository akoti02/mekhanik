/// nvidia-smi из System32 — без окна и не дольше 5 с (драйвер обновляется — может молчать); `None` — молчит или нет его.
fn замерить() -> Option<Замер> {
    use std::io::Read;
    use std::os::windows::process::CommandExt;
    use std::process::{Command, Stdio};
    let путь = std::env::var_os("SystemRoot").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(r"C:\Windows"))
        .join(r"System32\nvidia-smi.exe");
    // CREATE_NO_WINDOW: «Механик» без окна, nvidia-smi иначе открыл бы своё
    let mut р = Command::new(путь)
        .args(["--query-gpu=enforced.power.limit,power.default_limit,pstate", "--format=csv,noheader,nounits"])
        .stdin(Stdio::null()).stdout(Stdio::piped()).stderr(Stdio::null()).creation_flags(0x0800_0000).spawn().ok()?;
    let до = Instant::now() + Duration::from_secs(5);
    loop {
        match р.try_wait() {
            Ok(Some(_)) => break,
            Ok(None) if Instant::now() < до => std::thread::sleep(Duration::from_millis(50)),
            _ => { let _ = р.kill(); let _ = р.wait(); return None; }
        }
    }
    let mut т = String::new();
    р.stdout.take()?.read_to_string(&mut т).ok()?;
    Some(разобрать(&т))
}

