/// Зажата — предел мощности ниже этой доли обычного (13.11: 33 из 80 Вт; в покое от сети — 80–103 Вт).
pub const ДОЛЯ: f64 = 0.6;
/// Зажата столько подряд — зажим (короткий провал при смене питания — не повод).
pub const ДОЛЬШЕ: Duration = Duration::from_secs(60);
/// Сколько раз за эпизод просить лечение и через сколько повторять (скрипт сам лечит не чаще раза в 8 мин).
pub const ЛЕЧИТЬ_РАЗ: u32 = 3;
pub const ЛЕЧИТЬ_СНОВА: Duration = Duration::from_secs(10 * 60);
