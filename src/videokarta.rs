const ЗАНЯТО_ОТ_МБ: u64 = 256;
/// Итог задачи ждём столько: два шага лесенки по 20 с, запуск PowerShell, замеры.
const ИТОГ_ЖДАТЬ: Duration = Duration::from_secs(180);
/// Событие просьбы в журнале Windows «Приложение» (источник `Mekhanik`) — на него стоит триггер задачи.
