//! 🟥 13.11 (волна 2а, ключ `vnimanie`): шина событий «Механика» (И4, П6). Вместо опроса раз в 250 мс и 2 с —
//! отдельный поток Windows со скрытым окном сообщений ловит перемены мгновенно и шлёт их одним каналом:
//! смена окна впереди, свёртывание, замок и вход, сеть↔батарея, экран погас/горит, он есть/нет, сон и пробуждение,
//! конец сеанса (выключение, перезагрузка), заставка. «Механик» на эти события сразу возвращает уступки и пересчитывает
//! «его внимание» (`vnimanie.rs`), а не ждёт следующего шага опроса.
//!
//! Здесь — виды событий, общий канал и чистый разбор сырых чисел Windows в события (видно в тесте). Само скрытое окно,
//! подписки и цикл сообщений — `sobytiya_win.rs`; «его внимание» (кто впереди, звук, микрофон, камера, кадры DWM) —
//! `vnimanie.rs`. Дёшево: событиями, без частого опроса.

// Пока сведение не подключило шину к Мозгу, часть функций «не используется» — ожидание подключения, не мёртвый код.
#![allow(dead_code)]

use std::sync::mpsc::Sender;
use std::sync::{Mutex, OnceLock};

/// Откуда ПК питается.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Питание {
    Сеть,
    Батарея,
}

/// Состояние экрана его сеанса.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Экран {
    Погас,
    Горит,
    Притушен,
}

/// Он у ПК или нет (по датчику присутствия Windows).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Присутствие {
    Есть,
    Нет,
}

/// Событие шины. Номера процессов — только у «окно впереди»; остальное — состояние ПК и сеанса.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Событие {
    /// Вперёд вышло окно процесса (его номер).
    ОкноВперёд(u32),
    /// Переднее окно свернули.
    ОкноСвернули,
    /// Окно развернули из свёрнутого.
    ОкноРазвернули,
    /// Сеанс заблокирован (он отошёл или нажал Win+L).
    Замок,
    /// Сеанс разблокирован.
    Отпёрто,
    /// Он вошёл в сеанс.
    Вошёл,
    /// Он вышел из сеанса.
    Вышел,
    /// Сменился источник питания.
    Питание(Питание),
    /// Сменилось состояние экрана.
    Экран(Экран),
    /// Сменилось присутствие.
    Присутствие(Присутствие),
    /// ПК засыпает (современный ждущий режим или спячка).
    Засыпает,
    /// ПК проснулся.
    Проснулся,
    /// Сеанс заканчивается — выключение или перезагрузка Windows.
    КонецСеанса,
    /// Пошла (`true`) или кончилась (`false`) заставка.
    Заставка(bool),
}

// ───────────────────────────── чистый разбор сырых чисел Windows ─────────────────────────────

/// GUID_ACDC_POWER_SOURCE: 0 — от сети (PoAc), иначе — от батареи (PoDc) или ИБП (PoHot) — для нас «не сеть».
pub fn питание_из(данные: u32) -> Питание {
    if данные == 0 {
        Питание::Сеть
    } else {
        Питание::Батарея
    }
}

/// GUID_CONSOLE_DISPLAY_STATE: 0 — погас, 1 — горит, 2 — притушен.
pub fn экран_из(данные: u32) -> Экран {
    match данные {
        0 => Экран::Погас,
        2 => Экран::Притушен,
        _ => Экран::Горит,
    }
}

/// GUID_SESSION_USER_PRESENCE: 0 — он здесь (PowerUserPresent), иначе — его нет (PowerUserInactive/NotPresent).
pub fn присутствие_из(данные: u32) -> Присутствие {
    if данные == 0 {
        Присутствие::Есть
    } else {
        Присутствие::Нет
    }
}

/// WM_WTSSESSION_CHANGE wParam → событие: вход 5, выход 6, замок 7, отпёрто 8; прочее нам не нужно.
pub fn сеанс_из(wparam: usize) -> Option<Событие> {
    match wparam {
        0x5 => Some(Событие::Вошёл),
        0x6 => Some(Событие::Вышел),
        0x7 => Some(Событие::Замок),
        0x8 => Some(Событие::Отпёрто),
        _ => None,
    }
}

/// Код SetWinEventHook → событие: окно впереди 0x0003 (с номером процесса), свернули 0x16, развернули 0x17.
pub fn окно_из(событие: u32, pid: u32) -> Option<Событие> {
    match событие {
        0x0003 => Some(Событие::ОкноВперёд(pid)),
        0x0016 => Some(Событие::ОкноСвернули),
        0x0017 => Some(Событие::ОкноРазвернули),
        _ => None,
    }
}

/// WM_POWERBROADCAST wParam → сон/пробуждение: засыпает 0x4 (PBT_APMSUSPEND), проснулся 0x7/0x12
/// (PBT_APMRESUMESUSPEND/PBT_APMRESUMEAUTOMATIC). 0x8013 (смена настройки питания) разбирается отдельно по GUID.
pub fn сон_из(wparam: usize) -> Option<Событие> {
    match wparam {
        0x4 => Some(Событие::Засыпает),
        0x7 | 0x12 => Some(Событие::Проснулся),
        _ => None,
    }
}

// ───────────────────────────── общий канал (его читает Мозг) ─────────────────────────────

/// Отправитель событий. Обработчики Windows (оконная процедура, обратный вызов хука) — обычные функции без замыкания,
/// поэтому канал они берут отсюда, а не из захваченной переменной.
static КАНАЛ: OnceLock<Mutex<Option<Sender<Событие>>>> = OnceLock::new();

fn канал() -> &'static Mutex<Option<Sender<Событие>>> {
    КАНАЛ.get_or_init(|| Mutex::new(None))
}

/// Задать отправитель (зовёт `sobytiya_win::запустить` при старте потока).
pub fn задать_отправитель(tx: Sender<Событие>) {
    if let Ok(mut г) = канал().lock() {
        *г = Some(tx);
    }
}

/// Послать событие в канал. Приёмник пропал (Мозг перестал читать) — молча отбрасываем.
pub fn послать(с: Событие) {
    if let Ok(г) = канал().lock() {
        if let Some(tx) = г.as_ref() {
            let _ = tx.send(с);
        }
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn питание_по_числу() {
        assert_eq!(питание_из(0), Питание::Сеть);
        assert_eq!(питание_из(1), Питание::Батарея);
        assert_eq!(питание_из(2), Питание::Батарея, "ИБП — тоже не сеть");
    }

    #[test]
    fn экран_по_числу() {
        assert_eq!(экран_из(0), Экран::Погас);
        assert_eq!(экран_из(1), Экран::Горит);
        assert_eq!(экран_из(2), Экран::Притушен);
        assert_eq!(экран_из(99), Экран::Горит, "неизвестное — считаем, что горит (не морозим зря)");
    }

    #[test]
    fn присутствие_по_числу() {
        assert_eq!(присутствие_из(0), Присутствие::Есть);
        assert_eq!(присутствие_из(1), Присутствие::Нет);
    }

    #[test]
    fn сеанс_по_wparam() {
        assert_eq!(сеанс_из(0x5), Some(Событие::Вошёл));
        assert_eq!(сеанс_из(0x6), Some(Событие::Вышел));
        assert_eq!(сеанс_из(0x7), Some(Событие::Замок));
        assert_eq!(сеанс_из(0x8), Some(Событие::Отпёрто));
        assert_eq!(сеанс_из(0x1), None, "WTS_CONSOLE_CONNECT нам не нужен");
    }

    #[test]
    fn окно_по_коду() {
        assert_eq!(окно_из(0x0003, 4321), Some(Событие::ОкноВперёд(4321)));
        assert_eq!(окно_из(0x0016, 0), Some(Событие::ОкноСвернули));
        assert_eq!(окно_из(0x0017, 0), Some(Событие::ОкноРазвернули));
        assert_eq!(окно_из(0x0008, 0), None, "EVENT_SYSTEM_CAPTURESTART нам не нужен");
    }

    #[test]
    fn сон_по_wparam() {
        assert_eq!(сон_из(0x4), Some(Событие::Засыпает));
        assert_eq!(сон_из(0x7), Some(Событие::Проснулся));
        assert_eq!(сон_из(0x12), Some(Событие::Проснулся));
        assert_eq!(сон_из(0x8013), None, "смену настройки питания разбираем по GUID, не здесь");
    }

    #[test]
    fn канал_шлёт_и_без_приёмника_не_падает() {
        let (tx, rx) = std::sync::mpsc::channel();
        задать_отправитель(tx);
        послать(Событие::Замок);
        послать(Событие::ОкноВперёд(7));
        assert_eq!(rx.recv().ok(), Some(Событие::Замок));
        assert_eq!(rx.recv().ok(), Some(Событие::ОкноВперёд(7)));
        drop(rx);
        послать(Событие::Отпёрто); // приёмник пропал — не паникуем
    }
}
