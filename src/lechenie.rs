//! идентифицировать проблему и дальше оптимизировать компьютер… без каких-либо подачек от меня… полностью автономное».
//!
//! ЛЕЧЕНИЕ — круг «причина → действие → проверка → следующая ступень», всё сам:
//! - **Причина** (`классы`): память (зачисленная на пределе, мало ОЗУ, подкачка), видеокарта, процессор, диск; и
//!   «заранее» — он за ПК, а запас памяти тает (до зависания).
//! - **Действие** (`ступени`) — только обратимое и только с фоном: его окно на переднем плане и всё с тем же именем и под
//!   ним не трогается; системные процессы, звук, окно и голова БАРСа, судьи — тоже (`неприкасаемый`). Исключение
//!   26.10 (его слово): программа разработки, что грузит диск, уступает диск и память и тогда, когда окно разработки
//!   впереди (`трогать_можно`) — её только замедляем, не морозим и не закрываем.
//! - **Проверка** — через `ПРОВЕРКА` прошло: признак ушёл — «помогло», нет — следующая ступень. Счёт «помогло» по ступеням
//!   в `opyt.json`: ступень, что не помогла ни разу за 6 попыток, сутки не берётся.
//! - **Возврат** (`Книга`): всё, что поменяно у чужих процессов, записано в `izmeneniya.json` и возвращается само.
//! Пока его нет за ПК (ввода нет 2 мин и видео не играет) — не лечим: тормоз, которого он не видит, лечить нечем и незачем
//! (разум ночью должен думать). Сборки на краю памяти замирают и без него — это защита, не лечение (`storozh.rs`).

