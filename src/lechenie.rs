/// Что поменяли у чужого процесса — чтобы вернуть. `разработка` — программа разработки: её возвращаем, когда впереди
/// она сама (по имени), а не окно разработки, из которого она запущена.
#[derive(Clone, Debug, PartialEq)]
pub struct Запись { pub pid: u32, pub создан: u64, pub имя: String, pub что: Ступень, pub было: i64, pub класс: Класс,
    pub разработка: bool }

#[derive(Default)]
pub struct Книга { pub записи: Vec<Запись>, тих_с: HashMap<(u32, Ступень), Instant> }

impl Книга {
    fn путь() -> std::path::PathBuf { svyaz::папка().join("izmeneniya.json") }
    fn записать(&self) {
        if self.записи.is_empty() { let _ = std::fs::remove_file(Self::путь()); return; }
        let v: Vec<Value> = self.записи.iter().map(|з| json!({ "pid": з.pid, "created": з.создан, "name": з.имя,
            "what": format!("{:?}", з.что), "was": з.было, "dev": з.разработка })).collect();
        let _ = svyaz::записать(&Self::путь(), &Value::Array(v).to_string());
    }
    /// При старте: прошлый «Механик» упал, не вернув, — вернуть всё по файлу (номер сверяем по времени создания).
    pub fn вернуть_брошенное() {
        let Ok(т) = std::fs::read_to_string(Self::путь()) else { return };
        let _ = std::fs::remove_file(Self::путь());
        let v: Value = serde_json::from_str(&т).unwrap_or_default();
        let mut вернул = 0;
        for з in v.as_array().into_iter().flatten() {
            let pid = з.get("pid").and_then(Value::as_u64).unwrap_or(0) as u32;
            let создан = з.get("created").and_then(Value::as_u64).unwrap_or(0);
            let было = з.get("was").and_then(Value::as_i64).unwrap_or(-1);
            if pid == 0 || было < 0 || okna::создан(pid) != Some(создан) { continue; }
            let ок = match з.get("what").and_then(Value::as_str).unwrap_or("") {
                "ПриоритетФона" => okna::приоритет(pid, было as u32).is_some(),
                "ДискФона" => вернуть_диск(pid, было),
                "ВидеокартаФона" => okna::очередь_видеокарты(pid, было as i32).is_some(),
                _ => false,
            };
            if ок { вернул += 1; }
        }
        if вернул > 0 { журнал_барсу("механик_вернул_брошенное", &json!({ "процессов": вернул })); }
    }
    pub fn добавить(&mut self, з: Запись) { self.записи.push(з); self.записать(); }

    fn вернуть_одну(з: &Запись) -> bool {
        if okna::создан(з.pid) != Some(з.создан) { return true; } // процесса нет — возвращать некому
        match з.что {
            Ступень::ПриоритетФона => okna::приоритет(з.pid, з.было as u32).is_some(),
            Ступень::ДискФона => вернуть_диск(з.pid, з.было),
            Ступень::ВидеокартаФона => okna::очередь_видеокарты(з.pid, з.было as i32).is_some(),
            _ => true,
        }
    }

    /// Каждое окно: вернуть тем, кто вышел на передний план или затих на `ВЕРНУТЬ_ТИХ`; ушедших — забыть.
    pub fn обход(&mut self, кандидаты: &[Кандидат], передние: &HashSet<u32>, передний_имя: Option<&str>, лечим: &HashSet<Класс>) {
        if self.записи.is_empty() { return; }
        let mut оставить = Vec::new();
        let mut сменилось = false;
        for з in std::mem::take(&mut self.записи) {
            let к = кандидаты.iter().find(|к| к.pid == з.pid);
            let тёзка = передний_имя.is_some_and(|п| п.eq_ignore_ascii_case(&з.имя));
            let впереди = тёзка || !з.разработка && передние.contains(&з.pid);
            let тих = match з.что {
                Ступень::ПриоритетФона => к.is_none_or(|к| к.ядер < ПОЖИРАТЕЛЬ_ЯДЕР / 3.0),
                Ступень::ДискФона => к.is_none_or(|к| к.диск_мб_с < ПОЖИРАТЕЛЬ_ДИСК_МБ_С / 3.0),
                Ступень::ВидеокартаФона => к.is_none_or(|к| к.гпу < ПОЖИРАТЕЛЬ_ГПУ / 3.0),
                _ => true,
            } && !лечим.contains(&з.класс);
            let ключ = (з.pid, з.что);
            if тих { self.тих_с.entry(ключ).or_insert_with(Instant::now); } else { self.тих_с.remove(&ключ); }
            let давно_тих = self.тих_с.get(&ключ).is_some_and(|т| т.elapsed() >= ВЕРНУТЬ_ТИХ);
            if впереди || давно_тих || okna::создан(з.pid) != Some(з.создан) {
                if okna::создан(з.pid) == Some(з.создан) && Self::вернуть_одну(&з) {
                    журнал_барсу("механик_вернул", &json!({ "кому": з.имя, "pid": з.pid, "что": з.что.имя(), "было": з.было,
                        "почему": if впереди { "он открыл её — на переднем плане" } else { "затихла" } }));
                }
                self.тих_с.remove(&ключ);
                сменилось = true;
            } else {
                оставить.push(з);
            }
        }
        self.записи = оставить;
        if сменилось { self.записать(); }
    }

    /// Выход: вернуть всё.
    pub fn вернуть_всё(&mut self) {
        for з in self.записи.drain(..) { let _ = Self::вернуть_одну(&з); }
        let _ = std::fs::remove_file(Self::путь());
    }
}

// ───────────────────────────── эпизод ─────────────────────────────

/// Одно лечение одной причины: какая ступень сделана, когда проверять.
#[derive(Clone, Debug)]
pub struct Эпизод { pub класс: Класс, pub заранее: bool, pub начат: Instant, pub шаг: usize,
    pub сделано: Option<(Ступень, Instant, Value)>, pub сделано_всё: Vec<String>, pub ждём_ответ: Option<(String, Instant)> }

/// Чистая (видно в тесте): что делать с эпизодом на проверке. `есть` — причина ещё есть.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Итог { Ждать, Помогло, ДальшеСтупень, Кончился }

pub fn итог(сделано_давно: Option<Duration>, есть: bool) -> Итог {
    match (сделано_давно, есть) {
        (None, false) => Итог::Кончился,
        (None, true) => Итог::ДальшеСтупень,
        (Some(д), false) if д <= ПРОВЕРКА + Duration::from_secs(4) => Итог::Помогло,
        (Some(_), false) => Итог::Кончился,
        (Some(д), true) if д >= ПРОВЕРКА => Итог::ДальшеСтупень,
        (Some(_), true) => Итог::Ждать,
    }
}

