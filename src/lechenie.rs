#[derive(Clone, Debug, Default, PartialEq)]
pub struct Опыт { счёт: HashMap<String, (u32, u32, u64)> }

impl Опыт {
    fn путь() -> std::path::PathBuf { svyaz::папка().join("opyt.json") }
    pub fn прочитать() -> Опыт {
        let v: Value = std::fs::read_to_string(Self::путь()).ok().and_then(|т| serde_json::from_str(&т).ok()).unwrap_or_default();
        let счёт = v.as_object().into_iter().flatten().map(|(к, з)| (к.clone(), (
            з.get("раз").and_then(Value::as_u64).unwrap_or(0) as u32, з.get("помогло").and_then(Value::as_u64).unwrap_or(0) as u32,
            з.get("с_мс").and_then(Value::as_u64).unwrap_or(0)))).collect();
        Опыт { счёт }
    }
    fn записать(&self) {
        let v: serde_json::Map<String, Value> = self.счёт.iter().map(|(к, (р, п, с))|
            (к.clone(), json!({ "раз": р, "помогло": п, "с_мс": с }))).collect();
        let _ = svyaz::записать(&Self::путь(), &Value::Object(v).to_string());
    }
    fn ключ(к: Класс, ст: Ступень) -> String { format!("{} / {}", к.имя(), ст.имя()) }
    /// Чистая по сути (время — аргументом): ступень пропускаем — 6 попыток подряд без «помогло» за сутки.
    pub fn пропустить(&self, к: Класс, ст: Ступень, сейчас_мс: u64) -> bool {
        self.счёт.get(&Self::ключ(к, ст)).is_some_and(|(р, п, с)| *р >= ОПЫТ_ПОПЫТОК && *п == 0
            && сейчас_мс.saturating_sub(*с) < ОПЫТ_СУТКИ.as_millis() as u64)
    }
    pub fn отметить(&mut self, к: Класс, ст: Ступень, помогло: bool, сейчас_мс: u64) {
        let з = self.счёт.entry(Self::ключ(к, ст)).or_insert((0, 0, сейчас_мс));
        // сутки прошли — счёт заново
        if сейчас_мс.saturating_sub(з.2) >= ОПЫТ_СУТКИ.as_millis() as u64 { *з = (0, 0, сейчас_мс); }
        з.0 += 1;
        if помогло { з.1 += 1; }
        self.записать();
    }
    pub fn кратко(&self) -> Value {
        Value::Object(self.счёт.iter().map(|(к, (р, п, _))| (к.clone(), json!(format!("{п} из {р}")))).collect())
    }
}

