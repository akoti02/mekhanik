/// Класс причины; лечим в этом порядке. 🟥 26.10: диск — раньше видеокарты: экран ждал 500 мс, «Механик» сперва
/// выгрузил простаивающий 27B (не помогло — держал диск поиск по всей домашней папке), а до диска дошёл ни с чем.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Класс { Зачисленная, Память, Диск, Видеокарта, Процессор }

impl Класс {
    pub fn имя(self) -> &'static str {
        match self { Класс::Зачисленная => "зачисленная память", Класс::Память => "память (ОЗУ)", Класс::Видеокарта => "видеокарта", Класс::Процессор => "процессор",
            Класс::Диск => "диск" }
    }
}

/// Ступень лечения.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Ступень { Сборки, Выжать, ВыгрузитьРазум, ПриоритетФона, ДискФона, ВидеокартаФона }

impl Ступень {
    pub fn имя(self) -> &'static str {
        match self {
            Ступень::Сборки => "сборки замереть", Ступень::Выжать => "выжать память простаивающих",
            Ступень::ВыгрузитьРазум => "выгрузить простаивающий 27B", Ступень::ПриоритетФона => "фону — процессор ниже",
            Ступень::ДискФона => "фону — диск и память ниже", Ступень::ВидеокартаФона => "фону — видеокарта ниже",
        }
    }
}

/// Чистая (видно в тесте): лестница по классу.
pub fn ступени(к: Класс) -> &'static [Ступень] {
    match к {
        // зачисленную выжимание рабочих наборов не освобождает — только те, кто её держит
        Класс::Зачисленная => &[Ступень::Сборки, Ступень::ВыгрузитьРазум],
        Класс::Память => &[Ступень::Сборки, Ступень::Выжать, Ступень::ВыгрузитьРазум],
        Класс::Видеокарта => &[Ступень::ВидеокартаФона, Ступень::ВыгрузитьРазум],
        Класс::Процессор => &[Ступень::ПриоритетФона],
        Класс::Диск => &[Ступень::ДискФона],
    }
}

/// Сырьё окна для лечения (2 с).
#[derive(Clone, Debug, Default)]
pub struct Сырьё {
    /// Признаки тормоза сторожа по видам: «зачисленная», «память», «видеокарта», «процессор», «окно», «драйверы».
    pub признаки: Vec<&'static str>,
    pub зачислено_своб_мб: Option<u64>,
    pub доступно_мб: Option<u64>,
    /// Доля всех ядер, занятых за окно (None — снимка не было).
    pub процессор_весь: Option<f64>,
    pub диск_занят: Option<f64>,
    /// Он за ПК (ввод недавно или видео играет).
    pub за_пк: bool,
}

/// Чистая (видно в тесте): какие причины есть сейчас; `заранее` — память тает, а зависания ещё нет.
pub fn классы(с: &Сырьё) -> (Vec<Класс>, bool) {
    let mut к: Vec<Класс> = Vec::new();
    if с.признаки.contains(&"зачисленная") { к.push(Класс::Зачисленная); }
    if с.признаки.contains(&"память") { к.push(Класс::Память); }
    if с.признаки.contains(&"видеокарта") { к.push(Класс::Видеокарта); }
    let тормоз = !с.признаки.is_empty();
    if с.признаки.contains(&"процессор") || тормоз && с.процессор_весь.is_some_and(|д| д >= ПРОЦЕССОР_ВЕСЬ) {
        к.push(Класс::Процессор);
    }
    if тормоз && с.диск_занят.is_some_and(|д| д >= ДИСК_ЗАНЯТ) { к.push(Класс::Диск); }
    let mut заранее = false;
    if с.за_пк && !к.contains(&Класс::Зачисленная) && с.зачислено_своб_мб.is_some_and(|з| з < ЗАРАНЕЕ_ЗАЧИСЛЕНО_МБ) {
        к.push(Класс::Зачисленная);
        заранее = true;
    }
    if с.за_пк && !к.contains(&Класс::Память) && с.доступно_мб.is_some_and(|д| д < ЗАРАНЕЕ_ОЗУ_МБ) {
        к.push(Класс::Память);
        заранее = true;
    }
    // тормоз уже есть — это не «заранее»
    if !с.признаки.is_empty() { заранее = false; }
    к.sort();
    (к, заранее)
}

/// Процесс глазами лечения (за окно). `разработка` — запущен из окна разработки или сборщик по имени (`storozh::сборка`).
#[derive(Clone, Debug, PartialEq)]
pub struct Кандидат { pub pid: u32, pub имя: String, pub ядер: f64, pub диск_мб_с: f64, pub гпу: f64, pub рабочий_мб: u64,
    pub разработка: bool }

/// Чистая (видно в тесте): процесс нельзя трогать — системный, БАРС, его передний план (то же имя или потомок), чужой сеанс.
pub fn неприкасаемый(pid: u32, имя: &str, передние: &HashSet<u32>, передний_имя: Option<&str>, барс: &HashSet<u32>,
                     свой_сеанс: bool) -> bool {
    let н = имя.to_lowercase();
    !свой_сеанс || pid <= 4 || передние.contains(&pid) || барс.contains(&pid)
        || передний_имя.is_some_and(|п| п.eq_ignore_ascii_case(имя))
        || НЕПРИКАСАЕМЫЕ.iter().any(|и| *и == н)
}

/// Чистая (видно в тесте): брать ли процесс в кандидаты лечения. 🟥 26.10 (его слово: программу разработки, что
/// «токсично» грузит ПК, — замедлять): программу разработки — и тогда, когда окно разработки впереди (поиск по всему
/// диску шёл из переднего окна); само окно, его тёзки, системные, БАРС и чужой сеанс — неприкасаемы всегда.
pub fn трогать_можно(pid: u32, имя: &str, разработка: bool, передние: &HashSet<u32>, передний: Option<u32>,
                     передний_имя: Option<&str>, барс: &HashSet<u32>, свой_сеанс: bool) -> bool {
    if !разработка { return !неприкасаемый(pid, имя, передние, передний_имя, барс, свой_сеанс); }
    let само_окно: HashSet<u32> = передний.into_iter().collect();
    !неприкасаемый(pid, имя, &само_окно, передний_имя, барс, свой_сеанс)
}

/// Чистая (видно в тесте): передний план — процесс окна и все его потомки (до 6 колен).
pub fn передние(все: &[(u32, u32, String)], передний: Option<u32>) -> HashSet<u32> {
    let mut п: HashSet<u32> = передний.into_iter().collect();
    for _ in 0..6 {
        let дети: Vec<u32> = все.iter().filter(|(pid, р, _)| !п.contains(pid) && п.contains(р)).map(|(pid, _, _)| *pid).collect();
        if дети.is_empty() { break; }
        п.extend(дети);
    }
    п
}

/// Чистая (видно в тесте): кого брать на ступени (кандидаты — уже без неприкасаемых). Пусто — ступень неприменима.
pub fn цели(ст: Ступень, кандидаты: &[Кандидат], уже: &HashSet<(u32, Ступень)>, выжимали: &HashMap<u32, Instant>) -> Vec<(u32, String)> {
    // 🟥 26.10: программы разработки — только на ступени диска; процессор у них и так низший (`storozh.rs`), а память и
    // видеокарта у сборок и тестов — рабочие
    let свои: Vec<&Кандидат> = кандидаты.iter().filter(|к| ст == Ступень::ДискФона || !к.разработка).collect();
    let верх = |ключ: fn(&Кандидат) -> f64, порог: f64| -> Vec<(u32, String)> {
        свои.iter().filter(|к| ключ(к) >= порог && !уже.contains(&(к.pid, ст)))
            .max_by(|а, б| ключ(а).total_cmp(&ключ(б))).map(|к| vec![(к.pid, к.имя.clone())]).unwrap_or_default()
    };
    match ст {
        Ступень::ПриоритетФона => верх(|к| к.ядер, ПОЖИРАТЕЛЬ_ЯДЕР),
        Ступень::ДискФона => верх(|к| к.диск_мб_с, ПОЖИРАТЕЛЬ_ДИСК_МБ_С),
        Ступень::ВидеокартаФона => верх(|к| к.гпу, ПОЖИРАТЕЛЬ_ГПУ),
        Ступень::Выжать => {
            let mut в: Vec<&Кандидат> = свои.iter().copied().filter(|к| к.ядер < 0.05 && к.рабочий_мб >= ВЫЖАТЬ_ОТ_МБ
                && выжимали.get(&к.pid).is_none_or(|т| т.elapsed() >= ВЫЖАТЬ_ТОГО_ЖЕ_РАЗ_В)).collect();
            в.sort_by(|а, б| б.рабочий_мб.cmp(&а.рабочий_мб));
            в.into_iter().take(ВЫЖАТЬ_ЗА_РАЗ).map(|к| (к.pid, к.имя.clone())).collect()
        }
        Ступень::Сборки | Ступень::ВыгрузитьРазум => Vec::new(),
    }
}

/// Чистая (видно в тесте): что было до ступени диска — очередь диска и приоритет памяти одним числом книги (младший
/// байт — очередь, следующий — память; 0 — не знали).
pub fn было_диска(очередь: u32, память: Option<u32>) -> i64 {
    (очередь & 0xFF) as i64 | (((память.unwrap_or(0) & 0xFF) as i64) << 8)
}

/// Чистая (видно в тесте): обратно — (очередь диска, приоритет памяти; `None` — не знали, память не возвращаем: так в
/// записях до 26.10).
pub fn разобрать_диск(было: i64) -> (u32, Option<u32>) {
    ((было & 0xFF) as u32, Some(((было >> 8) & 0xFF) as u32).filter(|п| *п > 0))
}

/// Вернуть ступень диска: очередь диска и, если знали, приоритет памяти.
fn вернуть_диск(pid: u32, было: i64) -> bool {
    let (очередь, память) = разобрать_диск(было);
    let ок = okna::очередь_диска(pid, Some(очередь)).is_some();
    if let Some(п) = память { let _ = okna::память_процесса(pid, Some(п)); }
    ок
}

