/// Чистая (видно в тесте): просить ли БАРС выгрузить 27B — загружен, простаивает дольше `РАЗУМ_ПРОСТОЙ_С`.
pub fn разум_можно_выгрузить(б: &Барс) -> bool {
    б.жив && б.разум_загружен && б.разум_простой_с.is_some_and(|с| с >= РАЗУМ_ПРОСТОЙ_С)
}

/// Заранее (тормоза ещё нет) 27B выгружаем только у самого края: свободно зачисленной меньше этого (здесь Windows уже
/// растит файл подкачки рывком — 24.10 «мало виртуальной памяти»), простаивает дольше и прошлая выгрузка — не ближе.
/// Иначе подъём и выгрузка 27B по кругу сами стали бы тормозом, а ответ на его слово — медленнее.
pub const ЗАРАНЕЕ_РАЗУМ_ЗАЧИСЛЕНО_МБ: u64 = 1500;
pub const ЗАРАНЕЕ_РАЗУМ_ПРОСТОЙ_С: u64 = 180;
pub const ЗАРАНЕЕ_РАЗУМ_РАЗ_В: Duration = Duration::from_secs(15 * 60);

/// Чистая (видно в тесте): выгружать ли 27B на этой ступени.
pub fn разум_выгрузить(б: &Барс, заранее: bool, зачислено_своб_мб: Option<u64>, с_прошлой: Option<Duration>) -> bool {
    разум_можно_выгрузить(б) && (!заранее || зачислено_своб_мб.is_some_and(|з| з < ЗАРАНЕЕ_РАЗУМ_ЗАЧИСЛЕНО_МБ)
        && б.разум_простой_с.is_some_and(|с| с >= ЗАРАНЕЕ_РАЗУМ_ПРОСТОЙ_С)
        && с_прошлой.is_none_or(|д| д >= ЗАРАНЕЕ_РАЗУМ_РАЗ_В))
}
